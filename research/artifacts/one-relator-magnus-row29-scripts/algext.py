#!/usr/bin/env python3
"""Proper rank-2 overgroups of a rank-2 subgroup H of F(x,y), via Stallings folding.

If K >= H is finitely generated, the Stallings graph of H immerses into that of K, and
the image subgroup is generated by a folded quotient of Gamma_H.  Extra edges of K raise
the rank, so a rank-2 K properly containing a rank-2 H equals the subgroup of some folded
quotient of Gamma_H with rank 2 that is not H itself.  This script enumerates every set
partition of the vertices of Gamma_H, identifies, folds, and reports the rank and whether
the result differs from H.  Letters: x, X = x^-1, y, Y = y^-1.
Usage: algext.py WORD1 WORD2 [...]
"""
import sys

def stallings(words):
    edges, nv = set(), 1
    for w in words:
        cur = 0
        for i, ch in enumerate(w):
            nxt = 0 if i == len(w) - 1 else nv
            if i < len(w) - 1:
                nv += 1
            lab, inv = ch.lower(), ch.isupper()
            edges.add((nxt, lab, cur) if inv else (cur, lab, nxt))
            cur = nxt
    return fold(nv, edges)

def fold(nv, edges):
    parent = list(range(nv))
    def find(u):
        while parent[u] != u:
            parent[u] = parent[parent[u]]; u = parent[u]
        return u
    changed = True
    while changed:
        changed = False
        E = {(find(u), l, find(v)) for (u, l, v) in edges}
        out, inn = {}, {}
        for (u, l, v) in E:
            for key, val in (((u, l), v), ):
                if key in out and find(out[key]) != find(val):
                    parent[find(val)] = find(out[key]); changed = True
                out.setdefault(key, val)
            key = (v, l)
            if key in inn and find(inn[key]) != find(u):
                parent[find(u)] = find(inn[key]); changed = True
            inn.setdefault(key, u)
        edges = E
    E = {(find(u), l, find(v)) for (u, l, v) in edges}
    verts = sorted({find(u) for u in range(nv)})
    ren = {v: i for i, v in enumerate(verts)}
    return len(verts), frozenset((ren[u], l, ren[v]) for (u, l, v) in E)

def core_rank(nv, edges):
    return len(edges) - nv + 1

def canon_graph(nv, edges):
    """Rooted canonical form (root 0 fixed): relabel by BFS order over sorted labels."""
    adj = {}
    for (u, l, v) in edges:
        adj.setdefault(u, []).append((l, 0, v)); adj.setdefault(v, []).append((l, 1, u))
    order, seen = [0], {0: 0}
    i = 0
    while i < len(order):
        u = order[i]; i += 1
        for l, d, v in sorted(adj.get(u, [])):
            if v not in seen:
                seen[v] = len(order); order.append(v)
    return tuple(sorted((seen[u], l, seen[v]) for (u, l, v) in edges))

def partitions(items):
    if not items:
        yield []
        return
    first, rest = items[0], items[1:]
    for p in partitions(rest):
        for i in range(len(p)):
            yield p[:i] + [[first] + p[i]] + p[i + 1:]
        yield [[first]] + p

def main():
    words = sys.argv[1:]
    nv, E = stallings(words)
    base = canon_graph(nv, E)
    print('H = <%s>: vertices=%d edges=%d rank=%d' % (', '.join(words), nv, len(E), core_rank(nv, E)))
    found = {}
    for part in partitions(list(range(nv))):
        if len(part) == nv:
            continue
        rep = {}
        for block in part:
            for v in block:
                rep[v] = block[0]
        E2 = {(rep[u], l, rep[v]) for (u, l, v) in E}
        # relabel so the root (block containing 0) is 0
        blocks = sorted({rep[v] for v in range(nv)}, key=lambda b: (b != rep[0], b))
        ren = {b: i for i, b in enumerate(blocks)}
        n3, E3 = fold(len(blocks), {(ren[u], l, ren[v]) for (u, l, v) in E2})
        r = core_rank(n3, E3)
        key = canon_graph(n3, E3)
        if key != base:
            found.setdefault((r, key), part)
    ranks = sorted({r for (r, _) in found})
    print('proper folded quotients by rank: %s' % {r: sum(1 for (rr, _) in found if rr == r) for r in ranks})
    for (r, key), part in sorted(found.items()):
        if r == 2:
            print('RANK2 partition=%s graph=%s' % (part, key))
    print('SENTINEL_DONE')

if __name__ == '__main__':
    main()
