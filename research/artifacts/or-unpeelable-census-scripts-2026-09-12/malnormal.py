#!/usr/bin/env python3
"""Malnormality of the Magnus subgroups of free Magnus pieces.

For each class of census.gen(L) left uncertified by census.cert_word whose
Magnus piece has an interior letter a_h occurring exactly once, eliminate a_h:
B_0 is free on the remaining letters, and F_-, F_+ are generated by the images
of a_m..a_(n-g) and a_(m+g)..a_n.  Stallings folding decides whether F_- and
F_+ are proper and malnormal in B_0: a subgroup H of a free group is malnormal
iff every off-diagonal component of the fiber product of its folded graph with
itself is a tree.  Usage: malnormal.py L MAXPRINT
"""
import sys
from collections import Counter
import census as C
import census2 as C2

def stallings(gens):
    edges, nv = set(), 1
    for g in gens:
        cur = 0
        for i, x in enumerate(g):
            nxt = 0 if i == len(g) - 1 else nv
            if nxt:
                nv += 1
            edges.add((cur, x, nxt) if x > 0 else (nxt, -x, cur))
            cur = nxt
    while True:
        seen, merge = {}, None
        for (p, x, q) in edges:
            for key, other in (((p, x, 1), q), ((q, x, -1), p)):
                if key in seen and seen[key] != other:
                    merge = (min(seen[key], other), max(seen[key], other))
                    break
                seen[key] = other
            if merge:
                break
        if not merge:
            return edges
        a, b = merge
        edges = {(a if p == b else p, x, a if q == b else q) for (p, x, q) in edges}

def is_whole(edges, rank):
    verts = {p for p, _, _ in edges} | {q for _, _, q in edges}
    return len(verts) == 1 and len(edges) == rank

def is_malnormal(edges):
    parent = {}
    def find(v):
        parent.setdefault(v, v)
        while parent[v] != v:
            parent[v] = parent[parent[v]]
            v = parent[v]
        return v
    pe = []
    for (p, x, q) in edges:
        for (p2, x2, q2) in edges:
            if x == x2 and p != p2:
                u, v = (p, p2), (q, q2)
                pe.append((u, v))
                parent[find(u)] = find(v)
    V, E = Counter(), Counter()
    for v in list(parent):
        V[find(v)] += 1
    for u, v in pe:
        E[find(u)] += 1
    return all(E[r] < V[r] for r in V)

def free_piece(cs):
    m, n, g, top, bot = C.extremes(cs)
    tot = Counter()
    for h, e in cs:
        tot[h] += abs(e)
    once = [h for h in sorted(tot) if m < h < n and tot[h] == 1]
    if not once:
        return None
    hs = once[0]
    letters = list(range(m, n + 1, g))
    code = {h: i + 1 for i, h in enumerate(x for x in letters if x != hs)}
    i = next(i for i, (h, e) in enumerate(cs) if h == hs)
    rot = cs[i:] + cs[:i]
    V = []
    for h, e in rot[1:]:
        V.extend(C.power(code[h], e))
    u = C.inv(V) if rot[0][1] == 1 else V
    img = {h: ([code[h]] if h != hs else u) for h in letters}
    Fm = [img[h] for h in letters[:-1]]
    Fp = [img[h] for h in letters[1:]]
    return u, len(letters) - 1, Fm, Fp

def main():
    L, maxprint = int(sys.argv[1]), int(sys.argv[2])
    seen, stats, shown = set(), Counter(), 0
    for seq in C.gen(L):
        m, n, g, top, bot = C.extremes(seq)
        if C.peelable(top) or C.peelable(bot):
            continue
        c = C.canon(seq)
        if c in seen:
            continue
        seen.add(c)
        cs = list(c)
        w = C.seq_to_word(cs)
        if C.min_period(w) < len(w):
            continue
        C.BUDGET[0] = 3000
        if C.cert_word(w, 0)[0]:
            continue
        fp = free_piece(cs)
        if fp is None:
            stats['nonfree'] += 1
            continue
        u, rank, Fm, Fp = fp
        em, ep = stallings(Fm), stallings(Fp)
        prop = (not is_whole(em, rank)) and (not is_whole(ep, rank))
        mal = (is_malnormal(em), is_malnormal(ep))
        ppok = C2.pp_search(w, 4, 20000) is not None
        stats[('rank%d' % rank, 'proper' if prop else 'WHOLE', 'mal-,+=%s,%s' % mal, 'PP' if ppok else 'open')] += 1
        if shown < maxprint:
            shown += 1
            s = ''.join({1: 'x', -1: 'X', 2: 'y', -2: 'Y'}.get(z, '?') for z in u) if rank == 2 else str(u)
            print(' FREE %s u=%s proper=%s malnormal(F-,F+)=%s pp=%s' % (C.word_str(w), s, prop, mal, ppok))
    print('L=%d stats=%s' % (L, sorted(stats.items(), key=str)))
    print('SENTINEL_DONE', flush=True)

if __name__ == '__main__':
    main()
