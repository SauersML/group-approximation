#!/usr/bin/env python3
"""Exact label search for the even area-ten residue.

The structural contraction certificate leaves five even face partitions,
each with a designated internal length-ten identity outside Q.  They are a
subset of the 276 ribbon maps generated by the short-atlas certificate.  This
wrapper reuses that map/orientation machinery and evaluates every Q-nontrivial
face in the actual coefficient free product.
"""

from concurrent.futures import ProcessPoolExecutor, as_completed
from functools import lru_cache
from pathlib import Path
import argparse
import json


HERE = Path(__file__).parent


def definitions(path, marker):
    source = path.read_text().split(marker, 1)[0]
    namespace = {"__file__": str(path), "__name__": path.stem}
    exec(compile(source, str(path), "exec"), namespace)
    return namespace


atlas = definitions(
    HERE / "search-leavitt-area-ten-short-atlas.py",
    "def main():",
)
actual = definitions(
    HERE / "classify-leavitt-odd-five-seven-corners.py",
    "lengths = tuple(map(int, sys.argv[1:]))",
)


TARGET_PARTITIONS = {
    (2, 2, 2, 2, 2, 10, 10),
    (2, 2, 2, 2, 4, 8, 10),
    (2, 2, 2, 2, 6, 6, 10),
    (2, 2, 2, 4, 4, 6, 10),
    (2, 2, 4, 4, 4, 4, 10),
}


@lru_cache(None)
def is_actual_identity(word):
    blocks = actual["reduced_syllables"](word)
    if not blocks:
        return True
    unknown = [tokens for _, tokens in blocks
               if not actual["witnessed_nonidentity"](tokens)]
    if unknown:
        raise AssertionError((word, blocks, unknown))
    return False


def search_map(task):
    map_index, alpha, provenance = task
    partition = provenance[0]
    fs = atlas["faces"](alpha)
    valid_orientations = 0
    admissible_colours = 0
    long_words = set()
    for direction_bits in range(1 << 15):
        datum = atlas["orientation_data"](alpha, direction_bits)
        if datum is None:
            continue
        valid_orientations += 1
        edge_darts, orientations, occurrences = datum
        unequal = []
        for dart, twin in edge_darts:
            if (orientations[dart // 3] == -orientations[twin // 3]
                    and occurrences[dart] + occurrences[twin] == 2):
                unequal.append((dart // 3, twin // 3))

        for colour_bits in range(1 << 10):
            colours = tuple((colour_bits >> vertex) & 1
                            for vertex in range(10))
            if any(colours[first] == colours[second]
                   for first, second in unequal):
                continue
            admissible_colours += 1
            raw = tuple(
                atlas["face_word"](face, alpha, colours, orientations,
                                   occurrences)
                for face in fs
            )
            q_words = tuple(atlas["q_reduce"](word) for word in raw)
            q_nontrivial = [i for i, word in enumerate(q_words) if word]
            if len(q_nontrivial) < 2:
                # Zero means no boundary; one is the closed short-atlas case.
                continue
            # Every Q-nontrivial internal identity must have length ten in the
            # surviving even budgets.  Try each Q-nontrivial face as boundary.
            for outer in q_nontrivial:
                internal_long = [i for i in q_nontrivial if i != outer]
                if not internal_long or any(len(raw[i]) != 10
                                            for i in internal_long):
                    continue
                long_words.update(actual["canonical"](raw[i])
                                  for i in internal_long)
                if (not is_actual_identity(raw[outer])
                        and all(is_actual_identity(raw[i])
                                for i in internal_long)):
                    return {
                        "candidate": True,
                        "map_index": map_index,
                        "partition": partition,
                        "alpha": alpha,
                        "direction_bits": direction_bits,
                        "colours": colours,
                        "outer": outer,
                        "raw": raw,
                        "q_words": q_words,
                    }
    return {
        "candidate": False,
        "map_index": map_index,
        "partition": partition,
        "valid_orientations": valid_orientations,
        "admissible_colours": admissible_colours,
        "long_words": long_words,
        "actual_long_identities": tuple(
            word for word in long_words if is_actual_identity(word)
        ),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--workers", type=int, default=1)
    args = parser.parse_args()

    _, _, maps = atlas["generate_maps"]()
    tasks = [
        (index, alpha, provenance)
        for index, (alpha, provenance) in enumerate(maps.items())
        if provenance[0] in TARGET_PARTITIONS
    ]
    print("TASKS", len(tasks), flush=True)
    pool = ProcessPoolExecutor(max_workers=args.workers)
    futures = [pool.submit(search_map, task) for task in tasks]
    long_words = set()
    orientations = colours = 0
    try:
        for done, future in enumerate(as_completed(futures), 1):
            result = future.result()
            if result["candidate"]:
                print("CANDIDATE", json.dumps(result), flush=True)
                pool.shutdown(wait=False)
                return 1
            orientations += result["valid_orientations"]
            colours += result["admissible_colours"]
            long_words.update(result["long_words"])
            assert not result["actual_long_identities"], result
            print("DONE", done, "/", len(tasks), flush=True)
    finally:
        pool.shutdown(wait=True)
    identities = tuple(word for word in long_words if is_actual_identity(word))
    print("VALID_ORIENTATIONS", orientations)
    print("ADMISSIBLE_COLOURS", colours)
    print("REQUIRED_LENGTH_TEN_WORDS", len(long_words))
    print("ACTUAL_LENGTH_TEN_IDENTITIES", len(identities))
    print("NO_CANDIDATE", len(tasks))
    assert not identities
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
