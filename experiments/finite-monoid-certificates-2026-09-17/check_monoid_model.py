#!/usr/bin/env python3
"""Check of the finite-act certificate (Theorem M of
research/artifacts/finite-monoid-certificates-2026-09-17.md).

A certificate for a pattern (E, F, Q = {1} u E u FE in a group G) is a finite set Y,
maps phi_u : Y -> Y for u in E u F, and a base point y0, such that
  (W) the map sending the expression 1 to id, e to phi_e, fe to phi_f o phi_e
      is well defined on Q: expressions naming the same element give the same map on ALL of Y;
  (I) q -> phi_q(y0) is injective on Q.
The model X = [N]^Y, (S_u c)(y) = c(phi_u y) then has S_e T_f c = c o phi_f o phi_e exactly,
and at most C(|Q|,2)/N of its points have a non-injective chart.

Example 1 (Theorem A as a corollary): G = Z/2 * Z, E = F = {1, z, s}, heights a(s)=b(s)=1,
core {1, z}.  Y = disjoint union of levels R_r = K_Z B(r), r <= L, plus a sink; phi_u raises
level by lam*ht(u) via g -> u g, and goes to the sink past the top level.
Example 2 (a certificate outside Theorem A): G = Z, E = F = {1, s, s^-1}; every letter is a
read letter, the only height potential is zero and its core Z is infinite, so Theorem A says
nothing; Y = Z/5 with phi_s = +1 is a certificate.
The script checks (W) and (I) exhaustively, prints the monoid generated, and samples the
bad-chart fraction of X = [N]^Y against the bound C(|Q|,2)/N.
"""
import itertools
import random


# ---------- Z/2 * Z normal forms: tuples of 'z' or nonzero ints (s^n), alternating ----------
def mul(u, v):
    st = list(u)
    for t in v:
        if not st:
            st.append(t)
            continue
        top = st[-1]
        if t == 'z' and top == 'z':
            st.pop()
        elif t != 'z' and top != 'z':
            n = top + t
            st.pop()
            if n != 0:
                st.append(n)
        else:
            st.append(t)
    return tuple(st)


ONE = ()
Z_ = ('z',)
S_ = (1,)
SINV = (-1,)


def ball(radius):
    gens = [Z_, S_, SINV]
    seen = {ONE}
    frontier = [ONE]
    for _ in range(radius):
        nxt = []
        for g in frontier:
            for h in gens:
                x = mul(h, g)
                if x not in seen:
                    seen.add(x)
                    nxt.append(x)
        frontier = nxt
    return seen


def check_certificate(name, E, F, gmul, Y, phi, y0, N=50, samples=4000):
    Ylist = list(Y)
    ident = {y: y for y in Ylist}
    # expressions: ('1',), ('e', e), ('fe', f, e)
    exprs = [(ONE_OF[name], ident)]
    for e in E:
        exprs.append((e, phi[e]))
    for f in F:
        for e in E:
            comp = {y: phi[f][phi[e][y]] for y in Ylist}
            exprs.append((gmul(f, e), comp))
    by_elem = {}
    ok_w = True
    for g, m in exprs:
        if g in by_elem and by_elem[g] != m:
            ok_w = False
        by_elem.setdefault(g, m)
    Q = list(by_elem)
    pts = [by_elem[g][y0] for g in Q]
    ok_i = len(set(pts)) == len(pts)
    # monoid generated by the letter maps
    gens = [tuple(phi[u][y] for y in Ylist) for u in set(E) | set(F)]
    idx = {y: i for i, y in enumerate(Ylist)}
    gens = [tuple(idx[v] for v in g) for g in gens]
    mon = {tuple(range(len(Ylist)))}
    frontier = list(mon)
    while frontier:
        nxt = []
        for a in frontier:
            for b in gens:
                c = tuple(a[b[i]] for i in range(len(Ylist)))
                if c not in mon:
                    mon.add(c)
                    nxt.append(c)
        frontier = nxt
    # sampled bad-chart fraction on X = [N]^Y (only coordinates at phi_q(y0) matter)
    rng = random.Random(1)
    bad = 0
    for _ in range(samples):
        col = {y: rng.randrange(N) for y in set(pts)}
        vals = [col[p] for p in pts]
        if len(set(vals)) < len(vals):
            bad += 1
    bound = len(Q) * (len(Q) - 1) / 2 / N
    print(f"[{name}] |Y|={len(Ylist)} |Q|={len(Q)} well-defined={ok_w} injective={ok_i} "
          f"|monoid|={len(mon)} bad~{bad / samples:.4f} <= bound {bound:.4f}")
    return ok_w and ok_i and bad / samples <= bound + 0.02


ONE_OF = {}


def example_theorem_a():
    E = F = [ONE, Z_, S_]
    ht = {ONE: 0, Z_: 0, S_: 1}
    D, lam = 1, 2
    L = lam * 2
    levels = {r: {g for g in ball(r)} | {mul(Z_, g) for g in ball(r)} for r in range(L + 1)}
    Y = [(r, g) for r in range(L + 1) for g in levels[r]] + ['sink']
    phi = {}
    for u in E:
        m = {'sink': 'sink'}
        for (r, g) in Y[:-1]:
            s = r + lam * ht[u]
            if s > L:
                m[(r, g)] = 'sink'
            else:
                x = mul(u, g)
                assert x in levels[s], (u, g, s)
                m[(r, g)] = (s, x)
        phi[u] = m
    ONE_OF['thmA-Z2*Z'] = ONE
    return check_certificate('thmA-Z2*Z', E, F, mul, Y, phi, (0, ONE))


def example_cyclic():
    n = 5
    E = F = [0, 1, -1]
    Y = list(range(n))
    phi = {u: {y: (y + u) % n for y in Y} for u in E}
    ONE_OF['Z-in-Z/5'] = 0
    return check_certificate('Z-in-Z/5', E, F, lambda a, b: a + b, Y, phi, 0)


if __name__ == '__main__':
    r1 = example_theorem_a()
    r2 = example_cyclic()
    print('ALL OK' if r1 and r2 else 'FAILURE')
