#!/usr/bin/env python3
"""One-ring push b' = A_vc^{+-1} b0 in the loop braid descending link: finite-orbit tests.

Conventions as in experiments/loop-braid-bfmwz-push-2026-09-17/mutual_link.py:
  words in F_n are tuples of nonzero ints (i = x_i, -i = x_i^{-1});
  an element is a pair (phi, phi^{-1}) of automorphisms (dict i -> word);
  the group law is composition, mul(g, h) = g o h;
  A(i,j): x_i -> x_j x_i x_j^{-1};
  the cabling subgroup P_u of the ordered cable u = (a,b) is generated by
    A(i,j) (i,j not in {a,b}), x_k -> (x_a x_b) x_k (x_a x_b)^{-1}, and x_a,x_b -> x_q (.) x_q^{-1}.
The complex is the development of Q with these stabilizers: vertex p[tau] = coset p P_tau.
  p[tau] is in lk([b0]) iff p in P_b0 P_tau.
Rings: v = 1, w = 2, c = 3, others 4..n.  b0 = (1,2).

FINITE-ORBIT TEST (a certificate of NON-membership).  P acts on the right on the finite set
Omega = Hom(F_n, G) = G^n by rho . phi = rho o phi.  If p = h k with h in H, k in K, then
rho . p = (rho . h) . k, so the K-orbit of rho . p meets the H-orbit of rho.  If for some rho it
does not, then p is not in H K.  Orbits are computed from generators (a forward-closed subset of
a finite set is closed under the generated group).

Output: for each tested vertex u = s[tau] of lk(b0) (s in P_b0), whether u can be in lk(b').
"""
import itertools
import sys

import numpy as np
from scipy.sparse import coo_matrix
from scipy.sparse.csgraph import connected_components


# ---------------------------------------------------------------- free group words

def red(w):
    out = []
    for a in w:
        if out and out[-1] == -a:
            out.pop()
        else:
            out.append(a)
    return tuple(out)


def inv(w):
    return tuple(-a for a in reversed(w))


def apply(f, w):
    out = []
    for a in w:
        img = f.get(abs(a), (abs(a),))
        out.extend(img if a > 0 else inv(img))
    return red(out)


def compose(f, g, n):
    return {i: apply(f, g.get(i, (i,))) for i in range(1, n + 1)}


def ident(n):
    return {i: (i,) for i in range(1, n + 1)}


def elt(targets, P, n):
    """(phi, phi^-1) for x_s -> P x_s P^-1 (s in targets), valid when phi fixes the word P."""
    f, fi = ident(n), ident(n)
    P = tuple(P)
    for s in targets:
        f[s] = red(P + (s,) + inv(P))
        fi[s] = red(inv(P) + (s,) + P)
    return (f, fi)


def mul(g, h, n):
    return (compose(g[0], h[0], n), compose(h[1], g[1], n))


def inverse(g):
    return (g[1], g[0])


def A(i, j, n):
    return elt([i], [j], n)


def cabling_gens(rings, n):
    R = set(rings)
    others = [i for i in range(1, n + 1) if i not in R]
    out = []
    for i in others:
        for j in others:
            if i != j:
                out.append(('A%d%d' % (i, j), A(i, j, n)))
    for k in others:
        out.append(('th%d' % k, elt([k], list(rings), n)))
        out.append(('ze%d' % k, elt(list(rings), [k], n)))
    return out


# ---------------------------------------------------------------- finite groups

def perm_group(gens):
    """All elements of the permutation group generated by gens (tuples)."""
    idp = tuple(range(len(gens[0])))
    elems = {idp}
    frontier = [idp]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = tuple(g[x[i]] for i in range(len(x)))
                if y not in elems:
                    elems.add(y)
                    new.append(y)
        frontier = new
    return sorted(elems)


def group_tables(elems):
    idx = {e: i for i, e in enumerate(elems)}
    m = len(elems)
    mt = np.zeros((m, m), dtype=np.int64)
    for i, x in enumerate(elems):
        for j, y in enumerate(elems):
            mt[i, j] = idx[tuple(x[y[k]] for k in range(len(x)))]   # x o y
    e = idx[tuple(range(len(elems[0])))]
    it = np.array([int(np.where(mt[i] == e)[0][0]) for i in range(m)], dtype=np.int64)
    return mt, it, e


GROUPS = {
    'S3': [(1, 0, 2), (1, 2, 0)],
    'A4': [(1, 2, 0, 3), (0, 2, 3, 1)],
    'D4': [(1, 2, 3, 0), (3, 2, 1, 0)],
    'S4': [(1, 0, 2, 3), (1, 2, 3, 0)],
}


class Omega:
    """Omega = G^n, points encoded in base |G|; right action rho . phi = rho o phi."""

    def __init__(self, gname, n):
        self.elems = perm_group(GROUPS[gname])
        self.mt, self.it, self.e = group_tables(self.elems)
        self.m = len(self.elems)
        self.n = n
        self.size = self.m ** n
        pts = np.arange(self.size, dtype=np.int64)
        self.coord = []
        for i in range(n):
            self.coord.append(pts % self.m)
            pts = pts // self.m
        self.cache = {}

    def eval_word(self, w):
        val = np.full(self.size, self.e, dtype=np.int64)
        for a in w:
            g = self.coord[abs(a) - 1]
            if a < 0:
                g = self.it[g]
            val = self.mt[val, g]
        return val

    def perm(self, phi):
        """Array with entry [rho] = rho o phi."""
        key = tuple(tuple(phi[i]) for i in range(1, self.n + 1))
        if key in self.cache:
            return self.cache[key]
        out = np.zeros(self.size, dtype=np.int64)
        base = 1
        for i in range(1, self.n + 1):
            out += self.eval_word(phi[i]) * base
            base *= self.m
        self.cache[key] = out
        return out

    def orbit_labels(self, gens):
        rows, cols = [], []
        src = np.arange(self.size, dtype=np.int64)
        for _, g in gens:
            rows.append(src)
            cols.append(self.perm(g[0]))
        r = np.concatenate(rows)
        c = np.concatenate(cols)
        M = coo_matrix((np.ones(len(r), dtype=np.int8), (r, c)), shape=(self.size, self.size))
        _, lab = connected_components(M, directed=True, connection='weak')
        return lab.astype(np.int64)


def certified_not_in(om, p, labH, labK):
    """True iff the finite test certifies p not in H K (H, K given by orbit labels).

    If p = h k then rho . p = (rho . h) . k: the K-orbit of rho . p meets the H-orbit of rho.
    """
    img = om.perm(p[0])
    big = int(labK.max()) + 1
    pairs = np.unique(labH * big + labK)
    need = labH * big + labK[img]
    return not bool(np.isin(need, pairs).all())


# ---------------------------------------------------------------- the tests

def with_inverses(gens):
    out = []
    for name, g in gens:
        out.append((name, g))
        out.append((name + "'", inverse(g)))
    return out


def run(gname, n, report):
    om = Omega(gname, n)
    v, w, c = 1, 2, 3
    b0 = (v, w)
    Hg = cabling_gens(b0, n)
    labH = om.orbit_labels(Hg)
    rest = list(range(4, n + 1))
    types_avoid = [t for t in itertools.permutations(rest, 2)]
    types_c = [(c, d) for d in rest] + [(d, c) for d in rest]
    labK = {t: om.orbit_labels(cabling_gens(t, n)) for t in types_avoid + types_c}
    ident_el = (ident(n), ident(n))
    res = {}
    # (0) sanity: members of P_b0 P_tau are never certified
    bad = []
    for t in types_avoid + types_c:
        for name, s in with_inverses(Hg) + [('1', ident_el)]:
            if certified_not_in(om, s, labH, labK[t]):
                bad.append((name, t))
        for name, k in with_inverses(cabling_gens(t, n)):
            if certified_not_in(om, k, labH, labK[t]):
                bad.append(('K:' + name, t))
    res['sanity_members_pass'] = not bad
    # (0') power check: A_vc^{+-1} is certified NOT in P_b0 P_tau for tau containing c
    # (the clasp homomorphism lambda = e_vc - e_vd - e_wc + e_wd proves it)
    pw = [certified_not_in(om, A(v, c, n), labH, labK[t]) for t in types_c]
    res['power_c_types_certified'] = (sum(pw), len(pw))
    # (1) main: u = s[tau], s in P_b0, tau avoiding c: can u lie in lk(g b0), g = A_vc^{+-1}?
    main = {}
    for gsign, g in (('A_vc', A(v, c, n)), ("A_vc'", inverse(A(v, c, n)))):
        gi = inverse(g)
        for t in types_avoid:
            for name, s in with_inverses(Hg):
                p = mul(gi, s, n)
                if certified_not_in(om, p, labH, labK[t]):
                    main.setdefault((gsign, t), []).append(name)
    res['main'] = main
    # (2) control against the ESTABLISHED pair-twist result (loop-braid-pair-twist-push-mutual-link):
    # for the push g = tau_{w c} (x_w, x_c conjugated by x_w x_c) the triple-cable subgroup T of
    # (v,w,c) centralizes g, so T . Q_{avoid v,w,c} lies in lk(b0) and lk(g b0).  The finite test
    # must never certify a vertex t[tau] (t a generator of T, tau avoiding v,w,c) outside lk(g b0).
    tw = elt([w, c], [w, c], n)
    Tg = cabling_gens((v, w, c), n)
    ctrl = []
    for t in types_avoid:
        for name, s in with_inverses(Tg):
            for g in (tw, inverse(tw)):
                if certified_not_in(om, mul(inverse(g), s, n), labH, labK[t]):
                    ctrl.append((name, t))
    res['control_pair_twist_pass'] = not ctrl
    report.append((gname, n, res))
    return res


def main():
    report = []
    configs = [('S3', 5), ('S3', 6), ('D4', 5), ('A4', 5), ('S3', 7), ('A4', 6)]
    if len(sys.argv) > 1:
        configs = [(a.split(':')[0], int(a.split(':')[1])) for a in sys.argv[1:]]
    for gname, n in configs:
        res = run(gname, n, report)
        print('G=%s n=%d' % (gname, n))
        print('  (0) members of P_b0 P_tau never certified:', res['sanity_members_pass'])
        print('  (0\') A_vc certified outside P_b0 P_tau, tau containing c: %d of %d'
              % res['power_c_types_certified'])
        print('  (1) vertices s[tau] of lk(b0), tau avoiding c, certified NOT in lk(g b0):')
        if not res['main']:
            print('      none')
        for key in sorted(res['main']):
            print('     ', key, sorted(res['main'][key]))
        print('  (2) control: pair-twist push, triple-cable family member never certified:',
              res['control_pair_twist_pass'])
        sys.stdout.flush()


if __name__ == '__main__':
    main()
