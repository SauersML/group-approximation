#!/usr/bin/env python3
"""Verify the conditional representation-ring law of the Pauli gauge bridge.

For k logical bits and k private gauge bits, an equal-spin context packet has
one type for every (logical,gauge) character.  Restriction to the abelian edge
chart contributes D copies of that character.  The unique marked E_k spin
type, conditional on a logical character, contributes one copy of every gauge
character on both its Z and X charts.

The two edge equations must therefore force both context multiplicity tables
to be gauge-uniform, logical-character by logical-character, and identical.
"""

from __future__ import annotations

import json


def verify(k: int, packet_dimension: int) -> dict:
    logical_count = 1 << k
    gauge_count = 1 << k

    # Give every connector logical block a distinct positive test
    # multiplicity.  The edge equations determine both packet tables.
    connector = [(logical + 1) * packet_dimension
                 for logical in range(logical_count)]
    old = [[connector[logical] // packet_dimension
            for _ in range(gauge_count)]
           for logical in range(logical_count)]
    new = [[connector[logical] // packet_dimension
            for _ in range(gauge_count)]
           for logical in range(logical_count)]

    for logical in range(logical_count):
        for gauge in range(gauge_count):
            assert packet_dimension * old[logical][gauge] == connector[logical]
            assert packet_dimension * new[logical][gauge] == connector[logical]
        assert len(set(old[logical])) == 1
        assert old[logical] == new[logical]
        assert sum(old[logical]) == gauge_count * connector[logical] // packet_dimension

    # Coefficient matrix for one logical block.  Variables are the old gauge
    # multiplicities, the connector multiplicity, and the new gauge
    # multiplicities.  Its integer kernel is one-dimensional and generated by
    # (1,...,1,D,1,...,1).
    variable_count = 2 * gauge_count + 1
    rows = []
    for gauge in range(gauge_count):
        row = [0] * variable_count
        row[gauge] = packet_dimension
        row[gauge_count] = -1
        rows.append(row)
    for gauge in range(gauge_count):
        row = [0] * variable_count
        row[gauge_count] = -1
        row[gauge_count + 1 + gauge] = packet_dimension
        rows.append(row)

    # Exact rational elimination, represented by Python fractions.
    from fractions import Fraction
    matrix = [[Fraction(value) for value in row] for row in rows]
    rank = 0
    for column in range(variable_count):
        pivot = next((index for index in range(rank, len(matrix))
                      if matrix[index][column]), None)
        if pivot is None:
            continue
        matrix[rank], matrix[pivot] = matrix[pivot], matrix[rank]
        scale = matrix[rank][column]
        matrix[rank] = [value / scale for value in matrix[rank]]
        for index in range(len(matrix)):
            if index == rank or not matrix[index][column]:
                continue
            scale = matrix[index][column]
            matrix[index] = [left - scale * right
                             for left, right in zip(matrix[index], matrix[rank])]
        rank += 1
    assert variable_count - rank == 1

    generator = [1] * gauge_count + [packet_dimension] + [1] * gauge_count
    assert all(sum(coefficient * value
                   for coefficient, value in zip(row, generator)) == 0
               for row in rows)

    return {
        "logical_bits": k,
        "private_gauge_bits": k,
        "logical_characters": logical_count,
        "gauge_characters": gauge_count,
        "packet_dimension": packet_dimension,
        "incidence_rows_per_logical_character": len(rows),
        "incidence_columns_per_logical_character": variable_count,
        "incidence_rank": rank,
        "kernel_dimension": variable_count - rank,
        "primitive_positive_ray": generator,
        "conditional_uniformity_verified": True,
        "old_new_equality_verified": True,
    }


def main() -> None:
    records = [verify(k, 1 << (1 << k)) for k in range(1, 5)]
    print(json.dumps({"all_checks_pass": True, "records": records}, indent=2))


if __name__ == "__main__":
    main()

