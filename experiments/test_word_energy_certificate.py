"""Check the constructive proof against independent finite-action witnesses.

Run: python3 -m unittest discover -s experiments -p test_word_energy_certificate.py
"""

import copy
import random
import unittest

from word_energy_certificate import (
    build_certificate, inverse_word, reduce_word, verify_certificate,
)


def independent_endpoint(word, tables, point):
    """Deliberately avoid the production word-evaluation implementation."""
    for letter in word[::-1]:
        table = tables[abs(letter) - 1]
        point = table[point] if letter > 0 else table.index(point)
    return point


class CertificateTests(unittest.TestCase):
    def certificate(self, words, target, m=2):
        return build_certificate({
            "generator_count": m, "subgroup_words": words, "target_word": target,
        })

    def test_normal_closure_is_not_subgroup_membership(self):
        cert = self.certificate([[1]], [-2, 1, 2])
        result = verify_certificate(cert)
        self.assertEqual(result["target_displacement_squared"], 2)
        self.assertEqual(result["subgroup_displacements_squared"], [0])
        self.assertEqual(result["subgroup_words_moving_some_basis_vector"], [0])
        self.assertLessEqual(cert["dimension"], 5)
        self.assertEqual(self.certificate([[-2, 1, 2]], [-2, 1, 2])["status"], "member")

    def test_empty_words_and_rank_zero(self):
        for words in ([], [[]], [[], []]):
            self.assertEqual(self.certificate(words, [], m=0)["status"], "member")
        verify_certificate(self.certificate([], [1], m=1))
        self.assertEqual(self.certificate([[1]], [1, -1])["status"], "member")

    def test_cyclic_membership_and_nonmembership(self):
        for power in range(-12, 13):
            target = [1 if power > 0 else -1] * abs(power)
            cert = self.certificate([[1, 1, 1]], target, m=1)
            self.assertEqual(cert["status"] == "member", power % 3 == 0)
            if power % 3:
                verify_certificate(cert)

    def test_known_subgroup_products_with_inverses_and_cancellation(self):
        rng = random.Random(20260907)
        for _ in range(150):
            words = [[rng.choice([1, -1, 2, -2]) for _ in range(rng.randrange(1, 9))]
                     for _ in range(3)]
            target = []
            for _ in range(12):
                factor = rng.choice(words)
                target.extend(factor if rng.randrange(2) else inverse_word(factor))
            self.assertEqual(self.certificate(words, reduce_word(target))["status"], "member")

    def test_independent_finite_action_nonmembership_oracle(self):
        rng = random.Random(41729)
        checked = 0
        for _ in range(100):
            tables = [rng.sample(range(5), 5) for _ in range(2)]
            candidates = [[rng.choice([1, -1, 2, -2]) for _ in range(rng.randrange(1, 10))]
                          for _ in range(80)]
            fixed = [w for w in candidates if independent_endpoint(w, tables, 0) == 0]
            moved = [w for w in candidates if independent_endpoint(w, tables, 0) != 0]
            if not fixed or not moved:
                continue
            # The existing finite action is an independent proof that the
            # chosen target is outside the subgroup generated by fixed words.
            cert = self.certificate(fixed[:4], moved[0])
            result = verify_certificate(cert)
            self.assertTrue(result["verified"])
            for word in fixed[:4]:
                self.assertEqual(independent_endpoint(word, cert["permutations"],
                                                     cert["basepoint"]), cert["basepoint"])
            self.assertNotEqual(independent_endpoint(moved[0], cert["permutations"],
                                                     cert["basepoint"]), cert["basepoint"])
            checked += 1
        self.assertGreaterEqual(checked, 90)

    def test_verifier_rejects_tampering_and_noncertificates(self):
        cert = self.certificate([[1]], [-2, 1, 2])
        bad = copy.deepcopy(cert)
        bad["permutations"][0] = [0] * cert["dimension"]
        with self.assertRaises(ValueError):
            verify_certificate(bad)
        bad = copy.deepcopy(cert)
        bad["target_word"] = [1]
        with self.assertRaises(ValueError):
            verify_certificate(bad)
        bad = copy.deepcopy(cert)
        bad["subgroup_words"].append(cert["target_word"])
        with self.assertRaises(ValueError):
            verify_certificate(bad)
        with self.assertRaises(ValueError):
            verify_certificate(self.certificate([[1]], [1]))

    def test_polynomial_contexts_via_independent_support_replay(self):
        # Both relators have b-exponent zero, so b lies outside their normal
        # closure, independently of the builder's subgroup decision.
        relators = [[1, 2, -1, -2], [1, 1]]
        polynomials = [
            [(1, []), (2, [2]), (1j, [1, -2])],
            [(-1, [1]), (3j, [-2, -1, 2]), (2, [2, 1, -2])],
        ]
        words = [inverse_word(q) + r + q
                 for r, terms in zip(relators, polynomials) for _, q in terms]
        cert = self.certificate(words, [2])
        verify_certificate(cert)
        for r, terms in zip(relators, polynomials):
            residual = [0j] * cert["dimension"]
            for coefficient, q in terms:
                first = independent_endpoint(r + q, cert["permutations"], cert["basepoint"])
                second = independent_endpoint(q, cert["permutations"], cert["basepoint"])
                residual[first] += coefficient
                residual[second] -= coefficient
            self.assertEqual(residual, [0j] * cert["dimension"])

    def test_invalid_generator_data(self):
        for target in ([0], [3], [True], ["1"]):
            with self.assertRaises(ValueError):
                self.certificate([], target)


if __name__ == "__main__":
    unittest.main()
