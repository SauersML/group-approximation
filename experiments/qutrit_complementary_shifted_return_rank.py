"""Exact rank calculation for the complementary g2-shifted Leavitt return.

The first mixed qutrit return uses the branch-0 coefficient

    s_0 t_0 = p = 1-q.

The natural second placement uses the complementary branch

    s_1 t_1 = q.

This script computes the finite active envelope generated by the qutrit sign
packet and the returned root x_(c0,c2)(q), then computes exactly over
Q(omega), omega^2+omega+1=0, the ranks of

    G_(sigma,tau) P_q G_(sigma,tau) e_k

on the regular module.  The two central h characters selected by the qutrit
source are added only at the final normalization.

No floating point arithmetic, random sampling, or finite-field reduction is
used.  The coefficient algebra is the exact eight-element Jacobson algebra
D = F_2{1,q,a}, with q^2=q, qa=a, aq=a^2=0, a=q t_0.

Run from the repository root:

    python3 experiments/qutrit_complementary_shifted_return_rank.py
"""

from __future__ import annotations

from collections import deque
from fractions import Fraction

N = 6


def dmul(x: int, y: int) -> int:
    """Multiply bit triples for 1,q,a in D."""
    c0, cq, ca = x & 1, (x >> 1) & 1, (x >> 2) & 1
    d0, dq, da = y & 1, (y >> 1) & 1, (y >> 2) & 1
    r0 = c0 & d0
    rq = (c0 & dq) ^ (cq & d0) ^ (cq & dq)
    ra = (c0 & da) ^ (ca & d0) ^ (cq & da)
    return r0 | (rq << 1) | (ra << 2)


def eye():
    return tuple(tuple(1 if i == j else 0 for j in range(N)) for i in range(N))


def mmul(A, B):
    out = [[0] * N for _ in range(N)]
    for i in range(N):
        for k in range(N):
            aik = A[i][k]
            if not aik:
                continue
            for j in range(N):
                bkj = B[k][j]
                if bkj:
                    out[i][j] ^= dmul(aik, bkj)
    return tuple(tuple(row) for row in out)


def add_entry(A, i: int, j: int, value: int):
    out = [list(row) for row in A]
    out[i][j] ^= value
    return tuple(tuple(row) for row in out)


I = eye()

# Active basis (c0,c3,c1,c1',c2,c2').  The C3 actor is diag(1,1,r,r),
# r=[[0,1],[1,1]].
k = [list(row) for row in I]
for i, j in ((2, 3), (4, 5)):
    k[i][i] = 0
    k[i][j] = 1
    k[j][i] = 1
    k[j][j] = 1
k = tuple(tuple(row) for row in k)
k2 = mmul(k, k)
assert mmul(k2, k) == I

# D bit encodings: 1=1, 2=q, 3=p=1+q, 4=a=q t0.
H = add_entry(add_entry(I, 4, 2, 2), 5, 3, 2)
A = add_entry(I, 4, 0, 4)
W = add_entry(I, 4, 1, 2)
Pq = add_entry(I, 0, 4, 2)  # x_(c0,c2)(q), the branch-1 shifted return.

for generator in (H, A, W, Pq):
    assert mmul(generator, generator) == I


def enumerate_group(generators):
    seen = {I: 0}
    elements = [I]
    queue = deque([I])
    while queue:
        x = queue.popleft()
        for generator in generators:
            y = mmul(x, generator)
            if y not in seen:
                seen[y] = len(elements)
                elements.append(y)
                queue.append(y)
    return elements, seen


GROUP, INDEX = enumerate_group((k, k2, H, A, W, Pq))
assert len(GROUP) == 6144

# Cyclotomic integers a+b*omega, omega^2=-omega-1.
def cadd(x, y):
    return x[0] + y[0], x[1] + y[1]


def cmul(x, y):
    a0, a1 = x
    b0, b1 = y
    return a0 * b0 - a1 * b1, a0 * b1 + a1 * b0 - a1 * b1


def add_term(table, group_element, coefficient):
    value = cadd(table.get(group_element, (0, 0)), coefficient)
    if value == (0, 0):
        table.pop(group_element, None)
    else:
        table[group_element] = value


def gamul(left, right):
    out = {}
    for x, cx in left.items():
        for y, cy in right.items():
            add_term(out, mmul(x, y), cmul(cx, cy))
    return out


def singleton(x):
    return {x: (1, 0)}


# B=<H,A,W> is the commuting sign subgroup C2^3.
B = []
B_EXPONENTS = []
for eh in (0, 1):
    for ea in (0, 1):
        for ew in (0, 1):
            x = I
            if eh:
                x = mmul(x, H)
            if ea:
                x = mmul(x, A)
            if ew:
                x = mmul(x, W)
            B.append(x)
            B_EXPONENTS.append((eh, ea, ew))
assert len(set(B)) == 8


def eB(sigma: int, tau: int):
    out = {}
    for b, (eh, ea, ew) in zip(B, B_EXPONENTS):
        sign = (-1 if eh else 1) * (sigma if ea else 1) * (tau if ew else 1)
        add_term(out, b, (sign, 0))
    return out


# The selected nontrivial k-character projection is proportional to
# 1+omega^2 k+omega k^2.
eK = {I: (1, 0), k: (-1, -1), k2: (0, 1)}


def right_cosets(subgroup):
    unseen = set(range(len(GROUP)))
    reps = []
    coset_of = {}
    subpos = {}
    while unseen:
        rep_index = next(iter(unseen))
        rep = GROUP[rep_index]
        members = []
        for position, element in enumerate(subgroup):
            idx = INDEX[mmul(element, rep)]
            members.append(idx)
            coset_of[idx] = len(reps)
            subpos[idx] = position
        for idx in members:
            unseen.discard(idx)
        reps.append(rep_index)
    return reps, coset_of, subpos


B_REPS, B_COSET, B_POS = right_cosets(B)
K_SUBGROUP = (I, k, k2)
K_REPS, _, _ = right_cosets(K_SUBGROUP)
assert len(B_REPS) == 768
assert len(K_REPS) == 2048


def reduced_columns(sigma: int, tau: int):
    # Denominators 8,8,3 are irrelevant for rank.
    operator = gamul(gamul(gamul(eB(sigma, tau), singleton(Pq)), eB(sigma, tau)), eK)
    assert len(operator) == 192
    columns = []
    for rep_index in K_REPS:
        rep = GROUP[rep_index]
        column = {}
        for left, coefficient in operator.items():
            idx = INDEX[mmul(left, rep)]
            # An eB-range vector is determined by the coefficient at the
            # chosen representative of each B-right-coset.
            if B_POS[idx] == 0:
                row = B_COSET[idx]
                column[row] = cadd(column.get(row, (0, 0)), coefficient)
        columns.append({r: c for r, c in column.items() if c != (0, 0)})
    return columns


ZERO = (Fraction(0), Fraction(0))


def qmul(x, y):
    a0, a1 = x
    b0, b1 = y
    return a0 * b0 - a1 * b1, a0 * b1 + a1 * b0 - a1 * b1


def qsub(x, y):
    return x[0] - y[0], x[1] - y[1]


def qinv(x):
    a, b = x
    norm = a * a - a * b + b * b
    assert norm != 0
    return (a - b) / norm, -b / norm


def exact_rank(columns):
    pivots = {}
    for raw in columns:
        vector = {row: (Fraction(a), Fraction(b)) for row, (a, b) in raw.items()}
        while vector:
            row = min(vector)
            if row not in pivots:
                inverse = qinv(vector[row])
                vector = {r: qmul(value, inverse) for r, value in vector.items()}
                vector = {r: value for r, value in vector.items() if value != ZERO}
                pivots[row] = vector
                break
            factor = vector[row]
            pivot = pivots[row]
            for r, value in pivot.items():
                new_value = qsub(vector.get(r, ZERO), qmul(factor, value))
                if new_value == ZERO:
                    vector.pop(r, None)
                else:
                    vector[r] = new_value
    return len(pivots)


RANKS = {}
for sigma, tau in ((1, 1), (-1, 1), (1, -1), (-1, -1)):
    RANKS[(sigma, tau)] = exact_rank(reduced_columns(sigma, tau))

assert RANKS == {(1, 1): 88, (-1, 1): 84, (1, -1): 84, (-1, -1): 84}

# Two selected central h-characters and |<h>|=3 give normalized qutrit ranks
# 2*rank/(3*6144).
assert 2 * 88 * 1152 == 11 * 3 * 6144
assert 2 * 84 * 768 == 7 * 3 * 6144

# Existing branch-0 rank is 43/1152.  Even a direct sum of both branch
# source spaces has rank at most (43+11)/1152 = 3/64 < 1/18, the target.
assert 43 + 11 == 54
assert 54 * 64 == 3 * 1152
assert 3 * 18 < 64

print("active envelope order:", len(GROUP))
print("exact cyclotomic ranks:", RANKS)
print("(+,+) normalized qutrit rank: 11/1152")
print("other normalized qutrit ranks: 7/768")
print("branch-0 + branch-1 source bound: 3/64 < 1/18")
