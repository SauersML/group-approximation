"""Exact collision-universe partner search for fixed lifts in F2[Q].

Q = L_(F_2)(1,2)^x, generated by the twelve adjacent-transvection atlas
generators of kaplansky_asymmetric_atlas_search.

Collision lemma.  Let A be fixed and B*A = 1.  Join b ~ b' in supp(B) when
the sets bA and b'A share a group element.  Products coming from different
components of this graph have disjoint supports, so exactly one component
B_0 satisfies B_0*A = 1 (the others give 0), and B_0 contains a^(-1) for some
a in supp(A).  Walking B_0 from that root gives

    supp(B_0)  in  A^(-1) (A A^(-1))^r,     r < |supp(B_0)|.

So left partners of A are exhausted by collision depth r.  Dually, right
partners of a fixed B (B*A = 1, A unknown) lie in (B^(-1) B)^r B^(-1).
For a lift of the non-unit s0 or t0 every hit is automatically strict.

Rows are 128-bit BLAKE2b digests of exact reduced prefix keys.  A digest
collision can only merge two constraint rows, which weakens the system and
never removes a solution, so a reported miss is exact.  A reported hit is
re-verified in the exact prefix normal form before it is printed.
"""

import argparse
import hashlib
import json
import time

from depth_one_paired_leavitt_return_search import ONE, canonical, multiply
from kaplansky_asymmetric_atlas_search import (
    S0,
    atlas_generators,
    evaluate_sum,
    from_key,
    group_algebra_product,
    key,
    multiply_keys,
)
from depth_one_paired_leavitt_return_search import equal

T0 = canonical((("", "0"),))

# leavitt-cross-atlas-eleven-term-s0-lift, (ELA1)
ELA1 = ((0, 1, 2), (3, 5, 4), (6, 7, 8), (9, 11, 10), (1, 0), (6, 8),
        (0, 2, 9), (3, 1, 7), (5, 3, 1), (5, 3, 4), (5, 11, 10))
# eleven-term-s0-lift-has-no-radius-four-left-inverse, item 2
FIVE_T0 = ((6, 2), (0, 1, 2), (0, 2, 4), (2, 4, 7), (6, 7, 6))


def digest(value_key):
    return hashlib.blake2b(repr(value_key).encode(), digest_size=16).digest()


def setup():
    gens = tuple(key(g) for _, g in atlas_generators())
    one = key(ONE)
    for g in gens:
        assert multiply_keys(g, g) == one, "atlas generator is not an involution"
    return gens, one


def word_key(word, gens, one):
    value = one
    for index in word:
        value = multiply_keys(value, gens[index])
    return value


def fixed_support(words, gens, one):
    keys = [word_key(w, gens, one) for w in words]
    assert len(set(keys)) == len(keys), "repeated group element in fixed support"
    inverses = [word_key(tuple(reversed(w)), gens, one) for w in words]
    for k, ki in zip(keys, inverses):
        assert multiply_keys(k, ki) == one
    return keys, inverses


def universe(roots, steps, depth, side):
    """BFS: left side grows u -> u*s, right side grows u -> s*u."""
    words = dict(roots)
    layer = list(roots)
    sizes = [len(words)]
    for _ in range(depth):
        successor = []
        for u_key, u_word in layer:
            for s_key, s_word in steps:
                if side == "left":
                    v_key, v_word = multiply_keys(u_key, s_key), u_word + s_word
                else:
                    v_key, v_word = multiply_keys(s_key, u_key), s_word + u_word
                if v_key not in words:
                    words[v_key] = v_word
                    successor.append((v_key, v_word))
        layer = successor
        sizes.append(len(words))
    return words, sizes


def columns(universe_keys, fixed_keys, side):
    """Support digests of u*A (left) or B*u (right); parity per column."""
    out = []
    for u_key in universe_keys:
        support = set()
        for f_key in fixed_keys:
            left, right = (u_key, f_key) if side == "left" else (f_key, u_key)
            d = digest(key(multiply(frozenset(left), frozenset(right))))
            support ^= {d}
        out.append(support)
    return out


def peel(cols, target):
    """Drop columns forced to zero by rows (other than target) met once."""
    alive = [True] * len(cols)
    count = {}
    where = {}
    for c, support in enumerate(cols):
        for d in support:
            count[d] = count.get(d, 0) + 1
            where.setdefault(d, []).append(c)
    queue = [d for d, n in count.items() if n == 1 and d != target]
    while queue:
        d = queue.pop()
        if count.get(d) != 1:
            continue
        c = next(c for c in where[d] if alive[c])
        alive[c] = False
        for e in cols[c]:
            count[e] -= 1
            if count[e] == 1 and e != target:
                queue.append(e)
    return [c for c in range(len(cols)) if alive[c]]


def solve(cols, live, target):
    rows = {target: 0}
    for c in live:
        for d in cols[c]:
            rows.setdefault(d, len(rows))
    basis = {}
    for position, c in enumerate(live):
        value = 0
        for d in cols[c]:
            value ^= 1 << rows[d]
        combination = 1 << position
        while value:
            pivot = value.bit_length() - 1
            if pivot not in basis:
                basis[pivot] = (value, combination)
                break
            value ^= basis[pivot][0]
            combination ^= basis[pivot][1]
    value, combination = 1 << rows[target], 0
    while value:
        pivot = value.bit_length() - 1
        if pivot not in basis:
            return None, len(rows), len(basis)
        value ^= basis[pivot][0]
        combination ^= basis[pivot][1]
    chosen = [live[i] for i in range(len(live)) if (combination >> i) & 1]
    return chosen, len(rows), len(basis)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--fixed", choices=("ela1-left", "five-t0-right", "control-order7"),
                        required=True)
    parser.add_argument("--depth", type=int, default=1)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    start = time.time()
    gens, one = setup()
    if args.fixed == "control-order7":
        # Positive control: 1 + x + x^2 with x of order 7 is a unit of F2[<x>],
        # since x^2+x+1 is coprime to x^7-1 over F2.  Its left inverse must be
        # found once the collision universe covers <x>.
        from itertools import product as words_of
        from atlas_two_chart_search import I4, gf2_mul, transvection
        chart = [transvection(r, c) for r, c in ((0, 1), (1, 0), (1, 2), (2, 1), (2, 3), (3, 2))]

        def matrix_order(word):
            m = I4.copy()
            for i in word:
                m = gf2_mul(m, chart[i])
            p, n = m.copy(), 1
            while not (p == I4).all():
                p, n = gf2_mul(p, m), n + 1
            return n
        x_word = next(w for length in range(2, 7) for w in words_of(range(6), repeat=length)
                      if matrix_order(w) == 7)
        assert word_key(x_word * 7, gens, one) == one and word_key(x_word, gens, one) != one
        words, side, target_eval = ((), x_word, x_word * 2), "left", None
    elif args.fixed == "ela1-left":
        words, side, target_eval = ELA1, "left", S0
    else:
        words, side, target_eval = FIVE_T0, "right", T0
    fixed_keys, fixed_inverses = fixed_support(words, gens, one)
    if target_eval is not None:
        assert equal(evaluate_sum([from_key(k) for k in fixed_keys]), target_eval)
    roots = [(ki, tuple(reversed(w))) for ki, w in zip(fixed_inverses, words)]
    if side == "left":   # steps a a'^(-1)
        steps = {multiply_keys(a, ai): wa + tuple(reversed(wi))
                 for a, wa in zip(fixed_keys, words) for ai, wi in zip(fixed_inverses, words)}
    else:                # steps b^(-1) b'
        steps = {multiply_keys(bi, b): tuple(reversed(wi)) + wb
                 for bi, wi in zip(fixed_inverses, words) for b, wb in zip(fixed_keys, words)}
    universe_words, sizes = universe(roots, list(steps.items()), args.depth, side)
    universe_keys = list(universe_words)
    t_universe = time.time() - start
    cols = columns(universe_keys, fixed_keys, side)
    target = digest(one)
    live = peel(cols, target)
    chosen, n_rows, rank = solve(cols, live, target)
    record = {"fixed": args.fixed, "depth": args.depth, "fixed_support": len(words),
              "step_set": len(steps), "universe_sizes": sizes, "columns": len(cols),
              "live_after_peel": len(live), "rows_live": n_rows, "rank_live": rank,
              "seconds_universe": round(t_universe, 1), "seconds_total": None,
              "status": "NO_PARTNER_IN_UNIVERSE"}
    if chosen is not None:
        partner = [from_key(universe_keys[c]) for c in chosen]
        fixed = [from_key(k) for k in fixed_keys]
        forward = group_algebra_product(partner, fixed) if side == "left" else group_algebra_product(fixed, partner)
        reverse = group_algebra_product(fixed, partner) if side == "left" else group_algebra_product(partner, fixed)
        forward_ok, strict = forward == {one}, reverse != {one}
        # The control is a two-sided unit, so strictness is expected only for
        # lifts of s0 or t0, where it is automatic once forward_ok holds.
        record.update({"status": "PARTNER_FOUND_VERIFIED" if forward_ok else "DIGEST_FALSE_POSITIVE",
                       "strict": strict, "partner_support": len(chosen),
                       "partner_words": [universe_words[universe_keys[c]] for c in chosen]})
    record["seconds_total"] = round(time.time() - start, 1)
    with open(args.out, "w") as handle:
        json.dump(record, handle, indent=1)
    print(json.dumps({k: v for k, v in record.items() if k != "partner_words"}))


if __name__ == "__main__":
    main()
