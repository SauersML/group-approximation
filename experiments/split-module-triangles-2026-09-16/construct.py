def perm_matrix(p):
    n = len(p)
    M = np.zeros((n, n))
    for i in range(n):
        M[p[i], i] = 1.0
    return M


def vertex_module(gx, gy):
    elems = perm_elements([gx, gy])
    N = len(elems)
    classes, cls_of, idx, X, ident = character_table(elems)
    # regular representation on C[G]: basis e_g, x.e_g = e_{g then x}?  use right-regular via action on elements
    def regmat(s):
        M = np.zeros((N, N))
        for i, g in enumerate(elems):
            M[idx[mul(s, g)], i] = 1.0   # e_g -> e_{s then g}: M(s)M(t) = M(s then t)
        return M
    Rx, Ry = regmat(gx), regmat(gy)
    # a representation of the group generated by Rx, Ry; characters computed on this concrete action
    mats = {}
    for i, g in enumerate(elems):
        mats[i] = None
    # character of each class in this action: use elements to build R(g) as products along words
    words = {tuple(range(len(gx))): ()}
    Rg = {tuple(range(len(gx))): np.eye(N)}
    frontier = [tuple(range(len(gx)))]
    while frontier:
        new = []
        for g in frontier:
            for s, Rs in ((gx, Rx), (gy, Ry)):
                h = mul(g, s)
                if h not in Rg:
                    Rg[h] = Rg[g] @ Rs
                    new.append(h)
        frontier = new
    cx = [cls_of[idx[power(gx, j)]] for j in range(3)]
    cy = [cls_of[idx[power(gy, j)]] for j in range(3)]
    blocks = []
    info = []
    for t in range(X.shape[0]):
        psi = X[t]
        d = int(round(psi[ident].real))
        if np.allclose(psi, 1):
            continue
        fx = sum(psi[c] for c in cx).real / 3
        fy = sum(psi[c] for c in cy).real / 3
        if int(round(fx + fy - d)) != 0:
            continue
        # isotypic projector: e = d/N sum conj(psi(g)) R(g); check which of psi, conj(psi) it picks
        E = sum(np.conj(psi[cls_of[idx[g]]]) * Rg[g] for g in elems) * d / N
        U, sv, _ = np.linalg.svd(E)
        r = int(np.sum(sv > 0.5))
        Q = U[:, :r]
        Wx, Wy = Q.conj().T @ Rx @ Q, Q.conj().T @ Ry @ Q
        info.append((d, int(round(fx)), int(round(fy)), r))
        blocks.append((d, int(round(fx)), int(round(fy)), Wx, Wy))
    return blocks, N


def dsum(ms):
    n = sum(m.shape[0] for m in ms)
    M = np.zeros((n, n), dtype=complex)
    o = 0
    for m in ms:
        k = m.shape[0]
        M[o:o + k, o:o + k] = m
        o += k
    return M


def balanced(blocks):
    nonlin = [b for b in blocks if b[0] > 1]
    lin10 = [b for b in blocks if b[0] == 1 and b[1] == 1]  # adds to dim[y,W]
    lin01 = [b for b in blocks if b[0] == 1 and b[2] == 1]  # adds to dim[x,W]
    chosen = list(blocks)
    def dims(bl):
        dx = sum(b[3].shape[0] - np.linalg.matrix_rank((np.eye(b[3].shape[0]) + b[3] + b[3] @ b[3]) / 3, tol=1e-6) for b in bl)
        dy = sum(b[4].shape[0] - np.linalg.matrix_rank((np.eye(b[4].shape[0]) + b[4] + b[4] @ b[4]) / 3, tol=1e-6) for b in bl)
        return dx, dy
    dx, dy = dims(chosen)
    for _ in range(200):
        if dx == dy:
            break
        if dx > dy and lin10:
            chosen += lin10
        elif dy > dx and lin01:
            chosen += lin01
        else:
            raise RuntimeError("cannot balance")
        dx, dy = dims(chosen)
    Wx = dsum([b[3] for b in chosen])
    Wy = dsum([b[4] for b in chosen])
    return Wx, Wy, dx


def eig_basis(M, P):
    """basis of [x,W] = ker P ordered: w-eigenvectors then w^2-eigenvectors."""
    n = M.shape[0]
    cols = []
    for lam in (w, w * w):
        U, sv, Vh = np.linalg.svd(M - lam * np.eye(n))
        k = int(np.sum(sv < 1e-8))
        cols.append(Vh.conj().T[:, n - k:])
    return np.hstack(cols), [c.shape[1] for c in cols]


class Mat:
    def __init__(self, m):
        self.m = m
    def __mul__(self, o):
        return Mat(self.m @ o.m)
    def __pow__(self, k):
        base = self.m if k >= 0 else np.linalg.inv(self.m)
        r = np.eye(self.m.shape[0], dtype=complex)
        for _ in range(abs(k)):
            r = r @ base
        return Mat(r)


def enumerate_group(gens, cap=2000):
    key = lambda M: np.round(M * 1e6).astype(np.int64).tobytes() + np.round(M.imag * 1e6).astype(np.int64).tobytes()
    I = np.eye(gens[0].shape[0], dtype=complex)
    seen = {key(I): I}
    frontier = [I]
    while frontier and len(seen) <= cap:
        new = []
        for M in frontier:
            for g in gens:
                P = M @ g
                k = key(P.real + 0.0) if False else key(P)
                if k not in seen:
                    seen[k] = P
                    new.append(P)
        frontier = new
    return len(seen)


def build(name, rels, twist=False):
    """twist=True is the negative control: at vertex <c,a> the edge isomorphism for a is composed with the swap of
    the w- and w^2-eigenspaces, so alpha_{a,v} intertwines rho_a with its complex conjugate; relators must then fail."""
    pairs = [("a", "b"), ("b", "c"), ("c", "a")]
    mods, orders = {}, {}
    for pair in pairs:
        ws = vertex_words(rels, pair)
        gx, gy = vertex_group(ws, pair)
        blocks, N = vertex_module(gx, gy)
        mods[pair] = balanced(blocks)
        orders[pair] = N
    D = int(np.lcm.reduce([mods[p][2] for p in pairs]))
    assert D % 2 == 0 or True
    offs = {"a": 0, "b": D, "c": 2 * D}
    pi = {x: np.zeros((D, 3 * D), dtype=complex) for x in "abc"}
    filled = {x: [] for x in "abc"}
    for pair in pairs:
        Wx, Wy, Dv = mods[pair]
        k = D // Dv
        Wx, Wy = dsum([Wx] * k), dsum([Wy] * k)
        n = Wx.shape[0]
        I = np.eye(n)
        Px, Py = (I + Wx + Wx @ Wx) / 3, (I + Wy + Wy @ Wy) / 3
        assert np.linalg.matrix_rank(Px, tol=1e-6) + np.linalg.matrix_rank(Py, tol=1e-6) == n, "not split"
        Bx, sx = eig_basis(Wx, Px)
        By, sy = eig_basis(Wy, Py)
        if twist and pair == ("c", "a"):
            By = np.hstack([By[:, D // 2:], By[:, :D // 2]])
        assert sx == [D // 2, D // 2] and sy == [D // 2, D // 2], (sx, sy)
        Mv = np.hstack([Bx, By])
        Minv = np.linalg.inv(Mv)
        px = (Minv @ (I - Px))[:D, :] @ Mv
        py = (Minv @ (I - Py))[D:, :] @ Mv
        x, y = pair
        pi[x][:, offs[x]:offs[x] + D] = px[:, :D]
        pi[x][:, offs[y]:offs[y] + D] = px[:, D:]
        pi[y][:, offs[x]:offs[x] + D] = py[:, :D]
        pi[y][:, offs[y]:offs[y] + D] = py[:, D:]
        filled[x].append(np.abs(px[:, :D] - np.eye(D)).max())
        filled[y].append(np.abs(py[:, D:] - np.eye(D)).max())
    rho = np.diag([w] * (D // 2) + [w * w] * (D // 2))
    G = {}
    for x in "abc":
        J = np.zeros((3 * D, D))
        J[offs[x]:offs[x] + D, :] = np.eye(D)
        G[x] = np.eye(3 * D) + J @ (rho - np.eye(D)) @ pi[x]
    env = {x: Mat(G[x]) for x in "abc"}
    err = max(np.abs(eval(r.replace("^", "**"), {}, env).m - np.eye(3 * D)).max() for r in rels)
    vorders = {p: enumerate_group([G[p[0]], G[p[1]]]) for p in pairs}
    ok = err < TOL and all(vorders[p] == orders[p] for p in pairs) and max(max(v) for v in filled.values()) < 1e-8
    print(name + (" [twisted]" if twist else ""), "dim V =", 3 * D, "| max relator error %.2e" % err, "| vertex orders", [vorders[p] for p in pairs],
          "expected", [orders[p] for p in pairs], "| pi_x|U_x = id err %.1e" % max(max(v) for v in filled.values()),
          "| OK" if ok else "| FAIL")
    return ok


