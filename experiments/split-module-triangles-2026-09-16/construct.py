"""Numerical check of the split-module construction (Theorem A of
research/artifacts/split-module-triangles-of-finite-groups-2026-09-16.md) on the CCKW trivalent
triangle groups all of whose vertex groups have a faithful split module (found by vertex_split.py).

For each such group G = <a,b,c | a^3, b^3, c^3, R_ab, R_bc, R_ca>:
 1. at each vertex v = <x,y>, W_v = (sum of the isotypic components of the regular representation for
    all delta = 0 irreducibles) + (linear delta = 0 characters, whole Galois-closed families, to balance
    dim [x,W_v] = dim [y,W_v]), then k_v copies so that every edge module has the same dimension D;
    every W_v is closed under complex conjugation, so on every [x, W_v] the eigenvalues w and w^2 each
    have multiplicity D/2, and the edge modules match;
 2. V = U_a + U_b + U_c, each U_x = C^D with x acting as diag(w,...,w, w^2,...,w^2);
 3. the global matrix of x is  I + J_x (rho_x(x) - I) pi_x,  with pi_x assembled from the two vertices
    containing x as in the artifact (pi_x o iota_v = alpha_{x,v} o p^v_x);
 4. check every relator of the presentation (max-entry error < 1e-7) and that <A,B>, <B,C>, <C,A>
    have the vertex orders (group enumeration with entries rounded to 1e-6).
Floating point: this is a consistency check of the construction, not a certificate.
Run single-threaded: OPENBLAS_NUM_THREADS=1 (set below; multi-threaded BLAS made each 81x81 SVD take ~10 s here).
Command: timeout 600 python3 construct.py > construct.out 2>&1
"""
