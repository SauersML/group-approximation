#!/usr/bin/env python3
"""Class-three tensor models of Gamma_1 = Gamma_trap + EXTRA_RELS + (C1),(C2) at
right-orbit depth <= k.

Model.  V = M_2(A_1) + ... (A_i = F_2[x]/(p_i), S -> a, T -> a^{-1}), G0 = the
Levi matrices acting on V.  T = F_2 + V + V^2 + V^3 is the truncated tensor
algebra (V^j = j-th tensor power, V^4 = 0); G0 acts diagonally by algebra
automorphisms.  G = (1 + T_+) x| G0, element (a1, a2, a3, A) = (1 + a) A.
  u = (1 + v0 + c2 + c3, I), v0 = sum of E_11, c2, c3 random.
Every relator l = r must agree on (a1, A); its difference D = x y^{-1} lies in
1 + T_{>=2}, which is abelian and identified additively with T_2 + T_3.
Normal closure of the differences in G:
  K = G0-span(D) + Phi,  Phi = span{ e k2 + k2 e : e in V', k2 in pi_2(K) },
where V' = G0-module generated by v0 (the degree-1 parts of elements of G)
and pi_2(K) = G0-span of the T_2 parts of D (Phi is already G0-invariant).
Conjugation by (1+x)A sends 1+k to 1 + A.k + x1 (A.k)_2 + (A.k)_2 x1.
The head h = u.ust survives in G/K iff h - 1 is not in K.
Reported: h2 = survival in the class-two image (T_2 only, K2 = pi_2(K)),
          h3 = survival in the class-three model.
Usage:
  c3scan.py one P A DEPTH SEEDS [P2 A2 ...]   module(s) given as ints
  c3scan.py sweep DEGMAX DEPTH SEEDS          all p with p(0)=1, deg<=DEGMAX, a=x
"""
import random
import sys

import numpy as np

from words import DERIVED, TRAP_RELS, INVOL_RELS, EXTRA_RELS, LEFT, RIGHT


# ---------------------------------------------------------------- ring modules
def pmod(a, p):
    dp = p.bit_length() - 1
    while a and a.bit_length() - 1 >= dp:
        a ^= p << (a.bit_length() - 1 - dp)
    return a


def pmul(a, b, p):
    r = 0
    while b:
        if b & 1:
            r ^= a
        b >>= 1
        a <<= 1
    return pmod(r, p)


def inv(a, p):
    k = p.bit_length() - 1
    for b in range(1, 1 << k):
        if pmul(a, b, p) == 1:
            return b
    raise ValueError("not a unit")


def ring_module(p, xs):
    k = p.bit_length() - 1
    n = 4 * k
    xt = inv(xs, p)

    def vec(Y):
        v = np.zeros(n, np.int64)
        for e in range(4):
            for j in range(k):
                v[e * k + j] = Y[e] >> j & 1
        return v

    def mat(f):
        M = np.zeros((n, n), np.int64)
        for e in range(4):
            for j in range(k):
                Y = [0, 0, 0, 0]
                Y[e] = 1 << j
                M[:, e * k + j] = vec(f(Y))
        return M

    def m2(a, Y):
        a11, a12, a21, a22 = a
        y11, y12, y21, y22 = Y
        return (pmul(a11, y11, p) ^ pmul(a12, y21, p), pmul(a11, y12, p) ^ pmul(a12, y22, p),
                pmul(a21, y11, p) ^ pmul(a22, y21, p), pmul(a21, y12, p) ^ pmul(a22, y22, p))

    L = lambda a: mat(lambda Y: m2(a, Y))
    R = lambda b: mat(lambda Y: m2(Y, b))
    mats = {"as": L((1, xs, 0, 1)), "at": L((1, xt, 0, 1)), "c": L((1, 0, 1, 1)),
            "b1": R((1, 1, 0, 1)), "bs": R((1, 0, xs, 1)), "bt": R((1, 0, xt, 1))}
    return mats, vec((1, 0, 0, 0))


def direct_sum(parts):
    mats = {}
    for g in parts[0][0]:
        bl = [P[0][g] for P in parts]
        n = sum(B.shape[0] for B in bl)
        M = np.zeros((n, n), np.int64)
        o = 0
        for B in bl:
            M[o:o + B.shape[0], o:o + B.shape[0]] = B
            o += B.shape[0]
        mats[g] = M
    return mats, np.concatenate([P[1] for P in parts])


# ------------------------------------------------------- truncated tensor group
def act(A, a):
    a1, a2, a3 = a
    return (A @ a1 % 2, A @ a2 @ A.T % 2,
            np.einsum("ai,bj,ck,ijk->abc", A, A, A, a3, optimize=True) % 2)


def umul(a, b):
    """(1+a)(1+b) = 1 + c in T with T_4 = 0."""
    a1, a2, a3 = a
    b1, b2, b3 = b
    return ((a1 + b1) % 2,
            (a2 + b2 + np.multiply.outer(a1, b1)) % 2,
            (a3 + b3 + np.multiply.outer(a1, b2) + np.multiply.outer(a2, b1)) % 2)


def uinv(a):
    a1, a2, a3 = a
    aa = np.multiply.outer(a1, a1)
    return (a1.copy(), (a2 + aa) % 2,
            (a3 + np.multiply.outer(a1, a2) + np.multiply.outer(a2, a1)
             + np.multiply.outer(aa, a1)) % 2)


def gmul(X, Y):
    (a, A), (b, B) = X, Y
    return (umul(a, act(A, b)), A @ B % 2)


def ident(n):
    return ((np.zeros(n, np.int64), np.zeros((n, n), np.int64),
             np.zeros((n, n, n), np.int64)), np.eye(n, dtype=np.int64))


def word(vals, wd, n):
    acc = ident(n)
    for g in wd:
        acc = gmul(acc, vals[g])
    return acc


def diff(X, Y):
    """X Y^{-1} - 1 as a flat 0/1 vector on T_2 + T_3, or None if X, Y differ
    on (a1, A)."""
    (x, A), (y, B) = X, Y
    if (x[0] != y[0]).any() or (A != B).any():
        return None
    d = umul(x, uinv(y))
    assert not d[0].any()
    return np.concatenate([d[1].reshape(-1), d[2].reshape(-1)]).astype(np.uint8)


def build(mats, v, c2, c3):
    n = v.shape[0]
    zero = (np.zeros(n, np.int64), np.zeros((n, n), np.int64), np.zeros((n, n, n), np.int64))
    vals = {g: (zero, mats[g]) for g in LEFT + RIGHT}
    vals["u"] = ((v.copy(), c2, c3), np.eye(n, dtype=np.int64))
    for name, wd in DERIVED:
        vals[name] = word(vals, wd, n)
    return vals


def rel_diffs(vals, rels, n):
    out = []
    for name, l, r in rels:
        d = diff(word(vals, l, n), word(vals, r, n))
        if d is None:
            return None, name
        out.append(d)
    return out, None


def orbit_rel_diffs(vals, n, depth):
    """(C1) [bzb, czc] = 1 and (C2) [bz'b, az'a] = 1 (z' = d_c z) for right words
    z = d_(b_1)...d_(b_j) u, j <= depth; all true in P_{2,2}(J)."""
    def w(names, X):
        env = dict(vals)
        env["x"] = X
        return word(env, names, n)

    level, out = [vals["u"]], []
    for j in range(depth + 1):
        nxt = []
        for z in level:
            zc = w(["x", "c", "x", "c"], z)
            pairs = [(w([b, "x", b], z), w(["c", "x", "c"], z)) for b in RIGHT]
            pairs += [(w([b, "x", b], zc), w([a, "x", a], zc)) for b in RIGHT for a in ["as", "at"]]
            for X, Y in pairs:
                d = diff(gmul(X, Y), gmul(Y, X))
                assert d is not None
                out.append(d)
            nxt += [w(["x", b, "x", b], z) for b in RIGHT]
        level = nxt
    return out


# ------------------------------------------------------------ GF(2) row spans
class Span:
    """Row span over GF(2); rows packed little-endian into uint64 words.
    Invariant: basis row j is zero at the pivots of rows i < j."""

    def __init__(self, m):
        self.m = m
        self.W = (m + 63) // 64
        self.B = np.zeros((0, self.W), np.uint64)
        self.piv = []

    def pack(self, bits):
        bits = np.atleast_2d(bits).astype(np.uint8)
        pad = np.zeros((bits.shape[0], self.W * 64 - self.m), np.uint8)
        by = np.packbits(np.hstack([bits, pad]), axis=1, bitorder="little")
        return np.ascontiguousarray(by).view(np.uint64).copy()

    def unpack(self, R):
        by = np.ascontiguousarray(R).view(np.uint8)
        return np.unpackbits(by, axis=1, bitorder="little")[:, :self.m]

    def reduce(self, R):
        R = R.copy()
        for j, c in enumerate(self.piv):
            w, b = divmod(c, 64)
            idx = np.nonzero((R[:, w] >> np.uint64(b)) & np.uint64(1))[0]
            if idx.size:
                R[idx] ^= self.B[j]
        return R

    def add(self, R):
        """Add rows (packed); return the packed new basis rows."""
        R = self.reduce(R)
        new = []
        while True:
            nz = np.nonzero(R.any(axis=1))[0]
            if not nz.size:
                break
            r0 = R[nz[0]].copy()
            w = int(np.nonzero(r0)[0][0])
            word_ = int(r0[w])
            b = (word_ & -word_).bit_length() - 1
            c = 64 * w + b
            idx = np.nonzero((R[:, w] >> np.uint64(b)) & np.uint64(1))[0]
            R[idx] ^= r0
            self.B = np.vstack([self.B, r0[None, :]])
            self.piv.append(c)
            new.append(r0)
        return np.array(new, np.uint64).reshape(-1, self.W)

    def contains(self, bits):
        return not self.reduce(self.pack(bits)).any()

    def dim(self):
        return len(self.piv)


def act_rows(A, bits, n, with3=True):
    """G0 element A applied to rows of T_2 (+ T_3) coordinates."""
    r = bits.shape[0]
    X = bits.astype(np.int64)
    x2 = X[:, :n * n].reshape(r, n, n)
    y2 = np.einsum("ai,bj,rij->rab", A, A, x2, optimize=True) % 2
    out = [y2.reshape(r, -1)]
    if with3:
        x3 = X[:, n * n:].reshape(r, n, n, n)
        y3 = np.einsum("ai,bj,ck,rijk->rabc", A, A, A, x3, optimize=True) % 2
        out.append(y3.reshape(r, -1))
    return np.hstack(out).astype(np.uint8)


def g0_closure(mats, rows, n, with3=True):
    m = n * n + (n ** 3 if with3 else 0)
    S = Span(m)
    front = S.add(S.pack(rows))
    while front.shape[0]:
        bits = S.unpack(front)
        imgs = np.vstack([act_rows(A, bits, n, with3) for A in mats.values()])
        front = S.add(S.pack(imgs))
    return S


def module_basis(mats, v):
    """Basis of the G0-module V' generated by v (vectors of length n)."""
    n = v.shape[0]
    S = Span(n)
    front = S.add(S.pack(v[None, :]))
    while front.shape[0]:
        bits = S.unpack(front).astype(np.int64)
        imgs = np.vstack([(bits @ A.T) % 2 for A in mats.values()]).astype(np.uint8)
        front = S.add(S.pack(imgs))
    return S.unpack(S.B).astype(np.int64)


# ------------------------------------------------------------------- the test
def test(mats, v, depth, seed, extra=True):
    n = v.shape[0]
    rng = np.random.default_rng(seed)
    c2 = rng.integers(0, 2, (n, n)).astype(np.int64)
    c3 = rng.integers(0, 2, (n, n, n)).astype(np.int64)
    vals = build(mats, v, c2, c3)
    rels = TRAP_RELS + INVOL_RELS + (EXTRA_RELS if extra else [])
    D, bad = rel_diffs(vals, rels, n)
    if D is None:
        return {"fail": bad}
    if depth >= 0:
        D += orbit_rel_diffs(vals, n, depth)
    D = np.array(D, np.uint8)
    (h1, h2, h3), H = vals["h"]
    assert not h1.any() and (H == np.eye(n, dtype=np.int64)).all()
    hv = np.concatenate([h2.reshape(-1), h3.reshape(-1)]).astype(np.uint8)
    K2 = g0_closure(mats, D[:, :n * n], n, with3=False)
    surv2 = not K2.contains(hv[:n * n])
    Vp = module_basis(mats, v)
    k2 = K2.unpack(K2.B).astype(np.int64).reshape(-1, n, n)
    phi3 = (np.einsum("ei,kjl->ekijl", Vp, k2) + np.einsum("el,kij->ekijl", Vp, k2)) % 2
    phi3 = phi3.reshape(-1, n ** 3).astype(np.uint8)
    phi = np.hstack([np.zeros((phi3.shape[0], n * n), np.uint8), phi3])
    K = g0_closure(mats, np.vstack([D, phi]), n, with3=True)
    surv3 = not K.contains(hv)
    return {"h2": surv2, "h3": surv3, "dimK2": K2.dim(), "dimK": K.dim(),
            "dimV'": Vp.shape[0], "m": n * n + n ** 3}


def selftest(mats, v, seed=0):
    n = v.shape[0]
    rng = np.random.default_rng(seed)
    As = list(mats.values())

    def rnd():
        a = (rng.integers(0, 2, n), rng.integers(0, 2, (n, n)), rng.integers(0, 2, (n, n, n)))
        A = np.eye(n, dtype=np.int64)
        for _ in range(3):
            A = A @ As[rng.integers(len(As))] % 2
        return (tuple(x.astype(np.int64) for x in a), A)

    def eq(X, Y):
        return all((p == q).all() for p, q in zip(X[0], Y[0])) and (X[1] == Y[1]).all()

    X, Y, Z = rnd(), rnd(), rnd()
    assert eq(gmul(gmul(X, Y), Z), gmul(X, gmul(Y, Z))), "assoc"
    one = ident(n)
    assert eq((umul(X[0], uinv(X[0])), one[1]), one), "inverse"
    y = Y[0]
    k = (np.zeros(n, np.int64), X[0][1], X[0][2])
    lhs = umul(umul(y, k), uinv(y))
    rhs3 = (k[2] + np.multiply.outer(y[0], k[1]) + np.multiply.outer(k[1], y[0])) % 2
    assert not lhs[0].any() and (lhs[1] == k[1]).all() and (lhs[2] == rhs3).all(), "conj"
    return True


def parse_modules(args):
    parts = [ring_module(int(args[i], 0), int(args[i + 1], 0)) for i in range(0, len(args), 2)]
    return parts[0] if len(parts) == 1 else direct_sum(parts)


def polys(degmax):
    return [p for d in range(1, degmax + 1) for p in range(1 << d, 1 << (d + 1)) if p & 1]


def main():
    mode = sys.argv[1]
    if mode == "one":
        depth, seeds = int(sys.argv[2]), int(sys.argv[3])
        mats, v = parse_modules(sys.argv[4:])
        selftest(mats, v)
        for s in range(seeds):
            print("seed", s, test(mats, v, depth, s), flush=True)
    elif mode == "sweep":
        degmax, depth, seeds = map(int, sys.argv[2:5])
        for p in polys(degmax):
            if p == 0b11:
                continue
            mats, v = ring_module(p, 0b10)
            res = [test(mats, v, depth, s) for s in range(seeds)]
            print("p=%s depth %d:" % (bin(p), depth),
                  [(r.get("h2"), r.get("h3"), r.get("dimK")) if "fail" not in r else r
                   for r in res], flush=True)


if __name__ == "__main__":
    main()
