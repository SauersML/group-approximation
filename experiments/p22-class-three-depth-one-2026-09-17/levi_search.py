#!/usr/bin/env python3
"""Class-two models of Gamma_1 over NON-ring Levi modules.

In a finite quotient of Gamma_1 the Levi generators generate a quotient
G0 = Lbar x Rbar of H = <as,at,c | as,at commute> x <b1,bs,bt | bs,bt commute>
(all involutions), and the degree-one layer W = <<u>>/[<<u>>,<<u>>] is a cyclic
F_2[G0]-module generated by v = image of u.  For given finite groups Lbar, Rbar
(permutation groups with chosen generators) the largest such W is

    W_max = F_2[G0] / F_2[G0]{rho_1..rho_9},

with rho_i the degree-one relator elements (they say: as, at, bs, bt fix v;
R1-R3 at degree one; and the two EXTRA relations (1+at)(1+as)(1+c) v = 0,
(1+at)(1+as)(1+c)(1+at)(1+c) v = 0).  Every W with Levi image G0 is a
quotient of W_max.  c2scan.test then checks all relators of Gamma_trap +
EXTRA_RELS at degree one (as a check of rho_1..rho_9) and decides head
survival in the class-two tensor model over W_max, with (C) at depth <= D.
Usage: levi_search.py M TRIALS DEPTH SEEDS MAXORD   (random generators in S_M)
"""
