"""Exact scalar-involution gluing codes for finite SL(3,Z) charts.

Run this file with SageMath.  Scalar multiplication by -1 pairs the chart
cells.  For an integral cycle k, the parity of the sum on each pair defines
the binary gluing code between the plus and minus cycle lattices.  The code
has dimension log_2 [K:K_+ direct-sum K_-].

The script computes the code exactly, finds the ranks generated by all
words of weight at most four, and extracts a sparse basis from the natural
mod-2 cycle basis.  At p=3 it also certifies the two integral sector Gram
determinants and their gluing index.
"""

import argparse
import json
import math
import statistics

from sage.all import GF, ZZ, matrix

from sl3_degree_one_spectrum import coboundaries, nonzero_vectors


def add_binary_basis(value, basis):
    while value:
        pivot = value.bit_length() - 1
        if pivot in basis:
            value ^= basis[pivot]
        else:
            basis[pivot] = value
            return True
    return False


def involution_pairs(prime, vertices):
    points = nonzero_vectors(prime)
    point_index = {tuple(map(int, point)): index
                   for index, point in enumerate(points)}
    negative = [point_index[tuple(map(int, (-point) % prime))]
                for point in points]
    representatives = [index for index in range(vertices)
                       if index < negative[index]]
    if 2 * len(representatives) != vertices:
        raise AssertionError("scalar involution has a fixed chart point")
    return representatives, negative


def gluing_code(prime):
    names, vertices, _d0, d1 = coboundaries(prime)
    representatives, negative = involution_pairs(prime, vertices)
    field = GF(2)
    relator = matrix(field, d1.toarray().astype(int).tolist(), sparse=True)
    cycles = relator.transpose().right_kernel_matrix()
    pairs = [
        (relation * vertices + point,
         relation * vertices + negative[point])
        for relation in range(len(names))
        for point in representatives
    ]
    parity = matrix(field, len(pairs), d1.shape[0], sparse=True)
    for row, (first, second) in enumerate(pairs):
        parity[row, first] = 1
        parity[row, second] = 1
    natural = cycles * parity.transpose()
    generator = natural.row_space().basis_matrix()
    check = generator.right_kernel_matrix()
    if generator * check.transpose() != 0:
        raise AssertionError("invalid binary parity check")
    columns = [sum(int(check[row, column]) << row
                   for row in range(check.nrows()))
               for column in range(check.ncols())]

    low_basis = {}
    low_ranks = {}
    for index, syndrome in enumerate(columns):
        if syndrome == 0:
            add_binary_basis(1 << index, low_basis)
    low_ranks["1"] = len(low_basis)

    syndrome_groups = {}
    for index, syndrome in enumerate(columns):
        syndrome_groups.setdefault(syndrome, []).append(index)
    for group in syndrome_groups.values():
        first = group[0]
        for second in group[1:]:
            add_binary_basis((1 << first) | (1 << second), low_basis)
    low_ranks["2"] = len(low_basis)

    syndrome_lookup = {syndrome: index
                       for index, syndrome in enumerate(columns)}
    for first in range(len(columns)):
        for second in range(first + 1, len(columns)):
            third = syndrome_lookup.get(columns[first] ^ columns[second])
            if third is not None and third not in (first, second):
                add_binary_basis(
                    (1 << first) | (1 << second) | (1 << third), low_basis)
    low_ranks["3"] = len(low_basis)

    pair_representative = {}
    for first in range(len(columns)):
        for second in range(first + 1, len(columns)):
            syndrome = columns[first] ^ columns[second]
            word = (1 << first) | (1 << second)
            if syndrome in pair_representative:
                add_binary_basis(word ^ pair_representative[syndrome],
                                 low_basis)
            else:
                pair_representative[syndrome] = word
    low_ranks["4"] = len(low_basis)

    natural_words = []
    for row in natural.rows():
        word = sum(int(value) << index for index, value in enumerate(row))
        if word:
            natural_words.append((word.bit_count(), word))
    natural_words.sort()
    sparse_basis = {}
    selected_weights = []
    for weight, word in natural_words:
        if add_binary_basis(word, sparse_basis):
            selected_weights.append(weight)
    if len(selected_weights) != generator.nrows():
        raise AssertionError("natural words do not span the gluing code")

    zero_coordinates = [index for index, syndrome in enumerate(columns)
                        if syndrome == 0]
    return {
        "prime": prime,
        "vertices": vertices,
        "code_length": generator.ncols(),
        "code_dimension": generator.nrows(),
        "dual_dimension": check.nrows(),
        "weight_one_count": len(zero_coordinates),
        "weight_one_examples": [
            {
                "coordinate": index,
                "relator": names[index // len(representatives)],
                "scalar_pair_orbit": index % len(representatives),
            }
            for index in zero_coordinates[:20]
        ],
        "generated_rank_by_max_weight": low_ranks,
        "natural_nonzero_generators": len(natural_words),
        "natural_generator_weight_median": statistics.median(
            weight for weight, _word in natural_words),
        "greedy_natural_basis_max_weight": max(selected_weights),
        "greedy_natural_basis_weight_quartiles": [
            selected_weights[int((len(selected_weights) - 1) * quantile)]
            for quantile in (0.0, 0.25, 0.5, 0.75, 1.0)
        ],
    }


def sector_discriminants_at_three():
    prime = 3
    _names, vertices, _d0, d1 = coboundaries(prime)
    representatives, negative = involution_pairs(prime, vertices)
    dense = d1.toarray().astype(int)
    sectors = []
    for label, sign in (("plus", 1), ("minus", -1)):
        rows = []
        for relation in range(d1.shape[0] // vertices):
            for point in representatives:
                rows.append((
                    dense[relation * vertices + point]
                    + sign * dense[relation * vertices + negative[point]]
                ).tolist())
        reduced = matrix(ZZ, rows, sparse=True)
        cycles = reduced.left_kernel_matrix()
        gram = 2 * (cycles * cycles.transpose())
        determinant = ZZ(gram.det())
        sectors.append({
            "sector": label,
            "cycle_rank": cycles.nrows(),
            "gram_determinant": str(determinant),
            "gram_determinant_bits": determinant.nbits(),
            "gram_smith_nonunit_factors": [
                str(value) for value in gram.elementary_divisors()
                if value != 1
            ],
        })

    full_cycles = matrix(
        ZZ, dense.tolist(), sparse=True).left_kernel_matrix()
    full_determinant = ZZ(
        (full_cycles * full_cycles.transpose()).det())
    sector_product = math.prod(
        int(sector["gram_determinant"]) for sector in sectors)
    quotient, remainder = divmod(sector_product, int(full_determinant))
    index = math.isqrt(quotient)
    if remainder or index * index != quotient:
        raise AssertionError("sector determinant ratio is not a square")
    return {
        "full_cycle_gram_determinant": str(full_determinant),
        "sector_sublattice_index": str(index),
        "sector_sublattice_index_log2": index.bit_length() - 1,
        "sectors": sectors,
    }


def run(prime):
    result = gluing_code(prime)
    if prime == 3:
        result["integral_sector_discriminants"] = (
            sector_discriminants_at_three())
    return result


def verify(path):
    with open(path, "r", encoding="utf-8") as stream:
        expected = [json.loads(line) for line in stream if line.strip()]
    actual = [run(int(record["prime"])) for record in expected]
    if actual != expected:
        raise AssertionError("stored gluing-code results do not verify")
    return {"valid": True, "primes": [item["prime"] for item in actual]}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--primes", type=int, nargs="+")
    parser.add_argument("--verify")
    args = parser.parse_args()
    if args.verify:
        print(json.dumps(verify(args.verify)))
        return
    if not args.primes:
        parser.error("--primes is required unless --verify is used")
    for prime in args.primes:
        print(json.dumps(run(prime)), flush=True)


if __name__ == "__main__":
    main()
