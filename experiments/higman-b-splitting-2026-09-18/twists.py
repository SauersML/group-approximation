"""Twisted conjugates of R = [a,c]^2 by the elements of Bbar = B/Lambda_B.

For beta in B (a word from bbar_e<e>_words.txt), push beta through R syllable by syllable in
Gamma(3,m) = A.B (exact factorization):  beta R = alpha' beta_8,  so  beta R beta^-1 = alpha' . beta''
with alpha' in A and beta'' = beta_8 beta^-1 in B.  In Q_B = Gamma/Lambda_B, beta R beta^-1 lies in A
iff beta'' lies in Lambda_B; enum.g's faithful representation of Bbar decides this (checked by twists.g).
If it holds for every beta, then <<R>>_{Q_B} = <<S_beta : beta in Bbar>>_A with S_beta = alpha', and
Abar := A/<<R>>_{Q_B} = < a, c | a^m, c^m, S_beta (beta in Bbar) >.
usage: python3 twists.py e   (writes twists_e<e>.g)"""
import sys
e = int(sys.argv[1])
sys.argv = [sys.argv[0], str(e), '1']
from pathstab import push, red, inv, m

def left(s, word, j):
    """word * s^j = s^j' * word'  (word in B)."""
    w2, i2 = push(s, -j, inv(word))
    return (-i2) % m, inv(w2)

R = [('a', -1), ('c', -1), ('a', 1), ('c', 1)] * 2

def twist(beta):
    alpha = []; cur = beta
    for (s, j) in R:
        j2, cur = left(s, cur, j)
        alpha.append((s, j2))
    return red(alpha), red(list(cur) + list(inv(beta)))

def canon(w):
    """canonical representative of the cyclic word w up to rotation and inversion."""
    w = list(w)
    while len(w) >= 2 and w[0][0] == w[-1][0]:
        g = w[0][0]; x = (w[0][1] + w[-1][1]) % m
        w = w[1:-1]
        if x: w = [(g, x)] + w
    best = None
    for u in (tuple(w), inv(tuple(w))):
        for i in range(max(len(u), 1)):
            c = u[i:] + u[:i]
            if best is None or c < best: best = c
    return best

def gapword(w, gens):
    return '*'.join('%s^%d' % (gens[g], x if x <= m // 2 else x - m) for (g, x) in w) or 'One(F)'

words = [l.strip() for l in open('bbar_e%d_words.txt' % e)]
rels = set(); checks = []
for wd in words:
    beta = red([(ch, 1) for ch in wd])
    alpha, b2 = twist(beta)
    rels.add(canon(alpha)); checks.append(b2)
with open('twists_e%d.g' % e, 'w') as f:
    f.write('# generated by twists.py %d: %d elements of Bbar, %d distinct twisted relators\n' % (e, len(words), len(rels)))
    f.write('BetaPP:=[\n' + ',\n'.join('[' + ','.join('[%d,%d]' % (1 if g == 'b' else 2, x) for (g, x) in w) + ']' for w in checks) + '];;\n')
    f.write('TwistRels:=function(F) local a,c; a:=F.1; c:=F.2; return [\n' +
            ',\n'.join(gapword(w, {'a': 'a', 'c': 'c'}) for w in sorted(rels)) + ']; end;;\n')
print('e=%d: %d elements of Bbar, %d distinct twisted relators (up to rotation/inversion), max length %d'
      % (e, len(words), len(rels), max(len(w) for w in rels)))
