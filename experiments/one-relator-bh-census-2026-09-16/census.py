#!/usr/bin/env python3
"""Boone--Higman certificate census for two-generator one-relator groups G = <a,t | w>.

Search space (exact): every cyclically reduced word w over {a,A,t,T} (A = a^-1, T = t^-1)
of length L, for LMIN <= L <= LMAX, up to the group generated by cyclic rotation, inversion
w -> w^-1, and the eight signed permutations of {a,t}.  Each of these moves preserves the
isomorphism type of G.  The representative of a class is its ASCII-least member.

For each class the script looks for a certificate that G lies in a class for which the
Cairn graph has an ESTABLISHED embedding into a finitely presented simple group:
  PRIM      w primitive (Whitehead-minimal length 1): G = Z.
  POWER     w = u^k, k >= 2: G has torsion, hence is hyperbolic (B. B. Newman).
  FBC       in a basis adapted to a character chi (chi(a) = 0, chi(t) = 1), after
            chi-preserving Whitehead reduction, the lowest and highest levels each carry one
            a-letter: G = F_n x| Z (Moldavanskii criterion, proof in the artifact).
  BS        adapted word with two syllables at adjacent levels: G = BS(e, -f).
  POWERMAP  adapted word t^n a^e t^-n a^f with n >= 2 and min(|e|,|f|) = 1: an ascending
            HNN extension of F_n along a permuted power map.
  ASCIRR    adapted word of span n >= 2 whose lowest (or highest) level carries exactly one
            a-letter: G is the ascending HNN extension of F_n along an injective endomorphism
            psi whose abelianization is the companion matrix of the level polynomial.  If the
            other extreme level has exponent sum of absolute value >= 2 (psi nonsurjective)
            and the polynomials of k-th powers of the roots are irreducible over Q for
            k = 1..n (psi irreducible in Mutanguha's sense), G is hyperbolic (Mutanguha,
            arXiv:1908.08214, Theorem 6.3).
  TORUS     Whitehead-minimal image a^p t^q with |p|,|q| >= 2: G is virtually F_k x Z.
  C16       some image satisfies C'(1/6): G is hyperbolic.
  VFBC      vfib.py (research/artifacts/or-length15-residue-scripts) finds an index-k subgroup
            with a fibring character: G is virtually F_n x| Z.
  RESIDUE   none of the above (not certified; says nothing about G).
Every certificate line is JSON and is re-checked by verify_census.py.
Usage: census.py LMIN LMAX KMAX OUTFILE [TMO]  (KMAX = 0 disables VFBC; TMO seconds per vfib call)
"""
import sys, json, subprocess, os
from math import gcd

VFIB_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'research',
                        'artifacts', 'or-length15-residue-scripts')
INV = {'a': 'A', 'A': 'a', 't': 'T', 'T': 't'}

def inv(w):
    return ''.join(INV[c] for c in reversed(w))

def fred(w):
    st = []
    for c in w:
        if st and st[-1] == INV[c]:
            st.pop()
        else:
            st.append(c)
    return ''.join(st)

def cred(w):
    w = fred(w)
    i, j = 0, len(w) - 1
    while i < j and w[i] == INV[w[j]]:
        i += 1; j -= 1
    return w[i:j + 1]

def subst(w, img):
    full = {'a': img['a'], 't': img['t'], 'A': inv(img['a']), 'T': inv(img['t'])}
    return fred(''.join(full[c] for c in w))

def compose(theta, sigma):
    """theta o sigma, both given by images of a and t."""
    return {'a': subst(sigma['a'], theta), 't': subst(sigma['t'], theta)}

ID = {'a': 'a', 't': 't'}

# ---------------------------------------------------------------- enumeration
def transforms():
    out = []
    for swap in (False, True):
        for ia in (False, True):
            for it in (False, True):
                m = {}
                for x, X, flip in (('a', 'A', ia), ('t', 'T', it)):
                    y = ('t' if x == 'a' else 'a') if swap else x
                    Y = y.upper()
                    m[x], m[X] = (Y, y) if flip else (y, Y)
                out.append(str.maketrans(m))
    return out

TR = transforms()

def is_canonical(w):
    L = len(w)
    for tr in TR:
        s = w.translate(tr)
        for u in (s, inv(s)):
            uu = u + u
            for i in range(L):
                if uu[i:i + L] < w:
                    return False
    return True

def classes(L):
    """ASCII-least representatives of the classes of cyclically reduced words of length L."""
    out, w = [], ['A']
    letters = 'ATat'
    def rec():
        if len(w) == L:
            if w[-1] != INV[w[0]]:
                s = ''.join(w)
                if is_canonical(s):
                    out.append(s)
            return
        for c in letters:
            if c != INV[w[-1]]:
                w.append(c); rec(); w.pop()
    if L == 1:
        return ['A']
    rec()
    return out

# ---------------------------------------------------------------- Whitehead moves
def wh_moves():
    mv = []
    for y in 'aAtT':
        x = 't' if y.lower() == 'a' else 'a'
        for new in (x + y, INV[y] + x, INV[y] + x + y):
            img = dict(ID); img[x] = new
            mv.append((y, img))
    return mv

WH = wh_moves()

def wh_minimize(w, sigma=ID, only=None):
    """Greedy Whitehead reduction of the cyclic word cred(sigma(w)).  only: multipliers allowed."""
    cur = cred(subst(w, sigma))
    improved = True
    while improved:
        improved = False
        for y, th in WH:
            if only is not None and y not in only:
                continue
            v = cred(subst(cur, th))
            if len(v) < len(cur):
                cur, sigma, improved = v, compose(th, sigma), True
                break
    return cur, sigma

def proper_power(w):
    L = len(w)
    for d in range(1, L):
        if L % d == 0 and w[:d] * (L // d) == w:
            return w[:d], L // d
    return None

def expsums(w):
    return (w.count('a') - w.count('A'), w.count('t') - w.count('T'))

def syllables(w):
    """Cyclic syllables (letter, exponent) of a cyclically reduced word."""
    if not w:
        return []
    k = 0
    while k < len(w) and w[k].lower() == w[0].lower():
        k += 1
    if k == len(w):
        e = sum(1 if c.islower() else -1 for c in w)
        return [(w[0].lower(), e)]
    u = w[k:] + w[:k]
    out = []
    for c in u:
        s = 1 if c.islower() else -1
        if out and out[-1][0] == c.lower():
            out[-1] = (c.lower(), out[-1][1] + s)
        else:
            out.append((c.lower(), s))
    return out

# ---------------------------------------------------------------- characters and adapted bases
def characters(w, B):
    sa, st = expsums(w)
    if (sa, st) != (0, 0):
        g = gcd(abs(sa), abs(st))
        return [(st // g, -sa // g)]
    out = []
    for p in range(0, B + 1):
        for q in range(-B, B + 1):
            if (p, q) != (0, 0) and gcd(p, abs(q)) == 1 and (p > 0 or q > 0):
                out.append((p, q))
    return out

def adapt(p, q):
    """An automorphism sigma with t-exponent sums (sigma(a), sigma(t)) = (p, q), gcd(p,q) = 1.
    Then <a,t | w> = <a,t | cred(sigma(w))>, and the character (p, q) of the first becomes
    (a -> 0, t -> 1) on the second."""
    E, pu, pv = dict(ID), p, q
    sg = lambda x: 1 if x > 0 else -1
    while pu != 0 and pv != 0:
        s = sg(pu) * sg(pv)
        if abs(pu) >= abs(pv):
            E = compose({'a': 'a' + ('t' if s > 0 else 'T'), 't': 't'}, E); pu -= s * pv
        else:
            E = compose({'a': 'a', 't': 't' + ('a' if s > 0 else 'A')}, E); pv -= s * pu
    if pu != 0:
        E = compose({'a': 't', 't': 'a'}, E); pu, pv = pv, pu
    if pv == -1:
        E = compose({'a': 'a', 't': 'T'}, E)
    assert expsums(E['a'])[1] == p and expsums(E['t'])[1] == q, (p, q, E)
    return E

def molda(u):
    """Level data of a cyclically reduced word with t-exponent sum 0 and at least one a-letter."""
    h, letters = 0, []
    for c in u:
        if c == 't':
            h += 1
        elif c == 'T':
            h -= 1
        else:
            letters.append((h, 1 if c == 'a' else -1))
    syl = []
    for lv, e in letters:
        if syl and syl[-1][0] == lv:
            syl[-1] = (lv, syl[-1][1] + e)
        else:
            syl.append((lv, e))
    if len(syl) > 1 and syl[0][0] == syl[-1][0]:
        syl[0] = (syl[0][0], syl[0][1] + syl[-1][1]); syl.pop()
    m, M = min(lv for lv, _ in letters), max(lv for lv, _ in letters)
    cm = sum(1 for lv, _ in letters if lv == m)
    cM = sum(1 for lv, _ in letters if lv == M)
    sm = sum(1 for lv, _ in syl if lv == m)
    sM = sum(1 for lv, _ in syl if lv == M)
    esum = [0] * (M - m + 1)
    for lv, e in letters:
        esum[lv - m] += e
    return {'span': M - m, 'cnt_min': cm, 'cnt_max': cM, 'syl_min': sm, 'syl_max': sM,
            'nsyl': len(syl), 'syl': [(lv - m, e) for lv, e in syl], 'esum': esum}

def ascirr(d):
    """Characteristic polynomial coefficients of the abelianized endomorphism, or None."""
    import sympy
    n, e = d['span'], d['esum']
    if n < 2:
        return None
    if d['cnt_min'] == 1 and abs(e[n]) >= 2:
        coeffs = e                      # eps * sum_h e_h lam^(n-h): highest power first
    elif d['cnt_max'] == 1 and abs(e[0]) >= 2:
        coeffs = e[::-1]                # levels reversed, t replaced by t^-1
    else:
        return None
    lam, x = sympy.symbols('lam x')
    eps = coeffs[0]
    P = sympy.Poly([c * eps for c in coeffs], lam)          # monic
    for k in range(1, n + 1):
        chi = sympy.Poly(sympy.resultant(P.as_expr(), x - lam ** k, lam), x)
        if chi.degree() != n or not chi.is_irreducible:
            return None
    return coeffs

def adapted_tag(d):
    if d['span'] >= 1 and d['cnt_min'] == 1 and d['cnt_max'] == 1:
        return 'FBC'
    if d['nsyl'] == 2 and d['span'] >= 1:
        e1, e2 = d['syl'][0][1], d['syl'][1][1]
        if d['span'] == 1:
            return 'BS'
        if min(abs(e1), abs(e2)) == 1:
            return 'POWERMAP'
    if ascirr(d):
        return 'ASCIRR'
    return None

# ---------------------------------------------------------------- small cancellation
def max_piece(w):
    L = len(w)
    R = {u[i:] + u[:i] for u in (w, inv(w)) for i in range(L)}
    R = sorted(R)
    best = 0
    for i in range(len(R)):
        for j in range(i + 1, len(R)):
            k = 0
            while k < L and R[i][k] == R[j][k]:
                k += 1
            best = max(best, k)
    return best

# ---------------------------------------------------------------- vfib
def vfib(word, kmax, tmo):
    try:
        out = subprocess.run(['timeout', str(tmo), sys.executable, 'vfib.py', word, str(kmax), '1', '2'],
                             cwd=VFIB_DIR, capture_output=True, text=True).stdout
    except Exception:
        return None
    for line in out.splitlines():
        if line.startswith('CERT'):
            return line.strip()
    return None

# ---------------------------------------------------------------- certification
def certify(w, kmax, B=4, tmo=300):
    rec = {'w': w, 'L': len(w), 'expsums': expsums(w)}
    pp = proper_power(w)
    if pp:
        rec.update(tag='POWER', root=pp[0], k=pp[1]); return rec
    w0, s0 = wh_minimize(w)
    rec['minlen'] = len(w0)
    if len(w0) == 1:
        rec.update(tag='PRIM', sigma=s0, img=w0); return rec
    sy = syllables(w0)
    if len(sy) == 2 and sy[0][0] != sy[1][0] and min(abs(sy[0][1]), abs(sy[1][1])) >= 2:
        rec.update(tag='TORUS', sigma=s0, img=w0); return rec
    bases = [(w, ID)] + ([(w0, s0)] if w0 != w else [])
    first = None
    for base, sb in bases:
        for p, q in characters(base, B):
            s1 = compose(adapt(p, q), sb)
            img, s2 = wh_minimize(w, s1, only='aA')
            d = molda(img)
            if first is None:
                first = dict(d, char=(p, q), img=img)
            tag = adapted_tag(d)
            if tag:
                rec.update(tag=tag, sigma=s2, img=img, levels=d); return rec
    for base, sb in bases:
        mp = max_piece(base)
        if 6 * mp < len(base):
            rec.update(tag='C16', sigma=sb, img=base, piece=mp); return rec
    if kmax > 0:
        c = vfib(w0, kmax, tmo)
        if c:
            rec.update(tag='VFBC', sigma=s0, img=w0, vfib=c); return rec
    rec.update(tag='RESIDUE', w0=w0, adapted=first); return rec

def main():
    LMIN, LMAX, KMAX, OUT = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3]), sys.argv[4]
    TMO = int(sys.argv[5]) if len(sys.argv) > 5 else 300
    with open(OUT, 'w') as f:
        for L in range(LMIN, LMAX + 1):
            reps = classes(L)
            count = {}
            for w in reps:
                r = certify(w, KMAX, tmo=TMO)
                count[r['tag']] = count.get(r['tag'], 0) + 1
                f.write(json.dumps(r) + '\n'); f.flush()
            allfour = sum(1 for w in reps if all(c in w for c in 'aAtT'))
            print('L=%d classes=%d four-letter=%d %s' % (L, len(reps), allfour, sorted(count.items())), flush=True)
    print('SENTINEL_DONE', flush=True)

if __name__ == '__main__':
    main()
