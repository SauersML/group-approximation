"""Intersect the multiplicative Pauli packet with its comb conjugate.

The packet is the exact extraspecial group generated by the four root signs
for ``t_i`` and ``s_j``.  Its commutator table records
``t_i s_j = delta_ij``.  This audit asks how much of that table survives in a
single common finite subgroup after comb transport.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, "experiments")

from atlas_pauli_transported_carrier import (  # noqa: E402
    commute,
    equal,
    generated_subgroup_with_words,
    intersection_elements,
)
from atlas_raw_branch_pauli_cell import (  # noqa: E402
    element_order,
    generated_subgroup,
    order_histogram,
    root,
)
from atlas_raw_compressor_proper_infinite import (  # noqa: E402
    product,
    raw_and_comb,
    s,
    t,
)
from atlas_survivor_prefix_obstruction import leavitt_star  # noqa: E402


def main():
    raw, comb = raw_and_comb()
    generators = (
        root(t(0), 0, 1),
        root(t(1), 0, 1),
        root(s(0), 1, 2),
        root(s(1), 1, 2),
    )
    packet = generated_subgroup(generators, limit=64)
    words = generated_subgroup_with_words(generators, limit=64)
    def describe_intersection(conjugator):
        transported_packet = [
            product(leavitt_star(conjugator), value, conjugator)
            for value in packet
        ]
        intersection = intersection_elements(packet, transported_packet)
        entries = []
        for value in intersection:
            word = next(
                word for candidate, word in words if equal(value, candidate)
            )
            preimage_word = next(
                word for candidate, word in words
                if equal(
                    product(leavitt_star(conjugator), candidate, conjugator),
                    value,
                )
            )
            entries.append({
                "order": element_order(value),
                "word_in_Xt0_Xt1_Zs0_Zs1": list(word),
                "conjugate_preimage_word": list(preimage_word),
                "central_in_packet": all(
                    commute(value, other) for other in packet
                ),
            })
        return {
            "order": len(intersection),
            "entries": entries,
        }

    raw_second = product(raw, comb)
    raw_closure = None
    raw_closure_status = "exceeded_600"
    try:
        raw_closure = generated_subgroup((*generators, raw), limit=600)
        raw_closure_status = "finite"
    except AssertionError:
        pass
    raw_escape_orders = {
        "raw_times_Xt0": element_order(product(raw, generators[0]), 256),
        "raw_times_Xt1": element_order(product(raw, generators[1]), 256),
        "raw_Xt0_commutator": element_order(
            product(raw, generators[0], raw, generators[0]), 256
        ),
        "raw_Xt1_commutator": element_order(
            product(raw, generators[1], raw, generators[1]), 256
        ),
    }
    raw_commutators = (
        product(raw, generators[0], raw, generators[0]),
        product(raw, generators[1], raw, generators[1]),
    )
    raw_commutator_cell = None
    raw_commutator_cell_status = "exceeded_64"
    try:
        raw_commutator_cell = generated_subgroup(
            (generators[2], generators[3], *raw_commutators), limit=64
        )
        raw_commutator_cell_status = "finite"
    except AssertionError:
        pass
    raw_commutator_table = {
        "c0_commutes_Zs0": commute(raw_commutators[0], generators[2]),
        "c0_commutes_Zs1": commute(raw_commutators[0], generators[3]),
        "c1_commutes_Zs0": commute(raw_commutators[1], generators[2]),
        "c1_commutes_Zs1": commute(raw_commutators[1], generators[3]),
        "c0_commutes_c1": commute(raw_commutators[0], raw_commutators[1]),
    }
    original_centers = (
        product(generators[0], generators[2], generators[0], generators[2]),
        product(generators[1], generators[3], generators[1], generators[3]),
    )
    raw_centers = (
        product(
            raw_commutators[0], generators[2],
            raw_commutators[0], generators[2],
        ),
        product(
            raw_commutators[1], generators[3],
            raw_commutators[1], generators[3],
        ),
    )
    mixed_products = (
        product(generators[0], raw_commutators[0]),
        product(generators[1], raw_commutators[1]),
    )
    mixed_table = {
        "original_centers_equal": equal(original_centers[0], original_centers[1]),
        "raw_centers_equal": equal(raw_centers[0], raw_centers[1]),
        "original_center_equals_raw_center": equal(
            original_centers[0], raw_centers[0]
        ),
        "original_center_commutes_raw_center": commute(
            original_centers[0], raw_centers[0]
        ),
        "original_center_central_in_mixed_generators": all(
            commute(original_centers[0], value)
            for value in (*generators, *raw_commutators)
        ),
        "raw_center_central_in_mixed_generators": all(
            commute(raw_centers[0], value)
            for value in (*generators, *raw_commutators)
        ),
        "raw_conjugates_original_center_to_center_product": equal(
            product(raw, original_centers[0], raw),
            product(original_centers[0], raw_centers[0]),
        ),
        "raw_fixes_raw_center": equal(
            product(raw, raw_centers[0], raw), raw_centers[0]
        ),
        "X0_commutes_C0": commute(generators[0], raw_commutators[0]),
        "X0_commutes_C1": commute(generators[0], raw_commutators[1]),
        "X1_commutes_C0": commute(generators[1], raw_commutators[0]),
        "X1_commutes_C1": commute(generators[1], raw_commutators[1]),
        "A0_order": element_order(mixed_products[0], 256),
        "A1_order": element_order(mixed_products[1], 256),
        "A0_is_raw_conjugate_Xt0": equal(
            mixed_products[0], product(raw, generators[0], raw)
        ),
        "A1_is_raw_conjugate_Xt1": equal(
            mixed_products[1], product(raw, generators[1], raw)
        ),
        "A0_commutes_A1": commute(mixed_products[0], mixed_products[1]),
        "A0_Z0_commutator_is_center_product": equal(
            product(
                mixed_products[0], generators[2],
                mixed_products[0], generators[2],
            ),
            product(original_centers[0], raw_centers[0]),
        ),
        "A1_Z1_commutator_is_center_product": equal(
            product(
                mixed_products[1], generators[3],
                mixed_products[1], generators[3],
            ),
            product(original_centers[0], raw_centers[0]),
        ),
    }
    mixed_cell = None
    mixed_cell_status = "exceeded_256"
    try:
        mixed_cell = generated_subgroup(
            (*generators, *raw_commutators), limit=256
        )
        mixed_cell_status = "finite"
    except AssertionError:
        pass
    coefficient_cell = generated_subgroup(
        (
            mixed_products[0], mixed_products[1],
            original_centers[0], raw_centers[0],
        ),
        limit=32,
    )

    result = {
        "packet_order": len(packet),
        "packet_order_histogram": order_histogram(packet),
        "comb_intersection": describe_intersection(comb),
        "raw_second_intersection": describe_intersection(raw_second),
        "raw_relative_intersection": describe_intersection(raw),
        "packet_with_raw_closure_status": raw_closure_status,
        "packet_with_raw_closure_order": (
            None if raw_closure is None else len(raw_closure)
        ),
        "packet_with_raw_closure_histogram": (
            None if raw_closure is None else order_histogram(raw_closure)
        ),
        "raw_escape_orders_up_to_256": raw_escape_orders,
        "raw_commutator_table": raw_commutator_table,
        "raw_commutator_cell_status": raw_commutator_cell_status,
        "raw_commutator_cell_order": (
            None if raw_commutator_cell is None else len(raw_commutator_cell)
        ),
        "raw_commutator_cell_histogram": (
            None if raw_commutator_cell is None
            else order_histogram(raw_commutator_cell)
        ),
        "mixed_double_pauli_table": mixed_table,
        "mixed_double_pauli_closure_status": mixed_cell_status,
        "mixed_double_pauli_closure_order": (
            None if mixed_cell is None else len(mixed_cell)
        ),
        "mixed_double_pauli_closure_histogram": (
            None if mixed_cell is None else order_histogram(mixed_cell)
        ),
        "coefficient_sign_cell_order": len(coefficient_cell),
        "coefficient_sign_cell_histogram": order_histogram(coefficient_cell),
    }
    expected_path = Path(__file__).with_name(
        "atlas-multiplicative-pauli-comb-intersection.json"
    )
    with expected_path.open(encoding="utf-8") as stream:
        expected = json.load(stream)
    if json.loads(json.dumps(result)) != expected:
        raise AssertionError(result)
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
