def rewrite_raw(W, s):
    """letters (u, h) with raw heights h = s-exponent of the prefix."""
    h, out = 0, []
    for c in W:
        if abs(c) == s:
            h += 1 if c > 0 else -1
        else:
            out.append((abs(c), h, 1 if c > 0 else -1))
    return out if h == 0 else None


def sub_eq(G1, gensH):
    """is the subgroup with Stallings graph G1 equal to <gensH>?"""
    G2 = LG.Graph(gensH) if gensH else None
    if G2 is None:
        return G1 is None or G1.rank() == 0
    if G1 is None:
        return all(len(fr(g)) == 0 for g in gensH)
    return all(G1.member(g) for g in gensH) and G1.key() == G2.key()


def meet(gens1, gens2):
    """Stallings graph of <gens1> cap <gens2> (None if trivial)."""
    g1 = [g for g in gens1 if g]
    g2 = [g for g in gens2 if g]
    if not g1 or not g2:
        return None
    P = LG.pullback(LG.Graph(g1), LG.Graph(g2))
    base = [c for c in P if c[1]]
    if not base:
        return None
    return LG.Graph(base[0][2])


def decide(n, W0, s, Mlet, Nlet):
    """s in Mlet \\ Nlet with exponent 0 in W0."""
    R = rewrite_raw(W0, s)
    if R is None:
        return 'S-EXP-NONZERO', {}
    lets = sorted(set(u for u, _, _ in R))
    rng = {u: (min(h for v, h, _ in R if v == u), max(h for v, h, _ in R if v == u)) for u in lets}
    for u in (Mlet | Nlet) - {s}:
        if u not in rng:
            return 'LETTER-ABSENT', {}
    gens = [(u, i) for u in lets for i in range(rng[u][0], rng[u][1] + 1)]
    idx = {g: k + 1 for k, g in enumerate(gens)}
    r = len(gens)
    Rw = [idx[(u, h)] * e for u, h, e in R]
    m, img = whmin_track(Rw, r)
    if len(m) != 1:
        return 'VERTEX-NONFREE(%d)' % len(m), {}
    c = abs(m[0])
    others = [g for g in range(1, r + 1) if g != c]
    rel = {o: k + 1 for k, o in enumerate(others)}
    im = {g: tuple(fr([(rel[abs(x)] if x > 0 else -rel[abs(x)]) for x in img[idx[g]] if abs(x) != c]))
          for g in gens}
    Mp = sorted(Mlet - {s})
    Y = [im[(u, i)] for u in Mp for i in range(rng[u][0], rng[u][1] + 1)]
    Yp = [im[(u, i)] for u in Mp for i in range(rng[u][0] + 1, rng[u][1] + 1)]
    Ym = [im[(u, i)] for u in Mp for i in range(rng[u][0], rng[u][1])]
    Ep = [im[(u, i)] for u in lets for i in range(rng[u][0] + 1, rng[u][1] + 1)]
    Em = [im[(u, i)] for u in lets for i in range(rng[u][0], rng[u][1])]
    if not sub_eq(meet(Y, Ep), [g for g in Yp if g]):
        return 'NO-IMMERSION(+)', {}
    if not sub_eq(meet(Y, Em), [g for g in Ym if g]):
        return 'NO-IMMERSION(-)', {}
    lo = max(rng[u][0] for u in Nlet)
    hi = min(rng[u][1] for u in Nlet)
    if lo > hi:
        return 'N-SPLIT', {}
    info = {}
    for h0 in range(lo, hi + 1):
        Ng = [im[(u, h0)] for u in sorted(Nlet)]
        I = meet(Y, Ng)
        P = [im[(u, h0)] for u in sorted(Mlet & Nlet)]
        ok = sub_eq(I, [g for g in P if g])
        info[h0] = (I.rank() if I else 0, ok)
        if not ok:
            return 'EXCEPTIONAL-CANDIDATE', info
    return 'NONEXC', info


def run(w):
    n, W0 = magnus(w, 2)
    S = set(range(1, n + 1))
    T = set(range(2, n + 2))
    exps = {u: sum(1 if c == u else -1 if c == -u else 0 for c in W0) for u in range(1, n + 2)}
    out = []
    for s, Ml, Nl in ((1, S, T), (n + 1, T, S)):
        if exps[s] != 0:
            out.append((s, 'S-EXP-NONZERO', {}))
            continue
        v, info = decide(n, W0, s, Ml, Nl)
        out.append((s, v, info))
        if v == 'NONEXC':
            break
    return n, W0, exps, out


