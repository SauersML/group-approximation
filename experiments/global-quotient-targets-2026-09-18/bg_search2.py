#!/usr/bin/env python3
"""Search homomorphisms G = <a, b | r> -> G(1, n) = <c, s | (c^s)^-1 c (c^s) = c^n> (Baumslag--Gersten
type, in H for n != 1) that are nontrivial on the Magnus kernel K of G -> Z.

a |-> X, b |-> Y range over reduced words of length <= MAXLEN in c, s; a hit needs r(X, Y) = 1
(exact word problem: Britton's lemma for the HNN extension of BS(1, n) = Z[1/n] x| Z by s)
and phi(k0) != 1, where k0 is a normal generator of K: with (ea, eb) the exponent sums of r
and g = gcd(ea, eb), K is normally generated by a^(eb/g) b^(-ea/g) ... we use the simpler
test phi(a)^(eb/g) phi(b)^(-ea/g) != 1 together with phi(K) != 1 detected on the commutator
[phi(a), phi(b)] and on that element (K is the normal closure of the kernel of the
abelianisation map to Z, generated by [a, b] and a^(eb/g) b^(-ea/g)).

Usage: bg_search2.py N MAXLEN WORD ...
"""
import itertools
import sys
from fractions import Fraction as Fr
from math import gcd

INV = {'a': 'A', 'A': 'a', 'b': 'B', 'B': 'b', 'c': 'C', 'C': 'c', 's': 'S', 'S': 's'}


class BG:
    """G(1,n) = <c0, c1, s | c1^-1 c0 c1 = c0^n, s^-1 c0 s = c1>: the HNN extension of
    BS(1,n) = <c0, c1> along <c0> -> <c1>.  BS(1,n) elements are pairs (alpha, e) meaning
    c0^alpha c1^e with alpha in Z[1/n]."""

    def __init__(self, n):
        self.n = Fr(n)

    def mul(self, g, h):
        return (g[0] + h[0] * self.n ** (-g[1]), g[1] + h[1])

    def reduce(self, word):
        st = [(Fr(0), 0)]
        for L in word:
            if L in 'cC':
                st[-1] = self.mul(st[-1], (Fr(1 if L == 'c' else -1), 0))
                continue
            eps = 1 if L == 's' else -1
            if len(st) >= 3 and st[-2] == -eps:
                g = st[-1]
                if st[-2] == -1 and g[1] == 0 and g[0].denominator == 1:
                    img = (Fr(0), int(g[0]))      # s c0^j s^-1 ... (s^-1)(c0^j)(s) = c1^j
                    st.pop(); st.pop()
                    st[-1] = self.mul(st[-1], img)
                    continue
                if st[-2] == 1 and g[0] == 0:
                    img = (Fr(g[1]), 0)           # s c1^j s^-1 = c0^j
                    st.pop(); st.pop()
                    st[-1] = self.mul(st[-1], img)
                    continue
            st.append(eps)
            st.append((Fr(0), 0))
        return st

    def trivial(self, word):
        st = self.reduce(word)
        return len(st) == 1 and st[0] == (Fr(0), 0)


def inv(w):
    return [INV[x] for x in reversed(w)]


def words(maxlen, alph='cCsS'):
    out = []
    for L in range(1, maxlen + 1):
        for tup in itertools.product(alph, repeat=L):
            if all(INV[tup[i]] != tup[i + 1] for i in range(L - 1)):
                out.append(list(tup))
    return out


def power(w, k):
    return (w if k >= 0 else inv(w)) * abs(k)


def main():
    n = int(sys.argv[1]); maxlen = int(sys.argv[2])
    G = BG(n)
    W = words(maxlen)
    for r in sys.argv[3:]:
        ea = sum(1 if x == 'a' else -1 if x == 'A' else 0 for x in r)
        eb = sum(1 if x == 'b' else -1 if x == 'B' else 0 for x in r)
        g = gcd(ea, eb) or 1
        p, q = ea // g, eb // g
        hit = None
        for X in W:
            for Y in W:
                img = []
                for L in r:
                    img += {'a': X, 'A': inv(X), 'b': Y, 'B': inv(Y)}[L]
                if not G.trivial(img):
                    continue
                k0 = power(X, p) + power(Y, q)
                comm = inv(X) + inv(Y) + X + Y
                if G.trivial(k0) and G.trivial(comm):
                    continue
                hit = (''.join(X), ''.join(Y))
                break
            if hit:
                break
        print(r, 'n=%d' % n, hit if hit else 'none', flush=True)


if __name__ == '__main__':
    main()
