BASE_CODE = ("000", "001", "010", "011", "10", "11")
HARD_CASES = {
    11: (
        (False, 0, 2),
        (False, 3, 3),
        (False, 4, 2),
        (True, 2, 3),
        (True, 3, 2),
        (True, 6, 2),
    ),
    30: (
        (False, 3, 2),
        (False, 6, 3),
        (False, 7, 2),
        (True, 0, 2),
        (True, 3, 2),
        (True, 7, 3),
    ),
}
GENERATOR_NAMES = ("q", "l", "q*", "l*")


def leavitt_star(value):
    """The standard involution on a finite Leavitt-algebra expansion."""
    return {(right, left): coefficient for (left, right), coefficient
            in value.items() if coefficient & 1}


def cylinder_projection(word):
    prefix = tuple(int(bit) for bit in word)
    return {(prefix, prefix): 1}


def leavitt_is_zero(value):
    """Test exact zero, allowing Cuntz--Leavitt prefix expansions."""
    if not value:
        return True
    depths = {}
    for left, right in value:
        degree = len(left) - len(right)
        depths[degree] = max(depths.get(degree, 0), len(right))
    return not expand_terms(value, depths)


def evaluate_generator_word(word, generators):
    value = ONE
    for generator in word:
        value = leavitt_mul(value, generators[generator])
    return value


def monomial_pool(generators, max_depth):
    """All words of length at most ``max_depth`` in four generators."""
    pool = [(ONE, ())]
    layer = [(ONE, ())]
    for _ in range(max_depth):
        following = []
        for value, word in layer:
            for index, generator in enumerate(generators):
                following.append((
                    leavitt_mul(value, generator),
                    word + (index,),
                ))
        pool.extend(following)
        layer = following
    return pool


def span_certificates(pool, targets):
    """Express targets in the exact F_2-span of a Leavitt monomial pool."""
    depths = {}
    for value, _ in pool:
        for left, right in value:
            degree = len(left) - len(right)
            depths[degree] = max(depths.get(degree, 0), len(right))
    for value in targets:
        for left, right in value:
            degree = len(left) - len(right)
            depths[degree] = max(depths.get(degree, 0), len(right))

    expanded_pool = [expand_terms(value, depths) for value, _ in pool]
    expanded_targets = [expand_terms(value, depths) for value in targets]
    universe = {
        term
        for expansion in [*expanded_pool, *expanded_targets]
        for term in expansion
    }
    indices = {term: index for index, term in enumerate(sorted(universe))}

    def encode(expansion):
        vector = 0
        for term in expansion:
            vector ^= 1 << indices[term]
        return vector

    pivots = {}
    for column, expansion in enumerate(expanded_pool):
        vector = encode(expansion)
        combination = 1 << column
        while vector:
            pivot = vector.bit_length() - 1
            if pivot not in pivots:
                pivots[pivot] = (vector, combination)
                break
            old_vector, old_combination = pivots[pivot]
            vector ^= old_vector
            combination ^= old_combination

    certificates = []
    for expansion in expanded_targets:
        vector = encode(expansion)
        combination = 0
        while vector:
            pivot = vector.bit_length() - 1
            if pivot not in pivots:
                raise AssertionError("projection is outside the generated span")
            old_vector, old_combination = pivots[pivot]
            vector ^= old_vector
            combination ^= old_combination
        certificates.append([
            pool[index][1]
            for index in range(len(pool))
            if (combination >> index) & 1
        ])
    return certificates, len(universe), len(pivots)


def verify_projection_identities(generators, certificates, targets):
    for certificate, target in zip(certificates, targets):
        value = {}
        for word in certificate:
            value = leavitt_add(
                value, evaluate_generator_word(word, generators))
        if not leavitt_is_zero(leavitt_add(value, target)):
            raise AssertionError("reported projection identity is false")


def cardinality_contradictions(prefix_matrix, factor, letter_matrix):
    """Positive descendant-count contradictions after refining BASE_CODE."""
    prefix_components = support_components(prefix_matrix)
    component_of = {
        leaf: component
        for component, leaves in enumerate(prefix_components)
        for leaf in leaves
    }
    contradictions = []
    for letter_component in support_components(letter_matrix):
        first = letter_component[0]
        for second in letter_component[1:]:
            coefficients = collections.defaultdict(int)
            for sign, source_index in ((1, first), (-1, second)):
                source = CHART_LEAVES[factor][source_index]
                for leaf, target in enumerate(BASE_CODE):
                    if target.startswith(source):
                        coefficients[component_of[leaf]] += sign
            coefficients = {
                component: coefficient
                for component, coefficient in coefficients.items()
                if coefficient
            }
            if coefficients and (
                    all(value > 0 for value in coefficients.values())
                    or all(value < 0 for value in coefficients.values())):
                contradictions.append(coefficients)
    return prefix_components, contradictions


def hard_case_certificate(word, prefix_length, cache):
    prefix = ONE
    for factor, matrix in word[:prefix_length]:
        prefix = leavitt_mul(
            prefix, leavitt_chart_element(factor, matrix))
    factor, letter_matrix = word[prefix_length]
    letter = leavitt_chart_element(factor, letter_matrix)
    prefix_matrix = chart_matrix(prefix, BASE_CODE)
    if prefix_matrix is None:
        raise AssertionError("chosen prefix is absent from the base chart")
    if chart_matrix(letter, BASE_CODE) is not None:
        raise AssertionError("hard next letter unexpectedly lies in base chart")

    prefix_components, contradictions = cardinality_contradictions(
        prefix_matrix, factor, letter_matrix)
    if not contradictions:
        raise AssertionError("no positive descendant-count contradiction")

    cache_key = (value_key(prefix), value_key(letter))
    if cache_key not in cache:
        generators = (
            prefix,
            letter,
            leavitt_star(prefix),
            leavitt_star(letter),
        )
        targets = [cylinder_projection(leaf) for leaf in BASE_CODE]
        pool = monomial_pool(generators, 7)
        identities, ambient_dimension, generated_rank = span_certificates(
            pool, targets)
        verify_projection_identities(generators, identities, targets)
        cache[cache_key] = {
            "ambient_expansion_terms": ambient_dimension,
            "generated_span_rank": generated_rank,
            "maximum_identity_depth": max(
                len(word) for identity in identities for word in identity),
            "projection_identities": {
                leaf: [
                    "1" if not word else " ".join(
                        GENERATOR_NAMES[index] for index in word)
                    for word in identity
                ]
                for leaf, identity in zip(BASE_CODE, identities)
            },
        }
    return {
        "prefix_length": prefix_length,
        "prefix_support_components": [
            [BASE_CODE[index] for index in component]
            for component in prefix_components
        ],
        "positive_cardinality_contradictions": contradictions,
        **cache[cache_key],
    }


def main():
    results = []
    cache = {}
    for boundary_index, representative in survivor_representatives():
        hard_lookup = {
            (inverted, rotation): prefix_length
            for inverted, rotation, prefix_length in HARD_CASES[boundary_index]
        }
        orientations = []
        for inverted, rotation, word in oriented_rotations(representative):
            pair_obstruction = cardinality_obstruction(word[:2])
            if pair_obstruction["positive_cardinality_obstruction_rows"]:
                orientations.append({
                    "inverted": inverted,
                    "rotation": rotation,
                    "method": "first-two-letter-cardinality-obstruction",
                    "obstruction": pair_obstruction,
                })
                continue
            prefix_length = hard_lookup.get((inverted, rotation))
            if prefix_length is None:
                raise AssertionError("unclassified orientation")
            orientations.append({
                "inverted": inverted,
                "rotation": rotation,
                "method": "generated-projections-and-cardinality",
                **hard_case_certificate(word, prefix_length, cache),
            })
        if len(orientations) != 16:
            raise AssertionError("a length-eight relator needs 16 orientations")
        results.append({
            "boundary_index": boundary_index,
            "orientations": orientations,
        })

    print(json.dumps({
        "base_code": BASE_CODE,
        "central_class_representatives": [11, 30],
        "distinct_hard_prefix_pairs": len(cache),
        "all_orientations_obstructed": True,
        "results": results,
    }, indent=2))


if __name__ == "__main__":
    main()
