"""Certify an all-depth obstruction to scalar prefix-chart galleries.

The four radius-five atlas survivors form two genuine central classes.  For
each orientation of one representative from either class, a sequential
prefix gallery would need a scalar chart containing a running prefix ``q``
and the next letter ``l``.  This script proves that no such chart exists.

Most orientations already fail the positive-cardinality test for their first
two letters.  In each of the remaining orientations, exact arithmetic in the
binary Leavitt algebra proves that the star-algebra generated by ``q`` and
``l`` contains the six cylinder projections for

    D = (000, 001, 010, 011, 10, 11).

Consequently, any hypothetical scalar chart containing ``q`` and ``l`` must
refine D.  The support of q identifies the descendant codes below
``000,010,10`` and below ``001,011,11``.  The support of l then forces the
positive cardinality of the second class to be zero, a contradiction.

The output contains finite identities expressing every D-cylinder projection
as an F_2-linear combination of words in ``q,l,q*,l*``.  Thus the result is an
exact certificate, not a bounded chart enumeration.
"""

