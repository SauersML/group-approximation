"""Search for S-good periodic orders on the Hantzsche-Wendt (Promislow) group.

The group P is generated by the affine maps a(x) = diag(1,-1,-1)x + (1/2,1/2,0)
and b(x) = diag(-1,1,-1)x + (0,1/2,1/2) of R^3.  It is torsion-free and not
left-orderable.  For generic v, p in R^3 put H(g) = <v, g(p)> and order P by H.
The order is invariant under left translation by the translation lattice L, so
averaging over P/L gives an invariant random order.

For a finite S in P the random-order Jensen bound is nontrivial exactly when
N(g) = #{s in S : g = argmin_H (g s^{-1} S)} equals 1 for every g.  Because
H(beta s) = <A_beta v, s(p)> + <v, t_beta>, N depends only on the linear part
of g, so it suffices to check g in the four cosets.  We check it on the four
coset representatives and, as a sanity check, on a ball of the group.
"""
import itertools, random
from fractions import Fraction as Fr

def mul(g, h):
    A, t = g; B, u = h
    return (tuple(A[i]*B[i] for i in range(3)), tuple(A[i]*u[i] + t[i] for i in range(3)))

def inv(g):
    A, t = g
    return (A, tuple(-A[i]*t[i] for i in range(3)))

E = ((1,1,1), (Fr(0),Fr(0),Fr(0)))
a = ((1,-1,-1), (Fr(1,2),Fr(1,2),Fr(0)))
b = ((-1,1,-1), (Fr(0),Fr(1,2),Fr(1,2)))

def act(g, p):
    A, t = g
    return tuple(A[i]*p[i] + float(t[i]) for i in range(3))

def H(g, v, p):
    q = act(g, p)
    return sum(v[i]*q[i] for i in range(3))

def N(g, S, v, p):
    cnt = 0
    for s in S:
        beta = mul(g, inv(s))
        tr = [mul(beta, x) for x in S]
        m = min(tr, key=lambda h: H(h, v, p))
        if m == g:
            cnt += 1
    return cnt

def ball(gens, r):
    B = {E}
    frontier = {E}
    for _ in range(r):
        new = set()
        for g in frontier:
            for s in gens:
                h = mul(g, s)
                if h not in B:
                    new.add(h)
        B |= new
        frontier = new
    return B

def search(S, trials=20000, seed=1):
    rng = random.Random(seed)
    reps = [E, a, b, mul(a, b)]
    good = []
    for _ in range(trials):
        v = [rng.gauss(0,1) for _ in range(3)]
        p = [rng.gauss(0,1) for _ in range(3)]
        if all(N(g, S, v, p) == 1 for g in reps):
            good.append((v, p))
            if len(good) >= 3:
                break
    return good

if __name__ == "__main__":
    gens = [a, b, inv(a), inv(b)]
    Ball2 = sorted(ball(gens, 2), key=str)
    tests = {
        "S={e,a,b}": [E, a, b],
        "S={e,a}": [E, a],
        "S={e,a,b,ab}": [E, a, b, mul(a,b)],
        "S={e,a,b,a^-1b}": [E, a, b, mul(inv(a),b)],
    }
    # also all 3- and 4-element subsets of the radius-1 ball containing e
    B1 = sorted(ball(gens, 1), key=str)
    for k in (3, 4):
        for sub in itertools.combinations([x for x in B1 if x != E], k-1):
            tests["ball1 subset %s" % (len(tests),)] = [E] + list(sub)
    summary = {}
    for name, S in tests.items():
        good = search(S, trials=3000)
        ok_ball = None
        if good:
            v, p = good[0]
            ok_ball = all(N(g, S, v, p) == 1 for g in Ball2)
        summary[name] = (len(good) > 0, ok_ball)
        if not name.startswith("ball1") or good:
            print(name, "S-good order found:", len(good) > 0, "ball check:", ok_ball,
                  "example v,p:", [round(x,3) for x in good[0][0]] + [round(x,3) for x in good[0][1]] if good else None)
    n_sub = sum(1 for k in summary if k.startswith("ball1"))
    n_good = sum(1 for k, (g, _) in summary.items() if k.startswith("ball1") and g)
    print("radius-1 subsets tested:", n_sub, "with an S-good periodic order:", n_good)


def exact_check():
    """Exact rational re-check for S = {e,a,b} with rational heights."""
    S = [E, a, b]
    def Hq(g, v, p):
        A, t = g
        return sum(v[i]*(A[i]*p[i] + t[i]) for i in range(3))
    def Nq(g, v, p):
        cnt = 0
        for s in S:
            beta = mul(g, inv(s))
            tr = [mul(beta, x) for x in S]
            vals = [Hq(h, v, p) for h in tr]
            assert len(set(vals)) == len(vals), "tie"
            m = tr[vals.index(min(vals))]
            if m == g:
                cnt += 1
        return cnt
    rng = random.Random(7)
    for _ in range(5000):
        v = [Fr(rng.randint(-50, 50), 17) for _ in range(3)]
        p = [Fr(rng.randint(-50, 50), 19) for _ in range(3)]
        try:
            if all(Nq(g, v, p) == 1 for g in [E, a, b, mul(a, b)]):
                gens = [a, b, inv(a), inv(b)]
                B3 = ball(gens, 3)
                ok = all(Nq(g, v, p) == 1 for g in B3)
                return v, p, ok, len(B3)
        except AssertionError:
            continue
    return None

if __name__ == "__main__":
    res = exact_check()
    print("exact rational S={e,a,b} example (v, p, all N=1 on radius-3 ball, ball size):",
          None if res is None else ([str(x) for x in res[0]], [str(x) for x in res[1]], res[2], res[3]))
