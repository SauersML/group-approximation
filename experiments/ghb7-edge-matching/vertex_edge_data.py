#!/usr/bin/env python3
"""Exact vertex/edge data for the GHB_2(7) triangle via the CCKW quotient psi into SL_4(F_7).

psi: a -> I + E_03 + E_12,  b -> I + E_10 - E_23,  c -> I + E_31  (0-indexed E_ij).
psi is injective on the vertex groups <a,b>, <c,b>, <c,a> (cckw-ghb2-kms-group-structure item 5),
so the matrix groups generated below ARE the vertex groups X_0, X_1, X_2.

For each vertex group X with edge generators x, y we compute:
  |X|, the derived subgroup [X,X], |X^ab|, whether x,y map to a basis of X^ab = (Z/7)^2,
  the number of conjugacy classes, and |C_X(x^j)|, |C_X(y^j)| for j = 1..6.
Column orthogonality: sum_chi |chi(g)|^2 = |C_X(g)|.  Linear characters contribute |X^ab| to
this sum (|chi(g)| = 1).  So every nonlinear irreducible character vanishes at g iff
|C_X(g)| = |X^ab|.
"""
import itertools, json, sys
P = 7
N = 4

def mat_id():
    return tuple(tuple(1 if i == j else 0 for j in range(N)) for i in range(N))

def E(i, j, s=1):
    return tuple(tuple((s if (r, c) == (i, j) else 0) for c in range(N)) for r in range(N))

def add(A, B):
    return tuple(tuple((A[r][c] + B[r][c]) % P for c in range(N)) for r in range(N))

def mul(A, B):
    return tuple(tuple(sum(A[r][k] * B[k][c] for k in range(N)) % P for c in range(N)) for r in range(N))

I4 = mat_id()
a = add(add(I4, E(0, 3)), E(1, 2))
b = add(add(I4, E(1, 0)), E(2, 3, -1 % P))
c = add(I4, E(3, 1))

def inverse_by_power(A):
    # elements of p-groups here have order dividing 7^k; find inverse by repeated multiplication
    B = A
    prev = I4
    while True:
        nxt = mul(B, A)
        if nxt == I4:
            return B
        prev = B
        B = nxt
        if B == A:
            raise RuntimeError("no inverse found")

def closure(gens):
    seen = {I4}
    frontier = [I4]
    while frontier:
        new = []
        for g in frontier:
            for s in gens:
                h = mul(g, s)
                if h not in seen:
                    seen.add(h)
                    new.append(h)
        frontier = new
    return seen

def order(A):
    k, B = 1, A
    while B != I4:
        B = mul(B, A)
        k += 1
    return k

def comm(x, y, inv):
    return mul(mul(inv[x], inv[y]), mul(x, y))

def analyze(name, x, xname, y, yname):
    X = closure([x, y])
    inv = {g: inverse_by_power(g) if g != I4 else I4 for g in X}
    elems = list(X)
    # derived subgroup: closure of all commutators
    comms = {comm(g, h, inv) for g in elems for h in [x, y]}
    D = closure(list(comms))
    # D generated by commutators of generators and conjugates; for safety close under conjugation
    changed = True
    while changed:
        changed = False
        extra = set()
        for g in [x, y, inv[x], inv[y]]:
            for d in list(D):
                e = mul(mul(g, d), inv[g])
                if e not in D:
                    extra.add(e)
        if extra:
            D = closure(list(D | extra))
            changed = True
    ab_order = len(X) // len(D)
    # do x^i y^j (0<=i,j<7) give 49 distinct cosets of D?
    powx = [I4]
    powy = [I4]
    for _ in range(P - 1):
        powx.append(mul(powx[-1], x))
        powy.append(mul(powy[-1], y))
    cosets = set()
    for i in range(P):
        for j in range(P):
            g = mul(powx[i], powy[j])
            rep = min(mul(g, d) for d in D)
            cosets.add(rep)
    basis_ok = (len(cosets) == P * P) and ab_order == P * P
    # conjugacy classes
    remaining = set(elems)
    nclasses = 0
    while remaining:
        g = remaining.pop()
        cls = {mul(mul(h, g), inv[h]) for h in elems}
        remaining -= cls
        nclasses += 1
    def centralizer_order(g):
        return sum(1 for h in elems if mul(h, g) == mul(g, h))
    cx = [centralizer_order(powx[j]) for j in range(1, P)]
    cy = [centralizer_order(powy[j]) for j in range(1, P)]
    res = {
        "vertex": name,
        "order": len(X),
        "edge_generators": [xname, yname],
        "order_of_generators": [order(x), order(y)],
        "derived_subgroup_order": len(D),
        "abelianization_order": ab_order,
        "edge_generators_basis_of_abelianization": basis_ok,
        "conjugacy_classes": nclasses,
        "centralizer_orders_" + xname: cx,
        "centralizer_orders_" + yname: cy,
        "nonlinear_irreps_vanish_on_edge_powers": all(v == ab_order for v in cx + cy),
    }
    return res

out = [
    analyze("X_0=<a,b>", a, "a", b, "b"),
    analyze("X_1=<c,b>", c, "c", b, "b"),
    analyze("X_2=<c,a>", c, "c", a, "a"),
]
print(json.dumps(out, indent=1))
print("DONE")
