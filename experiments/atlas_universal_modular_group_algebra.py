"""Test the universal F2[A8] identity behind the atlas phase screens.

At the inner order-zero alignment, the right-trivialized derivative of every
boundary word acts on any rectangular Hom block through the diagonal A8
action.  It is therefore represented by one element d_w of F2[A8].  The
certified-zero equations contribute d_w, while centrality of a survivor s
contributes (g+1)d_s for generators g of A8.  If d_11 belongs to the left
ideal generated by those elements, then every F2[A8]-module satisfies the
same first-order no-go, including all indecomposables.

The verifier constructs that left ideal by closing an exact bitset row space
under the six generating left translations.  It stops as soon as d_11 lies
in the current space, so a positive result need not construct the entire
ideal.
"""

import argparse
from collections import deque
import hashlib
import json
from pathlib import Path
import sys
import time

import numpy as np

from atlas_boundary_inner_alignment import enumerate_gl4
from atlas_certified_a8_alignment import (
    CERTIFIED_REPRESENTATIVE_INDICES,
    PHASE_INDEX,
    boundary_words,
)
from atlas_certified_dual_number_certificate import ALIGNMENT_KEY
from atlas_subset_dual_central_no_go import SURVIVOR_REPRESENTATIVES
from atlas_two_chart_search import (
    I4,
    factor_generators,
    gf2_inv,
    gf2_mul,
    matrix_key,
)


BYTE_POPCOUNT = np.asarray([
    bin(value).count("1") for value in range(256)
], dtype=np.uint8)


def population_count(row, byte_width=None):
    if byte_width is None:
        byte_width = max(1, (row.bit_length() + 7) // 8)
    packed = row.to_bytes(byte_width, byteorder="little")
    return int(BYTE_POPCOUNT[
        np.frombuffer(packed, dtype=np.uint8)
    ].sum())


def insert_row(basis, row):
    reductions = []
    while row:
        pivot = row.bit_length() - 1
        entry = basis.get(pivot)
        if entry is None:
            return row, reductions
        other, row_id = entry
        row ^= other
        reductions.append(row_id)
    return 0, reductions


def reduce_row(basis, row):
    reductions = []
    while row:
        pivot = row.bit_length() - 1
        entry = basis.get(pivot)
        if entry is None:
            return row, reductions
        other, row_id = entry
        row ^= other
        reductions.append(row_id)
    return 0, reductions


def aligned_derivative(word, alignment, alignment_inverse, index_by_key):
    prefix = I4.copy()
    support = set()
    for factor, matrix in word:
        image = matrix
        if factor == 2:
            image = gf2_mul(gf2_mul(
                alignment, image
            ), alignment_inverse)
            support.symmetric_difference_update((
                index_by_key[matrix_key(prefix)],
            ))
        prefix = gf2_mul(prefix, image)
        if factor == 2:
            support.symmetric_difference_update((
                index_by_key[matrix_key(prefix)],
            ))
    if matrix_key(prefix) != matrix_key(I4):
        raise AssertionError("inner alignment stopped killing a selected word")
    result = 0
    for index in support:
        result |= 1 << index
    return result


class LeftTranslations:
    def __init__(self, permutations, dimension):
        self.permutations = tuple(
            np.asarray(permutation, dtype=np.int32)
            for permutation in permutations
        )
        self.dimension = dimension
        self.byte_width = (dimension + 7) // 8

    def all_images(self, row):
        weight = population_count(row, self.byte_width)
        if weight <= 256:
            images = [0] * len(self.permutations)
            remaining = row
            while remaining:
                bit = remaining & -remaining
                source = bit.bit_length() - 1
                for index, permutation in enumerate(self.permutations):
                    images[index] |= 1 << int(permutation[source])
                remaining ^= bit
            return images

        packed = row.to_bytes(self.byte_width, byteorder="little")
        bits = np.unpackbits(
            np.frombuffer(packed, dtype=np.uint8), bitorder="little"
        )[:self.dimension]
        images = []
        target = np.empty(self.dimension, dtype=np.uint8)
        for permutation in self.permutations:
            target[permutation] = bits
            repacked = np.packbits(target, bitorder="little")
            images.append(int.from_bytes(
                repacked.tobytes(), byteorder="little"
            ))
        return images


def basis_digest(basis, byte_width):
    digest = hashlib.sha256()
    for pivot in sorted(basis):
        row, row_id = basis[pivot]
        digest.update(pivot.to_bytes(4, byteorder="little"))
        digest.update(row_id.to_bytes(4, byteorder="little"))
        digest.update(row.to_bytes(byte_width, byteorder="little"))
    return digest.hexdigest()


def represented_group_algebra_rows(element, group_elements):
    operator = np.zeros((16, 16), dtype=np.uint8)
    remaining = element
    while remaining:
        bit = remaining & -remaining
        index = bit.bit_length() - 1
        matrix = group_elements[index]
        operator ^= np.kron(matrix, gf2_inv(matrix).T).astype(np.uint8)
        remaining ^= bit
    packed = np.packbits(operator, axis=1, bitorder="little")
    return [
        int.from_bytes(row.tobytes(), byteorder="little")
        for row in packed
    ]


def direct_natural_derivative_rows(word, alignment, alignment_inverse):
    prefix = I4.copy()
    terms = []
    for factor, matrix in word:
        image = matrix
        if factor == 2:
            image = gf2_mul(gf2_mul(
                alignment, image
            ), alignment_inverse)
        before = prefix
        prefix = gf2_mul(prefix, image)
        if factor == 2:
            terms.extend((before, prefix))
    if matrix_key(prefix) != matrix_key(I4):
        raise AssertionError("natural base word is not identity")

    operator = np.zeros((16, 16), dtype=np.uint8)
    for term in terms:
        operator ^= np.kron(term, gf2_inv(term).T).astype(np.uint8)
    packed = np.packbits(operator, axis=1, bitorder="little")
    return [
        int.from_bytes(row.tobytes(), byteorder="little")
        for row in packed
    ]


def verify_derivation(operations, phase_ids, seeds, translations, phase):
    rows = []
    pivots = set()
    for expected_id, operation in enumerate(operations):
        source = operation["source"]
        if source[0] == "seed":
            row = seeds[source[1]]
        elif source[0] == "translate":
            _kind, generator_index, parent_id = source
            if parent_id >= expected_id:
                raise AssertionError("translation points forward in certificate")
            row = translations.all_images(rows[parent_id])[generator_index]
        else:
            raise AssertionError("unknown certificate source")
        for row_id in operation["xor_basis_ids"]:
            if row_id >= expected_id:
                raise AssertionError("reduction points forward in certificate")
            row ^= rows[row_id]
        if not row:
            raise AssertionError("certificate inserts a zero row")
        pivot = row.bit_length() - 1
        if pivot != operation["pivot"] or pivot in pivots:
            raise AssertionError("certificate pivot is invalid")
        pivots.add(pivot)
        rows.append(row)

    remainder = phase
    for row_id in phase_ids:
        if row_id >= len(rows):
            raise AssertionError("phase reduction uses an unknown row")
        remainder ^= rows[row_id]
    if remainder:
        raise AssertionError("certificate does not reduce the phase to zero")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--max-seconds", type=float, default=120.0)
    parser.add_argument("--report-every", type=int, default=250)
    parser.add_argument("--certificate")
    parser.add_argument("--verify-certificate")
    args = parser.parse_args()
    started = time.monotonic()

    elements = list(enumerate_gl4())
    if len(elements) != 20160:
        raise AssertionError("GL(4,2) enumeration changed")
    index_by_key = {
        matrix_key(element): index for index, element in enumerate(elements)
    }
    generators = [
        word[0][1] for _name, word in factor_generators()[:6]
    ]
    permutations = []
    for generator in generators:
        permutations.append([
            index_by_key[matrix_key(gf2_mul(generator, element))]
            for element in elements
        ])
    translations = LeftTranslations(permutations, len(elements))

    alignment = np.frombuffer(
        bytes.fromhex(ALIGNMENT_KEY), dtype=np.uint8
    ).reshape(4, 4)
    alignment_inverse = gf2_inv(alignment)
    words = boundary_words()
    selected = sorted(set(
        CERTIFIED_REPRESENTATIVE_INDICES
        + SURVIVOR_REPRESENTATIVES
        + (PHASE_INDEX,)
    ))
    derivatives = {
        index: aligned_derivative(
            words[index], alignment, alignment_inverse, index_by_key
        )
        for index in selected
    }
    for index in selected:
        if represented_group_algebra_rows(
                derivatives[index], elements
        ) != direct_natural_derivative_rows(
                words[index], alignment, alignment_inverse
        ):
            raise AssertionError(
                "group-algebra derivative disagrees with direct matrix "
                "derivative at boundary index %d" % index
            )

    seeds = [
        derivatives[index]
        for index in CERTIFIED_REPRESENTATIVE_INDICES
    ]
    for index in SURVIVOR_REPRESENTATIVES:
        derivative = derivatives[index]
        for generator_image in translations.all_images(derivative):
            seeds.append(generator_image ^ derivative)

    if args.verify_certificate:
        certificate_text = Path(args.verify_certificate).read_text()
        certificate = json.loads(certificate_text)
        if certificate.get("format") != "atlas-f2-a8-left-ideal-dag-v1":
            raise AssertionError("unknown certificate format")
        if certificate.get("group_order") != len(elements):
            raise AssertionError("certificate group order changed")
        if certificate.get("seed_rows") != len(seeds):
            raise AssertionError("certificate seed count changed")
        verify_derivation(
            certificate["basis_operations"],
            certificate["phase_reduction_basis_ids"],
            seeds,
            translations,
            derivatives[PHASE_INDEX],
        )
        print(json.dumps({
            "certificate_verified": True,
            "certificate_sha256": hashlib.sha256(
                certificate_text.encode("utf-8")
            ).hexdigest(),
            "basis_operations": len(certificate["basis_operations"]),
            "phase_reductions": len(
                certificate["phase_reduction_basis_ids"]
            ),
            "elapsed_seconds": round(time.monotonic() - started, 3),
        }, indent=2))
        return

    basis = {}
    basis_rows = []
    operations = []
    queue = deque()
    for seed_index, seed in enumerate(seeds):
        residual, reductions = insert_row(basis, seed)
        if residual:
            row_id = len(basis_rows)
            pivot = residual.bit_length() - 1
            basis[pivot] = (residual, row_id)
            basis_rows.append(residual)
            operations.append({
                "source": ["seed", seed_index],
                "xor_basis_ids": reductions,
                "pivot": pivot,
            })
            queue.append(row_id)

    phase = derivatives[PHASE_INDEX]
    phase_remainder, phase_reduction_ids = reduce_row(basis, phase)
    translations_processed = 0
    timed_out = False
    while phase_remainder and queue:
        if time.monotonic() - started > args.max_seconds:
            timed_out = True
            break
        parent_id = queue.popleft()
        parent = basis_rows[parent_id]
        for generator_index, image in enumerate(
                translations.all_images(parent)):
            translations_processed += 1
            residual, reductions = insert_row(basis, image)
            if residual:
                row_id = len(basis_rows)
                pivot = residual.bit_length() - 1
                basis[pivot] = (residual, row_id)
                basis_rows.append(residual)
                operations.append({
                    "source": [
                        "translate", generator_index, parent_id
                    ],
                    "xor_basis_ids": reductions,
                    "pivot": pivot,
                })
                queue.append(row_id)
                phase_remainder, phase_reductions = reduce_row(
                    basis, phase_remainder
                )
                phase_reduction_ids.extend(phase_reductions)
                if len(basis) % args.report_every == 0:
                    print(json.dumps({
                        "event": "progress",
                        "rank": len(basis),
                        "queue": len(queue),
                        "phase_remainder_weight":
                            population_count(
                                phase_remainder, translations.byte_width
                            ),
                        "elapsed_seconds": round(
                            time.monotonic() - started, 3
                        ),
                    }), file=sys.stderr, flush=True)
                    if not phase_remainder:
                        break
        if not phase_remainder:
            break
    check_remainder, check_reductions = reduce_row(basis, phase)
    if check_remainder != phase_remainder:
        raise AssertionError("incremental phase reduction changed remainder")
    if not phase_remainder:
        replay = phase
        for row_id in phase_reduction_ids:
            replay ^= basis_rows[row_id]
        if replay:
            raise AssertionError("recorded phase reduction does not replay")

    certificate_sha256 = None
    if args.certificate:
        certificate = {
            "format": "atlas-f2-a8-left-ideal-dag-v1",
            "group_order": len(elements),
            "seed_rows": len(seeds),
            "basis_operations": operations,
            "phase_reduction_basis_ids": phase_reduction_ids,
        }
        verify_derivation(
            operations,
            phase_reduction_ids,
            seeds,
            translations,
            phase,
        )
        certificate_text = json.dumps(
            certificate, sort_keys=True, separators=(",", ":")
        ) + "\n"
        certificate_sha256 = hashlib.sha256(
            certificate_text.encode("utf-8")
        ).hexdigest()
        Path(args.certificate).write_text(certificate_text)

    print(json.dumps({
        "coefficient_field": "F2",
        "group": "GL(4,2) ~= A8",
        "group_order": len(elements),
        "certified_zero_derivatives":
            len(CERTIFIED_REPRESENTATIVE_INDICES),
        "central_survivors": list(SURVIVOR_REPRESENTATIVES),
        "centrality_generators": len(generators),
        "seed_rows": len(seeds),
        "derivative_support_sizes": {
            str(index): population_count(derivatives[index])
            for index in selected
        },
        "left_ideal_rank_reached": len(basis),
        "queued_rows_remaining": len(queue),
        "left_translations_processed": translations_processed,
        "phase_remainder_weight": population_count(
            phase_remainder, translations.byte_width
        ),
        "phase_in_generated_left_ideal": phase_remainder == 0,
        "timed_out": timed_out,
        "basis_sha256": basis_digest(basis, translations.byte_width),
        "certificate_sha256": certificate_sha256,
        "certificate_basis_operations": len(operations),
        "certificate_phase_reductions": len(phase_reduction_ids),
        "certificate_max_row_reductions": max(
            len(operation["xor_basis_ids"])
            for operation in operations
        ),
        "independent_phase_reduction_length": len(check_reductions),
        "elapsed_seconds": round(time.monotonic() - started, 3),
    }, indent=2))


if __name__ == "__main__":
    main()
