"""Common quotient of two I_2(5) shadows.

For a fibred I_2(5) flat V, rho_V : P -> G_V = pi_1 M(C'_V) is induced by the inclusion M(A) in M(C'_V),
where C'_V (16 walls) = 6 fibre walls + 10 collision walls (h4-i25-fibred-shadows-are-rigid-cluster-braid-groups).
Its kernel K_V is normally generated by the meridians of the 44 walls outside C'_V.  Hence
    K_V K_V' = normal closure of the meridians of the walls outside C_0 := C'_V cap C'_V',
    P / (K_V K_V') = pi_1 M(C_0),
and (rho_V, rho_V') has image G_V x_{pi_1 M(C_0)} G_V' (fibre product).
This script lists C'_V for the three flats, labels each wall (fibre p_i / fibre q / A_z / A_x-A_z), and
prints C_0 for each pair and for all three, and whether C_0 lies in A' = A_x u A_y.
Run: python3 common.py > common.log   (numpy; needs fibred.py of ../h4-case1-fibred-quotient-2026-09-17)."""
import itertools, os, sys
import numpy as np
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'h4-case1-fibred-quotient-2026-09-17'))
from fibred import setup, through, walls, is_wall

n, sim, W, om = setup('H4'); x = om[0]; y = om[3]
Ax = through(W, [x]); Ay = through(W, [y]); Az = through(W, [x, y])
Ap = walls(Ax + Ay); Ayz = [w for w in Ay if not is_wall(w, Az)]; Axz = [w for w in Ax if not is_wall(w, Az)]


def idx(v):
    v = v / np.linalg.norm(v)
    for k, w in enumerate(W):
        if abs(abs(np.dot(v, w)) - 1) < 1e-9:
            return k
    return None


def name(k):
    w = W[k]
    if is_wall(w, Az):
        return 'z%d' % [idx(u) for u in Az].index(k)
    if is_wall(w, Ayz):
        return 'p%d' % ([idx(u) for u in Ayz].index(k) + 1)
    if is_wall(w, Axz):
        return 'x%d' % [idx(u) for u in Axz].index(k)
    return 'o%d' % k


flats = []
for w1 in Ayz:
    for w2 in Axz:
        B2 = np.array([w1, w2]); Pr = B2.T @ np.linalg.pinv(B2.T)
        AV = [w for w in W if np.linalg.norm(Pr @ w - w) < 1e-9]
        if len(AV) != 5:
            continue
        B = walls(Ap + AV)
        fib = [w for w in B if abs(np.dot(w, x)) > 1e-9]
        good = all(is_wall(np.dot(v, x) * u - np.dot(u, x) * v, Ax) for u, v in itertools.combinations(fib, 2))
        key = frozenset(idx(w) for w in AV)
        if good and key not in [f[0] for f in flats]:
            flats.append((key, fib))

C = []
for AV, fib in flats:
    coll = set(idx(np.dot(v, x) * u - np.dot(u, x) * v) for u, v in itertools.combinations(fib, 2))
    C.append(set(idx(f) for f in fib) | coll)


def main():
    for k, (AV, fib) in enumerate(flats):
        fibi = [idx(f) for f in fib]
        coll = set()
        for u, v in itertools.combinations(fib, 2):
            coll.add(idx(np.dot(v, x) * u - np.dot(u, x) * v))
        Cv = set(fibi) | coll
        print('V%d: walls of V %s' % (k, sorted(name(i) for i in AV)))
        print('    fibre walls %s' % sorted(name(i) for i in fibi))
        print('    collision walls %s' % sorted(name(i) for i in coll))
        print('    |C\'_V| = %d' % len(Cv))
    Api = {idx(w) for w in Ap}
    for i, j in itertools.combinations(range(len(C)), 2):
        C0 = C[i] & C[j]
        print('C_0(V%d,V%d) = %s  (%d walls; inside A_x u A_y: %s)' % (i, j, sorted(name(k) for k in C0), len(C0), C0 <= Api))
        print('    only in V%d: %s ; only in V%d: %s' % (i, sorted(name(k) for k in C[i] - C[j]), j, sorted(name(k) for k in C[j] - C[i])))
    C0 = C[0] & C[1] & C[2]
    print('C_0(all) = %s (%d walls)' % (sorted(name(k) for k in C0), len(C0)))

    # pairs of fibre points from different flats: where do they collide?
    print()
    for i, j in itertools.combinations(range(len(flats)), 2):
        fi = [idx(f) for f in flats[i][1]]; fj = [idx(f) for f in flats[j][1]]
        for a in fi:
            for b in fj:
                if a in fj or b in fi:
                    continue
                u, v = W[a], W[b]
                nv = np.dot(v, x) * u - np.dot(u, x) * v
                k = idx(nv)
                print('V%d q %s  x  V%d q %s : collide on %s' % (i, name(a), j, name(b),
                      name(k) + (' (A_x)' if k is not None and is_wall(W[k], Ax) else '') if k is not None else 'NON-WALL'))


if __name__ == '__main__':
    main()
