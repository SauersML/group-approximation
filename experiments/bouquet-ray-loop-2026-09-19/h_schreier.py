#!/usr/bin/env python3
"""Infinite-order certificates for H = <S, T> through vertex stabilisers.

For y != z let K_y = Stab_H(y).  Then k -> k|_y is a homomorphism K_y -> B with
(k^n)|_y = (k|_y)^n, so an element of infinite order among the y-sections of K_y is the
y-section of an element of H of infinite order, and H is infinite.  K_y is generated by the
Schreier generators r_x g r_{x^g}^{-1} (g in {S, T}, r_x coset words from a BFS on the
root action of <sigma, tau>).  The script tests their y-sections u_i, the products u_i u_j^{+-1}
and the commutators [u_i, u_j] with the power-section-graph certificate of same_point_screen.
Usage: python3 h_schreier.py NAMEFILE > h_schreier.out
"""
import sys, itertools
from bouquets import bouquets
from loopgraph import reduce, inv, fmt, N
from same_point_screen import infinite_order

def schreier_sections(R, I, y):
    gens = {"S": I["S"], "T": I["T"]}; perm = {"S": I["sigma"], "T": I["tau"]}
    rep = {y: ()}; todo = [y]
    while todo:
        x = todo.pop(0)
        for g in "ST":
            for e in (1, -1):
                q = perm[g][x] if e == 1 else list(perm[g]).index(x)
                if q not in rep:
                    rep[q] = reduce(rep[x] + (gens[g] if e == 1 else inv(gens[g]))); todo.append(q)
    out = set()
    for x in rep:
        for g in "ST":
            w = reduce(rep[x] + gens[g] + inv(rep[perm[g][x]]))
            u = reduce(R.sec(w, y))
            if u: out.add(u)
    return sorted(out, key=len)

def certify(R, I):
    for y in range(N):
        if y == I["z"]: continue
        us = schreier_sections(R, I, y)
        cands = [(f"u{i}", u) for i, u in enumerate(us)]
        for (i, a), (j, b) in itertools.combinations(list(enumerate(us)), 2):
            cands += [(f"u{i}u{j}", reduce(a + b)), (f"u{i}U{j}", reduce(a + inv(b))),
                      (f"[u{i},u{j}]", reduce(inv(a) + inv(b) + a + b))]
        for lab, u in cands:
            if not u: continue
            c = infinite_order(R, u)
            if c: return f"infinite: y = {y}, {lab} = {fmt(u)} has infinite order, certificate {c}"
    return "undecided"

if __name__ == "__main__":
    want = [l.strip() for l in open(sys.argv[1]) if l.strip()]
    cases = {name: (R, I) for name, R, I in bouquets() if name in set(want)}
    for name in want:
        if name in cases: print(name, "|", certify(*cases[name]), flush=True)
