# parse_targets.py -- lane hl-hyperbolic-rf-2, 2026-09-14.
# From a Caprace-Conder-Kaluba-Witzel table source (arXiv:2011.09276, table_*.tex) extract, for each
# group named in <names file>, the finite simple quotients CCKW list (L_2-quotients column and "Small
# quotients" column) as GAP constructor strings. Magma's infinite-family entries L_2(\infty^k) have no
# finite target list; they are skipped and recorded as comments in the output.
# Usage: python3.12 parse_targets.py <table.tex> <names> <out.g>
import math, re, sys

ROW = re.compile(r"\$G_\{?(\d+)\}?\^\{(\d+),(\d+),(\d+)\}\$\s*&\s*\$(\d+)\$\s*&\s*(\S+)\s*&\s*(\S+)\s*&"
                 r"\s*(\d+)\s*&(.*?)&(.*?)&")
SKIPPED = []

def conv(seg):
    s = seg.replace("\\textrm", "").replace("{", "").replace("}", "").replace(" ", "")
    if s.startswith("\\times"):
        return []
    if "\\infty" in s:
        SKIPPED.append(seg)
        return []
    m = re.fullmatch(r"Alt_(\d+)", s)
    if m: return ["AlternatingGroup(%s)" % m.group(1)]
    m = re.fullmatch(r"\^2A_(\d+)\((\d+)\)", s)
    if m:
        n, q = int(m.group(1)), int(m.group(2)); r = math.isqrt(q)
        if r * r != q: raise ValueError("unitary field size not a square: %r" % seg)
        return ["PSU(%d,%d)" % (n + 1, r)]
    m = re.fullmatch(r"A_(\d+)\((\d+)\)", s)
    if m: return ["PSL(%d,%s)" % (int(m.group(1)) + 1, m.group(2))]
    m = re.fullmatch(r"[BC]_(\d+)\((\d+)\)", s)
    if m: return ["PSp(%d,%s)" % (2 * int(m.group(1)), m.group(2))]
    m = re.fullmatch(r"G_2\((\d+)\)", s)
    if m: return ['SimpleGroup("G2(%s)")' % m.group(1)]
    m = re.fullmatch(r"M_(\d+)", s)
    if m: return ["MathieuGroup(%s)" % m.group(1)]
    m = re.fullmatch(r"J_(\d+)", s)
    if m: return ['SimpleGroup("J%s")' % m.group(1)]
    if s in ("HS_", "HS"): return ['SimpleGroup("HS")']
    if s.startswith("^2F_4(2)"): return ['SimpleGroup("2F4(2)\'")']
    m = re.fullmatch(r"L_2\((\d+)(?:\^(\d+))?\)", s)
    if m:
        q = int(m.group(1)) ** (int(m.group(2)) if m.group(2) else 1)
        return ["PSL(2,%d)" % q]
    raise ValueError("unrecognised quotient %r" % seg)

tab = open(sys.argv[1]).read()
names = [l.strip() for l in open(sys.argv[2]) if l.strip()]
recs, skipped = {}, {}
for r in ROW.findall(tab):
    key = "G_%s^{%s,%s,%s}" % (r[0], r[1], r[2], r[3])
    targets = []
    del SKIPPED[:]
    for col in (r[8], r[9]):
        for seg in re.findall(r"\$(.*?)\$", col):
            for t in conv(seg):
                if t not in targets: targets.append(t)
    recs[key] = targets
    skipped[key] = list(SKIPPED)
with open(sys.argv[3], "w") as f:
    f.write("# generated by parse_targets.py from %s (arXiv:2011.09276 source)\n" % sys.argv[1].split("/")[-1])
    for n in names:
        if skipped[n]:
            f.write("# %s: skipped infinite-family entries %s\n" % (n, ", ".join(skipped[n])))
    f.write("TARGETS := [\n")
    for n in names:
        f.write('  rec(name := "%s", targets := [%s]),\n' % (n, ", ".join('"%s"' % t.replace('"', '\\"') for t in recs[n])))
    f.write("];\n")
print("targets for", len(names), "groups;", sum(1 for n in names if recs[n]), "with at least one listed simple quotient;",
      sum(1 for n in names if skipped[n]), "with skipped infinite families")
