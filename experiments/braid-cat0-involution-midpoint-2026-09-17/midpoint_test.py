"""Midpoint test for CAT(1) of the diagonal link X_n of |NCP_n|.

Lemma M. Let g be an isometry of a CAT(1) space X and z a point with g^2 z = z and d_X(z, g z) < pi. Then g reverses
the unique geodesic [z, g z], so its midpoint m is g-fixed and d_X(z, m) < pi/2.
Since X_n -> B_n is 1-Lipschitz (d_B <= d_X), if d_B(z, Fix_X(g)) >= pi/2 and d_X(z, g z) < pi, then X_n is not CAT(1).

Isometries: the group generated by rotation rho, reflection r and the Kreweras isometry Phi (Lemma D of the
2026-09-13 artifact; order-reversing). Fixed sets:
  * g order preserving: Fix(g) is spanned by g-fixed vertices, and d_B(z, Fix) >= pi/2 iff cos d_B(z, v) <= 0 for
    every g-fixed vertex v (cos d_B(z, .) is linear on a face sharing an apartment with z).
  * g order reversing: fixed points are sum_v lam_v e_v over g-invariant chains with lam_v = lam_{gv}, so
    d_B(z, Fix) >= pi/2 iff cos d_B(z, v) + cos d_B(z, g v) <= 0 whenever v < g v.
Upper bounds for d_X: shortest vertex paths whose steps share a noncrossing spanning tree (an X-apartment, HKS
Proposition 4.4), with step length d_B.
Usage: python3 midpoint_test.py n
"""
import sys, math, time
import numpy as np
from ncp_lib import set_partitions, is_noncrossing, canon, blocks, rank, nblocks, join_P, kreweras, leq, \
    noncrossing_trees, tree_flats

n = int(sys.argv[1]); m = n - 1
t0 = time.time()
ALL = [p for p in set_partitions(n) if is_noncrossing(p)]
ZERO, ONE = tuple(range(n)), tuple([0] * n)
Vt = [p for p in ALL if p not in (ZERO, ONE)]
idx = {p: i for i, p in enumerate(Vt)}
N = len(Vt)
fmt = lambda p: '{' + ','.join(''.join('123456789abcdef'[x] for x in b) for b in blocks(p) if len(b) > 1) + '}'


def cosd(x, z):
    a, b = rank(x), rank(z)
    k = n - nblocks(x) - nblocks(z) + nblocks(join_P(x, z))
    return (k - a * b / m) / math.sqrt((a - a * a / m) * (b - b * b / m))


COS = np.array([[cosd(x, z) for z in Vt] for x in Vt])
mem = [0] * N
for t, T in enumerate(noncrossing_trees(n)):
    for q in tree_flats(T, n):
        if q in idx:
            mem[idx[q]] |= 1 << t
D = np.full((N, N), np.inf)
for i in range(N):
    D[i, i] = 0.0
    for j in range(i + 1, N):
        if mem[i] & mem[j] and COS[i, j] > -1 + 1e-12:
            D[i, j] = D[j, i] = math.acos(max(-1.0, min(1.0, COS[i, j])))
for k in range(N):
    D = np.minimum(D, D[:, k, None] + D[None, k, :])
print('n', n, 'vertices', N, 'all-pairs vertex paths done', round(time.time() - t0, 1), 's', flush=True)


def relabel(p, f):
    return canon([tuple(f(x) for x in b) for b in blocks(p)], n)


rho = [idx[relabel(p, lambda x: (x + 1) % n)] for p in Vt]
refl = [idx[relabel(p, lambda x: (-x) % n)] for p in Vt]
kre = [idx[kreweras(p)] for p in Vt]
gens = [(tuple(rho), False), (tuple(refl), False), (tuple(kre), True)]
ident = (tuple(range(N)), False)
group = {ident}
frontier = [ident]
while frontier:
    new = []
    for g in frontier:
        for h in gens:
            c = (tuple(h[0][g[0][i]] for i in range(N)), g[1] != h[1])
            if c not in group:
                group.add(c); new.append(c)
    frontier = new
print('isometry group order', len(group), flush=True)

best_pass, best_any = (9, None), (9, None)
passes = 0
cands = set()
for perm, rev in group:
    if all(perm[i] == i for i in range(N)):
        continue
    fixed = [v for v in range(N) if perm[v] == v]
    pairs = [(v, perm[v]) for v in range(N) if rev and leq(Vt[v], Vt[perm[v]]) and perm[v] != v]
    for z in range(N):
        gz = perm[z]
        if gz == z or perm[gz] != z:
            continue
        ub = D[z, gz] / math.pi
        if ub < best_any[0]:
            best_any = (ub, (fmt(Vt[z]), fmt(Vt[gz]), rev))
        if rev:
            far = all(COS[z, a] + COS[z, b] <= 1e-12 for a, b in pairs)
        else:
            far = all(COS[z, v] <= 1e-12 for v in fixed)
        if far and COS[z, gz] > -1 + 1e-9:
            cands.add((round(ub, 6), round(math.acos(COS[z, gz]) / math.pi, 6), fmt(Vt[z]), fmt(Vt[gz]), rev,
                       len(fixed)))
        if far:
            passes += 1
            if ub < best_pass[0]:
                best_pass = (ub, (fmt(Vt[z]), fmt(Vt[gz]), rev, len(fixed), len(pairs)))
print('min d_X upper bound over period-2 vertices (any):', best_any)
print('period-2 vertices far from Fix(g):', passes, '| min upper bound among them:', best_pass)
print('far period-2 pairs with d_B < pi (not antipodal):', len(cands),
      '| (vertex-path bound/pi, d_B/pi, z, gz, g order-reversing, #fixed vertices of g):')
for c in sorted(cands)[:40]:
    print('  ', c)
print('VERDICT:', 'X_n NOT CAT(1) (vertex path < pi with far fixed set)' if best_pass[0] < 1 - 1e-9 else
      'no refutation from vertex paths', '|', round(time.time() - t0, 1), 's')
