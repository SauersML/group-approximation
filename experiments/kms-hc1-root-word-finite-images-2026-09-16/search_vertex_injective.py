#!/usr/bin/env python3
"""Search 2 (2026-09-16): small matrix images of Gamma_p that are injective on
all three vertex groups, and the order of rho(rs).

Search space (exact, exhaustive): n x n matrices over F_p of the form
I + sum of at most T distinct off-diagonal elementary terms with coefficients
in {1,-1}, for each of a, b, c separately, subject to a fixed choice of a and c
(listed below) and b ranging over the whole space.  Injectivity on vertex
groups is certified by [a,b]!=1, [b,c]!=1, [a,c,c]!=1 together with the
relators (every nontrivial normal subgroup of Heis(p) or U_B2(p) meets the
centre, which is generated by [a,b], resp. [a,c,c]).
Usage: search_vertex_injective.py <p> <n> <T>
"""
import itertools
import sys

import numpy as np

import kmslib as K

p, n, T = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3])
I = np.eye(n, dtype=np.int64)
off = [(i, j) for i in range(n) for j in range(n) if i != j]


def elem(terms):
    M = I.copy()
    for (i, j, e) in terms:
        M[i, j] = (M[i, j] + e) % p
    return M


def all_elems(T):
    for t in range(1, T + 1):
        for pos in itertools.combinations(off, t):
            for signs in itertools.product((1, -1), repeat=t):
                yield tuple((i, j, e) for (i, j), e in zip(pos, signs))


def make_rep(mats):
    try:
        return K.Rep(mats, p)
    except ValueError:
        return None


def nontriv(rep, u):
    return not rep.is_identity(u)


a, b, c = K.gen(0), K.gen(1), K.gen(2)
found = 0
ac_pairs = []
# enumerate (a,c) with a a single term and c at most two terms, U_B2 injective
for ta in all_elems(1):
    for tc in all_elems(2):
        rep = make_rep([elem(ta), I, elem(tc)])
        if rep is None:
            continue
        if not (rep.is_identity(a * p) and rep.is_identity(c * p)):
            continue
        if not (rep.is_identity(K.lcomm(a, c, a)) and rep.is_identity(K.lcomm(a, c, c, a))
                and rep.is_identity(K.lcomm(a, c, c, c))):
            continue
        if not nontriv(rep, K.lcomm(a, c, c)):
            continue
        ac_pairs.append((ta, tc))
print(f"p={p} n={n}: U_B2-injective (a single term, c <=2 terms) pairs: {len(ac_pairs)}", flush=True)
# modulo simultaneous permutation conjugation keep a = I+E_01
ac_pairs = [pr for pr in ac_pairs if pr[0] == ((0, 1, 1),)]
print(f"  with a=I+E01: {len(ac_pairs)}", flush=True)
stats = {}
for (ta, tc) in ac_pairs:
    for tb in all_elems(T):
        rep = make_rep([elem(ta), elem(tb), elem(tc)])
        if rep is None:
            continue
        rel = rep.check_relators(p)
        if not all(rel.values()):
            continue
        if not (nontriv(rep, K.comm(a, b)) and nontriv(rep, K.comm(b, c))):
            continue
        found += 1
        rs = rep.eval(K.rs_word())
        wt = rep.is_identity(K.root_word(p))
        Nm = (rs - I) % p
        # nilpotency index of rs - I (if unipotent)
        P = Nm.copy()
        idx = 1
        while P.any() and idx <= n + 1:
            P = (P @ Nm) % p
            idx += 1
        key = (wt, idx)
        stats[key] = stats.get(key, 0) + 1
        if found <= 5 or not wt:
            print(f"  a={ta} b={tb} c={tc}: rho(w)=I:{wt} nilindex(rs-1)={idx}", flush=True)
print(f"total vertex-injective triples: {found}; (rho(w)=I, nilindex) counts: {stats}", flush=True)
