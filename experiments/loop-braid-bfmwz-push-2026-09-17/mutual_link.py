#!/usr/bin/env python3
"""BFMWZ-style push for the loop braid descending links X_n(F): local checks.

Conventions as in experiments/zaremsky-2-12-loop-braided-v-type-f-infi-2026-09-16/cabling.py
(functions red/inv/apply/compose/ident/canon/alpha_auto are copied from there):
  * words in F_n are tuples of nonzero ints (i = x_i, -i = x_i^{-1});
  * an automorphism is a dict i -> word, composition compose(f, g) = f o g;
  * A(i,j) : x_i -> x_j x_i x_j^{-1}  (McCool generator, "ring i passes through ring j").

The cabling subgroup P_u of the cable u = (a,b) (cable product x_a x_b) is the image of the
cabling map kappa_u : P_{n-1} -> P_n.  It is generated by
  A(i,j)                 for i, j not in {a,b};
  A(k,b) o A(k,a)        (x_k conjugated by x_a x_b);
  A(a,q) o A(b,q)        (x_a and x_b both conjugated by x_q).
The triple-cable subgroup T = kappa_u(P'_e), e = (f,w) with f the fused ring of u, is the
cabling subgroup of the triple (a,b,w) with cable product x_a x_b x_w.

Checks (each prints True/False):
  (0) sanity of the P_u necessary-condition test: generators of P_u pass; the cable twist
      tau_ab, A(w,a), tau_bw fail;
  (1) (W) the clasp homomorphisms chi vanish on the generators of P_u and of P_z for z = (w,c),
      (c,w), and are nonzero on the push g;
  (2) (PM) the push g = tau_bw (conjugate x_b, x_w by x_b x_w) centralizes T for the order
      (a,b,w), and g = tau_wa centralizes T for the order (w,a,b); T is contained in P_u; g is
      not in P_u;
  (3) the naive push A(w,a)^{+-1}, A(w,b)^{+-1} does NOT conjugate T into P_u (fails a
      necessary condition), so the "ring passes through ring" push is the wrong one.
"""
import itertools
import sys


def red(w):
    out = []
    for a in w:
        if out and out[-1] == -a:
            out.pop()
        else:
            out.append(a)
    return tuple(out)


def inv(w):
    return tuple(-a for a in reversed(w))


def apply(f, w):
    out = []
    for a in w:
        img = f.get(abs(a), (abs(a),))
        out.extend(img if a > 0 else inv(img))
    return red(out)


def compose(f, g, n):
    """(f o g)(x_i) = f(g(x_i))."""
    return {i: apply(f, g.get(i, (i,))) for i in range(1, n + 1)}


def ident(n):
    return {i: (i,) for i in range(1, n + 1)}


def canon(f, n):
    return tuple(red(f.get(i, (i,))) for i in range(1, n + 1))


def alpha_auto(i, j, n):
    f = ident(n)
    f[i] = (j, i, -j)
    return f


def alpha_inv(i, j, n):
    f = ident(n)
    f[i] = (-j, i, j)
    return f


# ---------------------------------------------------------------- group elements with inverses
# an element is a pair (phi, phi^{-1}) of automorphisms of F_n

def A(i, j, n):
    return (alpha_auto(i, j, n), alpha_inv(i, j, n))


def mul(g, h, n):
    return (compose(g[0], h[0], n), compose(h[1], g[1], n))


def inverse(g):
    return (g[1], g[0])


def conj_ring_by(k, rings, n):
    """x_k -> P x_k P^{-1}, P = x_{r1} ... x_{rs} (k not in rings)."""
    P = tuple(rings)
    f, fi = ident(n), ident(n)
    f[k] = red(P + (k,) + inv(P))
    fi[k] = red(inv(P) + (k,) + P)
    return (f, fi)


def cable_through(rings, q, n):
    """x_s -> x_q x_s x_q^{-1} for every s in rings."""
    f, fi = ident(n), ident(n)
    for s in rings:
        f[s] = (q, s, -q)
        fi[s] = (-q, s, q)
    return (f, fi)


def twist(rings, n):
    """x_s -> P x_s P^{-1} for s in rings, P = product of the rings in order (fixes P)."""
    P = tuple(rings)
    f, fi = ident(n), ident(n)
    for s in rings:
        f[s] = red(P + (s,) + inv(P))
        fi[s] = red(inv(P) + (s,) + P)
    return (f, fi)


def cabling_gens(rings, n):
    """Generators of the cabling subgroup of the cable with ordered rings `rings`."""
    R = set(rings)
    out = []
    others = [i for i in range(1, n + 1) if i not in R]
    for i in others:
        for j in others:
            if i != j:
                out.append(('A%d%d' % (i, j), A(i, j, n)))
    for k in others:
        out.append(('k%d-through-cable' % k, conj_ring_by(k, rings, n)))
        out.append(('cable-through-%d' % k, cable_through(rings, k, n)))
    return out


def same(g, h, n):
    return canon(g[0], n) == canon(h[0], n)


# ---------------------------------------------------------------- conjugators and invariants

def conjugator(word, i):
    w = red(word)
    L = len(w)
    if L % 2 == 0:
        return None
    m = L // 2
    if w[m] != i or tuple(w[:m]) != inv(w[m + 1:]):
        return None
    return tuple(w[:m])


def e_matrix(phi, n):
    """e[(i,j)] = exponent sum of x_j in the conjugator W_i of phi(x_i)."""
    e = {}
    for i in range(1, n + 1):
        W = conjugator(phi[i], i)
        assert W is not None, "not basis-conjugating"
        for j in range(1, n + 1):
            if j != i:
                e[(i, j)] = sum(1 if x == j else -1 for x in W if abs(x) == j)
    return e


def in_H(word, a, b, n):
    """Is word in H = <x_a x_b, x_i (i != a,b)>?  Basis {y = x_a x_b, x_b, x_i}: x_a = y x_b^{-1}."""
    Y = n + 1
    out = []
    for x in word:
        if x == a:
            out.extend((Y, -b))
        elif x == -a:
            out.extend((b, -Y))
        else:
            out.append(x)
    return all(abs(x) != b for x in red(out))


def run_split(w, letter):
    """Split w = letter^l * rest; return (l, rest)."""
    l = 0
    i = 0
    while i < len(w) and abs(w[i]) == letter:
        l += 1 if w[i] > 0 else -1
        i += 1
    return l, tuple(w[i:])


def nec_Pu_one(phi, a, b, n):
    """Necessary conditions for phi in P_u, u = (a,b), cable product x_a x_b."""
    Wa = conjugator(phi[a], a)
    Wb = conjugator(phi[b], b)
    D = red(inv(Wb) + Wa)
    l, rest = run_split(D, b)
    m, rest2 = run_split(rest, a)
    if rest2:
        return False, 'no common conjugator for x_a, x_b'
    U = red(Wa + ((a,) * (-m) if m < 0 else (-a,) * m))
    if red(U + (b,) + inv(U)) != red(phi[b]):
        return False, 'common conjugator check failed'
    if not in_H(U, a, b, n):
        return False, 'cable conjugator not in H'
    for i in range(1, n + 1):
        if i not in (a, b):
            if not in_H(conjugator(phi[i], i), a, b, n):
                return False, 'conjugator of x_%d not in H' % i
    e = e_matrix(phi, n)
    if e[(a, b)] != 0 or e[(b, a)] != 0:
        return False, 'twist exponent e_ab=%d e_ba=%d' % (e[(a, b)], e[(b, a)])
    return True, 'ok'


def nec_Pu(g, a, b, n):
    ok1, r1 = nec_Pu_one(g[0], a, b, n)
    if not ok1:
        return False, r1
    ok2, r2 = nec_Pu_one(g[1], a, b, n)
    if not ok2:
        return False, 'inverse: ' + r2
    return True, 'ok'


def chi(g, cable_u, cable_z, n):
    """Clasp number of z = (c,d) through u = (a,b): e_ca - e_da - e_cb + e_db."""
    a, b = cable_u
    c, d = cable_z
    e = e_matrix(g[0], n)
    return e[(c, a)] - e[(d, a)] - e[(c, b)] + e[(d, b)]


# ---------------------------------------------------------------- the checks

def random_product(gens, length, n, rng):
    g = (ident(n), ident(n))
    for _ in range(length):
        name, h = rng.choice(gens)
        g = mul(g, h if rng.random() < 0.5 else inverse(h), n)
    return g


def run(n, a, b, w, rng, report):
    ok_all = True
    Pu = cabling_gens((a, b), n)
    # (0) sanity: P_u generators and random products pass; tau_ab, A(w,a), tau_bw fail
    s0 = all(nec_Pu(h, a, b, n)[0] for _, h in Pu)
    s0 &= all(nec_Pu(random_product(Pu, 6, n, rng), a, b, n)[0] for _ in range(30))
    bad = {'tau_ab': twist((a, b), n), 'A_wa': A(w, a, n), 'A_wb': A(w, b, n),
           'tau_bw': twist((b, w), n), 'tau_wa': twist((w, a), n)}
    fails = {k: nec_Pu(g, a, b, n) for k, g in bad.items()}
    s0 &= all(not r[0] for r in fails.values())
    report.append('  (0) P_u test sanity: %s   [non-members: %s]'
                  % (s0, '; '.join('%s: %s' % (k, r[1]) for k, r in fails.items())))
    ok_all &= s0
    # (1) (W): clasp homomorphisms
    others = [c for c in range(1, n + 1) if c not in (a, b, w)]
    s1 = True
    vals = []
    for c in others:
        for z in ((w, c), (c, w)):
            Pz = cabling_gens(z, n)
            s1 &= all(chi(h, (a, b), z, n) == 0 for _, h in Pu + Pz)
            for name in ('A_wa', 'tau_bw', 'tau_wa'):
                v = chi(bad[name], (a, b), z, n)
                vals.append((name, z, v))
                s1 &= (v != 0)
    report.append('  (1) (W) chi vanishes on P_u, P_z and is nonzero on the pushes: %s   %s'
                  % (s1, sorted(set((nm, v) for nm, _, v in vals))))
    ok_all &= s1
    # (2) (PM): the twist centralizes the triple-cable subgroup; T <= P_u; push not in P_u
    for order, gname in (((a, b, w), 'tau_bw'), ((w, a, b), 'tau_wa')):
        T = cabling_gens(order, n)
        g = bad[gname]
        cent = all(same(mul(g, h, n), mul(h, g, n), n) for _, h in T)
        inPu = all(nec_Pu(h, a, b, n)[0] for _, h in T)
        gout = not nec_Pu(g, a, b, n)[0]
        conjin = all(nec_Pu(mul(inverse(g), mul(h, g, n), n), a, b, n)[0] for _, h in T)
        s2 = cent and inPu and gout and conjin
        report.append('  (2) order %s, push %s: centralizes T %s, T passes P_u test %s, '
                      'push not in P_u %s, g^-1 T g passes P_u test %s'
                      % (order, gname, cent, inPu, gout, conjin))
        ok_all &= s2
    # (3) the ring-through-ring pushes fail
    for order in ((a, b, w), (w, a, b)):
        T = cabling_gens(order, n)
        res = []
        for gname, g in (('A_wa', A(w, a, n)), ('A_wa^-1', inverse(A(w, a, n))),
                         ('A_wb', A(w, b, n)), ('A_wb^-1', inverse(A(w, b, n)))):
            failing = [nm for nm, h in T
                       if not nec_Pu(mul(inverse(g), mul(h, g, n), n), a, b, n)[0]]
            res.append((gname, len(failing), failing[:2]))
        s3 = all(r[1] > 0 for r in res)
        report.append('  (3) order %s: ring-through-ring pushes fail (PM): %s   %s'
                      % (order, s3, res))
        ok_all &= s3
    return ok_all


def main():
    import random
    rng = random.Random(20260917)
    report = []
    ok = True
    for n in (5, 6, 7):
        for (a, b, w) in itertools.permutations(range(1, 5), 3):
            report.append('n=%d, u=(a,b)=(%d,%d), w=%d' % (n, a, b, w))
            ok &= run(n, a, b, w, rng, report)
    print('\n'.join(report))
    print('ALL CHECKS PASSED' if ok else 'SOME CHECK FAILED')
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
