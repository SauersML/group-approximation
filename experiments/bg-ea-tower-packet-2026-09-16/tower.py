#!/usr/bin/env python3
"""Rank-one induced-module tower quotients of staggered chains.

Chain: a_i (i in Z) with a_(i+1)^(-1) a_i a_(i+1) = a_i^2 (Baumslag--Gersten),
or more generally a bottom-linear rank-one relator whose Fox polynomial f(x)
annihilates the class [1] of V = Q[x^{+-1}]/(f).

Window groups (left-module convention, (m,s)(m',s') = (m + s.m', s s')):
  S[q,q]   = Z = <a_q>
  S[p,q]   = Ind_{<a_(p+1)>}^{S[p+1,q]} V  x|  S[p+1,q],   a_p = 1 (x) [1]
where a_(p+1) acts on V by the companion matrix X of multiplication by x.

Elements are canonical hashable tuples, so equality in S[p,q] is decided
exactly (rational arithmetic, canonical left-coset representatives).
"""
from fractions import Fraction
import math
import itertools
import random
import sys


def mat_vec(X, v):
    return tuple(sum(X[i][j] * v[j] for j in range(len(v))) for i in range(len(v)))


def mat_inv(X):
    n = len(X)
    A = [list(row) + [Fraction(int(i == j)) for j in range(n)] for i, row in enumerate(X)]
    for c in range(n):
        piv = next(r for r in range(c, n) if A[r][c] != 0)
        A[c], A[piv] = A[piv], A[c]
        pv = A[c][c]
        A[c] = [x / pv for x in A[c]]
        for r in range(n):
            if r != c and A[r][c] != 0:
                fac = A[r][c]
                A[r] = [x - fac * y for x, y in zip(A[r], A[c])]
    return [row[n:] for row in A]


class TopZ:
    """S[q,q] = Z generated by a_q."""

    def __init__(self, q):
        self.p = q
        self.q = q
        self.id = 0

    def mul(self, x, y):
        return x + y

    def inv(self, x):
        return -x

    def gen(self, i):
        assert i == self.q
        return 1

    def decompose(self, s):
        # s = rep * a_q^k with rep canonical
        return 0, s


class Level:
    """S[p,q] = Ind V  x|  sub, sub = S[p+1,q]."""

    def __init__(self, sub, X):
        self.sub = sub
        self.p = sub.p - 1
        self.q = sub.q
        self.X = [[Fraction(x) for x in row] for row in X]
        self.Xinv = mat_inv(self.X)
        self.d = len(X)
        self.zero = tuple(Fraction(0) for _ in range(self.d))
        self.one = tuple(Fraction(int(i == 0)) for i in range(self.d))
        self.id = ((), sub.id)
        self._pow = {0: [[Fraction(int(i == j)) for j in range(self.d)] for i in range(self.d)]}

    def Xpow_vec(self, j, v):
        M = self.X if j >= 0 else self.Xinv
        for _ in range(abs(j)):
            v = mat_vec(M, v)
        return v

    # module helpers: dict rep_key -> vector
    @staticmethod
    def canon(md):
        return tuple(sorted(((k, v) for k, v in md.items() if any(c != 0 for c in v)), key=repr))

    def act(self, t, m):
        """t in sub acting on module element m (tuple form); returns dict."""
        out = {}
        for r, v in m:
            rep, k = self.sub.decompose(self.sub.mul(t, r))
            w = self.Xpow_vec(k, v)
            old = out.get(rep, self.zero)
            out[rep] = tuple(a + b for a, b in zip(old, w))
        return out

    def add(self, md, m):
        md = dict(md)
        for r, v in m:
            old = md.get(r, self.zero)
            md[r] = tuple(a + b for a, b in zip(old, v))
        return md

    def mul(self, x, y):
        m1, s1 = x
        m2, s2 = y
        md = self.add(dict(m1), self.canon(self.act(s1, m2)))
        return (self.canon(md), self.sub.mul(s1, s2))

    def inv(self, x):
        m, s = x
        si = self.sub.inv(s)
        md = self.act(si, m)
        md = {k: tuple(-c for c in v) for k, v in md.items()}
        return (self.canon(md), si)

    def gen(self, i):
        if i == self.p:
            return (((self.sub.id, self.one),), self.sub.id)
        return ((), self.sub.gen(i))

    def decompose(self, s):
        """s = rep * a_p^k, rep canonical for the left coset s<a_p>."""
        m, t = s
        rt, j = self.sub.decompose(t)
        v = self.Xpow_vec(j, self.one)  # t . (id (x) [1]) = rt (x) X^j [1]
        md = dict(m)
        c = md.get(rt, self.zero)
        i0 = next(i for i in range(self.d) if v[i] != 0)
        k = math.floor(c[i0] / v[i0])
        md[rt] = tuple(a - k * b for a, b in zip(c, v))
        return (self.canon(md), t), k


def window(p, q, X):
    G = TopZ(q)
    for _ in range(q - p):
        G = Level(G, X)
    return G


def word_eval(G, word):
    """word: list of (i, e) meaning a_i^e."""
    x = G.id
    for i, e in word:
        g = G.gen(i)
        if e < 0:
            g = G.inv(g)
        for _ in range(abs(e)):
            x = G.mul(x, g)
    return x


def rewrite_ab(letters):
    """letters over a,A,b,B with zero b-exponent -> list of (i,e)."""
    E = 0
    out = []
    for ch in letters:
        if ch == 'b':
            E += 1
        elif ch == 'B':
            E -= 1
        elif ch in 'aA':
            out.append((-E, 1 if ch == 'a' else -1))
    assert E == 0
    return out
