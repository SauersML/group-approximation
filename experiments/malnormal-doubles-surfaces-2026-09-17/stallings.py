"""Stallings graphs over F_2 = <a,b> and fibre products.

Letters: 0=a, 1=A=a^-1, 2=b, 3=B=b^-1; inverse(x) = x ^ 1.
A graph is a list of dicts adj[v] = {letter: target}; every edge is stored in
both directions (v -x-> u and u -x^1-> v).  Folded means the dicts are
well defined (determinism), which is enforced by construction.
"""

INV = lambda x: x ^ 1
CH = "aAbB"


def word(s):
    return [CH.index(c) for c in s]


def show(w):
    return "".join(CH[x] for x in w)


def reduce_word(w):
    out = []
    for x in w:
        if out and out[-1] == INV(x):
            out.pop()
        else:
            out.append(x)
    return out


class Graph:
    def __init__(self):
        self.adj = []

    def new(self):
        self.adj.append({})
        return len(self.adj) - 1

    def nv(self):
        return len(self.adj)

    def ne(self):
        return sum(len(d) for d in self.adj) // 2


def fold_subgroup(gens):
    """Stallings graph (base vertex 0) of the subgroup generated by gens.
    Naive folding: adjacency sets, merge two targets of a repeated label."""
    adj = [dict()]

    def add(v, x, u):
        adj[v].setdefault(x, set()).add(u)
        adj[u].setdefault(INV(x), set()).add(v)

    for g in gens:
        g = reduce_word(g)
        if not g:
            continue
        v = 0
        for i, x in enumerate(g):
            if i == len(g) - 1:
                u = 0
            else:
                adj.append(dict())
                u = len(adj) - 1
            add(v, x, u)
            v = u
    alive = [True] * len(adj)
    queue = list(range(len(adj)))
    while queue:
        v = queue.pop()
        if not alive[v]:
            continue
        for x in list(adj[v]):
            s = adj[v].get(x, set())
            if len(s) > 1:
                it = sorted(s)
                keep, gone = it[0], it[1]
                for y, ts in list(adj[gone].items()):
                    for t in list(ts):
                        adj[t][INV(y)].discard(gone)
                        tt = keep if t == gone else t
                        add(keep, y, tt)
                adj[gone] = dict()
                alive[gone] = False
                queue.append(keep)
                queue.append(v)
                for y, ts in adj[keep].items():
                    queue.extend(ts)
                break
    idx = {}
    for v in range(len(adj)):
        if alive[v]:
            idx[v] = len(idx)
    G = Graph()
    for v in idx:
        G.adj.append({x: idx[next(iter(s))] for x, s in adj[v].items() if s})
    return prune(G)



def prune(G, base=0):
    """Remove hanging trees (degree-1 vertices other than base)."""
    alive = [True] * G.nv()
    changed = True
    while changed:
        changed = False
        for v in range(G.nv()):
            if alive[v] and v != base and len([1 for x, u in G.adj[v].items() if alive[u]]) == 1:
                alive[v] = False
                changed = True
    idx = {}
    for v in range(G.nv()):
        if alive[v]:
            idx[v] = len(idx)
    H = Graph()
    for v in idx:
        H.adj.append({x: idx[u] for x, u in G.adj[v].items() if alive[u]})
    return H


def check_folded(G):
    for v, d in enumerate(G.adj):
        for x, u in d.items():
            if G.adj[u].get(INV(x)) != v:
                return False
    return True


def read(G, v, w):
    for x in w:
        v = G.adj[v].get(x)
        if v is None:
            return None
    return v


def product_component_rank(G, g0, H, h0):
    """Rank of pi_1 of the component of (g0,h0) in the fibre product G x H."""
    seen = {(g0, h0)}
    stack = [(g0, h0)]
    edges2 = 0
    while stack:
        g, h = stack.pop()
        for x, g2 in G.adj[g].items():
            h2 = H.adj[h].get(x)
            if h2 is None:
                continue
            edges2 += 1
            if (g2, h2) not in seen:
                seen.add((g2, h2))
                stack.append((g2, h2))
    return edges2 // 2 - len(seen) + 1, len(seen)


def is_malnormal(C):
    """C is malnormal in F iff every off-diagonal component of C x C is a tree."""
    n = C.nv()
    seen = set()
    for g in range(n):
        for h in range(n):
            if g == h or (g, h) in seen:
                continue
            comp = {(g, h)}
            stack = [(g, h)]
            e2 = 0
            diag = False
            while stack:
                p, q = stack.pop()
                if p == q:
                    diag = True
                for x, p2 in C.adj[p].items():
                    q2 = C.adj[q].get(x)
                    if q2 is None:
                        continue
                    e2 += 1
                    if (p2, q2) not in comp:
                        comp.add((p2, q2))
                        stack.append((p2, q2))
            seen |= comp
            if not diag and e2 // 2 - len(comp) + 1 > 0:
                return False
    return True


def offdiag_depth(C):
    """K(C): longest reduced path length in the off-diagonal part of C x C
    (finite iff C is malnormal).  Brute force DFS, for small graphs."""
    n = C.nv()
    best = 0

    def dfs(p, q, last, L):
        nonlocal best
        best = max(best, L)
        for x, p2 in C.adj[p].items():
            if last is not None and x == INV(last):
                continue
            q2 = C.adj[q].get(x)
            if q2 is None or p2 == q2:
                continue
            if L > 4 * n * n:
                raise ValueError("not malnormal")
            dfs(p2, q2, x, L + 1)

    for p in range(n):
        for q in range(n):
            if p != q:
                dfs(p, q, None, 0)
    return best


def infinite_index(C):
    return any(len(d) < 4 for d in C.adj)


def rank(G):
    return G.ne() - G.nv() + 1
