"""Filling cyclic-core certificates for surface subgroups in D(F_2, C).

Certificate: a finitely generated A <= F_2 (Stallings graph Gamma_A), vertices
v of Gamma_A and c of Gamma_C such that the component of (v, c) in the fibre
product Gamma_A x Gamma_C has rank 1, generated by a loop w, and w is not in a
proper free factor of pi_1(Gamma_A, v).  Then (after conjugation) A cap C = <w>,
<A, A-bar> = A *_<w> A-bar is one-ended and hyperbolic, and by Wilton's theorem
(research/cyclic-graphs-of-free-groups-contain-surface-subgroups) it contains a
quasiconvex surface subgroup; so does D(F_2, C).

"Not in a proper free factor" is certified by Stallings' criterion: in some
basis the Whitehead graph of the cyclic word is connected with no cut vertex.
The basis is the graph basis of Gamma_A, improved by greedy Whitehead reduction.

Usage: python3 search_filling.py <gen_len> <C words ...>
"""
import itertools
import sys
from stallings import (INV, word, show, reduce_word, fold_subgroup, read, is_malnormal,
                       offdiag_depth, infinite_index, rank)


def all_words(L):
    out, frontier = [], [[]]
    for _ in range(L):
        nf = []
        for w in frontier:
            for x in range(4):
                if not (w and w[-1] == INV(x)):
                    nf.append(w + [x])
        out += nf
        frontier = nf
    return out


def rank1_components(A, C):
    """Yield (v, c, loop) for components of A x C of rank 1; loop is the
    cyclically reduced label of the core circle together with its vertex path in A."""
    seen = set()
    for v0 in range(A.nv()):
        for c0 in range(C.nv()):
            if (v0, c0) in seen:
                continue
            comp = {(v0, c0)}
            stack = [(v0, c0)]
            adj = {}
            e2 = 0
            while stack:
                v, c = stack.pop()
                nb = {}
                for x, v2 in A.adj[v].items():
                    c2 = C.adj[c].get(x)
                    if c2 is None:
                        continue
                    nb[x] = (v2, c2)
                    e2 += 1
                    if (v2, c2) not in comp:
                        comp.add((v2, c2))
                        stack.append((v2, c2))
                adj[(v, c)] = nb
            seen |= comp
            if e2 // 2 - len(comp) + 1 != 1:
                continue
            # prune to the core circle
            alive = set(comp)
            changed = True
            while changed:
                changed = False
                for p in list(alive):
                    if sum(1 for q in adj[p].values() if q in alive) <= 1:
                        alive.discard(p)
                        changed = True
            start = min(alive)
            x0 = min(x for x, q in adj[start].items() if q in alive)
            loop, verts = [x0], [start]
            p, last = adj[start][x0], x0
            while p != start:
                verts.append(p)
                x = [y for y, q in adj[p].items() if q in alive and y != INV(last)][0]
                loop.append(x)
                p, last = adj[p][x], x
            yield start, loop


def graph_basis_word(A, v, loop):
    """Express the closed path (from v, label loop) in the basis of non-tree edges."""
    n = A.nv()
    parent = {v: None}
    order = [v]
    for u in order:
        for x, u2 in sorted(A.adj[u].items()):
            if u2 not in parent:
                parent[u2] = (u, x)
                order.append(u2)
    tree = set()
    for u2, pe in parent.items():
        if pe is not None:
            u, x = pe
            tree.add((u, x))
            tree.add((u2, INV(x)))
    labels = {}
    k = 0
    for u in range(n):
        for x, u2 in sorted(A.adj[u].items()):
            if (u, x) in tree or (u, x) in labels:
                continue
            labels[(u, x)] = 2 * k
            labels[(u2, INV(x))] = 2 * k + 1
            k += 1
    out = []
    u = v
    for x in loop:
        if (u, x) in labels:
            out.append(labels[(u, x)])
        u = A.adj[u][x]
    return reduce_cyc(out), k


def reduce_cyc(w):
    w = reduce_word(w)
    while len(w) > 1 and w[0] == INV(w[-1]):
        w = w[1:-1]
    return w


def whitehead_auts(r):
    letters = list(range(2 * r))
    for a in letters:
        others = [x for x in letters if x not in (a, INV(a))]
        for bits in range(1, 2 ** len(others)):
            S = {others[i] for i in range(len(others)) if bits >> i & 1}
            yield a, S


def apply_wh(w, a, S):
    out = []
    for x in w:
        if x in (a, INV(a)):
            out.append(x)
            continue
        # image of letter x: x -> (a^-1 if x^-1 in S) x (a if x in S)
        pre = [INV(a)] if INV(x) in S else []
        post = [a] if x in S else []
        out += pre + [x] + post
    return reduce_cyc(out)


def minimize(w, r):
    improved = True
    while improved:
        improved = False
        for a, S in whitehead_auts(r):
            w2 = apply_wh(w, a, S)
            if len(w2) < len(w):
                w, improved = w2, True
                break
    return w


def whitehead_filling(w, r):
    """Connected with no cut vertex (Stallings criterion, sufficient)."""
    if len(w) < 2:
        return False
    V = list(range(2 * r))
    E = set()
    for i in range(len(w)):
        s, t = w[i], w[(i + 1) % len(w)]
        E.add(frozenset((INV(s), t)) if INV(s) != t else frozenset((t,)))
    adj = {v: set() for v in V}
    for e in E:
        e = tuple(e)
        if len(e) == 2:
            adj[e[0]].add(e[1])
            adj[e[1]].add(e[0])

    def connected(removed):
        vs = [v for v in V if v != removed]
        seen, st = {vs[0]}, [vs[0]]
        while st:
            u = st.pop()
            for q in adj[u]:
                if q != removed and q not in seen:
                    seen.add(q)
                    st.append(q)
        return len(seen) == len(vs)

    return connected(None) and all(connected(v) for v in V)


def certify_A(A, C):
    if rank(A) < 2:
        return None
    for vc, loop in rank1_components(A, C):
        v = vc[0]
        bw, r = graph_basis_word(A, v, loop)
        if r != rank(A):
            continue
        mw = minimize(bw, r)
        if whitehead_filling(mw, r):
            return show(loop), v
    return None


def search(C, L, max_pairs=None):
    W = all_words(L)
    tried = 0
    for i, u in enumerate(W):
        for v in W[i + 1:]:
            A = fold_subgroup([u, v])
            tried += 1
            cert = certify_A(A, C)
            if cert:
                return (show(u), show(v)) + cert, tried
            if max_pairs and tried >= max_pairs:
                return None, tried
    return None, tried


if __name__ == "__main__":
    L = int(sys.argv[1])
    C = fold_subgroup([word(g) for g in sys.argv[2:]])
    print("C", sys.argv[2:], "V", C.nv(), "rank", rank(C), "malnormal", is_malnormal(C),
          "inf-index", infinite_index(C))
    print(search(C, L))
