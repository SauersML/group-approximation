"""Compute the two-primary Smith data of the 234 atlas derivatives.

Let ``L`` be the integral left ideal in ``Z[A8]`` generated by the 234
right-trivialized boundary derivatives.  The known rational and mod-two
computations give

    rank_Q(L) = 20040,       rank_F2(L/2L) = 20005.

Thus exactly 35 nonzero Smith factors of ``L -> Z[A8]`` are even.  A full
Smith form of the 20160 by 4.7-million orbit matrix is the wrong computation.
The first integral Bockstein is enough:

    beta : ker(A mod 2) -> coker(A mod 2),
           x             |-> (A x)/2 mod (im(A mod 2)).

In Smith coordinates, ``rank(beta)`` is exactly the number of factors with
2-adic valuation one.  Hence ``35-rank(beta)`` is the number divisible by
four.  This script constructs beta while closing the derivative span under
the six left translations.  It retains a mod-four lift of every admitted
mod-two row; every dependent translation supplies a Bockstein value.  The
values are finally closed under A8, because beta is equivariant.

The same quotient computation closes the four classes ``1+h`` for the raw
S3 transvections.  Their A8-span measures whether the covariance bridges
occupy the whole 35-dimensional non-permutation sector or only a submodule.

Only exact bit arithmetic is used.  A mod-four vector is represented by two
Python integers ``lo + 2*hi``.  The output is a compact, independently
checkable arithmetic certificate (ranks and SHA-256 digests), not a floating
point experiment.
"""

import hashlib
import json

import numpy as np

from atlas_certified_a8_alignment import boundary_words
from atlas_two_chart_search import (
    I4,
    factor_generators,
    gf2_inv,
    gf2_mul,
    matrix_key,
)


INNER_ALIGNMENT_HEX = "00000100000100000100000000000001"
BYTE_POPCOUNT = np.asarray([
    bin(value).count("1") for value in range(256)
], dtype=np.uint8)


def population_count(row):
    byte_width = max(1, (row.bit_length() + 7) // 8)
    packed = row.to_bytes(byte_width, byteorder="little")
    return int(BYTE_POPCOUNT[
        np.frombuffer(packed, dtype=np.uint8)
    ].sum())


def enumerate_gl4():
    generators = [word[0][1] for _name, word in factor_generators()[:6]]
    elements = [I4.copy()]
    seen = {matrix_key(I4)}
    for element in elements:
        for generator in generators:
            target = gf2_mul(element, generator)
            key = matrix_key(target)
            if key not in seen:
                seen.add(key)
                elements.append(target)
    if len(elements) != 20160:
        raise AssertionError("GL4(F2) enumeration failed")
    return elements


def group_algebra_derivative(word, alignment, alignment_inverse):
    prefix = I4.copy()
    coefficients = {}
    for factor, matrix in word:
        image = matrix
        if factor == 2:
            image = gf2_mul(gf2_mul(
                alignment, matrix), alignment_inverse)
        before = prefix
        prefix = gf2_mul(prefix, image)
        if factor == 2:
            before_key = matrix_key(before)
            after_key = matrix_key(prefix)
            coefficients[before_key] = coefficients.get(before_key, 0) + 1
            coefficients[after_key] = coefficients.get(after_key, 0) - 1
    if matrix_key(prefix) != matrix_key(I4):
        raise AssertionError("boundary word is nontrivial at alignment")
    return {key: value for key, value in coefficients.items() if value}


class LeftTranslations:
    def __init__(self, permutations, dimension):
        self.permutations = tuple(
            np.asarray(permutation, dtype=np.int32)
            for permutation in permutations
        )
        self.dimension = dimension
        self.byte_width = (dimension + 7) // 8

    def all_images(self, row):
        if population_count(row) <= 256:
            images = [0] * len(self.permutations)
            remaining = row
            while remaining:
                bit = remaining & -remaining
                source = bit.bit_length() - 1
                for index, permutation in enumerate(self.permutations):
                    images[index] |= 1 << int(permutation[source])
                remaining ^= bit
            return images
        packed = row.to_bytes(self.byte_width, byteorder="little")
        bits = np.unpackbits(
            np.frombuffer(packed, dtype=np.uint8), bitorder="little"
        )[:self.dimension]
        images = []
        target = np.empty(self.dimension, dtype=np.uint8)
        for permutation in self.permutations:
            target[permutation] = bits
            repacked = np.packbits(target, bitorder="little")
            images.append(int.from_bytes(
                repacked.tobytes(), byteorder="little"
            ))
        return images


def subtract_mod4(left, right):
    """Coordinatewise ``left-right`` in (Z/4)^n, in bit-sliced form."""
    alo, ahi = left
    blo, bhi = right
    # -b has slices (blo, bhi xor blo).  Addition has the carry alo & blo.
    return alo ^ blo, ahi ^ bhi ^ blo ^ (alo & blo)


def derivative_mod4(coefficients, index_by_key):
    lo = 0
    hi = 0
    for key, coefficient in coefficients.items():
        value = coefficient % 4
        bit = 1 << index_by_key[key]
        if value & 1:
            lo |= bit
        if value & 2:
            hi |= bit
    return lo, hi


def reduce_mod2(basis, row):
    while row:
        pivot = row.bit_length() - 1
        entry = basis.get(pivot)
        if entry is None:
            return row
        row ^= entry[0]
    return 0


def quotient_normal_form(basis, row):
    """Eliminate every image pivot, retaining all complementary coordinates.

    Ordinary echelon reduction may stop at the highest nonpivot, which is
    correct for testing span membership but not for choosing a representative
    in a quotient: lower image pivots can remain.  Moving each encountered
    nonpivot into ``free`` gives the unique complement representative.
    """
    free = 0
    while row:
        pivot = row.bit_length() - 1
        entry = basis.get(pivot)
        if entry is None:
            bit = 1 << pivot
            free |= bit
            row ^= bit
        else:
            row ^= entry[0]
    return free


def insert_binary(basis, row):
    row = reduce_mod2(basis, row)
    if not row:
        return False, 0
    basis[row.bit_length() - 1] = (row, len(basis))
    return True, row


def reduce_lift(basis, pair):
    """Reduce the low slice and make the same integral operations mod four."""
    lo, hi = pair
    while lo:
        pivot = lo.bit_length() - 1
        entry = basis.get(pivot)
        if entry is None:
            break
        _low, _row_id, lift = entry
        lo, hi = subtract_mod4((lo, hi), lift)
    return lo, hi


def digest_rows(rows, width):
    digest = hashlib.sha256()
    for row in rows:
        digest.update(row.to_bytes(width, "little"))
    return digest.hexdigest()


def main():
    elements = list(enumerate_gl4())
    order = len(elements)
    width = (order + 7) // 8
    index_by_key = {
        matrix_key(element): index for index, element in enumerate(elements)
    }
    source_generators = [
        word[0][1] for _name, word in factor_generators()[:6]
    ]
    permutations = [
        [
            index_by_key[matrix_key(gf2_mul(generator, element))]
            for element in elements
        ]
        for generator in source_generators
    ]
    translations = LeftTranslations(permutations, order)

    alignment = np.frombuffer(
        bytes.fromhex(INNER_ALIGNMENT_HEX), dtype=np.uint8
    ).reshape(4, 4).copy()
    alignment_inverse = gf2_inv(alignment)
    seeds = [
        derivative_mod4(
            group_algebra_derivative(word, alignment, alignment_inverse),
            index_by_key,
        )
        for word in boundary_words()
    ]

    # pivot -> (mod-two row, row id, reduced mod-four lift)
    basis = {}
    lifts = []
    queue = []
    bockstein_values = []
    dependencies = 0

    def admit(pair):
        nonlocal dependencies
        lo, hi = reduce_lift(basis, pair)
        if lo:
            row_id = len(lifts)
            basis[lo.bit_length() - 1] = (lo, row_id, (lo, hi))
            lifts.append((lo, hi))
            queue.append(row_id)
            return
        dependencies += 1
        if hi:
            # The reduced lift is 2*hi, hence hi is its Bockstein value.
            bockstein_values.append(hi)

    for seed in seeds:
        admit(seed)

    head = 0
    translated_candidates = 0
    while head < len(queue):
        lo, hi = lifts[queue[head]]
        head += 1
        lo_images = translations.all_images(lo)
        hi_images = translations.all_images(hi)
        for lo_image, hi_image in zip(lo_images, hi_images):
            translated_candidates += 1
            admit((lo_image, hi_image))

    # Canonical final mod-two image basis (discard lift metadata).
    image_basis = {
        pivot: (entry[0], entry[1]) for pivot, entry in basis.items()
    }

    # Generate the equivariant Bockstein image in the quotient F2[A8]/I.
    beta_basis = {}
    beta_rows = []
    beta_queue = []

    def admit_quotient(row, target_basis, target_rows, target_queue):
        row = quotient_normal_form(image_basis, row)
        row = reduce_mod2(target_basis, row)
        if not row:
            return False
        target_basis[row.bit_length() - 1] = (row, len(target_rows))
        target_rows.append(row)
        target_queue.append(len(target_rows) - 1)
        return True

    for value in bockstein_values:
        admit_quotient(value, beta_basis, beta_rows, beta_queue)
    head = 0
    while head < len(beta_queue):
        row = beta_rows[beta_queue[head]]
        head += 1
        for image in translations.all_images(row):
            admit_quotient(image, beta_basis, beta_rows, beta_queue)

    # The raw covariance bridges 1+h, closed in the same quotient.
    identity_index = index_by_key[matrix_key(I4)]
    bridge_basis = {}
    bridge_rows = []
    bridge_queue = []
    bridge_remainders = []
    for row, column in ((0, 1), (1, 0), (1, 2), (2, 1)):
        h = I4.copy()
        h[row, column] ^= 1
        target = (1 << identity_index) ^ (
            1 << index_by_key[matrix_key(h)]
        )
        remainder = quotient_normal_form(image_basis, target)
        bridge_remainders.append(remainder)
        admit_quotient(
            remainder, bridge_basis, bridge_rows, bridge_queue
        )
    head = 0
    while head < len(bridge_queue):
        row = bridge_rows[bridge_queue[head]]
        head += 1
        for image in translations.all_images(row):
            admit_quotient(image, bridge_basis, bridge_rows, bridge_queue)

    rational_image_rank = 20040
    rational_cokernel_rank = order - rational_image_rank
    mod2_image_rank = len(image_basis)
    even_smith_factors = rational_image_rank - mod2_image_rank
    valuation_one_factors = len(beta_basis)
    valuation_at_least_two_factors = (
        even_smith_factors - valuation_one_factors
    )
    if valuation_at_least_two_factors < 0:
        raise AssertionError("Bockstein rank exceeds the even Smith count")
    print(json.dumps({
        "group": "A8 ~= GL4(F2)",
        "group_order": order,
        "boundary_seeds": len(seeds),
        "translated_candidates": translated_candidates,
        "dependent_candidates": dependencies,
        "rational_image_rank": rational_image_rank,
        "rational_cokernel_rank": rational_cokernel_rank,
        "mod2_image_rank": mod2_image_rank,
        "mod2_cokernel_dimension": order - mod2_image_rank,
        "even_nonzero_smith_factors": even_smith_factors,
        "bockstein_rank": valuation_one_factors,
        "smith_factors_divisible_by_four": valuation_at_least_two_factors,
        "two_primary_conclusion": (
            f"(Z/2)^{even_smith_factors}"
            if valuation_at_least_two_factors == 0
            else "higher-two-power-torsion-present"
        ),
        "raw_bockstein_values": len(bockstein_values),
        "bridge_remainder_weights": [
            population_count(value) for value in bridge_remainders
        ],
        "bridge_a8_span_dimension_in_mod2_cokernel": len(bridge_basis),
        "bridge_span_is_entire_extra_sector": (
            len(bridge_basis) == even_smith_factors
        ),
        "mod2_basis_digest": digest_rows(
            [basis[pivot][0] for pivot in sorted(basis)], width
        ),
        "bockstein_basis_digest": digest_rows(
            [beta_basis[pivot][0] for pivot in sorted(beta_basis)], width
        ),
        "bridge_basis_digest": digest_rows(
            [bridge_basis[pivot][0] for pivot in sorted(bridge_basis)], width
        ),
    }, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
