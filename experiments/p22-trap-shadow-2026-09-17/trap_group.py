#!/usr/bin/env python3
"""The finitely presented trap-relator group Gamma of P_{2,2}(J).

J = F_2<S,T | TS=1>, Q = 1 + ST (char 2).  P = P_{2,2}(J) <= EL_4(J).

Gamma is generated by seven involutions
    as = x_12(S), at = x_12(T), c = x_21(1)            (left Levi)
    b1 = x_34(1), bs = x_43(S), bt = x_43(T)           (right Levi)
    u  = x_13(1) = n(E_11)                              (unipotent)
and the derived words (all involutions in P)
    w1  = u c u c           = n(E_21)
    r   = u b1 u b1         = n(E_12)
    us  = w1 as w1 as       = n(E_11 S)
    ut  = w1 at w1 at       = n(E_11 T)
    ws  = us c us c         = n(E_21 S)
    wt  = ut c ut c         = n(E_21 T)
    ust = wt as wt as       = n(E_11 ST)
    h   = u ust             = n(E_11 Q) = x_13(Q)   (the head)
The relations are exactly those consumed by the two-step trap proof
(jacobson-double-parabolic-two-step-trap-proof, Steps 0-4):
    TRAP_R1  us = r bs r bs         (right transport of the S-coefficient)
    TRAP_R2  ut = r bt r bt         (right transport of the T-coefficient)
    TRAP_R3  u  = ws at ws at       (TS = 1 on the left)
    LR       [x, y] = 1 for x in {as,at,c}, y in {b1,bs,bt}
    UU       the eight unipotent words pairwise commute
EXTRA relations (also true in P, optional) are listed in EXTRA_RELS.

This module checks every relation exactly in P by 4x4 matrix arithmetic over
J and exports the word lists for the finite-quotient search.
"""

# ---------------- the ring J (char 2) ----------------


def jmul_mono(a, b):
    i, j = a
    k, l = b
    if j <= k:
        return (i + k - j, l)
    return (i, j - k + l)


def jadd(x, y):
    return frozenset(set(x) ^ set(y))


def jmul(x, y):
    out = set()
    for a in x:
        for b in y:
            out ^= {jmul_mono(a, b)}
    return frozenset(out)


ZERO = frozenset()
ONE = frozenset({(0, 0)})
S = frozenset({(1, 0)})
T = frozenset({(0, 1)})
ST = frozenset({(1, 1)})
Q = frozenset({(0, 0), (1, 1)})


def mat_id():
    return tuple(tuple(ONE if r == c else ZERO for c in range(4)) for r in range(4))


def mat_mul(A, B):
    out = []
    for r in range(4):
        row = []
        for c in range(4):
            acc = ZERO
            for k in range(4):
                acc = jadd(acc, jmul(A[r][k], B[k][c]))
            row.append(acc)
        out.append(tuple(row))
    return tuple(out)


def elem(i, j, a):
    """x_ij(a), indices 1..4."""
    M = [list(r) for r in mat_id()]
    M[i - 1][j - 1] = jadd(M[i - 1][j - 1], a)
    return tuple(tuple(r) for r in M)


GENS = {
    "as": elem(1, 2, S),
    "at": elem(1, 2, T),
    "c": elem(2, 1, ONE),
    "b1": elem(3, 4, ONE),
    "bs": elem(4, 3, S),
    "bt": elem(4, 3, T),
    "u": elem(1, 3, ONE),
}
GEN_NAMES = list(GENS)

# derived words, in order; each is a list of earlier names
DERIVED = [
    ("w1", ["u", "c", "u", "c"]),
    ("r", ["u", "b1", "u", "b1"]),
    ("us", ["w1", "as", "w1", "as"]),
    ("ut", ["w1", "at", "w1", "at"]),
    ("ws", ["us", "c", "us", "c"]),
    ("wt", ["ut", "c", "ut", "c"]),
    ("ust", ["wt", "as", "wt", "as"]),
    ("h", ["u", "ust"]),
]

# expected values in P (for the exact check)
EXPECT = {
    "w1": elem(2, 3, ONE),
    "r": elem(1, 4, ONE),
    "us": elem(1, 3, S),
    "ut": elem(1, 3, T),
    "ws": elem(2, 3, S),
    "wt": elem(2, 3, T),
    "ust": elem(1, 3, ST),
    "h": elem(1, 3, Q),
}

UNIP = ["u", "us", "ut", "ust", "w1", "ws", "wt", "r"]
LEFT = ["as", "at", "c"]
RIGHT = ["b1", "bs", "bt"]

# relations lhs == rhs, as word lists
TRAP_RELS = [
    ("TRAP_R1", ["us"], ["r", "bs", "r", "bs"]),
    ("TRAP_R2", ["ut"], ["r", "bt", "r", "bt"]),
    ("TRAP_R3", ["u"], ["ws", "at", "ws", "at"]),
]
for x in LEFT:
    for y in RIGHT:
        TRAP_RELS.append(("LR_%s_%s" % (x, y), [x, y], [y, x]))
for i, x in enumerate(UNIP):
    for y in UNIP[i + 1:]:
        TRAP_RELS.append(("UU_%s_%s" % (x, y), [x, y], [y, x]))


def _comm(name, x, y):
    return (name, [x, y], [y, x])


EXTRA_RELS = [
    _comm("X_as_at", "as", "at"),
    _comm("X_bs_bt", "bs", "bt"),
    _comm("X_b1_r", "b1", "r"),
]
for w in ["w1", "ws", "wt"]:
    EXTRA_RELS.append(_comm("X_c_" + w, "c", w))
    for b in ["bs", "bt"]:
        EXTRA_RELS.append(_comm("X_%s_%s" % (b, w), b, w))
for a in ["as", "at"]:
    for x in ["u", "us", "ut", "ust", "r"]:
        EXTRA_RELS.append(_comm("X_%s_%s" % (a, x), a, x))
for b in ["bs", "bt"]:
    for x in ["u", "us", "ut", "ust"]:
        EXTRA_RELS.append(_comm("X_%s_%s" % (b, x), b, x))


def evaluate():
    val = dict(GENS)
    for name, word in DERIVED:
        M = mat_id()
        for g in word:
            M = mat_mul(M, val[g])
        val[name] = M
    return val


def word_val(val, word):
    M = mat_id()
    for g in word:
        M = mat_mul(M, val[g])
    return M


def check():
    val = evaluate()
    ok = True
    for g in GEN_NAMES:
        if mat_mul(val[g], val[g]) != mat_id():
            print("FAIL involution", g)
            ok = False
    for name, M in EXPECT.items():
        if val[name] != M:
            print("FAIL derived value", name)
            ok = False
    for name, lhs, rhs in TRAP_RELS + EXTRA_RELS:
        if word_val(val, lhs) != word_val(val, rhs):
            print("FAIL relation", name)
            ok = False
    if val["h"] == mat_id():
        print("FAIL head trivial")
        ok = False
    print("exact check in P_{2,2}(J): %d trap relations, %d extra relations, head nontrivial: %s"
          % (len(TRAP_RELS), len(EXTRA_RELS), ok))
    return ok


if __name__ == "__main__":
    import sys
    sys.exit(0 if check() else 1)
