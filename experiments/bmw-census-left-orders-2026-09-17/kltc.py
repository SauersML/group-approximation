# klt.py with canonical short words.  Same lemma as klt.py (header there): a chain L_0, L_1, ..., L_k of
# subgroups of K, each transitive on X, with L_{i+1} <= phi_v(Stab_{L_i}(v)) and L_j <= phi_v(Stab_{L_k}(v)),
# makes every L_i level-transitive, so K is infinite and Gamma is irreducible.  If only some L_i moves v
# (not transitive), the weaker conclusion still holds: a finite L_i would satisfy
# |L_i| >= |L_i v| * |phi_v(Stab_{L_i}(v))| > |L_{i+1}| >= ... >= |L_j| >= |L_i| along the cycle, impossible
# as soon as one orbit L_i v has more than one point and the cycle returns to L_i (j = i).  So K is infinite
# whenever the closing edge returns to a group of the cycle and one group of the cycle moves v.
# Here L_{i+1} is generated by ALL sections at v of the Schreier generators of Stab_{L_i}(v) (so the
# containment L_{i+1} <= phi_v(Stab_{L_i}(v)) holds by definition), each replaced by an exactly equal
# shortest word of K found in a ball of radius RB (exactness by selfrep.trivial).  Closing: every generator
# of L_j is exactly equal to one of the generators of L_{k+1} or to a product of at most D of them.
# usage: kltc.py census.json side v RB NL steps D init|K idx
import sys, json, itertools
from lo_census import load
from selfrep import build, act_path, trivial, inv
from kkps import red
from klt import level1_orbit, section_pool

def main(path, side, v, RB, NL, steps, D, init, idx):
    G = next(G for i, G in load(path) if i == idx); K = build(G, side)
    Vx = list(itertools.product(K['X'], repeat=NL)); ix = {x: i for i, x in enumerate(Vx)}
    perm = lambda w: tuple(ix[act_path(K, w, x)[0]] for x in Vx)
    ball = {}; fr = [()]; ball.setdefault(perm(()), []).append(())
    for _ in range(RB):
        nf = []
        for w in fr:
            for a in range(K['nL']):
                w2 = red(K, w + (a,))
                if len(w2) == len(w) + 1:
                    p = perm(w2); lst = ball.setdefault(p, [])
                    if len(lst) < 6: lst.append(w2); nf.append(w2)
        fr = nf
    def eq(s, t): return trivial(K, red(K, s + inv(K, t)))
    def canon(s):
        for w in ball.get(perm(s), []):
            if len(w) <= len(s) and eq(s, w): return w
        return s
    def dedupe(ws):
        out = []
        for w in sorted(set(ws), key=lambda s: (len(s), s)):
            if w and not any(len(u) == len(w) and eq(u, w) for u in out): out.append(w)
        return out
    L0 = [(a,) for a in range(K['nL'])] if init == 'K' else [tuple(map(int, w.split('.'))) for w in init.split(',')]
    chain = [dedupe(L0)]; orbits = []
    for k in range(steps):
        S = chain[-1]
        orbits.append(len(level1_orbit(K, S, v)))
        nxt = dedupe(canon(s) for s in section_pool(K, S, v))
        print(json.dumps(dict(step=k, orbit=orbits[-1], ngens=len(S), gens=S, next_ngens=len(nxt))), flush=True)
        # closing edge: L_j <= <nxt>
        gens = nxt + [inv(K, s) for s in nxt]
        prods = {perm(()): [()]}
        layer = [()]
        for _ in range(D):
            nl = []
            for w in layer:
                for s in gens:
                    w2 = red(K, w + s); p = perm(w2); lst = prods.setdefault(p, [])
                    if len(lst) < 4: lst.append(w2); nl.append(w2)
            layer = nl
        for j in range(k, -1, -1):
            expr = {}
            for t in chain[j]:
                hit = next((w for w in prods.get(perm(t), []) if eq(w, t)), None)
                if hit is None: break
                expr[str(t)] = hit
            if len(expr) == len(chain[j]):
                cyc = orbits[j:k + 1]
                return dict(v=v, close_from=k, close_to=j, orbits_on_cycle=cyc, chain=chain, last=nxt, expressions=expr,
                            infinite=max(cyc) > 1, level_transitive=min(cyc) == len(K['X']))
        chain.append(nxt)
    return None

if __name__ == "__main__":
    a = sys.argv
    r = main(a[1], a[2], int(a[3]), int(a[4]), int(a[5]), int(a[6]), int(a[7]), a[8], int(a[9]))
    print(json.dumps(dict(census=a[1], side=a[2], idx=int(a[9]), init=a[8], certificate=r)), flush=True)
