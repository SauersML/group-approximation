# Level-transitivity certificate for the invariant-subtree group K (selfrep.build), hence irreducibility.
# Lemma.  Let L_j, ..., L_k be subgroups of K (given by generating words) such that
#   (a) every L_i is transitive on the first level X, and
#   (b) for a vertex v in X, the section group phi_v(Stab_{L_i}(v)) contains L_{i+1} (i < k), and
#       phi_v(Stab_{L_k}(v)) contains L_j.
# Then every L_i is transitive on every level X^n.  (Induction on n: given xw, x'w' in X^{n+1}, move x and x'
# to v by elements of L_i; Stab_{L_i}(v) acts on v X^n through phi_v, whose image contains a group that is
# transitive on X^n by the induction hypothesis.)  phi_v is a homomorphism on Stab(v), so (b) holds as soon as
# the generators of the smaller group are products of sections at v of elements of Stab_{L_i}(v).
# A group transitive on every level X^n has at least 3^n elements for every n, so K is infinite; H_x maps
# onto K, so H_x is infinite, pr_V(Gamma) is non-discrete and Gamma is irreducible (Burger-Mozes, Prop. 1.2).
# Construction: L_0 = K; L_{i+1} is generated by a pruned set of sections at v of Schreier generators of
# Stab_{L_i}(v) (pruning keeps (b) for i -> i+1 by definition).  The closing containment L_j <= phi_v(...) is
# found by meet-in-the-middle products on the action on level NL and every identity is verified exactly
# (selfrep.trivial).  Transitivity on X is checked directly on the letter permutations.
# usage: klt.py census.json side steps D NL [init=w1,w2,...] idx...   (words as dot-separated letters)
import sys, json, itertools
from lo_census import load
from selfrep import build, act_path, trivial, inv
from kkps import red

def level1_orbit(K, S, v):
    rep = {v: ()}; todo = [v]
    while todo:
        u = todo.pop()
        for g in S:
            u2 = act_path(K, g, (u,))[0][0]
            if u2 not in rep: rep[u2] = red(K, g + rep[u]); todo.append(u2)
    return rep

def section_pool(K, S, v):
    rep = level1_orbit(K, S, v)
    P = set()
    for u, r in rep.items():
        for g in S:
            u2 = act_path(K, g + r, (v,))[0][0]
            w = red(K, inv(K, rep[u2]) + g + r)
            y, s = act_path(K, w, (v,)); assert y == (v,)
            s = red(K, s)
            if s: P.add(s)
    return sorted(P, key=lambda s: (len(s), s))

def run(K, steps, D, NL, maxgens=8, init=None):
    V = list(itertools.product(K['X'], repeat=NL)); ix = {x: i for i, x in enumerate(V)}
    perm = lambda w: tuple(ix[act_path(K, w, x)[0]] for x in V)
    mul = lambda p, q: tuple(p[i] for i in q)
    def pinv(p):
        r = [0] * len(p)
        for i, x in enumerate(p): r[x] = i
        return tuple(r)
    for v in K['X']:
        chain = [init or [(a,) for a in range(K['nL'])]]
        for k in range(steps):
            S = chain[-1]
            if len(level1_orbit(K, S, v)) != len(K['X']): break      # (a) fails for L_k
            pool = section_pool(K, S, v)
            pool = pool + [inv(K, s) for s in pool if inv(K, s) not in pool]
            P = [(s, perm(s)) for s in pool]
            ball = {perm(()): ()}; fr = [(perm(()), ())]
            for _ in range(D):
                nf = []
                for p, w in fr:
                    for s, q in P:
                        r = mul(p, q)
                        if r not in ball: ball[r] = w + s; nf.append((r, w + s))
                fr = nf
            for j in range(k, -1, -1):                                  # closing edge L_k -> L_j
                expr = {}
                for t in chain[j]:
                    pt = perm(t); hit = None
                    for x, wx in ball.items():
                        y = mul(pinv(x), pt)
                        if y in ball:
                            cand = red(K, wx + ball[y])
                            if trivial(K, red(K, cand + inv(K, t))): hit = cand; break
                    if hit is None: break
                    expr[str(t)] = hit
                if len(expr) == len(chain[j]):
                    return dict(v=v, chain=chain, close_from=k, close_to=j, expressions=expr)
            # L_{k+1}: shortest pool elements, greedily, while the level-NL group grows (at most maxgens)
            from sympy.combinatorics import Permutation, PermutationGroup
            nxt, order = [], 1
            for s, q in P:
                if len(nxt) >= maxgens: break
                o = PermutationGroup([Permutation(list(perm(t))) for t in nxt + [s]]).order()
                if o > order: nxt.append(s); order = o
            chain.append(nxt)
    return None

if __name__ == "__main__":
    path, side, steps, D, NL = sys.argv[1], sys.argv[2], *map(int, sys.argv[3:6])
    init = None
    if sys.argv[6].startswith('init='):          # init=0.3,2.3 : L_0 generated by the words (0,3) and (2,3)
        init = [tuple(map(int, w.split('.'))) for w in sys.argv[6][5:].split(',')]; del sys.argv[6]
    for i, G in load(path):
        if i in set(map(int, sys.argv[6:])):
            K = build(G, side)
            r = run(K, steps, D, NL, init=init)
            print(json.dumps(dict(census=path, idx=i, side=side, fixed_letter=K['f'], steps=steps, D=D, NL=NL,
                                  certificate=r)), flush=True)
