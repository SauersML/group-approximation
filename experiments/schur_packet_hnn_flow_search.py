#!/usr/bin/env python3
"""Enumerate central-character flows for HNN charts of the support packet.

The support compiler has commutator matrix

    [[J, J z_e],
     [z_f,     1]].

For a central character k=(j,e,f), its evaluated F_2 matrix is
[[j,j+e],[f,0]].  A full-center Pauli edge is generated by one nonzero
p-row and one nonzero q-column.  Its commutator is a nonzero central word
ell.  Two such edges are isomorphic after any T in GL(3,2) carrying
ell_source to ell_target.  The induced character transport satisfies
k_source=T^t k_target.

This script exhausts the 168 central automorphisms and all packet pivots.  It
looks for transports sending the forbidden character (1,0,1) to the harmless
parent-absent/child-absent character (1,0,0), then computes the exact packet
dimension and Pauli restriction-multiplicity ratios.  It also finds small
families whose distinct harmless targets create branching pressure.

No third-party packages are required.
"""
from __future__ import annotations

import json
from itertools import combinations, product


Bit3 = tuple[int, int, int]
Bit2 = tuple[int, int]
Matrix3 = tuple[Bit3, Bit3, Bit3]

NONZERO2: tuple[Bit2, ...] = ((1, 0), (0, 1), (1, 1))
NONZERO3: tuple[Bit3, ...] = tuple(
    x for x in product((0, 1), repeat=3) if x != (0, 0, 0)
)

# Coefficient vectors in the central basis (J,z_e,z_f).
COMMUTATOR_COEFFICIENTS: tuple[tuple[Bit3, Bit3], tuple[Bit3, Bit3]] = (
    ((1, 0, 0), (1, 1, 0)),
    ((0, 0, 1), (0, 0, 0)),
)

FORBIDDEN: Bit3 = (1, 0, 1)
HARMLESS: Bit3 = (1, 0, 0)


def xor3(*vectors: Bit3) -> Bit3:
    return tuple(a ^ b ^ c for a, b, c in zip(*vectors))  # type: ignore[return-value]


def add3(left: Bit3, right: Bit3) -> Bit3:
    return tuple(a ^ b for a, b in zip(left, right))  # type: ignore[return-value]


def dot3(left: Bit3, right: Bit3) -> int:
    return sum(a & b for a, b in zip(left, right)) & 1


def mat_vec(matrix: Matrix3, vector: Bit3) -> Bit3:
    return tuple(dot3(row, vector) for row in matrix)  # type: ignore[return-value]


def transpose(matrix: Matrix3) -> Matrix3:
    return tuple(tuple(matrix[i][j] for i in range(3)) for j in range(3))  # type: ignore[return-value]


def mat_mul(left: Matrix3, right: Matrix3) -> Matrix3:
    right_t = transpose(right)
    return tuple(
        tuple(dot3(row, column) for column in right_t) for row in left
    )  # type: ignore[return-value]


IDENTITY: Matrix3 = ((1, 0, 0), (0, 1, 0), (0, 0, 1))


def rank_f2(rows: list[list[int]]) -> int:
    work = [row[:] for row in rows]
    pivot_row = 0
    for column in range(len(work[0])):
        pivot = next(
            (row for row in range(pivot_row, len(work)) if work[row][column]),
            None,
        )
        if pivot is None:
            continue
        work[pivot_row], work[pivot] = work[pivot], work[pivot_row]
        for row in range(len(work)):
            if row != pivot_row and work[row][column]:
                work[row] = [a ^ b for a, b in zip(work[row], work[pivot_row])]
        pivot_row += 1
    return pivot_row


def invert3(matrix: Matrix3) -> Matrix3:
    augmented = [list(row) + list(IDENTITY[i]) for i, row in enumerate(matrix)]
    pivot_row = 0
    for column in range(3):
        pivot = next(row for row in range(pivot_row, 3) if augmented[row][column])
        augmented[pivot_row], augmented[pivot] = augmented[pivot], augmented[pivot_row]
        for row in range(3):
            if row != pivot_row and augmented[row][column]:
                augmented[row] = [a ^ b for a, b in zip(augmented[row], augmented[pivot_row])]
        pivot_row += 1
    return tuple(tuple(row[3:]) for row in augmented)  # type: ignore[return-value]


def all_gl3() -> list[Matrix3]:
    matrices = []
    for flat in product((0, 1), repeat=9):
        matrix: Matrix3 = (
            tuple(flat[0:3]),  # type: ignore[assignment]
            tuple(flat[3:6]),  # type: ignore[assignment]
            tuple(flat[6:9]),  # type: ignore[assignment]
        )
        if rank_f2([list(row) for row in matrix]) == 3:
            matrices.append(matrix)
    assert len(matrices) == 168
    return matrices


def packet_rank(character: Bit3) -> int:
    j, e, f = character
    return rank_f2([[j, j ^ e], [f, 0]])


def packet_dimension(character: Bit3) -> int:
    return 1 << packet_rank(character)


def pivot_word(row: Bit2, column: Bit2) -> Bit3:
    result: Bit3 = (0, 0, 0)
    for i in range(2):
        for j in range(2):
            if row[i] & column[j]:
                result = add3(result, COMMUTATOR_COEFFICIENTS[i][j])
    return result


def packet_pivots() -> dict[Bit3, list[tuple[Bit2, Bit2]]]:
    pivots: dict[Bit3, list[tuple[Bit2, Bit2]]] = {}
    for row, column in product(NONZERO2, repeat=2):
        word = pivot_word(row, column)
        if word != (0, 0, 0):
            pivots.setdefault(word, []).append((row, column))
    return pivots


def transport_character(matrix: Matrix3, source: Bit3) -> Bit3:
    """Solve source=T^t target for target."""
    inverse_transpose = invert3(transpose(matrix))
    target = mat_vec(inverse_transpose, source)
    assert mat_vec(transpose(matrix), target) == source
    return target


def matrix_weight(matrix: Matrix3) -> int:
    return sum(sum(row) for row in matrix)


def character_text(character: Bit3) -> str:
    return "".join(str(bit) for bit in character)


def matrix_rows(matrix: Matrix3) -> list[str]:
    return ["".join(str(bit) for bit in row) for row in matrix]


def orbit(matrix: Matrix3, start: Bit3) -> list[Bit3]:
    output = [start]
    current = transport_character(matrix, start)
    while current != start:
        if current in output:
            raise AssertionError("character transport is not a permutation")
        output.append(current)
        current = transport_character(matrix, current)
    return output


def search() -> dict[str, object]:
    pivots = packet_pivots()
    gl3 = all_gl3()
    assert set(pivots) == {
        (0, 0, 1),
        (0, 1, 0),
        (0, 1, 1),
        (1, 0, 0),
        (1, 0, 1),
        (1, 1, 0),
    }

    transitions = []
    for matrix, source_word in product(gl3, pivots):
        target_word = mat_vec(matrix, source_word)
        if target_word not in pivots:
            continue
        target = transport_character(matrix, FORBIDDEN)
        if dot3(FORBIDDEN, source_word) != 1:
            continue
        assert dot3(target, target_word) == 1
        transitions.append((matrix, source_word, target_word, target))

    to_harmless = [item for item in transitions if item[3] == HARMLESS]
    involutive_to_harmless = [
        item for item in to_harmless if mat_mul(item[0], item[0]) == IDENTITY
    ]
    assert to_harmless
    assert involutive_to_harmless
    involutive_to_harmless.sort(
        key=lambda item: (matrix_weight(item[0]), item[0], item[1], item[2])
    )

    best_matrix, best_source_word, best_target_word, _ = involutive_to_harmless[0]
    best_orbit = orbit(best_matrix, FORBIDDEN)
    assert best_orbit == [FORBIDDEN, HARMLESS]

    forbidden_dimension = packet_dimension(FORBIDDEN)
    harmless_dimension = packet_dimension(HARMLESS)
    assert (forbidden_dimension, harmless_dimension) == (4, 2)
    restriction_ratio = (forbidden_dimension // 2, harmless_dimension // 2)
    assert restriction_ratio == (2, 1)

    nonzero_targets = sorted(
        {target for _, _, _, target in transitions if target != FORBIDDEN}
    )
    assert (0, 0, 0) not in nonzero_targets

    rank_one_targets = sorted(
        {
            target
            for _, _, _, target in transitions
            if packet_rank(target) == 1 and target != FORBIDDEN
        }
    )

    # Pick one minimum-weight involutive chart for each distinct rank-one
    # target.  Each target receives the same Hilbert mass as the forbidden
    # source, so simultaneous charts exhibit exact branching demand.
    target_charts = []
    for target in rank_one_targets:
        candidates = [
            item
            for item in transitions
            if item[3] == target and mat_mul(item[0], item[0]) == IDENTITY
        ]
        if not candidates:
            continue
        candidates.sort(key=lambda item: (matrix_weight(item[0]), item[0], item[1], item[2]))
        matrix, source_word, target_word, _ = candidates[0]
        target_charts.append(
            {
                "target": character_text(target),
                "target_rank": packet_rank(target),
                "target_dimension": packet_dimension(target),
                "matrix": matrix_rows(matrix),
                "source_commutator": character_text(source_word),
                "target_commutator": character_text(target_word),
                "orbit": [character_text(x) for x in orbit(matrix, FORBIDDEN)],
            }
        )

    all_target_charts = []
    for target in nonzero_targets:
        candidates = [
            item
            for item in transitions
            if item[3] == target and mat_mul(item[0], item[0]) == IDENTITY
        ]
        if not candidates:
            continue
        candidates.sort(key=lambda item: (matrix_weight(item[0]), item[0], item[1], item[2]))
        matrix, source_word, target_word, _ = candidates[0]
        all_target_charts.append(
            {
                "target": character_text(target),
                "target_rank": packet_rank(target),
                "target_dimension": packet_dimension(target),
                "matrix": matrix_rows(matrix),
                "source_commutator": character_text(source_word),
                "source_pivot_witness": pivots[source_word][0],
                "target_commutator": character_text(target_word),
                "target_pivot_witness": pivots[target_word][0],
                "orbit": [character_text(x) for x in orbit(matrix, FORBIDDEN)],
            }
        )

    # Search subsets of rank-one targets with pairwise distinct characters.
    # The normalized Hilbert mass required at every target equals the source
    # mass because (dim source / 2)/(dim target / 2) copies compensate the
    # packet dimension.  Thus b charts require b*q target mass.
    branching_families = []
    for size in range(2, len(target_charts) + 1):
        for family in combinations(target_charts, size):
            branching_families.append(
                {
                    "branch_count": size,
                    "targets": [chart["target"] for chart in family],
                    "total_target_mass_per_source_mass": size,
                }
            )

    state_table = [
        {
            "character": character_text(character),
            "rank": packet_rank(character),
            "dimension": packet_dimension(character),
        }
        for character in product((0, 1), repeat=3)
    ]

    return {
        "central_basis": ["J", "z_e", "z_f"],
        "gl3_size": len(gl3),
        "packet_pivot_words": {
            character_text(word): len(witnesses) for word, witnesses in sorted(pivots.items())
        },
        "state_table": state_table,
        "pauli_transitions_from_forbidden": len(transitions),
        "transitions_to_harmless": len(to_harmless),
        "involutive_transitions_to_harmless": len(involutive_to_harmless),
        "best_forbidden_harmless_chart": {
            "matrix": matrix_rows(best_matrix),
            "source_commutator": character_text(best_source_word),
            "target_commutator": character_text(best_target_word),
            "orbit": [character_text(x) for x in best_orbit],
            "packet_dimensions": [forbidden_dimension, harmless_dimension],
            "pauli_restriction_multiplicities": list(restriction_ratio),
        },
        "rank_one_target_count": len(target_charts),
        "rank_one_target_charts": target_charts,
        "nonzero_target_count": len(all_target_charts),
        "nonzero_target_charts": all_target_charts,
        "maximum_distinct_rank_one_branches": len(target_charts),
        "maximum_target_mass_per_source_mass": len(target_charts),
        "regular_flow_certificate": {
            "central_sector_mass": "1/8",
            "all_chart_equalities_satisfied": True,
            "forbidden_mass_after_five_rank_one_charts_at_most": "1/6",
            "note": "full-center charts equate Hilbert mass and do not expose ambient irrep multiplicity",
        },
        "sample_branching_families": branching_families[-8:],
    }


if __name__ == "__main__":
    print(json.dumps(search(), indent=2, sort_keys=True))
