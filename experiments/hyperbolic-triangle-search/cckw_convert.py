# cckw_convert.py: TeX presentations of Caprace-Conder-Kaluba-Witzel (arXiv:2011.09276, source file
# presentations_3_3_4.tex) -> GAP records. Usage: python3.11 cckw_convert.py <tex> <names file> <out.g>
import re, sys

def tex_word_to_gap(w):
    w = w.strip()
    out = []; i = 0
    def need_star():
        return out and (out[-1][-1].isalnum() or out[-1][-1] == ')')
    while i < len(w):
        ch = w[i]
        if ch in 'abc':
            if need_star(): out.append('*')
            out.append(ch); i += 1
        elif ch == '(':
            if need_star(): out.append('*')
            out.append('('); i += 1
        elif ch == ')':
            out.append(')'); i += 1
        elif ch == '^':
            m = re.match(r'\^\{(-?\d+)\}', w[i:])
            if not m: raise ValueError("bad exponent in %r at %d" % (w, i))
            out.append('^' + m.group(1)); i += len(m.group(0))
        elif ch.isspace():
            i += 1
        else:
            raise ValueError("unexpected %r in %r" % (ch, w))
    return ''.join(out)

tex = open(sys.argv[1]).read()
names = [l.strip() for l in open(sys.argv[2]) if l.strip()]
recs = {}
for m in re.finditer(r'G\^\{(\d+),(\d+),(\d+)\}_\{(\d+)\}\s*=\s*\\langle a, b, c\\mid\{\}&(.*?)\\rangle', tex):
    key = "G_%s^{%s,%s,%s}" % (m.group(4), m.group(1), m.group(2), m.group(3))
    rels = [r.strip() for r in m.group(5).split(',') if r.strip()]
    recs[key] = [tex_word_to_gap(r) for r in rels]
with open(sys.argv[3], 'w') as f:
    f.write('# generated by cckw_convert.py from presentations_3_3_4.tex (arXiv:2011.09276 source)\n')
    f.write('CCKW := [\n')
    for n in names:
        if n not in recs: raise KeyError(n)
        f.write('  rec(name := "%s", rels := [%s]),\n' % (n, ', '.join(recs[n])))
    f.write('];\n')
print("converted", len(names), "of", len(recs), "presentations")
