"""Extract an infinite projection from every hard atlas prefix pair.

The companion script ``atlas_survivor_prefix_obstruction.py`` proves that
the star algebra generated by each hard pair ``q,l`` contains the six
cylinder projections for

    D = (000, 001, 010, 011, 10, 11).

This script gives the structural consequence.  It finds a D-cylinder ``e``,
its proper binary child ``f``, and a word ``v`` in ``q,l,q*,l*`` and the
D-cylinder projections such that

    v* v = e,       v v* = f < e.

Thus the generated star algebra contains an infinite projection and cannot
embed in a finite-dimensional matrix algebra.  Every identity is checked by
exact arithmetic in the binary Leavitt algebra.
"""

import collections
import json
import sys

sys.path.insert(0, "experiments")

from atlas_kernel_collision_enumerator import ONE  # noqa: E402
from atlas_survivor_prefix_gallery import (  # noqa: E402
    chart_matrix,
    oriented_rotations,
    survivor_representatives,
    value_key,
)
from atlas_survivor_prefix_obstruction import (  # noqa: E402
    BASE_CODE,
    HARD_CASES,
    cylinder_projection,
    leavitt_is_zero,
    leavitt_star,
)
from atlas_two_chart_search import (  # noqa: E402
    leavitt_add,
    leavitt_chart_element,
    leavitt_mul,
)


def corner(left, value, right):
    return leavitt_mul(
        leavitt_mul(cylinder_projection(left), value),
        cylinder_projection(right),
    )


def support_graph(matrix):
    graph = collections.defaultdict(set)
    for row in range(len(BASE_CODE)):
        for column in range(len(BASE_CODE)):
            if row != column and int(matrix[row, column]):
                graph[row].add(column)
                graph[column].add(row)
    return graph


def path_between(graph, source, target):
    parents = {source: None}
    queue = collections.deque([source])
    while queue:
        vertex = queue.popleft()
        if vertex == target:
            break
        for following in sorted(graph[vertex]):
            if following not in parents:
                parents[following] = vertex
                queue.append(following)
    if target not in parents:
        raise AssertionError("vertices lie in different q-support components")
    path = []
    vertex = target
    while vertex is not None:
        path.append(vertex)
        vertex = parents[vertex]
    return list(reversed(path))


def matrix_unit_path(q, matrix, source, target):
    """Return a partial isometry from the source cylinder to the target."""
    q_star = leavitt_star(q)
    graph = support_graph(matrix)
    path = path_between(graph, source, target)
    value = cylinder_projection(BASE_CODE[source])
    factors = []
    for old, new in zip(path, path[1:]):
        old_leaf = BASE_CODE[old]
        new_leaf = BASE_CODE[new]
        if int(matrix[new, old]):
            edge = corner(new_leaf, q, old_leaf)
            factors.append(f"p_{new_leaf} q p_{old_leaf}")
        elif int(matrix[old, new]):
            edge = corner(new_leaf, q_star, old_leaf)
            factors.append(f"p_{new_leaf} q* p_{old_leaf}")
        else:
            raise AssertionError("support-graph edge has no matrix entry")
        value = leavitt_mul(edge, value)
    return value, factors, [BASE_CODE[index] for index in path]


def find_splitting_corner(q, next_unit):
    """Find an l-corner joining a D-cylinder to a child in its q-component."""
    matrix = chart_matrix(q, BASE_CODE)
    if matrix is None:
        raise AssertionError("q is not in the six-cylinder chart")
    components = []
    unseen = set(range(len(BASE_CODE)))
    graph = support_graph(matrix)
    while unseen:
        root = min(unseen)
        component = set([root])
        queue = collections.deque([root])
        while queue:
            vertex = queue.popleft()
            for following in graph[vertex]:
                if following not in component:
                    component.add(following)
                    queue.append(following)
        components.append(component)
        unseen -= component

    component_of = {
        vertex: component
        for component in components
        for vertex in component
    }
    for range_index, range_leaf in enumerate(BASE_CODE):
        for source_index, source_leaf in enumerate(BASE_CODE):
            value = corner(range_leaf, next_unit, source_leaf)
            if len(value) != 1:
                continue
            (alpha, beta), coefficient = next(iter(value.items()))
            if coefficient != 1:
                continue
            alpha_word = "".join(map(str, alpha))
            beta_word = "".join(map(str, beta))

            # l maps the proper child beta of e to the base cylinder b.
            if (alpha_word == range_leaf and beta_word.startswith(source_leaf)
                    and len(beta_word) == len(source_leaf) + 1
                    and component_of[range_index] is component_of[source_index]):
                return {
                    "e_index": source_index,
                    "b_index": range_index,
                    "child": beta_word,
                    "corner": value,
                    "orientation": "child-to-base",
                    "corner_expression": f"p_{range_leaf} l p_{source_leaf}",
                }

            # l maps the base cylinder b to the proper child alpha of e.
            if (beta_word == source_leaf and alpha_word.startswith(range_leaf)
                    and len(alpha_word) == len(range_leaf) + 1
                    and component_of[range_index] is component_of[source_index]):
                return {
                    "e_index": range_index,
                    "b_index": source_index,
                    "child": alpha_word,
                    "corner": value,
                    "orientation": "base-to-child",
                    "corner_expression": f"p_{range_leaf} l p_{source_leaf}",
                }
    raise AssertionError("no splitting l-corner found")


def certify_pair(q, next_unit):
    matrix = chart_matrix(q, BASE_CODE)
    splitting = find_splitting_corner(q, next_unit)
    e_index = splitting["e_index"]
    b_index = splitting["b_index"]
    e = cylinder_projection(BASE_CODE[e_index])
    f = cylinder_projection(splitting["child"])
    bridge, bridge_factors, path = matrix_unit_path(
        q, matrix, e_index, b_index)
    splitting_corner = splitting["corner"]

    # bridge maps e -> b.  Compose with the l-corner in the orientation
    # which maps b -> f.
    if splitting["orientation"] == "child-to-base":
        v = leavitt_mul(leavitt_star(splitting_corner), bridge)
        expression = f"({splitting['corner_expression']})* " + " ".join(
            reversed(bridge_factors))
    else:
        v = leavitt_mul(splitting_corner, bridge)
        expression = f"{splitting['corner_expression']} " + " ".join(
            reversed(bridge_factors))

    if not leavitt_is_zero(leavitt_add(leavitt_mul(leavitt_star(v), v), e)):
        raise AssertionError("v* v is not e")
    if not leavitt_is_zero(leavitt_add(leavitt_mul(v, leavitt_star(v)), f)):
        raise AssertionError("v v* is not f")

    other_child = BASE_CODE[e_index] + ("1" if splitting["child"].endswith("0") else "0")
    complement = cylinder_projection(other_child)
    if not leavitt_is_zero(leavitt_add(e, leavitt_add(f, complement))):
        raise AssertionError("binary child decomposition failed")
    if not complement:
        raise AssertionError("proper complement vanished")

    return {
        "infinite_projection": BASE_CODE[e_index],
        "proper_equivalent_child": splitting["child"],
        "nonzero_complement": other_child,
        "q_support_path": path,
        "bridge_factors": bridge_factors,
        "splitting_corner": splitting["corner_expression"],
        "splitting_orientation": splitting["orientation"],
        "partial_isometry_expression": expression.strip(),
        "verified_identities": [
            "v* v = e",
            "v v* = f",
            "e = f + p_complement",
        ],
    }


def hard_pairs():
    pairs = {}
    for boundary_index, representative in survivor_representatives():
        lookup = {
            (inverted, rotation): prefix_length
            for inverted, rotation, prefix_length in HARD_CASES[boundary_index]
        }
        for inverted, rotation, word in oriented_rotations(representative):
            prefix_length = lookup.get((inverted, rotation))
            if prefix_length is None:
                continue
            q = ONE
            for factor, matrix in word[:prefix_length]:
                q = leavitt_mul(q, leavitt_chart_element(factor, matrix))
            factor, matrix = word[prefix_length]
            next_unit = leavitt_chart_element(factor, matrix)
            pairs.setdefault(
                (value_key(q), value_key(next_unit)),
                (boundary_index, inverted, rotation, prefix_length, q,
                 next_unit),
            )
    return list(pairs.values())


def main():
    results = []
    for (boundary_index, inverted, rotation, prefix_length, q,
         next_unit) in hard_pairs():
        results.append({
            "boundary_index": boundary_index,
            "inverted": inverted,
            "rotation": rotation,
            "prefix_length": prefix_length,
            **certify_pair(q, next_unit),
        })
    if len(results) != 6:
        raise AssertionError("expected six distinct hard prefix pairs")
    print(json.dumps({
        "distinct_hard_prefix_pairs": len(results),
        "all_contain_an_infinite_projection": True,
        "results": results,
    }, indent=2))


if __name__ == "__main__":
    main()
