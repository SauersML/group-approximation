#!/usr/bin/env python3
"""Linton graph certificates for the NONFREE length-16 classes whose Magnus piece is primitive.

For each NONFREE word of lg_words16.out: Nielsen-adapt to t-exponent sum 0 (census.adapt with the
unique character), take the canonical Magnus sequence (census.magnus, census.canon), form W_0 in
F(a_0, a_1, a_2) (letters coded 1, 2, 3), and run the full Whitehead descent of pieces.py.  When
W_0 is primitive the descent returns an automorphism phi of F(3) with phi(W_0) conjugate to
x_i^(+-1).  Killing x_i gives rho: F(3) -> F(2), and rho.phi induces an isomorphism
B_0 = F(3)/<<W_0>> -> F(2).  The HNN structure t a_h t^-1 = a_(h+1) becomes K = F(2),
A = <rho phi(a_0), rho phi(a_1)>, B = <rho phi(a_1), rho phi(a_2)>, psi(rho phi(a_h)) =
rho phi(a_(h+1)), and lintongraph.certify(2, A, B) is run.

Checks printed per class: phi(W_0) cyclically reduces to one letter; the images phi(x_1..x_3)
fold to the rose on 3 letters (so phi is onto, hence an automorphism, independently of how phi was
built); rho phi(W_0) freely reduces to 1; then the certificate verdict with its data.
Usage: primcert.py LG_WORDS16_OUT
"""
import sys, os, math
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'research/artifacts/or-unpeelable-census-scripts-2026-09-12'))
sys.path.insert(0, os.path.join(ROOT, 'research/artifacts/one-relator-linton-graph-certificates-scripts'))
sys.path.insert(0, HERE)
import census as C
import lintongraph as LG
import pieces as P


def rose_check(imgs, k):
    """True iff the subgroup generated by imgs is all of F(k): its folded Stallings graph is one
    vertex with k loops."""
    G = LG.Graph([tuple(v) for v in imgs])
    labels = sorted(e[1] for e in G.E)
    return G.nv == 1 and labels == list(range(1, k + 1))


def main():
    code = {'a': 1, 'A': -1, 't': 2, 'T': -2}
    words = []
    for line in open(sys.argv[1]):
        f = line.split()
        if len(f) >= 6 and f[0] == 'VERDICT' and f[-1] == 'NONFREE':
            words.append(f[2])
    counts = {}
    for wtxt in words:
        w = [code[ch] for ch in wtxt]
        phis = P.phis_for(w)
        assert len(phis) == 1, wtxt
        x, y = phis[0]
        seq = C.magnus(C.adapt(list(w), x, y))
        cs = list(C.canon(seq))
        letters, g, W = P.piece(cs)
        if len(letters) != 3 or g != 1:
            print('SKIP %s levels=%d g=%d' % (wtxt, len(letters), g)); counts['SKIP'] = counts.get('SKIP', 0) + 1
            continue
        Wm, phi = P.wh_descend(W, 3)
        if len(Wm) != 1:
            print('NONPRIM %s W0=%s whmin=%d' % (wtxt, P.wstr(W), len(Wm)), flush=True)
            counts['NONPRIM'] = counts.get('NONPRIM', 0) + 1
            continue
        img = P.apply(phi, W, cyclic=True)
        assert len(img) == 1, (wtxt, img)
        xi = abs(img[0])
        assert rose_check([phi[j] for j in (1, 2, 3)], 3), wtxt
        other = [j for j in (1, 2, 3) if j != xi]
        ren = {xi: [], other[0]: [1], other[1]: [2]}
        rho_phi = {h: P.apply(ren, phi[h]) for h in (1, 2, 3)}
        assert P.apply(rho_phi, W) == [], (wtxt, 'rho phi(W_0) != 1')
        Agens = [tuple(rho_phi[1]), tuple(rho_phi[2])]
        Bgens = [tuple(rho_phi[2]), tuple(rho_phi[3])]
        verdict, info = LG.certify(2, Agens, Bgens)
        V = ' '.join('%s:%s' % (p, LG.wstr(n, 2)) for p, n in info.get('V', []))
        print('VERDICT PRIM %s phi=%d,%d W0=%s kill=x%d A=[%s,%s] B=[%s,%s] rankA=%s rankB=%s sZ=%s depth=%s '
              'mixed_nc=%s V=[%s] H=%s t=%s hloops=%s tloops=%s cycle=%s -> %s'
              % (wtxt, x, y, P.wstr(W), xi, LG.wstr(Agens[0], 2), LG.wstr(Agens[1], 2),
                 LG.wstr(Bgens[0], 2), LG.wstr(Bgens[1], 2), info.get('rankA'), info.get('rankB'),
                 info.get('sZ'), info.get('depth'), info.get('mixed_noncyclic'), V, info.get('H'),
                 info.get('t'), info.get('hloops'), info.get('tloops'), bool(info.get('cycle')), verdict),
              flush=True)
        key = verdict.split('(')[0]
        counts[key] = counts.get(key, 0) + 1
    print('COUNTS %s' % sorted(counts.items()))
    print('SENTINEL_DONE', flush=True)


if __name__ == '__main__':
    main()
