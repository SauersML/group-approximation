#!/usr/bin/env python3
"""Integer-labelled girth surfaces for the six hyperbolic rank-3 KMS families of CCKW (lane hl-surface-subgroups).

Vertex types i = 0,1,2 with half girths m_i; the edge of type k carries generator g_k, and the vertex group of
type i is generated by g_j, g_k ({i,j,k} = {0,1,2}, j < k).  A vertex group is U3 (relators [x,y,x],[x,y,y]) or
U4 with a designated x-generator (relators [x,y,x],[x,y,y,x],[x,y,y,y]).  Labels are nonzero integers in LABELS;
a vertex word is required to be trivial in the INTEGRAL group (normal-form laws below), so a solution is a girth
surface for the family at every odd prime not dividing a label.
Families (g_0 = c, g_1 = a, g_2 = b; X_0 = <a,b>, X_1 = <b,c>, X_2 = <a,c>):
  HC2_1  (3,3,4): X_0 U3, X_1 U3, X_2 U4 with x = a (type 1)
  HB2_2  (3,4,4): X_0 U3, X_1 U4 x = c (type 0), X_2 U4 x = c (type 0)
  HC2_2  (3,4,4): X_0 U3, X_1 U4 x = b (type 2), X_2 U4 x = a (type 1)
  HBC2_2 (3,4,4): X_0 U3, X_1 U4 x = b (type 2), X_2 U4 x = c (type 0)
  HB2_3  (4,4,4): X_0 U4 x = a (1), X_1 U4 x = b (2), X_2 U4 x = a (1)
  HBC2_3 (4,4,4): X_0 U4 x = a (1), X_1 U4 x = b (2), X_2 U4 x = c (0)
usage: kms_girth_search.py FAMILY T [max_solutions_per_surface] [max_surfaces_with_solutions] > out.json
"""
import sys, json, time
from itertools import product

FAMILIES = {
    "HC2_1": ((3, 3, 4), [("U3",), ("U3",), ("U4", 1)]),
    "HB2_2": ((3, 4, 4), [("U3",), ("U4", 0), ("U4", 0)]),
    "HC2_2": ((3, 4, 4), [("U3",), ("U4", 2), ("U4", 1)]),
    "HBC2_2": ((3, 4, 4), [("U3",), ("U4", 2), ("U4", 0)]),
    "HB2_3": ((4, 4, 4), [("U4", 1), ("U4", 2), ("U4", 1)]),
    "HBC2_3": ((4, 4, 4), [("U4", 1), ("U4", 2), ("U4", 0)]),
}
import os
LABELS = tuple(int(x) for x in os.environ.get("KMS_LABELS", "-2,-1,1,2").split(","))
assert 0 not in LABELS
PAIR = {0: (1, 2), 1: (0, 2), 2: (0, 1)}
TABLE_CACHE = {}

def word_trivial(kind, letters):
    """letters: list of (edge_type, exponent); U3: x = first letter type; U4: x = designated type."""
    if kind[0] == "U3":
        xk = letters[0][0]; beta = alpha = mu = 0
        for k, e in letters:
            if k == xk: alpha += e
            else: mu += alpha * e; beta += e
        return beta == 0 and alpha == 0 and mu == 0
    xk = kind[1]; beta = gamma = mu = nu = 0
    for k, e in letters:
        if k == xk: gamma += e
        else: nu += gamma * e * (e - 1) // 2 + e * mu; mu += e * gamma; beta += e
    return beta == 0 and gamma == 0 and mu == 0 and nu == 0

def surfaces(T, M):
    r = [[-1] * T for _ in range(3)]; nch = [1]; found = []
    def path_ok(t, k):
        for j in range(3):
            if j == k: continue
            m2 = 2 * M[3 - j - k]; s, steps, cur, closed = t, 0, k, False
            while True:
                nx = r[cur][s]
                if nx < 0: break
                steps += 1; s = nx; cur = j if cur == k else k
                if s == t and cur == k: closed = True; break
                if steps >= m2: return False
            if closed:
                if steps != m2: return False
                continue
            s, back, cur = t, 0, j
            while True:
                nx = r[cur][s]
                if nx < 0: break
                back += 1; s = nx; cur = k if cur == j else j
                if back > m2: return False
            if steps + back >= m2: return False
        return True
    def relabel(root):
        lab = {root: 0}; order = [root]; q = 0
        while q < len(order):
            u = order[q]; q += 1
            for kk in range(3):
                v = r[kk][u]
                if v not in lab: lab[v] = len(order); order.append(v)
        return tuple(lab[r[kk][u]] for u in order for kk in range(3))
    def rec(t, k):
        while t < nch[0] and r[k][t] >= 0:
            k += 1
            if k == 3: k = 0; t += 1
        if t == nch[0]:
            if nch[0] == T:
                cur = relabel(0)
                if cur == tuple(r[kk][u] for u in range(T) for kk in range(3)) and all(relabel(x) >= cur for x in range(1, T)):
                    found.append([list(x) for x in r])
            return
        cands = [s for s in range(t + 1, nch[0]) if r[k][s] < 0]
        if nch[0] < T: cands.append(nch[0])
        for s in cands:
            new = (s == nch[0])
            if new: nch[0] += 1
            r[k][t] = s; r[k][s] = t
            if path_ok(t, k) and path_ok(s, k): rec(t, k)
            r[k][t] = -1; r[k][s] = -1
            if new: nch[0] -= 1
    rec(0, 0)
    return found

def closes(r, T, M):
    for i in range(3):
        j, k = PAIR[i]
        for t in range(T):
            u, cur, seen = t, j, [t]
            for _ in range(2 * M[i]):
                u = r[cur][u]; cur = k if cur == j else j; seen.append(u)
            if u != t or len(set(seen[:-1])) != 2 * M[i]: return False
    return True

def orientable(r, T):
    col = {0: 0}; st = [0]
    while st:
        u = st.pop()
        for k in range(3):
            v = r[k][u]
            if v not in col: col[v] = 1 - col[u]; st.append(v)
            elif col[v] == col[u]: return False
    return True

def constraints(r, T, M, kinds):
    eid, edges = {}, []
    for k in range(3):
        for t in range(T):
            if t < r[k][t]: eid[(k, t)] = len(edges); edges.append((k, t, r[k][t]))
    cons = []
    for i in range(3):
        j, k = PAIR[i]; done = set()
        for t0 in range(T):
            if t0 in done: continue
            occ, types, u, cur = [], [], t0, j
            for _ in range(2 * M[i]):
                v = r[cur][u]; done.add(u)
                occ.append((eid[(cur, min(u, v))], 1 if u < v else -1)); types.append(cur)
                u = v; cur = k if cur == j else j
            vars_ = [e for e, _ in occ]; signs = [s for _, s in occ]
            key = (kinds[i], tuple(types), tuple(signs))
            if key not in TABLE_CACHE:
                TABLE_CACHE[key] = [vals for vals in product(LABELS, repeat=len(vars_))
                                    if word_trivial(kinds[i], [(types[q], signs[q] * vals[q]) for q in range(len(vars_))])]
            allowed = TABLE_CACHE[key]
            cons.append((vars_, allowed))
    return edges, cons

def solve(nvar, cons, limit):
    assign = [None] * nvar; sols = []
    bycon = [[] for _ in range(nvar)]
    for ci, (vs, _) in enumerate(cons):
        for q, v in enumerate(vs): bycon[v].append((ci, q))
    live = [list(al) for _, al in cons]
    order = []
    seen = set()
    for vs, al in sorted(cons, key=lambda c: len(c[1])):
        for v in vs:
            if v not in seen: seen.add(v); order.append(v)
    def rec(pos, live):
        if len(sols) >= limit: return
        if pos == nvar:
            sols.append(list(assign)); return
        v = order[pos]
        for val in LABELS:
            newlive = list(live); ok = True
            for ci, q in bycon[v]:
                filt = [tp for tp in live[ci] if tp[q] == val]
                if not filt: ok = False; break
                newlive[ci] = filt
            if ok:
                assign[v] = val; rec(pos + 1, newlive); assign[v] = None
            if len(sols) >= limit: return
    rec(0, live)
    return sols

def main():
    fam, T = sys.argv[1], int(sys.argv[2])
    limit = int(sys.argv[3]) if len(sys.argv) > 3 else 3
    maxsurf = int(sys.argv[4]) if len(sys.argv) > 4 else 10**9
    M, kinds = FAMILIES[fam]
    t0 = time.time(); S = surfaces(T, M)
    report = {"family": fam, "half_girths": M, "T": T, "labels": LABELS, "surfaces": len(S), "certificates": []}
    sys.stderr.write("%s T=%d: %d girth surfaces (%.1fs)\n" % (fam, T, len(S), time.time() - t0))
    with_sol = 0
    for idx, r in enumerate(S):
        assert closes(r, T, M)
        edges, cons = constraints(r, T, M, kinds)
        sols = solve(len(edges), cons, limit)
        ori = orientable(r, T)
        sys.stderr.write("  surface %d orientable %s solutions>=%d\n" % (idx, ori, len(sols)))
        for sol in sols:
            # independent re-evaluation of every vertex word
            for vs, al in cons: assert tuple(sol[v] for v in vs) in set(al)
            report["certificates"].append({"surface_index": idx, "orientable": ori, "T": T, "r0": r[0], "r1": r[1], "r2": r[2],
                                           "labels": [[k, t, s, sol[e]] for e, (k, t, s) in enumerate(edges)]})
        if sols:
            with_sol += 1
            if with_sol >= maxsurf: break
    report["surfaces_with_solutions"] = with_sol
    sys.stderr.write("done %.1fs, surfaces with solutions %d\n" % (time.time() - t0, with_sol))
    json.dump(report, sys.stdout)

if __name__ == "__main__":
    main()
