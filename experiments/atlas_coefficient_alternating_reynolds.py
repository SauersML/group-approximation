"""Compute the exact alternating-Reynolds operator on the coefficient algebra.

Let ``A`` be the five-dimensional abelian algebra generated by the four raw
coefficient cuts and their complementary carrier.  Let ``E'`` average
conjugation over the comb-transported order-32 Pauli packet.  This script
computes the trace-preserving self-adjoint contraction ``E_A E'|_A`` exactly
over the rationals and records its characteristic polynomial.
"""

import itertools
import json
import sys
from fractions import Fraction
from pathlib import Path

sys.path.insert(0, "experiments")

from atlas_double_pauli_comb_blocks import (  # noqa: E402
    cut,
    ga_add,
    ga_equal,
    ga_mul,
    ga_single,
    ga_sub,
    ga_trace,
    rational_string,
)
from atlas_raw_branch_pauli_cell import (  # noqa: E402
    generated_subgroup,
    inverse,
    root,
)
from atlas_raw_compressor_proper_infinite import (  # noqa: E402
    product,
    raw_and_comb,
    s,
    t,
)
from atlas_survivor_prefix_obstruction import leavitt_star  # noqa: E402


def matrix_mul(left, right):
    return [[sum(left[i][k] * right[k][j] for k in range(len(right)))
             for j in range(len(right[0]))]
            for i in range(len(left))]


def matrix_add_scalar_identity(matrix, scalar):
    return [[entry + (scalar if i == j else 0)
             for j, entry in enumerate(row)]
            for i, row in enumerate(matrix)]


def characteristic_polynomial(matrix):
    """Faddeev--LeVerrier coefficients of ``det(lambda I-matrix)``."""
    size = len(matrix)
    identity = [[Fraction(i == j) for j in range(size)] for i in range(size)]
    auxiliary = identity
    coefficients = [Fraction(1)]
    for degree in range(1, size + 1):
        product_matrix = matrix_mul(matrix, auxiliary)
        coefficient = -sum(product_matrix[i][i] for i in range(size)) / degree
        coefficients.append(coefficient)
        auxiliary = matrix_add_scalar_identity(product_matrix, coefficient)
    return coefficients


def polynomial_evaluate(coefficients, value):
    result = Fraction(0)
    for coefficient in coefficients:
        result = result * value + coefficient
    return result


def matrix_vec_mul(matrix, vector):
    return [sum(matrix[i][j] * vector[j] for j in range(len(vector)))
            for i in range(len(matrix))]


def main():
    raw, comb = raw_and_comb()
    identity = ga_single(product())
    x = (root(t(0), 0, 1), root(t(1), 0, 1))
    z = (root(s(0), 1, 2), root(s(1), 1, 2))
    c_raw = tuple(product(raw, value, raw, value) for value in x)
    a = tuple(product(x[index], c_raw[index]) for index in range(2))
    c = product(x[0], z[0], x[0], z[0])
    d = product(c_raw[0], z[0], c_raw[0], z[0])
    q = cut(identity, ga_single(d), negative=True)
    p = cut(identity, ga_single(c), negative=True)
    b = tuple(ga_add(
        ga_mul(p, ga_single(a[index])),
        ga_mul(ga_sub(identity, p), ga_single(x[index])),
    ) for index in range(2))

    coefficient_cuts = []
    labels = []
    for epsilon0, epsilon1 in itertools.product((-1, 1), repeat=2):
        labels.append(str((epsilon0, epsilon1)))
        coefficient_cuts.append(ga_mul(
            cut(q, b[0], negative=epsilon0 == -1),
            cut(q, b[1], negative=epsilon1 == -1),
        ))
    complement = ga_sub(identity, q)
    atoms = [*coefficient_cuts, complement]
    labels.append("outside_q")
    atom_traces = [ga_trace(value) for value in atoms]

    raw_pauli_packet = generated_subgroup((*x, *z), limit=64)
    transported_packet = [
        product(leavitt_star(comb), value, comb)
        for value in raw_pauli_packet
    ]

    # Average unique orbit representatives.  Orbit averaging equals group
    # averaging because every orbit point has the same stabilizer size.
    averaged_atoms = []
    orbit_orders = []
    for source in atoms:
        orbit = []
        for packet_element in transported_packet:
            moved = ga_mul(
                ga_single(packet_element),
                source,
                ga_single(inverse(packet_element)),
            )
            if not any(ga_equal(moved, old) for old in orbit):
                orbit.append(moved)
        orbit_orders.append(len(orbit))
        averaged_atoms.append(ga_add(*(
            [(coefficient / len(orbit), group_value)
             for coefficient, group_value in moved]
            for moved in orbit
        )))

    # Column j gives the coefficients of E_A E'(atom_j) in the atom basis.
    transition = []
    for target, target_trace in zip(atoms, atom_traces):
        transition.append([
            ga_trace(ga_mul(target, averaged)) / target_trace
            for averaged in averaged_atoms
        ])

    characteristic = characteristic_polynomial(transition)
    spectral_data = [
        (Fraction(1), [1, 1, 1, 1, 1]),
        (Fraction(19, 64), [1, 1, -1, -1, 0]),
        (Fraction(11, 64), [1, -1, 0, 0, 0]),
        (Fraction(11, 64), [0, 0, 1, -1, 0]),
        (Fraction(1, 16), [1, 1, 1, 1, -1]),
    ]
    result = {
        "atom_labels": labels,
        "atom_traces": [rational_string(value) for value in atom_traces],
        "transported_pauli_packet_order": len(transported_packet),
        "orbit_orders": orbit_orders,
        "alternating_reynolds_matrix": [
            [rational_string(value) for value in row]
            for row in transition
        ],
        "characteristic_polynomial_coefficients": [
            rational_string(value) for value in characteristic
        ],
        "characteristic_at_one": rational_string(
            polynomial_evaluate(characteristic, Fraction(1))),
        "exact_eigenpairs": [{
            "eigenvalue": rational_string(eigenvalue),
            "eigenvector": eigenvector,
            "verified": matrix_vec_mul(transition, eigenvector) == [
                eigenvalue * entry for entry in eigenvector],
        } for eigenvalue, eigenvector in spectral_data],
        "nontrivial_spectral_radius": "19/64",
        "preserves_identity_vector": all(
            sum(transition[i][j] for j in range(5)) == 1
            for i in range(5)),
        "weighted_self_adjoint": all(
            atom_traces[i] * transition[i][j]
            == atom_traces[j] * transition[j][i]
            for i in range(5) for j in range(5)),
    }
    expected_path = Path(__file__).with_name(
        "atlas-coefficient-alternating-reynolds.json")
    with expected_path.open(encoding="utf-8") as stream:
        expected = json.load(stream)
    if result != expected:
        raise AssertionError(result)
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
