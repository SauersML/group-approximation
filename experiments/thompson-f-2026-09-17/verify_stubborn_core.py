#!/usr/bin/env python3
"""Independent check that a list Z of positive normal forms is STUBBORN for S = S_(3,5).

Z stubborn: every z in Z has at most one s in S with  #{z' in Z : s z in S z'} = 1.

Independence from stubborn_core.cpp: products are computed as PL homeomorphisms of [0,1]
(exact integer coordinates over 2^K, every division checked), with
x_0, x_1 the standard generators and x_i = x_0^{-(i-1)} x_1 x_0^{i-1}; no normal-form
rewriting is used.  The relation x_j x_i = x_i x_{j+1} (i < j) is re-checked here, so the
monoid generated by the x_i is the positive monoid of F, and equal PL maps <=> equal elements.

Usage: verify_stubborn_core.py corefile     (one word per line, letters separated by ',')
"""
import bisect, json, sys

K = 256
ONE = 1 << K


def dy(p, q):
    assert q & (q - 1) == 0 and (p * ONE) % q == 0
    return p * ONE // q


def canon(pts):
    out = [pts[0]]
    for i in range(1, len(pts) - 1):
        x0, y0 = out[-1]
        x1, y1 = pts[i]
        x2, y2 = pts[i + 1]
        if (y1 - y0) * (x2 - x1) != (y2 - y1) * (x1 - x0):
            out.append((x1, y1))
    out.append(pts[-1])
    return (tuple(p[0] for p in out), tuple(p[1] for p in out))


def make(points):
    return canon([(dy(*a), dy(*b)) for a, b in points])


def ev(f, x):
    xs, ys = f
    i = bisect.bisect_right(xs, x) - 1
    if i >= len(xs) - 1:
        assert x == ONE
        return ONE
    q, r = divmod((x - xs[i]) * (ys[i + 1] - ys[i]), xs[i + 1] - xs[i])
    if r:
        raise ArithmeticError("dyadic depth exceeds K")
    return ys[i] + q


def inv(f):
    return (f[1], f[0])


def comp(f, g):
    """f o g (apply g first); the group product f*g."""
    gi = inv(g)
    xs = sorted(set(g[0]) | {ev(gi, x) for x in f[0]})
    return canon([(x, ev(f, ev(g, x))) for x in xs])


IDENT = make([((0, 1), (0, 1)), ((1, 1), (1, 1))])
X0 = make([((0, 1), (0, 1)), ((1, 2), (1, 4)), ((3, 4), (1, 2)), ((1, 1), (1, 1))])
X1 = make([((0, 1), (0, 1)), ((1, 2), (1, 2)), ((3, 4), (5, 8)), ((7, 8), (3, 4)), ((1, 1), (1, 1))])

GEN = {0: X0, 1: X1}


def gen(i):
    if i not in GEN:
        p = gen(i - 1)
        GEN[i] = comp(comp(inv(X0), p), X0)
    return GEN[i]


def word(w):
    f = IDENT
    for i in w:
        f = comp(f, gen(i))
    return f


def main():
    for i in range(6):
        for j in range(i + 1, 7):
            assert comp(gen(j), gen(i)) == comp(gen(i), gen(j + 1)), ("relation", i, j)
    Z = [tuple(int(t) for t in line.split(",")) for line in open(sys.argv[1]) if line.strip()]
    D = len(Z[0])
    assert all(len(z) == D and list(z) == sorted(z) for z in Z), "not normal forms of one degree"
    assert len(set(Z)) == len(Z), "repeated word"
    S = [(i, j) for i in range(3) for j in range(i, 4)]
    assert len(S) == 9
    zmaps = [word(z) for z in Z]
    assert len(set(zmaps)) == len(Z), "two words give the same element"
    smaps = [word(s) for s in S]
    prod = [[comp(sm, zm) for sm in smaps] for zm in zmaps]
    count = {}
    for row in prod:
        assert len(set(row)) == 9
        for w in row:
            count[w] = count.get(w, 0) + 1
    hist = {}
    for row in prod:
        c = sum(1 for w in row if count[w] == 1)
        hist[c] = hist.get(c, 0) + 1
    ok = max(hist) <= 1
    print(json.dumps({"file": sys.argv[1], "D": D, "size": len(Z), "S_Z": len(count),
                      "private_count_histogram": {str(k): v for k, v in sorted(hist.items())},
                      "max_letter": max(max(z) for z in Z), "stubborn": ok}))
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
