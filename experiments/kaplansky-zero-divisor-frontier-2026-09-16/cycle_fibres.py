#!/usr/bin/env python3
"""Magnus fibres of the unrecognized 5- and 6-cycle relators.

Input: the census files of research/artifacts/zds-three-support-theory-2026-09-13/
(cycle_relators.json for k = 5, cycle_relators6.json for k = 6). For every
class of type G we test the raw relator of the class representative and the
least forms printed by the census.

For a relator r in F(u, v) (letters +-1 = u, +-2 = v) and an epimorphism
phi: F(u, v) -> Z with phi(r) = 0 we
  1. change basis by Euclidean Nielsen moves to (a, t) with phi(a) = 0,
     phi(t) = 1, tracking u = U(a, t), v = V(a, t);
  2. rewrite r(U, V) in the letters a_j = t^j a t^-j;
  3. if the least index m and the largest index M each occur exactly once,
     then N = <a_m, ..., a_{M-1}> is normal in the group generated by u, v,
     with cyclic quotient, and conjugation by t acts on N as the image of an
     endomorphism theta of the free group F(x_0, ..., x_{n-1}), n = M - m.
     theta is checked to be an automorphism by computing an explicit inverse
     from the relation shifted down by one.
  4. for n = 2 we test theta([x0, x1]) against [x0, x1]^{+-1} up to conjugacy.

Exclusion rule (proved in research/artifacts/kaplansky-zero-divisor-frontier-2026-09-16.md):
a class is excluded in torsion-free hosts with cyclic centralizers if some form
and some phi give n <= 1, or n = 2 with theta([x0, x1]) conjugate to [x0, x1]^-1.
"""
import json
import math
import re
import sys
from collections import Counter, defaultdict

ART = "research/artifacts/zds-three-support-theory-2026-09-13/"


def red(w):
    out = []
    for c in w:
        if out and out[-1] == -c:
            out.pop()
        else:
            out.append(c)
    return out


def cred(w):
    w = red(w)
    while len(w) >= 2 and w[0] == -w[-1]:
        w = w[1:-1]
    return w


def inv(w):
    return [-c for c in reversed(w)]


def subst(w, img):
    """img: dict letter(positive) -> word."""
    out = []
    for c in w:
        out.extend(img[c] if c > 0 else inv(img[-c]))
    return red(out)


def canon_cyclic(w):
    w = cred(w)
    if not w:
        return ()
    return min(tuple(w[i:] + w[:i]) for i in range(len(w)))


def exps(w):
    return (sum(1 if c == 1 else -1 if c == -1 else 0 for c in w),
            sum(1 if c == 2 else -1 if c == -2 else 0 for c in w))


def phis(r, bound=4):
    eu, ev = exps(r)
    if (eu, ev) != (0, 0):
        g = math.gcd(eu, ev)
        p, q = ev // g, -eu // g
        return [(p, q), (-p, -q)]
    out = []
    for p in range(-bound, bound + 1):
        for q in range(-bound, bound + 1):
            if math.gcd(p, q) == 1:
                out.append((p, q))
    return out


def basis_change(p, q):
    """Return (U, V, a_letter, t_letter) with u = U, v = V in letters 1, 2 of
    a new basis (s1, s2), where phi(a) = 0 and phi(t) = +1."""
    U, V = [1], [2]
    P, Q = p, q
    while P != 0 and Q != 0:
        if abs(P) >= abs(Q):
            s = 1 if (P > 0) == (Q > 0) else -1
            # s1 = s1' s2^s, phi(s1') = P - s Q
            img = {1: [1] + [2 * s], 2: [2]}
            U, V = subst(U, img), subst(V, img)
            P = P - s * Q
        else:
            s = 1 if (P > 0) == (Q > 0) else -1
            img = {1: [1], 2: [2] + [1 * s]}
            U, V = subst(U, img), subst(V, img)
            Q = Q - s * P
    if P == 0:
        # a = s1, t = s2 with phi(s2) = Q = +-1
        if Q == -1:
            img = {1: [1], 2: [-2]}
            U, V = subst(U, img), subst(V, img)
        a, t = 1, 2
    else:
        if P == -1:
            img = {1: [-1], 2: [2]}
            U, V = subst(U, img), subst(V, img)
        a, t = 2, 1
    # relabel so that a = letter 1 and t = letter 2
    if a == 2:
        img = {1: [2], 2: [1]}
        U, V = subst(U, img), subst(V, img)
    return U, V


def rewrite(rp):
    """rp: cyclically reduced word in a = 1, t = 2 with t-exponent 0.
    Return the list of (j, e) for a_j^e."""
    h = 0
    out = []
    for c in rp:
        if abs(c) == 2:
            h += 1 if c > 0 else -1
        else:
            out.append((h, 1 if c > 0 else -1))
    assert h == 0
    return out


def fibre(r, p, q):
    U, V = basis_change(p, q)
    rp = cred(subst(r, {1: U, 2: V}))
    if not rp:
        return ("trivial", None)
    rho = rewrite(rp)
    if not rho:
        return ("t-power", None)
    idx = [j for j, _ in rho]
    m, M = min(idx), max(idx)
    cm, cM = idx.count(m), idx.count(M)
    if m == M:
        return ("n0" if cm == 1 else "not-fibred", None)
    if cm != 1 or cM != 1:
        return ("not-fibred", (m, M, cm, cM))
    n = M - m
    # letters x_i = a_{m+i} encoded as i+1
    word = [((j - m) + 1) * e for j, e in rho]
    # solve for x_n (index M) : rotate so that it is last
    pos = [i for i, c in enumerate(word) if abs(c) == n + 1][0]
    rot = word[pos + 1:] + word[:pos]
    eps = 1 if word[pos] > 0 else -1
    # rot * x_n^eps = 1  =>  x_n^eps = rot^-1
    xn = red(inv(rot)) if eps == 1 else red(rot)
    theta = {i: [i + 1] for i in range(1, n)}
    theta[n] = xn
    # inverse: shift relation down by one: letters index -1..n-1; solve x_{-1}
    word_dn = [c - 1 if c > 0 else c + 1 for c in word]  # x_i -> x_{i-1}; x_0 -> "x_{-1}" = 0
    pos0 = [i for i, c in enumerate(word_dn) if c == 0][0]
    eps0 = 1 if word[pos0] > 0 else -1
    rot0 = word_dn[pos0 + 1:] + word_dn[:pos0]
    xm1 = red(inv(rot0)) if eps0 == 1 else red(rot0)
    theta_inv = {i: [i - 1] for i in range(2, n + 1)}
    theta_inv[1] = xm1
    ok = all(subst(subst([i], theta_inv), theta) == [i] and
             subst(subst([i], theta), theta_inv) == [i] for i in range(1, n + 1))
    if not ok:
        return ("theta-not-verified", None)
    if n == 1:
        return ("n1", theta)
    if n == 2:
        z = [1, 2, -1, -2]
        tz = subst(z, theta)
        if canon_cyclic(tz) == canon_cyclic(inv(z)):
            return ("n2-inverting", theta)
        if canon_cyclic(tz) == canon_cyclic(z):
            return ("n2-preserving", theta)
        return ("n2-other", theta)
    return ("n%d" % n if n <= 4 else "n>=5", theta)


def forms_of(cls):
    out = [list(cls["relator"])]
    for s in re.findall(r"\(([-0-9, ]+)\)", cls["detail"]):
        out.append([int(x) for x in s.split(",")])
    return out


def run(k):
    fn = ART + ("cycle_relators.json" if k == 5 else "cycle_relators6.json")
    data = json.load(open(fn))[str(k)]
    G = [c for c in data["classes_detail"] if c["type"] == "G"]
    verdict = Counter()
    by_form = defaultdict(Counter)
    examples = {}
    for c in G:
        outcomes = set()
        for r in forms_of(c):
            r = cred(r)
            for (p, q) in phis(r):
                kind, theta = fibre(r, p, q)
                outcomes.add(kind)
                if kind == "n2-inverting" and "n2-inverting" not in examples:
                    examples["n2-inverting"] = (r, (p, q), theta)
        if outcomes & {"n0", "n1", "n2-inverting"}:
            v = "EXCLUDED"
        else:
            fib = sorted(o for o in outcomes if o.startswith("n"))
            v = "open:" + ("/".join(fib) if fib else "not-fibred")
        verdict[v] += 1
        by_form[c["detail"]][v] += 1
    print("k =", k, " G classes:", len(G))
    for v, cnt in sorted(verdict.items()):
        print("  ", cnt, v)
    print("  by census least form:")
    for d, cnt in by_form.items():
        print("    ", dict(cnt), "|", d)
    for kind, ex in examples.items():
        print("  example", kind, "relator", ex[0], "phi", ex[1], "theta", ex[2])
    return verdict


if __name__ == "__main__":
    for k in (5, 6):
        run(k)
