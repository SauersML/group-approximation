#!/usr/bin/env python3
"""Numerical sanity checks for `finite-abelian-actions-have-invariant-masas`.

Part A (exact identities, checked in floating point): the A_4-action on M_2
generated by Ad X, Ad Z, Ad U with U = (1 - iX - iY - iZ)/2.
  * U is unitary, U X U* = Y, U Y U* = Z, U Z U* = X, U^3 = -1;
  * the generated subgroup of Aut(M_2) has 12 elements;
  * the rank-one projections p with Ad g(p) in {p, 1-p} for all g form the
    empty set: the fixed symmetric 3x3 matrices under the SO(3) image are
    scalars only.

Part B (greedy construction following the proof): for several finite
abelian actions on M_n, start from D = C1 and repeat
  - B = D' (commutant); if B^G is not inside D, add a self-adjoint fixed
    element of B outside D;
  - otherwise add a spectral element b in B_chi outside D, after checking
    that b is normal (the step c = d of the proof);
until B = D.  Check that the result is an invariant masa (dim D = n,
D' = D, alpha_g(D) = D).

Single-threaded, deterministic seed, runs in well under a minute.
"""
import itertools
import numpy as np

TOL = 1e-8
rng = np.random.default_rng(20260916)


def vec(m):
    return m.reshape(-1)


def mat(v, n):
    return v.reshape(n, n)


def orth(vs):
    """Orthonormal basis (columns) of the complex span of the given vectors."""
    if len(vs) == 0:
        return np.zeros((0, 0))
    a = np.array(vs).T
    u, s, _ = np.linalg.svd(a, full_matrices=False)
    r = int((s > TOL * max(1.0, s[0])).sum())
    return u[:, :r]


def null_space(a):
    _, s, vh = np.linalg.svd(a)
    r = int((s > TOL * max(1.0, s[0] if len(s) else 1.0)).sum())
    return vh[r:].conj().T


def generated_algebra(gens, n):
    """Basis of the unital *-algebra generated by commuting normal gens."""
    basis = orth([vec(np.eye(n))] + [vec(g) for g in gens] + [vec(g.conj().T) for g in gens])
    while True:
        mats = [mat(basis[:, i], n) for i in range(basis.shape[1])]
        prods = [vec(x @ y) for x in mats for y in mats]
        new = orth(list(basis.T) + prods)
        if new.shape[1] == basis.shape[1]:
            return basis
        basis = new


def commutant(dbasis, n):
    rows = []
    for i in range(dbasis.shape[1]):
        d = mat(dbasis[:, i], n)
        # x d - d x = 0, as a linear map in vec(x)
        rows.append(np.kron(np.eye(n), d.T) - np.kron(d, np.eye(n)))
    return null_space(np.vstack(rows))


def in_span(basis, v):
    if basis.shape[1] == 0:
        return np.linalg.norm(v) < 1e-7
    coeff = basis.conj().T @ v
    return np.linalg.norm(v - basis @ coeff) < 1e-7 * max(1.0, np.linalg.norm(v))


def residual(basis, v):
    coeff = basis.conj().T @ v
    return v - basis @ coeff


def part_a():
    X = np.array([[0, 1], [1, 0]], dtype=complex)
    Y = np.array([[0, -1j], [1j, 0]], dtype=complex)
    Z = np.array([[1, 0], [0, -1]], dtype=complex)
    I = np.eye(2, dtype=complex)
    U = (I - 1j * X - 1j * Y - 1j * Z) / 2
    ad = lambda w, m: w @ m @ w.conj().T
    assert np.allclose(U.conj().T @ U, I)
    assert np.allclose(ad(U, X), Y) and np.allclose(ad(U, Y), Z) and np.allclose(ad(U, Z), X)
    assert np.allclose(U @ U @ U, -I)
    assert np.allclose(U, np.array([[1 - 1j, -1 - 1j], [1 - 1j, 1 + 1j]]) / 2)

    # group generated in Aut(M_2), elements represented by their SO(3) matrices
    paulis = [X, Y, Z]

    def rot(w):
        return np.array([[np.real(np.trace(ad(w, paulis[j]) @ paulis[i])) / 2
                          for j in range(3)] for i in range(3)])

    gens = [rot(X), rot(Z), rot(U)]
    group = [np.eye(3)]
    frontier = [np.eye(3)]
    while frontier:
        nxt = []
        for g in frontier:
            for s in gens:
                h = s @ g
                if not any(np.allclose(h, k) for k in group):
                    group.append(h)
                    nxt.append(h)
        frontier = nxt
    assert len(group) == 12, len(group)
    # is the group A_4?  12 elements, the involutions form V_4, elements of order 3: 8
    orders = []
    for g in group:
        k, h = 1, g
        while not np.allclose(h, np.eye(3)):
            h = h @ g
            k += 1
        orders.append(k)
    assert sorted(orders) == [1, 2, 2, 2, 3, 3, 3, 3, 3, 3, 3, 3], sorted(orders)

    # fixed symmetric matrices S = R S R^T for all R: only scalars
    rows = [np.kron(R, R) - np.eye(9) for R in group]
    ns = null_space(np.vstack(rows).astype(complex))
    assert ns.shape[1] == 1 and in_span(ns, vec(np.eye(3)).astype(complex))
    # a rank-one projection p = (1 + a.sigma)/2 with Ad g(p) in {p, 1-p} for all
    # g needs R_g a = +-a, hence a a^T fixed, hence a a^T scalar: impossible.
    return len(group)


def part_b_case(n, unitaries, orders, name):
    """Abelian group Z_{orders[0]} x ... acting by Ad unitaries[j] (the Ad's commute)."""
    ad = lambda w, m: w @ m @ w.conj().T
    for u, o in zip(unitaries, orders):
        assert np.allclose(np.linalg.matrix_power(u, o), np.linalg.matrix_power(u, o)[0, 0] * np.eye(n))
    probe = rng.normal(size=(n, n)) + 1j * rng.normal(size=(n, n))
    for u, v in itertools.combinations(unitaries, 2):
        assert np.allclose(ad(u, ad(v, probe)), ad(v, ad(u, probe)))
    group = list(itertools.product(*[range(o) for o in orders]))

    def act(g, m):
        for u, k in zip(unitaries, g):
            for _ in range(k):
                m = ad(u, m)
        return m

    chars = list(itertools.product(*[range(o) for o in orders]))

    def chi(c, g):
        return np.prod([np.exp(2j * np.pi * ci * gi / o) for ci, gi, o in zip(c, g, orders)])

    def E(c, m):
        return sum(np.conj(chi(c, g)) * act(g, m) for g in group) / len(group)

    D = generated_algebra([], n)
    steps, normal_checks = 0, 0
    while True:
        steps += 1
        assert steps < 10 * n * n
        B = commutant(D, n)
        Bm = [mat(B[:, i], n) for i in range(B.shape[1])]
        if B.shape[1] == D.shape[1]:
            break
        # random element of B, split into spectral parts
        x = sum((rng.normal() + 1j * rng.normal()) * b for b in Bm)
        fixed = E(chars[0], x)
        added = False
        for y in [(fixed + fixed.conj().T) / 2, (fixed - fixed.conj().T) / 2j]:
            if not in_span(D, vec(y)):
                D = generated_algebra([mat(vec(dd), n) for dd in []] +
                                      [mat(D[:, i], n) for i in range(D.shape[1])] + [y], n)
                added = True
                break
        if added:
            continue
        # B^G inside D (for this random sample; repeat if needed)
        for c in chars[1:]:
            b = E(c, x)
            if not in_span(D, vec(b)):
                assert np.allclose(b.conj().T @ b, b @ b.conj().T, atol=1e-7), "spectral element not normal"
                normal_checks += 1
                D = generated_algebra([mat(D[:, i], n) for i in range(D.shape[1])] + [b], n)
                added = True
                break
        assert added, "B != D but no spectral part of a random element escapes D"
    dmats = [mat(D[:, i], n) for i in range(D.shape[1])]
    assert D.shape[1] == n, (name, D.shape[1])
    for d1, d2 in itertools.product(dmats, repeat=2):
        assert np.allclose(d1 @ d2, d2 @ d1, atol=1e-7)
    for g in group:
        for d in dmats:
            assert in_span(D, vec(act(g, d)))
    return name, n, D.shape[1], steps, normal_checks


def random_unitary(n):
    q, r = np.linalg.qr(rng.normal(size=(n, n)) + 1j * rng.normal(size=(n, n)))
    return q * (np.diag(r) / abs(np.diag(r)))


def part_b():
    results = []
    w = np.exp(2j * np.pi / 3)
    for n in [3, 4, 5, 6]:
        V = random_unitary(n)
        u = V @ np.diag([w ** (k % 3) for k in range(n)]) @ V.conj().T
        results.append(part_b_case(n, [u], [3], f"Z3 generic Ad u, n={n}"))
    # Z3 x Z3 on M_3 by clock and shift (implementing unitaries do not commute)
    clock = np.diag([1, w, w ** 2])
    shift = np.roll(np.eye(3), 1, axis=0).astype(complex)
    assert not np.allclose(clock @ shift, shift @ clock)
    V = random_unitary(3)
    results.append(part_b_case(3, [V @ clock @ V.conj().T, V @ shift @ V.conj().T], [3, 3],
                               "Z3xZ3 clock/shift, n=3"))
    # Z3 x Z3 on M_6 = M_3 (x) M_2 with a degenerate spectrum
    c6 = np.kron(clock, np.eye(2))
    s6 = np.kron(shift, np.diag([1, w]))
    V = random_unitary(6)
    results.append(part_b_case(6, [V @ c6 @ V.conj().T, V @ s6 @ V.conj().T], [3, 3],
                               "Z3xZ3 twisted, n=6"))
    # Z2 x Z4 on M_4 by Ad of Pauli-type pair
    i4 = np.diag([1, 1j, -1, -1j])
    s4 = np.roll(np.eye(4), 1, axis=0).astype(complex)
    V = random_unitary(4)
    results.append(part_b_case(4, [V @ np.linalg.matrix_power(s4, 2) @ V.conj().T, V @ i4 @ V.conj().T],
                               [2, 4], "Z2xZ4, n=4"))
    return results


if __name__ == "__main__":
    print("Part A: A_4 group order", part_a(), "; only scalar fixed symmetric matrices: OK")
    for r in part_b():
        print("Part B:", r[0], "| dim D =", r[2], "| steps", r[3], "| normality checks", r[4])
    print("ALL CHECKS PASSED")
