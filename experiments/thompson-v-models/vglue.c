/* vglue.c -- simulated annealing over exact actions of S4 *_{C2} S3 on [k].
 *
 * Generators of Bleak--Quick (2.4), right action: a = (00 01), b = (01 10 11), c = (1 00).
 * <a,b> is S4 on the four depth-2 cylinders, <a,c> is S3 on {00, 01, 1}, and they meet in <a>.
 * A finite set carrying a free S4-action and a free S3-action that agree on a is an exact
 * action of the amalgam, so a^2, b^3, (ab)^4, c^2, (ac)^3 hold exactly and a, b, c are
 * fixed-point-free. The search space is the gluing: c is conjugated by involutions that
 * commute with a (pair flips and pair swaps).
 * Objective: mean normalized Hamming defect of the relators in relfile, one per line
 * (rel_V.txt holds the four long words of (2.4)).
 * Numerics only suggest; they prove nothing about soficity of V.
 *
 * usage: vglue k iters T0 T1 seed relfile      (k divisible by 24)
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#include <time.h>
#define MAXW 1024
#define MAXR 16

static unsigned long long rs;
static unsigned long long rnd(void){ rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }
static double urand(void){ return (rnd() >> 11) * (1.0/9007199254740992.0); }

/* letters 0=a 1=b 2=c, inverses 3..5 */
static int parse_seq(const char *s, int *i, int *out, int n){
  while (s[*i] && s[*i] != ')' && s[*i] != '\n' && s[*i] != '\r'){
    int buf[MAXW]; int m = 0;
    if (s[*i] == '('){ (*i)++; m = parse_seq(s, i, buf, 0); if (s[*i] == ')') (*i)++; }
    else if (s[*i] >= 'a' && s[*i] <= 'c'){ buf[0] = s[*i] - 'a'; m = 1; (*i)++; }
    else { (*i)++; continue; }
    int rep = 1, inv = 0;
    if (s[*i] == '^'){
      (*i)++; if (s[*i] == '-'){ inv = 1; (*i)++; }
      rep = atoi(s + *i); while (s[*i] >= '0' && s[*i] <= '9') (*i)++;
    }
    for (int r = 0; r < rep; r++){
      if (inv) for (int j = m-1; j >= 0; j--) out[n++] = (buf[j] + 3) % 6;
      else for (int j = 0; j < m; j++) out[n++] = buf[j];
    }
  }
  return n;
}

static int NR; static int W[MAXR][MAXW]; static int WL[MAXR];
static int k; static int *P[6];

static double word_defect(const int *w, int L){
  int mv = 0;
  for (int x = 0; x < k; x++){ int y = x; for (int j = 0; j < L; j++) y = P[w[j]][y]; if (y != x) mv++; }
  return (double)mv / k;
}
static double avg_defect(double *per){
  double s = 0; for (int r = 0; r < NR; r++){ double d = word_defect(W[r], WL[r]); per[r] = d; s += d; }
  return s / NR;
}

/* group generated by ng permutations of {0..n-1}; product g.s = first g then s */
static int find_el(int N, int n, int el[][4], const int *p){
  for (int q = 0; q < N; q++) if (!memcmp(el[q], p, sizeof(int)*n)) return q;
  return -1;
}
static int build_free(int n, int ng, const int gens[][4], int apos, int m, int **out){
  int el[24][4], mult[24][4], N = 1;
  for (int i = 0; i < n; i++) el[0][i] = i;
  for (int e = 0; e < N; e++) for (int s = 0; s < ng; s++){
    int p[4]; for (int i = 0; i < n; i++) p[i] = gens[s][el[e][i]];
    int f = find_el(N, n, el, p); if (f < 0){ memcpy(el[N], p, sizeof(int)*n); f = N++; }
    mult[e][s] = f;
  }
  int *idx = malloc(sizeof(int)*N*m); for (int q = 0; q < N*m; q++) idx[q] = -1;
  int p = 0;
  for (int j = 0; j < m; j++) for (int e = 0; e < N; e++) if (idx[j*N+e] < 0){
    idx[j*N+e] = p; idx[j*N+mult[e][apos]] = p+1; p += 2;
  }
  for (int j = 0; j < m; j++) for (int e = 0; e < N; e++) for (int s = 0; s < ng; s++)
    out[s][idx[j*N+e]] = idx[j*N+mult[e][s]];
  free(idx);
  return N;
}
static void set_inv(int g){ for (int x = 0; x < k; x++) P[g+3][P[g][x]] = x; }

int main(int argc, char **argv){
  if (argc < 7){ fprintf(stderr, "usage: vglue k iters T0 T1 seed relfile\n"); return 1; }
  k = atoi(argv[1]); long iters = atol(argv[2]); double T0 = atof(argv[3]), T1 = atof(argv[4]);
  rs = strtoull(argv[5], 0, 10) * 2654435761ULL + 12345; for (int i = 0; i < 20; i++) rnd();
  if (k % 24){ fprintf(stderr, "k must be divisible by 24\n"); return 1; }
  FILE *f = fopen(argv[6], "r"); if (!f){ fprintf(stderr, "cannot open %s\n", argv[6]); return 1; }
  char line[4096];
  while (NR < MAXR && fgets(line, sizeof line, f)){
    int i = 0; int L = parse_seq(line, &i, W[NR], 0); if (L > 0) WL[NR++] = L;
  }
  fclose(f);
  for (int g = 0; g < 6; g++) P[g] = malloc(sizeof(int)*k);
  int *aux = malloc(sizeof(int)*k), *save = malloc(sizeof(int)*k), *tt = malloc(sizeof(int)*k);
  for (int x = 0; x < k; x++) P[0][x] = x ^ 1;
  const int g4[2][4] = {{1,0,2,3},{0,2,3,1}};  /* a, b on cylinders 00,01,10,11 */
  const int g3[2][4] = {{1,0,2,0},{2,1,0,0}};  /* a, c on 00,01,1 */
  int *o4[2] = {aux, P[1]}; if (build_free(4, 2, g4, 0, k/24, o4) != 24){ fprintf(stderr, "S4 size\n"); return 1; }
  for (int x = 0; x < k; x++) if (aux[x] != P[0][x]){ fprintf(stderr, "S4 pairing\n"); return 1; }
  int *o3[2] = {aux, P[2]}; if (build_free(3, 2, g3, 0, k/6, o3) != 6){ fprintf(stderr, "S3 size\n"); return 1; }
  for (int x = 0; x < k; x++) if (aux[x] != P[0][x]){ fprintf(stderr, "S3 pairing\n"); return 1; }
  /* random gluing: c <- tau^-1 c tau, tau(2i+e) = 2 pi(i) + (e xor f_i) commutes with a */
  int h = k/2; int *pi = malloc(sizeof(int)*h);
  for (int i = 0; i < h; i++) pi[i] = i;
  for (int i = h-1; i > 0; i--){ int j = rnd() % (i+1); int t = pi[i]; pi[i] = pi[j]; pi[j] = t; }
  for (int i = 0; i < h; i++){ int fl = rnd() & 1; tt[2*i] = 2*pi[i] + fl; tt[2*i+1] = 2*pi[i] + (1-fl); }
  for (int x = 0; x < k; x++) aux[tt[x]] = x;              /* aux = tau^-1 */
  memcpy(save, P[2], sizeof(int)*k);
  for (int x = 0; x < k; x++) P[2][x] = aux[save[tt[x]]];
  for (int g = 0; g < 3; g++) set_inv(g);
  /* exact short relations */
  const char *SH[6] = {"a^2", "b^3", "(ab)^4", "c^2", "(ac)^3", "c^-1(ac)^2a"};
  int shortbad = 0;
  for (int r = 0; r < 6; r++){ int w[64]; int i = 0; int L = parse_seq(SH[r], &i, w, 0); if (word_defect(w, L) != 0.0) shortbad++; }
  int fpf = 1; for (int g = 0; g < 3; g++) for (int x = 0; x < k; x++) if (P[g][x] == x) fpf = 0;
  double per[MAXR], bestper[MAXR], baseper[MAXR];
  double cur = avg_defect(per), best = cur, base = cur;
  memcpy(bestper, per, sizeof per); memcpy(baseper, per, sizeof per);
  for (int x = 0; x < k; x++) tt[x] = x;
  time_t t0 = time(0);
  for (long it = 0; it < iters; it++){
    double T = T0 * pow(T1/T0, (double)it/iters);
    int i = rnd() % h, j = rnd() % h, type = rnd() % 3;
    if (type && i == j) continue;
    if (type == 0){ tt[2*i] = 2*i+1; tt[2*i+1] = 2*i; }
    else if (type == 1){ tt[2*i] = 2*j; tt[2*j] = 2*i; tt[2*i+1] = 2*j+1; tt[2*j+1] = 2*i+1; }
    else { tt[2*i] = 2*j+1; tt[2*j+1] = 2*i; tt[2*i+1] = 2*j; tt[2*j] = 2*i+1; }
    memcpy(save, P[2], sizeof(int)*k);
    for (int x = 0; x < k; x++) P[2][x] = tt[save[tt[x]]];
    memcpy(P[5], P[2], sizeof(int)*k);
    tt[2*i] = 2*i; tt[2*i+1] = 2*i+1; tt[2*j] = 2*j; tt[2*j+1] = 2*j+1;
    double nd = avg_defect(per);
    if (nd <= cur || urand() < exp((cur - nd) / T)){
      cur = nd; if (cur < best){ best = cur; memcpy(bestper, per, sizeof per); }
    } else { memcpy(P[2], save, sizeof(int)*k); memcpy(P[5], save, sizeof(int)*k); }
  }
  printf("k=%d iters=%ld T0=%g T1=%g seed=%s rel=%s short_bad=%d fpf=%d base_avg=%.5f best_avg=%.5f per:",
         k, iters, T0, T1, argv[5], argv[6], shortbad, fpf, base, best);
  for (int r = 0; r < NR; r++) printf(" %.4f", bestper[r]);
  printf(" base:");
  for (int r = 0; r < NR; r++) printf(" %.4f", baseper[r]);
  printf(" lens:");
  for (int r = 0; r < NR; r++) printf(" %d", WL[r]);
  printf(" secs=%ld\n", (long)(time(0) - t0));
  return 0;
}
