"""Structure of the radius-2 kernel window as cross-chart commuting pairs.

The 20 spanning-tree kernel generators of the radius-2 window are cross-chart
commutators of adjacent transvections.  This script extracts the exact
commuting relation

    C = { (x, y) : x in factor-1 generators, y in factor-2 generators,
                   [x, y] = 1 in Q }

and, for each generator on one side, computes the subgroup of GL_4(F2)
generated by its partners on the other side.

Why this matters.  Let phi : Pbar = A8 * A8 -> F be a homomorphism into a
finite group killing the radius-2 window, with both factor restrictions
alpha, beta injective.  Then beta(y) centralises alpha(x) for every
(x, y) in C, hence beta(y) centralises alpha(<S_y>) where
S_y = { x : (x,y) in C }.  If <S_y> = A8 for every y, then
beta(A8) <= C_F(alpha(A8)): the two images commute, F is a quotient of
A8 x A8, and the whole "two non-commuting copies of A8" family is EMPTY --
no finite-quotient screen beyond the direct product needs to be run at all.
"""

import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from atlas_kernel_collision_enumerator import (  # noqa: E402
    enumerate_ball,
    spanning_tree_kernel_words,
)
from atlas_two_chart_search import gf2_mul, transvection  # noqa: E402

NAMES = ["e12", "e21", "e23", "e32", "e34", "e43"]
PAIRS = [(0, 1), (1, 0), (1, 2), (2, 1), (2, 3), (3, 2)]
GENS = [transvection(r, c) for r, c in PAIRS]
KEY_TO_INDEX = {g.tobytes(): i for i, g in enumerate(GENS)}


def subgroup_order(matrices):
    identity = np.eye(4, dtype=np.uint8)
    seen = {identity.tobytes()}
    frontier = [identity]
    while frontier:
        nxt = []
        for g in frontier:
            for s in matrices:
                h = gf2_mul(g, s)
                key = h.tobytes()
                if key not in seen:
                    seen.add(key)
                    nxt.append(h)
        frontier = nxt
    return len(seen)


def main():
    states, _ = enumerate_ball(2)
    words, _sizes, _depths = spanning_tree_kernel_words(states)
    print("radius-2 spanning-tree kernel generators:", len(words))

    commuting = set()
    unparsed = []
    for word in words:
        letters = [(factor, KEY_TO_INDEX.get(matrix.tobytes()))
                   for factor, matrix in word]
        if len(letters) != 4 or any(i is None for _f, i in letters):
            unparsed.append(word)
            continue
        # a commutator [a, b] = a b a^-1 b^-1 has letters a b a b (each
        # adjacent transvection is an involution over F2).
        (f0, i0), (f1, i1), (f2, i2), (f3, i3) = letters
        if (f0, i0) == (f2, i2) and (f1, i1) == (f3, i3) and f0 != f1:
            x, y = ((i0, i1) if f0 == 1 else (i1, i0))
            commuting.add((x, y))
        else:
            unparsed.append(word)

    print("parsed as cross-chart commutators:", len(commuting),
          " unparsed:", len(unparsed))

    print("\ncommuting relation (rows = factor-1 gen, cols = factor-2 gen):")
    print("        " + "  ".join("%3s" % n for n in NAMES))
    for x in range(6):
        row = "".join("  %3s" % (".  " if (x, y) not in commuting else " C ")
                      for y in range(6))
        print("   %3s %s" % (NAMES[x], row))

    print("\nS_y = factor-1 partners of each factor-2 generator y:")
    all_full = True
    for y in range(6):
        partners = [x for x in range(6) if (x, y) in commuting]
        order = subgroup_order([GENS[x] for x in partners]) if partners else 1
        full = order == 20160
        all_full &= full
        print("   y=%3s  S_y = %-28s |<S_y>| = %6d%s"
              % (NAMES[y], "{" + ",".join(NAMES[x] for x in partners) + "}",
                 order, "  = A8" if full else ""))

    print("\nS'_x = factor-2 partners of each factor-1 generator x:")
    for x in range(6):
        partners = [y for y in range(6) if (x, y) in commuting]
        order = subgroup_order([GENS[y] for y in partners]) if partners else 1
        full = order == 20160
        all_full &= full
        print("   x=%3s  S'_x = %-27s |<S'_x>| = %6d%s"
              % (NAMES[x], "{" + ",".join(NAMES[y] for y in partners) + "}",
                 order, "  = A8" if full else ""))

    print()
    if all_full:
        print("VERDICT: every one-sided partner set generates A8.  Any finite")
        print("quotient killing the radius-2 window has COMMUTING images, so")
        print("it factors through A8 x A8.  The Goursat-uncovered family of")
        print("two non-commuting copies of A8 is empty -- no further screen")
        print("is needed.")
    else:
        print("VERDICT: some partner set generates a proper subgroup; the")
        print("uniform argument does not close, and longer windows or an")
        print("explicit per-F scan are required.")


if __name__ == "__main__":
    main()
