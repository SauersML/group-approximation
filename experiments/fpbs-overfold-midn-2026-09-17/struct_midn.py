"""Structured mid-n levels for the relative (O) test (rel.c via midn.job).

Usage:
  python3 struct_midn.py psl p count seed j smax timeout [lawset] [workers]
      Q = projective line P^1(F_p) (n = p+1) with a, b random elements of
      PSL(2,p) acting by Moebius maps, kept if the action is transitive.
  python3 struct_midn.py cay lo hi count seed j smax timeout [lawset] [workers]
      Q = right-regular (Cayley) action of the group generated by two random
      permutations of degree 4..8 whose order lies in [lo, hi].
Output lines as in midn.py; VIOLATION is an exact counterexample to (O).
"""
import os
import random
import sys
from multiprocessing import Pool
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, '..', 'fpbs-overfold-relative-rank-2026-09-17'))
from midn import job, transitive  # noqa: E402
from struct_search import cayley  # noqa: E402


def psl_perm(p, M):
    a, b, c, d = M
    inf = p
    out = []
    for x in range(p + 1):
        if x == inf:
            y = inf if c % p == 0 else a * pow(c, p - 2, p) % p
        else:
            den = (c * x + d) % p
            y = inf if den == 0 else (a * x + b) * pow(den, p - 2, p) % p
        out.append(y)
    return out


def rand_sl2(p, rng):
    while True:
        a, b, c = rng.randrange(p), rng.randrange(p), rng.randrange(p)
        if a % p:
            d = (1 + b * c) * pow(a, p - 2, p) % p
            return (a, b, c, d)


def main():
    fam = sys.argv[1]
    if fam == 'psl':
        p, count, seed, j, smax, timeout = map(int, sys.argv[2:8])
        rest = sys.argv[8:]
    else:
        lo, hi, count, seed, j, smax, timeout = map(int, sys.argv[2:9])
        rest = sys.argv[9:]
    lawset = None
    if rest and rest[0] != '-':
        lawset = set(int(x) for x in rest[0].split(','))
    workers = int(rest[1]) if len(rest) > 1 else 4
    rng = random.Random(seed)
    levels, seen = [], set()
    tries = 0
    while len(levels) < count and tries < 10 ** 6:
        tries += 1
        if fam == 'psl':
            PA = psl_perm(p, rand_sl2(p, rng))
            PB = psl_perm(p, rand_sl2(p, rng))
            if not transitive(PA, PB):
                continue
        else:
            k = rng.randrange(4, 9)
            al = list(range(k)); rng.shuffle(al)
            be = list(range(k)); rng.shuffle(be)
            r = cayley(tuple(al), tuple(be), hi)
            if r is None or len(r[0]) < lo:
                continue
            PA, PB = r
        key = (tuple(PA), tuple(PB))
        if key in seen:
            continue
        seen.add(key)
        levels.append((PA, PB, j, smax, timeout, lawset))
    print(f'# struct_midn {" ".join(sys.argv[1:])} levels {len(levels)}', flush=True)
    with Pool(workers) as pool:
        for line in pool.imap_unordered(job, levels):
            print(line, flush=True)


if __name__ == '__main__':
    main()
