#!/usr/bin/env python3
"""Search the singular, unpeelable, unit-Alexander slice for relators whose Magnus vertex group
B_0 = <a_0..a_n | W_0> is BS(p,q) * F_(n-1) because W_0 = U^-1 V^p U V^-q with (U, V, X_2..X_n) a free
basis of F(a_0..a_n).  Then BS(p,q) embeds in B_0 and hence in G = <a,t | w> = B_0 *_psi.

Candidates are generated by breadth-first Nielsen moves from the standard basis (a_0,..,a_n),
keeping every basis of total length <= WMAX (sum of the n+1 word lengths).  For each pair (U, V) taken from one basis, with V of
unit exponent vector (so the Alexander polynomial of G is a unit when |p - q| = 1), and each
(p, q) in PQ, W_0 = U^-1 V^p U V^-q is cyclically reduced and filtered by ok() (copied from
gen_walk21.py: t-exponent 0, heights 0..n all used, unit Alexander polynomial, a singular extreme,
both extremes unpeelable).  Survivors are run through the landed census certificate search
census.cert_word (PEEL / PP / R1 / CYC in all small zero-exponent bases); only relators it fails
are reported.  Output lines: OPEN <w in a,t> <|w|> p q U V [X_2..X_n] seq
(letters +-(h+1) stand for a_h^(+-1); a_h = t^h a t^-h).

Usage: bs_search.py NMAX WMAX LMAX [PQ]   e.g. bs_search.py 2 5 40 "1,2 2,3"
"""
import sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'research', 'artifacts', 'or-unpeelable-census-scripts-2026-09-12'))
sys.path.insert(0, '/home/user/group-approximation/research/artifacts/or-unpeelable-census-scripts-2026-09-12')
import census as C

NMAX, WMAX, LMAX = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3])
PQ = [tuple(int(x) for x in s.split(',')) for s in (sys.argv[4] if len(sys.argv) > 4 else '1,2 2,3').split()]


def red(w):
    out = []
    for x in w:
        if out and out[-1] == -x: out.pop()
        else: out.append(x)
    return out


def inv(w): return [-x for x in reversed(w)]


def cred(w):
    w = red(w)
    while len(w) >= 2 and w[0] == -w[-1]: w = w[1:-1]
    return w


def pw(w, k):
    return red((w if k > 0 else inv(w)) * abs(k))


def expvec(w):
    v = [0] * (NMAX + 1)
    for x in w: v[abs(x) - 1] += 1 if x > 0 else -1
    return v


def to_seq(W):
    """cyclic word in letters +-(h+1) (a_h) -> cyclic syllable list [(h, e)], rotated to a syllable boundary"""
    W = cred(W)
    if not W: return None
    k = len(W)
    # rotate so W[0] starts a syllable
    r = 0
    while r < k and abs(W[r - 1]) == abs(W[r]) and (W[r - 1] > 0) == (W[r] > 0): r += 1
    if r == k: return None
    W = W[r:] + W[:r]
    seq = []
    for x in W:
        h, e = abs(x) - 1, (1 if x > 0 else -1)
        if seq and seq[-1][0] == h: seq[-1] = (h, seq[-1][1] + e)
        else: seq.append((h, e))
    if len(seq) > 1 and seq[0][0] == seq[-1][0]:
        seq[0] = (seq[0][0], seq[0][1] + seq[-1][1]); seq.pop()
    return seq


def ok(seq):
    k = len(seq)
    if k < 3: return False
    if any(seq[i][0] == seq[(i+1) % k][0] for i in range(k)): return False
    hs = [h for h, _ in seq]
    if min(hs) != 0 or max(hs) != NMAX: return False
    sums = [sum(e for h, e in seq if h == l) for l in range(NMAX + 1)]
    nz = [x for x in sums if x]
    if not (len(nz) == 1 and abs(nz[0]) == 1): return False
    top = [e for h, e in seq if h == NMAX]; bot = [e for h, e in seq if h == 0]
    if C.peelable(top) or C.peelable(bot): return False
    if not (sums[0] == 0 or sums[NMAX] == 0): return False
    return True


def bases():
    start = tuple(tuple([i + 1]) for i in range(NMAX + 1))
    seen = {start}; frontier = [start]
    while frontier:
        nf = []
        for B in frontier:
            for i in range(NMAX + 1):
                for j in range(NMAX + 1):
                    if i == j: continue
                    for s in (1, -1):
                        for side in (0, 1):
                            y = list(B[j]) if s == 1 else inv(list(B[j]))
                            nw = red(list(B[i]) + y) if side == 0 else red(y + list(B[i]))
                            nb = list(B); nb[i] = tuple(nw); nb = tuple(nb)
                            if sum(map(len, nb)) > WMAX: continue
                            if nb not in seen:
                                seen.add(nb); nf.append(nb)
        frontier = nf
    return seen


def main():
    pairs = {}
    for B in sorted(bases(), key=lambda b: (sum(map(len, b)), b)):
        for i in range(NMAX + 1):
            for j in range(NMAX + 1):
                if i == j: continue
                V = list(B[j]); ev = expvec(V)
                if sorted(map(abs, ev)) != [0] * NMAX + [1]: continue
                pairs.setdefault((B[i], B[j]), [list(B[k]) for k in range(NMAX + 1) if k not in (i, j)])
    print('pairs', len(pairs), file=sys.stderr)
    seen = set(); nslice = 0
    best = None
    for U, V in sorted(pairs, key=lambda uv: len(uv[0]) + len(uv[1])):
        X = pairs[(U, V)]
        U, V = list(U), list(V)
        for p, q in PQ:
            W0 = cred(inv(U) + pw(V, p) + U + pw(V, -q))
            seq = to_seq(W0)
            if seq is None or not ok(seq): continue
            w = C.cyc_reduce(C.seq_to_word(seq))
            if len(w) > LMAX: continue
            key = min(tuple(x) for x in [w])
            if key in seen: continue
            seen.add(key); nslice += 1
            C.BUDGET[0] = 4000
            good, why = C.cert_word(w, 0)
            if good: continue
            print('OPEN', C.word_str(w), len(w), p, q, repr(U).replace(' ', ''), repr(V).replace(' ', ''), repr(X).replace(' ', ''), repr(seq).replace(' ', ''), flush=True)
            if best is None or len(w) < best: best = len(w)
    print('in slice', nslice, 'min open length', best, file=sys.stderr)


main()
