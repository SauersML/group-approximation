#!/usr/bin/env python3
"""State-side dual for the qudit rounding constant.
SR_d: c*(d,n) = sup_psi c(psi), c(psi) = min c s.t. a stabilizer mixture with Weyl vector m has
      |m_v - (1+c) x_v| <= c for all v != 0, x_v = <psi|D(v)|psi>   (dual of the l1 weight).
The modulus is replaced by N_dir half-planes: rhs c gives a lower bound on c(psi), rhs c*cos(pi/N_dir)
an upper bound.
CC_d: g*(d,n) = sup_psi g(psi), g(psi) = min g s.t. a stabilizer mixture rho has
      1 - tr(rho Pi_S) <= g (1 - <psi|Pi_S|psi>) for every stabilizer code projector Pi_S != I.
Run: nice -n 10 timeout 1200 python3 dual_lp.py mode d n restarts steps seed [N_dir]
"""
import sys, json, itertools
import numpy as np
from scipy.optimize import linprog
from weyl import weyl_ops, pair_reps, stabilizer_states, expectations

def sr_lp(x, E, reps, ndir, inner):
    # E: (states, ops) ; variables mu (N), c
    N = E.shape[0]; th = np.exp(-1j * np.pi * 2 * np.arange(ndir) / ndir)
    Er = E[:, reps]; xr = x[reps]
    rows = []; rhs = []
    s = np.cos(np.pi / ndir) if inner else 1.0
    for t in th:
        A = np.real(t * Er).T                     # (reps, N)
        bx = np.real(t * xr)
        rows.append(np.hstack([A, -(bx + s)[:, None]])); rhs.append(bx)
    A = np.vstack(rows); b = np.concatenate(rhs)
    obj = np.zeros(N + 1); obj[-1] = 1
    res = linprog(obj, A_ub=A, b_ub=b, A_eq=np.hstack([np.ones((1, N)), [[0]]]), b_eq=[1],
                  bounds=[(0, None)] * (N + 1), method='highs')
    return res.fun, res.x

def code_projectors(states, d, n):
    """all stabilizer code projectors: for each stabilizer state phi, and each subgroup, its code space.
    We generate them as projectors onto spans of subsets of stabilizer states that are code spaces:
    easier route -- a code projector Pi_S is a sum of stabilizer states. Enumerate via Weyl subgroups."""
    vecs, mats = weyl_ops(d, n)
    D = d ** n
    projs = {}
    # isotropic subgroups generated by k independent commuting Weyl ops, with characters
    def key(P):
        return tuple(np.round(P.real, 5).ravel()) + tuple(np.round(P.imag, 5).ravel())
    import itertools
    frontier = [np.eye(D, dtype=complex)]
    seen = set()
    for k in range(1, n + 1):
        new = []
        for P in frontier:
            for M in mats:
                if not np.allclose(M @ P, P @ M):
                    continue
                MP = M @ P
                ev = np.linalg.eigvals(MP)
                for j in range(d):
                    Q = P @ sum(((np.exp(-2j * np.pi * j / d)) ** t) * np.linalg.matrix_power(M, t) for t in range(d)) / d
                    r = np.real(np.trace(Q))
                    if r > 0.5 and r < np.real(np.trace(P)) - 0.5:
                        kk = key(Q)
                        if kk not in seen:
                            seen.add(kk); new.append(Q)
        frontier = new; projs.update({key(Q): Q for Q in new})
    return list(projs.values())

def cc_lp(psi, Pst, Ppsi_fn):
    # Pst: (projectors, states) values tr(phi Pi); variables mu (N), g
    N = Pst.shape[1]; q = Ppsi_fn(psi)
    A = np.hstack([-Pst, -(1 - q)[:, None]]); b = -np.ones(len(q))
    obj = np.zeros(N + 1); obj[-1] = 1
    res = linprog(obj, A_ub=A, b_ub=b, A_eq=np.hstack([np.ones((1, N)), [[0]]]), b_eq=[1],
                  bounds=[(0, None)] * (N + 1), method='highs')
    return res.fun

if __name__ == '__main__':
    mode, d, n, R, S, seed = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4]), int(sys.argv[5]), int(sys.argv[6])
    ndir = int(sys.argv[7]) if len(sys.argv) > 7 else 24
    rng = np.random.default_rng(seed); D = d ** n
    vecs, mats = weyl_ops(d, n); reps, neg = pair_reps(d, n, vecs)
    st = stabilizer_states(d, n); E = expectations(st, mats)
    print(f"mode={mode} d={d} n={n} states={len(st)} ops={len(vecs)}", flush=True)
    if mode == 'sr':
        def val(psi):
            x = np.einsum('i,vij,j->v', np.conj(psi), mats, psi)
            return sr_lp(x, E, reps, ndir, False)[0]
        def val_up(psi):
            x = np.einsum('i,vij,j->v', np.conj(psi), mats, psi)
            return sr_lp(x, E, reps, ndir, True)[0]
    else:
        projs = code_projectors(st, d, n)
        PM = np.array(projs)
        Pst = np.real(np.einsum('si,pij,sj->ps', np.conj(st), PM, st))
        print("code projectors:", len(projs), flush=True)
        def val(psi):
            return cc_lp(psi, Pst, lambda p: np.real(np.einsum('i,pij,j->p', np.conj(p), PM, p)))
        val_up = val
    def rand_state():
        v = rng.normal(size=D) + 1j * rng.normal(size=D); return v / np.linalg.norm(v)
    best = (-1, None)
    for r in range(R):
        psi = rand_state(); cur = val(psi); scale = 0.5
        for s in range(S):
            q = psi + scale * rand_state(); q /= np.linalg.norm(q); v = val(q)
            if v > cur: psi, cur = q, v
            else: scale *= 0.95
            if scale < 1e-4: break
        if cur > best[0] + 1e-7:
            best = (cur, psi); print(f"restart {r}: lower={cur:.6f} upper={val_up(psi):.6f}", flush=True)
    print(json.dumps({"mode": mode, "d": d, "n": n, "best_lower": best[0], "best_upper": val_up(best[1]),
                      "psi": [[float(z.real), float(z.imag)] for z in best[1]]}))
