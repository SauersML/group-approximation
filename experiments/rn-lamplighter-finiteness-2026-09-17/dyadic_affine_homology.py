#!/usr/bin/env python3
"""Machine check for dyadic-affine-germ-groupoids-are-not-k-graph-groupoids.

G_r = germ groupoid of Aff(Z[1/2r], <2, r>) on Z_2, r odd, |r| >= 3 (the groupoid of V_2(BS(1,r))).
  A. Brute-force transfer / conjugation maps on H_*(S_m), S_m = 2^m Z[1/r] x| <r>, and the resulting
     Pimsner-Voiculescu computation H_0 = 0, H_1 = H_2 = Z/|r-1|.
  B. Independent LHS/Koszul computation over U = <2, r> (and a few other U), compared with A.
  C. Prime-support lemma for Koszul complexes of commuting nonnegative integer matrices (finite k-graphs):
     H_0 (x) Z_(l) = 0 forces H_* (x) Z_(l) = 0.  Random + exhaustive small search.
  D. Lemma D analogue: every germ of Aff(Z[1/2r], <2,r>) on Z_2 is lambda_v h lambda_w^{-1} with h in BS(1,r).
Pure python; single-threaded.
"""
import random, itertools, math
from fractions import Fraction as F

random.seed(20260918)

def v2(x):
    x = F(x)
    if x == 0: return 10**9
    n, d, k = x.numerator, x.denominator, 0
    while n % 2 == 0: n //= 2; k += 1
    while d % 2 == 0: d //= 2; k -= 1
    return k

def in_Zr(x, r):  # x in Z[1/r]
    d = F(x).denominator
    for p in prime_factors(abs(r)):
        while d % p == 0: d //= p
    return d == 1

def prime_factors(n):
    ps, p = [], 2
    while p * p <= n:
        if n % p == 0:
            ps.append(p)
            while n % p == 0: n //= p
        p += 1
    if n > 1: ps.append(n)
    return ps

# ---------------- Part A ----------------
# affine map (k, b) means x -> r^k x + b ; composition (g h)(x) = g(h(x))
def comp(g, h, r):
    return (g[0] + h[0], F(r) ** g[0] * h[1] + g[1])
def inv(g, r):
    return (-g[0], -g[1] / F(r) ** g[0])
def in_S(g, m, r):
    return v2(g[1]) >= m and in_Zr(g[1], r)
def ab(g, m, r):
    """S_m -> Z + Z/n,  n = |r-1|:  r^k x + b  ->  (k, b/2^m mod n); b/2^m lies in Z[1/r] and r is a unit mod n."""
    n = abs(r - 1)
    c = g[1] / 2 ** m
    return (g[0], (c.numerator * pow(c.denominator, -1, n)) % n) if n > 1 else (g[0], 0)
def add(a, b, n):
    return (a[0] + b[0], (a[1] + b[1]) % n)
def transfer(g, m, r):
    reps = [(0, F(0)), (0, F(2) ** m)]
    n, tot = abs(r - 1), (0, 0)
    for rho in reps:
        grho = comp(g, rho, r)
        hits = [rp for rp in reps if in_S(comp(inv(rp, r), grho, r), m + 1, r)]
        assert len(hits) == 1
        tot = add(tot, ab(comp(inv(hits[0], r), grho, r), m + 1, r), n)
    return tot
def alpha(g):  # conjugation by x -> 2x
    return (g[0], 2 * g[1])

def rand_S(m, r):
    return (random.randint(-3, 3), F(random.randint(-50, 50) * 2 ** m, abs(r) ** random.randint(0, 3)))

def part_A(out):
    out.append("== Part A: brute-force PV computation for G_r (groupoid of V_2(BS(1,r)) on Z_2)")
    for r in [3, 5, 7, 9, 11, 13, 15, 21, -3, -5, -7, -9]:
        n, s = abs(r - 1), (r - 1) // 2
        for m in range(0, 7):
            t, tau = (1, F(0)), (0, F(2) ** m)
            # ab is a homomorphism, transfer is a homomorphism (random checks)
            for _ in range(20):
                g, h = rand_S(m, r), rand_S(m, r)
                assert in_S(g, m, r) and in_S(h, m, r)
                assert ab(comp(g, h, r), m, r) == add(ab(g, m, r), ab(h, m, r), n)
                assert transfer(comp(g, h, r), m, r) == add(transfer(g, m, r), transfer(h, m, r), n)
                assert ab(alpha(g), m + 1, r) == ab(g, m, r)
            Tt, Ttau = transfer(t, m, r), transfer(tau, m, r)
            At, Atau = ab(alpha(t), m + 1, r), ab(alpha(tau), m + 1, r)
            assert Tt == (2, s % n) and Ttau == (0, 1 % n), (r, m, Tt, Ttau)
            assert At == (1, 0) and Atau == (0, 1 % n)
            # basis f = t + s*tau:  T f = 2 f,  alpha f = f
            Tf = add(Tt, (0, (s * Ttau[1]) % n), n)
            assert Tf == (2, (2 * s) % n)
        out.append(f"r={r:4d}: for m=0..6  T_m = [[2,0],[{s},1]] (cols t,tau), alpha_* = id, "
                   f"ab/transfer homomorphic on 20 random pairs; T(t+{s}tau) = 2(t+{s}tau)")
        out.append(f"        => H_0(N)=Z[1/2], D=1/2 invertible; H_1(N)=Z[1/2]f + Z/{n} tau, D f=f/2, D tau=0;"
                   f" H_2(N)=0.  PV: H_0(G_r)=0, H_1(G_r)=Z/{n}, H_2(G_r)=Z/{n}, H_>=3=0")

# ---------------- Part B ----------------
def ideal_gen(cs, N):
    """generator (positive integer, N-free part) of the ideal of Z[1/N] generated by rationals cs in Z[1/N]"""
    g = 0
    for c in cs:
        c = F(c)
        num = abs(c.numerator)
        for p in prime_factors(N):
            while num and num % p == 0: num //= p
        g = math.gcd(g, num)
    return g   # 0 means zero ideal
def koszul_pid(cs, N):
    """Koszul homology of commuting scalars cs on R = Z[1/N]; returns list of 'R/(g)^C(r-1,j)' or free ranks."""
    r = len(cs); g = ideal_gen(cs, N)
    if g == 0:
        return [("R", math.comb(r, j)) for j in range(r + 1)]
    return [(f"Z/{g}" if g > 1 else "0", math.comb(r - 1, j) if j < r else 0) for j in range(r + 1)]

def part_B(out):
    out.append("== Part B: independent LHS/Koszul computation over U (rows q=0: Z[1/2], q=1: Z[1/m])")
    cases = [(3, [2, 3]), (5, [2, 5]), (7, [2, 7]), (3, [2, -3]), (15, [2, 3, 5]), (3, [4, 3]), (5, [8, 5]),
             (3, [6, 3]), (3, [2]), (1, [2]), (1, [-2]), (3, [12, 3])]
    for m, U in cases:
        row0 = koszul_pid([1 - F(1, 2) ** v2(u) for u in U], 2)
        odd = [F(u) / F(2) ** v2(u) for u in U]
        row1 = koszul_pid([1 - o for o in odd], max(m, 1))
        g = math.gcd(*[abs(v2(u)) for u in U])
        H0 = row0[0]
        two_local_H0_zero = (H0[0] == "0") or (H0[0].startswith("Z/") and int(H0[0][2:]) % 2 == 1)
        two_local_row1 = row1[0][0] != "0"
        out.append(f"m={m:2d} U={U}: v_2(U)={g}Z; row0 {row0}; row1 {row1}; "
                   f"H_0 (x) Z_(2) = 0: {two_local_H0_zero}; row1 (x) Z_(2) != 0: {two_local_row1}")
        assert two_local_H0_zero and two_local_row1
        if m == 3 and U == [2, 3]:
            assert row0[0][0] == "0" and row0[1][0] == "0" and row1[0] == ("Z/2", 1) and row1[1] == ("Z/2", 1)
            out.append("      BS(1,3): row 0 exact, row 1 = (Z/2, Z/2, 0): H_1 = H_2 = Z/2, agreeing with Part A")

# ---------------- Part C ----------------
def snf_diag(M):
    """invariant factors (nonzero) of an integer matrix (list of rows)."""
    A = [row[:] for row in M]
    if not A or not A[0]: return []
    R, C = len(A), len(A[0]); diag = []; t = 0
    while t < min(R, C):
        piv = None
        for i in range(t, R):
            for j in range(t, C):
                if A[i][j] != 0 and (piv is None or abs(A[i][j]) < abs(A[piv[0]][piv[1]])): piv = (i, j)
        if piv is None: break
        i, j = piv; A[t], A[i] = A[i], A[t]
        for row in A: row[t], row[j] = row[j], row[t]
        while True:
            p = A[t][t]; done = True
            for i in range(t + 1, R):
                q = A[i][t] // p
                if q:
                    A[i] = [a - q * b for a, b in zip(A[i], A[t])]
                if A[i][t] != 0: done = False
            for j in range(t + 1, C):
                q = A[t][j] // p
                if q:
                    for row in A: row[j] -= q * row[t]
                if A[t][j] != 0: done = False
            if done:
                bad = [(i, j) for i in range(t + 1, R) for j in range(t + 1, C) if A[i][j] % p]
                if not bad: break
                i, j = bad[0]; A[t] = [a + b for a, b in zip(A[t], A[i])]; continue
            piv = min(((i, j) for i in range(t, R) for j in range(t, C) if (i == t or j == t) and A[i][j] != 0),
                      key=lambda ij: abs(A[ij[0]][ij[1]]))
            i, j = piv; A[t], A[i] = A[i], A[t]
            for row in A: row[t], row[j] = row[j], row[t]
        diag.append(abs(A[t][t])); t += 1
    return diag

def koszul_homology(Ms):
    """H_* of the Koszul complex of the commuting operators 1 - M_i^T on Z^V.  Returns [(rank, torsion list)]."""
    k, V = len(Ms), len(Ms[0])
    ops = [[[(1 if a == b else 0) - Ms[i][b][a] for b in range(V)] for a in range(V)] for i in range(k)]
    subsets = {j: list(itertools.combinations(range(k), j)) for j in range(k + 1)}
    def dmat(j):  # C_j -> C_{j-1}, basis (S, v)
        rows = [(S, a) for S in subsets[j - 1] for a in range(V)]
        cols = [(S, b) for S in subsets[j] for b in range(V)]
        ri = {x: n for n, x in enumerate(rows)}
        D = [[0] * len(cols) for _ in rows]
        for c, (S, b) in enumerate(cols):
            for pos, i in enumerate(S):
                T = S[:pos] + S[pos + 1:]
                for a in range(V):
                    D[ri[(T, a)]][c] += (-1) ** pos * ops[i][a][b]
        return D
    ds = {j: dmat(j) for j in range(1, k + 1)}
    res = []
    for j in range(k + 1):
        dim = math.comb(k, j) * V
        rk_out = len(snf_diag(ds[j])) if j >= 1 else 0
        inv_in = snf_diag(ds[j + 1]) if j + 1 <= k else []
        res.append((dim - rk_out - len(inv_in), [x for x in inv_in if x > 1]))
    return res

def primes_of(H):
    ps = set()
    for rank, tors in H:
        if rank: ps.add(0)
        for x in tors: ps |= set(prime_factors(x))
    return ps

def random_commuting(k, V):
    B = [[random.randint(0, 2) for _ in range(V)] for _ in range(V)]
    I = [[int(a == b) for b in range(V)] for a in range(V)]
    def mul(X, Y): return [[sum(X[a][c] * Y[c][b] for c in range(V)) for b in range(V)] for a in range(V)]
    pw = [I, B, mul(B, B)]
    Ms = []
    for _ in range(k):
        cs = [random.randint(0, 2) for _ in range(3)]
        if sum(cs) == 0: cs[0] = 2
        M = [[sum(cs[e] * pw[e][a][b] for e in range(3)) for b in range(V)] for a in range(V)]
        Ms.append(M)
    return Ms

def part_C(out):
    out.append("== Part C: prime-support lemma  H_0 (x) Z_(l) = 0  =>  H_* (x) Z_(l) = 0  (l prime or l = 0: Q)")
    tested = viol = 0; h0zero_nonacyclic = 0; h0zero = 0
    for _ in range(2500):
        k, V = random.choice([(1, 1), (2, 1), (3, 1), (1, 2), (2, 2), (3, 2), (2, 3), (1, 3)])
        Ms = random_commuting(k, V)
        H = koszul_homology(Ms); tested += 1
        P0 = primes_of([H[0]])
        if not primes_of(H) <= P0: viol += 1
        if not P0: h0zero += 1
        if not P0 and primes_of(H): h0zero_nonacyclic += 1
    out.append(f"random commuting tuples (k<=3, |V|<=3): {tested} tested, {viol} prime-support violations, "
               f"{h0zero} with H_0 = 0, of which {h0zero_nonacyclic} have H_* != 0")
    assert viol == 0 and h0zero_nonacyclic == 0
    # exhaustive: all pairs of commuting 2x2 matrices with entries in {0,1,2}
    mats = [[[a, b], [c, d]] for a, b, c, d in itertools.product(range(3), repeat=4)]
    def commute(X, Y):
        return all(sum(X[i][l] * Y[l][j] for l in range(2)) == sum(Y[i][l] * X[l][j] for l in range(2))
                   for i in range(2) for j in range(2))
    cnt = viol = found = 0
    for X in mats:
        for Y in mats:
            if not commute(X, Y): continue
            H = koszul_homology([X, Y]); cnt += 1
            if not primes_of(H) <= primes_of([H[0]]): viol += 1
            if H[0] == (0, []) and H[1] == (0, [2]) and H[2] == (0, [2]): found += 1
    out.append(f"exhaustive commuting pairs of 2x2 matrices over {{0,1,2}}: {cnt} pairs, {viol} violations; "
               f"pairs with homology (0, Z/2, Z/2) of G_3: {found}")
    assert viol == 0 and found == 0
    # calibration on known k-graph groupoids
    for name, Ms in [("lamplighter 2-graph (2,2)", [[[2]], [[2]]]), ("F_3(t), S-rank 2: (3, 9)", [[[3]], [[9]]]),
                     ("O_2 x O_3 product (2,3)", [[[2]], [[3]]]), ("rank-3 (2,4,8)", [[[2]], [[4]], [[8]]])]:
        out.append(f"calibration {name}: H_* = {koszul_homology(Ms)}")

# ---------------- Part D ----------------
def part_D(out):
    out.append("== Part D: germs of Aff(Z[1/2r], <2,r>) on Z_2 are lambda_v h lambda_w^{-1}, h in BS(1,r)")
    tot = 0
    for r in [3, 5, 7, -3, 9]:
        for _ in range(400):
            a, c = random.randint(-4, 4), random.randint(-3, 3)
            u = F(2) ** a * F(r) ** c
            beta = F(random.randint(-200, 200), 2 ** random.randint(0, 5) * abs(r) ** random.randint(0, 2))
            # point omega in Z_2 (integer approximation is enough: germs of affine maps are determined by the map)
            M = max(0, -a) + random.randint(0, 3) + max(0, -v2(beta)) + 2
            w = random.randrange(2 ** M)
            gw = u * w + beta
            if v2(gw) < 0: continue            # g(omega) must lie in Z_2 on the ball w + 2^M Z_2
            mod = 2 ** (M + a)
            v = (gw.numerator * pow(gw.denominator, -1, mod)) % mod   # v = g(w) mod 2^(M+a), 0 <= v < 2^(M+a)
            b = (gw - v) / F(2) ** (M + a)
            assert v2(b) >= 0 and in_Zr(b, r)                            # h(y) = r^c y + b is in BS(1,r)
            # lambda_v h lambda_w^{-1}(x) = v + 2^(M+a) h((x - w)/2^M) equals g(x) = u x + beta identically
            for x in [w, w + 2 ** M, w - 3 * 2 ** M]:
                assert v + F(2) ** (M + a) * (F(r) ** c * (F(x) - w) / F(2) ** M + b) == u * x + beta
            tot += 1
    out.append(f"{tot} random (g, ball) pairs checked, all decompose with h in BS(1,r)")

# ---------------- Part E ----------------
def vp(x, p):
    x = F(x)
    if x == 0: return 10**9
    n, d, k = x.numerator, x.denominator, 0
    while n % p == 0: n //= p; k += 1
    while d % p == 0: d //= p; k -= 1
    return k

def part_E(out):
    out.append("== Part E: V_p(Z[1/m] x| U'), U' <= Z[1/m]^x torsion-free, on Z_p; germs = Aff(Z[1/pm], <p> x U')")
    tot = 0
    for p, m, Up in [(3, 7, [7]), (3, 2, [2]), (5, 7, [7]), (5, 3, [3]), (3, 10, [2, 5]), (7, 2, [2])]:
        for _ in range(150):
            a = random.randint(-3, 3); us = [random.randint(-2, 2) for _ in Up]
            u1 = F(1)
            for q, e in zip(Up, us): u1 *= F(q) ** e
            u = F(p) ** a * u1
            beta = F(random.randint(-300, 300), p ** random.randint(0, 3) * m ** random.randint(0, 2))
            M = max(0, -a) + max(0, -vp(beta, p)) + random.randint(1, 3)
            w = random.randrange(p ** M); gw = u * w + beta
            if vp(gw, p) < 0: continue
            mod = p ** (M + a)
            v = (gw.numerator * pow(gw.denominator, -1, mod)) % mod
            b = (gw - v) / F(p) ** (M + a)
            assert vp(b, p) >= 0 and in_Zr(b, m)
            for x in [w, w + p ** M, w - 2 * p ** M]:
                assert v + F(p) ** (M + a) * (u1 * (F(x) - w) / F(p) ** M + b) == u * x + beta
            tot += 1
        J = ideal_gen([1 - F(q) for q in Up], m)          # ideal (u'-1) of Z[1/m]
        bad = sorted(l for l in set(prime_factors(J)) | ({p} if J % p == 0 else set())
                     if (p - 1) % l and m % l) if J else ["Q"]
        out.append(f"p={p} m={m} U'={Up}: H_0 = Z/{p - 1}; E2_(0,1) = Z[1/{m}]/({J}); primes l with "
                   f"H_0 (x) Z_(l) = 0 != H_1 (x) Z_(l): {bad}  -> {'EXCLUDED' if bad else 'no obstruction'}")
    out.append(f"{tot} germ decompositions lambda_v h lambda_w^-1 (h in Z[1/m] x| U') verified for odd p")

if __name__ == "__main__":
    out = []
    part_A(out); part_B(out); part_C(out); part_D(out); part_E(out)
    out.append("ALL CHECKS PASSED")
    print("\n".join(out))
