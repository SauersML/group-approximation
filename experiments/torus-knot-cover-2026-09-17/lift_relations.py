"""Check the torus-knot form of the lifted Thompson group T-bar.

Thompson's T is generated by the Cannon-Floyd-Parry maps A, B, C of the
circle R/Z.  Funar-Sergiescu (arXiv:0802.2996, Remark 2.1) set
A = beta alpha^2, B = beta^2 alpha, C = beta^2 with alpha^4 = beta^3 = 1.
Here each map is lifted to a homeomorphism of R commuting with x -> x+1,
and the script computes, with exact rational arithmetic:

  * which composition convention makes Remark 2.1 hold;
  * the lifts a, b of alpha, beta with translation numbers in (-1/2, 1/2];
  * the integers p, q, n with a^4 = z^p, b^3 = z^q, (ba)^5 = z^n, where
    z(x) = x + 1;
  * the two commutator relators, which must lift to the identity.

A map is stored by its nodes (x, f(x)) on one period, and extended by
f(x + k) = f(x) + k.  Equality of PL maps is tested on the grid 2^-10 Z,
which contains every breakpoint of every word evaluated (depth <= 8).
"""
from fractions import Fraction as Fr
import math


class Lift:
    def __init__(self, nodes):
        self.nodes = [(Fr(x), Fr(y)) for x, y in nodes]
        x0 = self.nodes[0][0]
        assert self.nodes[-1][0] == x0 + 1
        assert self.nodes[-1][1] == self.nodes[0][1] + 1

    def __call__(self, t):
        x0 = self.nodes[0][0]
        k = math.floor(t - x0)
        s = t - k
        for (xa, ya), (xb, yb) in zip(self.nodes, self.nodes[1:]):
            if xa <= s <= xb:
                return ya + (yb - ya) * (s - xa) / (xb - xa) + k
        raise ValueError(t)

    def inv(self):
        return Lift([(y, x) for x, y in self.nodes])


h = Fr(1, 2)
q4 = Fr(1, 4)
e8 = Fr(1, 8)
A = Lift([(0, 0), (h, q4), (3 * q4, h), (1, 1)])
B = Lift([(0, 0), (h, h), (3 * q4, 5 * e8), (7 * e8, 3 * q4), (1, 1)])
C = Lift([(0, 3 * q4), (h, 1), (3 * q4, 3 * h), (1, 7 * q4)])
GEN = {"A": A, "B": B, "C": C}
GEN.update({k.lower(): v.inv() for k, v in list(GEN.items())})

GRID = [Fr(i, 2 ** 10) for i in range(2 ** 10)]


def word(ws, conv):
    """ws: list of maps.  conv='left': product g h = g o h (h acts first).
    conv='right': product g h = h o g (g acts first)."""
    seq = ws if conv == "right" else list(reversed(ws))

    def f(t):
        for g in seq:
            t = g(t)
        return t

    return f


def equal(f, g):
    return all(f(t) == g(t) for t in GRID)


def translation(f):
    """f is a lift of the identity of the circle; return m with f = z^m."""
    m = f(Fr(0))
    assert m.denominator == 1 and equal(f, lambda t: t + m)
    return int(m)


results = {}
for conv in ("left", "right"):
    # beta = C^{-1} (= C^2 on the circle, since C^3 = 1)
    # alpha from B = beta^2 alpha, i.e. alpha = C^{-1} B (in the convention)
    alpha_w = [GEN["c"], GEN["B"]]
    # candidate lifts: a = alpha z^i, b = beta z^j, choose |tau| <= 1/2
    def power(ws, k):
        return word(ws * k, conv)
    a4 = translation(power(alpha_w, 4))
    b3 = translation(power([GEN["c"]], 3))
    ia = -round(Fr(a4, 4))              # a = alpha_hat z^ia
    jb = -round(Fr(b3, 3))
    Z = Lift([(0, 1), (1, 2)])
    Zi = Z.inv()
    zpow = lambda k: ([Z] * k if k >= 0 else [Zi] * (-k))
    a_w = alpha_w + zpow(ia)
    b_w = [GEN["c"]] + zpow(jb)
    p = translation(power(a_w, 4))
    q = translation(power(b_w, 3))
    n = translation(power(b_w + a_w, 5))
    # Remark 2.1 substitution: A = beta alpha^2, B = beta^2 alpha, C = beta^2
    remA = equal(lambda t: word(b_w + a_w + a_w, conv)(t) % 1,
                 lambda t: A(t) % 1)
    remB = equal(lambda t: word(b_w + b_w + a_w, conv)(t) % 1,
                 lambda t: B(t) % 1)
    remC = equal(lambda t: word(b_w + b_w, conv)(t) % 1,
                 lambda t: C(t) % 1)
    # commutator relators of Remark 2.1, evaluated on the lifts a, b
    inv_w = lambda ws: [g.inv() for g in reversed(ws)]
    X = b_w + a_w + b_w                                    # beta alpha beta
    Y1 = a_w * 2 + b_w + a_w + b_w + a_w * 2               # a^2 b a b a^2
    Y2 = (a_w * 2 + b_w * 2 + a_w * 2 + b_w + a_w + b_w + a_w * 2
          + b_w + a_w * 2)                                 # a2b2a2baba2ba2
    comm = lambda U, V: U + V + inv_w(U) + inv_w(V)
    c1 = translation(word(comm(X, Y1), conv))
    c2 = translation(word(comm(X, Y2), conv))
    results[conv] = dict(p=p, q=q, n=n, remark21=(remA, remB, remC),
                         comm1=c1, comm2=c2,
                         euler=12 * n - 15 * p - 20 * q)

for conv, r in results.items():
    print(conv, r)
