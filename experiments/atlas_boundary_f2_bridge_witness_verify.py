"""Independently verify the dual F2 boundary/bridge certificate.

The certificate is one Boolean function ``ell:A8->F2`` (stored by its support)
such that

    <ell, x d_q> = 0   for every x in A8 and all 234 boundary words q,
    <ell, 1+h> = 1    for each of four generators h of H.

Therefore no bridge ``1+h`` belongs to the left ideal generated by the
boundary derivatives.  Verification uses direct convolution, not the row
echelon computation that discovered ``ell``.
"""

import argparse
import json

import numpy as np

from atlas_boundary_group_algebra_audit import group_algebra_derivative
from atlas_boundary_h_tangent_screen import INNER_ALIGNMENT_HEX
from atlas_boundary_inner_alignment import enumerate_gl4
from atlas_certified_a8_alignment import boundary_words
from atlas_two_chart_search import I4, gf2_inv, gf2_mul, matrix_key


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--certificate", required=True)
    args = parser.parse_args()
    with open(args.certificate, "r", encoding="utf-8") as stream:
        certificate = json.load(stream)
    supports = certificate["dual_witness_supports"]
    if not supports or any(support != supports[0] for support in supports):
        raise AssertionError("the four stored functionals are not identical")

    elements = list(enumerate_gl4())
    index = {matrix_key(element): position
             for position, element in enumerate(elements)}
    functional = np.zeros(len(elements), dtype=np.uint8)
    functional[supports[0]] = 1
    alignment = np.frombuffer(bytes.fromhex(INNER_ALIGNMENT_HEX),
                              dtype=np.uint8).reshape(4, 4).copy()
    alignment_inverse = gf2_inv(alignment)
    derivatives = [group_algebra_derivative(
        word, alignment, alignment_inverse) for word in boundary_words()]

    unique_terms = sorted({key for derivative in derivatives
                           for key in derivative})
    right_translate = {}
    for key in unique_terms:
        term = np.frombuffer(key, dtype=np.uint8).reshape(4, 4)
        right_translate[key] = np.asarray([
            index[matrix_key(gf2_mul(element, term))]
            for element in elements
        ], dtype=np.int32)
    failures = []
    for boundary_index, derivative in enumerate(derivatives):
        convolution = np.zeros(len(elements), dtype=np.uint8)
        for key, coefficient in derivative.items():
            if coefficient & 1:
                convolution ^= functional[right_translate[key]]
        if np.any(convolution):
            failures.append(boundary_index)

    bridge_pairings = []
    for row, column in ((0, 1), (1, 0), (1, 2), (2, 1)):
        h = I4.copy()
        h[row, column] ^= 1
        bridge_pairings.append(int(
            functional[index[matrix_key(I4)]]
            ^ functional[index[matrix_key(h)]]))
    if failures or bridge_pairings != [1, 1, 1, 1]:
        raise AssertionError("stored dual certificate failed")
    print(json.dumps({
        "certificate_verified": True,
        "field": "F2",
        "group_order": len(elements),
        "functional_support_size": int(functional.sum()),
        "boundary_words_annihilated_with_all_left_translates": 234,
        "bridge_pairings": bridge_pairings,
    }, indent=2))


if __name__ == "__main__":
    main()
