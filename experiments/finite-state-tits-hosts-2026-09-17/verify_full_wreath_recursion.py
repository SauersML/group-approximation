#!/usr/bin/env python3
"""Certificate that R = <A_5, b>, b = (b, alpha, beta, 1, 1), satisfies psi(R) = R wr A_5.

Letters are 0..4. A_5 acts at the root (finitary). b acts trivially on level 1 and has
sections b at 0, alpha at 1, beta at 2, 1 at 3 and 4.

For a in A_5 with a(0) = 0, h_a = b^{-1} (a b a^{-1}) lies in R. Its section at letter j is
s_j(b)^{-1} s_{a^{-1} j}(b), and its section at 0 is b^{-1} b = 1. So h_a has trivial root
permutation and sections in A_5 at 1..4. Let H = <h_a : a in A_5, a(0) = 0>, a subgroup of
1 x A_5^4 inside R.

Claim: H = 1 x A_5^4. Since A_5 is nonabelian simple, a subgroup of A_5^4 whose projection to
every pair of coordinates is all of A_5^2 is all of A_5^4 (Goursat, together with the
structure of subdirect products of nonabelian simple groups). The script checks the six
pair projections by closure.

Consequence: (1,c,1,1,1) is in R for every c in A_5. Conjugating by root elements gives c at
any single coordinate, then (b,1,1,1,1) = b * (1,alpha,beta,1,1)^{-1} is in R. So psi(R)
contains R^5, and A_5 at the root gives psi(R) = R^5 x| A_5. The inclusion psi(R) <= R wr A_5
holds because the generators have root permutations in A_5 and sections in R.
"""
from itertools import permutations, combinations

N = 5
def compose(p, q):  # (p*q)(i) = p(q(i))
    return tuple(p[q[i]] for i in range(N))
def inverse(p):
    r = [0] * N
    for i, pi in enumerate(p):
        r[pi] = i
    return tuple(r)
def sign(p):
    s, seen = 1, [False] * N
    for i in range(N):
        if not seen[i]:
            j, L = i, 0
            while not seen[j]:
                seen[j] = True
                j = p[j]
                L += 1
            if L % 2 == 0:
                s = -s
    return s

ID = tuple(range(N))
A5 = [p for p in permutations(range(N)) if sign(p) == 1]
assert len(A5) == 60
alpha = (1, 2, 3, 4, 0)   # 5-cycle
beta = (1, 2, 0, 3, 4)    # 3-cycle (0 1 2)

def closure(gens):
    elems = {gens[0][:0] or None}
    start = tuple(ID for _ in gens[0])
    elems = {start}
    frontier = [start]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = tuple(compose(g[i], x[i]) for i in range(len(g)))
                if y not in elems:
                    elems.add(y)
                    new.append(y)
        frontier = new
    return elems

# A_5 generated by alpha, beta?
assert len(closure([(alpha,), (beta,)])) == 60

sec_b = {0: None, 1: alpha, 2: beta, 3: ID, 4: ID}
gens = []
for a in A5:
    if a[0] != 0:
        continue
    ai = inverse(a)
    h = []
    for j in range(1, N):
        s_j = sec_b[j]
        s_aj = sec_b[ai[j]]
        assert s_j is not None and s_aj is not None
        h.append(compose(inverse(s_j), s_aj))
    gens.append(tuple(h))

ok = True
for (i, j) in combinations(range(4), 2):
    proj = [(g[i], g[j]) for g in gens]
    size = len(closure(proj))
    print(f"pair projection coords ({i+1},{j+1}): order {size}")
    ok = ok and size == 3600
print("H = 1 x A_5^4:", ok)
print("psi(R) = R wr A_5:", ok)
