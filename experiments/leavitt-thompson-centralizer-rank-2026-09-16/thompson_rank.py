"""Sanity checks for research/artifacts/leavitt-thompson-unit-centralizer-rank-2026-09-16.md.

Part A (V dynamics, Lemmas 2-4 of the artifact).  For random elements g of Thompson's group V:
  * detect finite order (g^m = id for some m <= MAXORD, with a rule-count cap),
  * search clean germs g^p(v z) = v gamma z (gamma nonempty, v of length L, rigid iteration),
    for g and for g^{-1},
  * check: finite order  => no germs;  order not detected => germs for g and for g^{-1};
  * classify random rational points by their cocycle sequence and check the trichotomy
    (bounded => rigid periodic cylinder; unbounded below => repelling periodic point).
Part B (centralizer rank probe).  For a few Thompson units u_g of R = L_(F_2)(1,2), computed in the
groupoid model (elements = finite sets of pairs (alpha, beta) at a common |beta|):
  * dim C_R(u) cap R_N by exact F_2 linear algebra,
  * increments of dim span{u^i z : i <= j, z in C cap R_N}, whose eventual value is the rank of the
    F_2[u]-module generated by C cap R_N, compared with the bound |P_a| * sum_O c_|O|(O).
Evidence only; nothing here is used in any proof.
"""
import itertools
import random
import sys

MAXORD = 64
RULECAP = 4000


def words(n):
    return [''.join(t) for t in itertools.product('01', repeat=n)]


def random_code(n, rng):
    leaves = ['']
    while len(leaves) < n:
        w = leaves.pop(rng.randrange(len(leaves)))
        leaves += [w + '0', w + '1']
    return leaves


def random_V(n, rng):
    b = random_code(n, rng)
    a = random_code(n, rng)
    rng.shuffle(a)
    return list(zip(b, a))  # rule (beta, alpha): g(beta z) = alpha z


def Lmax(g):
    return max(max(len(b), len(a)) for b, a in g)


def star(g, w):
    for b, a in g:
        if w.startswith(b):
            return a + w[len(b):]
    raise ValueError('word shorter than code: ' + w)


def inverse(g):
    return [(a, b) for b, a in g]


def compose(h, g):  # h o g
    Lh = max(len(b) for b, _ in h)
    rules = []
    for b, a in g:
        if len(a) >= Lh:
            rules.append((b, star(h, a)))
        else:
            for w in words(Lh - len(a)):
                rules.append((b + w, star(h, a + w)))
    return reduce_rules(rules)


def reduce_rules(rules):
    d = dict(rules)
    changed = True
    while changed:
        changed = False
        for b in list(d):
            if b and b in d and b[-1] == '0':
                sib = b[:-1] + '1'
                if sib in d and d[b][-1:] == '0' and d[sib][-1:] == '1' and d[b][:-1] == d[sib][:-1]:
                    a = d.pop(b)
                    d.pop(sib)
                    d[b[:-1]] = a[:-1]
                    changed = True
    return sorted(d.items())


def is_identity(g):
    return all(a == b for b, a in g)


def order(g):
    p = g
    for m in range(1, MAXORD + 1):
        if is_identity(p):
            return m
        if len(p) > RULECAP:
            return None
        p = compose(g, p)
    return None


def germs(g):
    """All clean germs (v, p, gamma) found by rigid iteration from v in {0,1}^L."""
    L = Lmax(g)
    out = []
    for v in words(L):
        e = v
        for n in range(1, 3000):
            e = star(g, e)
            if len(e) < L:
                break
            if e.startswith(v):
                if len(e) > L:
                    out.append((v, n, e[L:]))
                break
    return out


def normalize(u, r):
    # primitive root
    for d in range(1, len(r) + 1):
        if len(r) % d == 0 and r[:d] * (len(r) // d) == r:
            r = r[:d]
            break
    while u and u[-1] == r[-1]:
        u = u[:-1]
        r = r[-1] + r[:-1]
    return u, r


def apply_point(g, pt):
    u, r = pt
    L = Lmax(g)
    while len(u) < L:
        u += r
    for b, a in g:
        if u.startswith(b):
            return normalize(a + u[len(b):], r), len(a) - len(b)
    raise ValueError


def cocycle_rigid_return(g, pt, K):
    """Rigid iteration of the prefix of length K; return p if it returns to itself (g^p = id on it)."""
    u, r = pt
    while len(u) < K:
        u += r
    a0 = u[:K]
    e = a0
    L = Lmax(g)
    for n in range(1, 5000):
        if len(e) < L:
            return None
        e = star(g, e)
        if e == a0:
            return n
    return None


def part_A(seed=7, trials=300):
    rng = random.Random(seed)
    stats = dict(finite=0, infinite_undetected=0, fin_with_germ=0, inf_without_germ=0,
                 A0_ok=0, A0_bad=0, Ap=0, B_ok=0, B_bad=0, P_a_sizes=[])
    for t in range(trials):
        n = rng.randrange(2, 7)
        if rng.random() < 0.3:  # equal-length codes give many finite-order elements
            k = rng.randrange(1, 3)
            b = words(k)
            a = words(k)
            rng.shuffle(a)
            g = list(zip(b, a))
            h = random_V(n, rng)
            g = compose(inverse(h), compose(g, h))
        else:
            g = random_V(n, rng)
        g = reduce_rules(g)
        o = order(g)
        G1 = germs(g)
        G2 = germs(inverse(g))
        if o is not None:
            stats['finite'] += 1
            if G1 or G2:
                stats['fin_with_germ'] += 1
        else:
            stats['infinite_undetected'] += 1
            if not (G1 and G2):
                stats['inf_without_germ'] += 1
        # attracting periodic points from germs
        Pa = set()
        for v, p, gam in G1:
            q = normalize(v, gam)
            cur = q
            for _ in range(10000):
                Pa.add(cur)
                cur, _c = apply_point(g, cur)
                if cur == q:
                    break
        stats['P_a_sizes'].append(len(Pa))
        # random rational points: classify
        L = Lmax(g)
        for _ in range(5):
            pt = normalize(''.join(rng.choice('01') for _ in range(rng.randrange(0, 6))),
                           ''.join(rng.choice('01') for _ in range(rng.randrange(1, 4))))
            cs = [0]
            cur = pt
            seen = {pt: 0}
            period = None
            for m in range(1, 400):
                cur, c = apply_point(g, cur)
                cs.append(cs[-1] + c)
                if cur in seen and period is None:
                    period = (seen[cur], m)
                seen.setdefault(cur, m)
            lo, hi = min(cs), max(cs)
            if hi - lo <= 40 and period is not None:
                # expect A0: rigid periodic cylinder around pt
                K = L - min(cs)
                if cocycle_rigid_return(g, pt, K):
                    stats['A0_ok'] += 1
                else:
                    stats['A0_bad'] += 1
            elif cs[-1] < lo + 40 and lo < -40:
                # expect B: pt periodic with negative cocycle
                if period is not None and period[0] == 0:
                    stats['B_ok'] += 1
                else:
                    stats['B_bad'] += 1
            else:
                stats['Ap'] += 1
    sizes = stats.pop('P_a_sizes')
    stats['max_P_a'] = max(sizes)
    return stats


# ---------------- Part B: groupoid model of R ----------------

def toggle(S, x):
    if x in S:
        S.remove(x)
    else:
        S.add(x)


def pad(W, M):
    out = set()
    for a, b in W:
        d = M - len(b)
        assert d >= 0
        if d == 0:
            toggle(out, (a, b))
        else:
            for w in words(d):
                toggle(out, (a + w, b + w))
    return out


def common(*Ws):
    M = max([len(b) for W in Ws for _, b in W] or [0])
    return [pad(W, M) for W in Ws]


def left_mul(g, W):
    L = Lmax(g)
    out = set()
    for a, b in W:
        if len(a) >= L:
            toggle(out, (star(g, a), b))
        else:
            for w in words(L - len(a)):
                toggle(out, (star(g, a + w), b + w))
    return common(out)[0]


def right_mul(W, g):
    L = Lmax(g)
    gi = inverse(g)
    out = set()
    for a, b in W:
        if len(b) >= L:
            toggle(out, (a, star(gi, b)))
        else:
            for w in words(L - len(b)):
                toggle(out, (a + w, star(gi, b + w)))
    return common(out)[0]


class Elim:
    """Incremental F_2 elimination over bit vectors (python ints)."""

    def __init__(self):
        self.piv = {}

    def add(self, v, tag=0):
        while v:
            h = v.bit_length() - 1
            if h in self.piv:
                pv, pt = self.piv[h]
                v ^= pv
                tag ^= pt
            else:
                self.piv[h] = (v, tag)
                return None
        return tag  # dependent: tag records the combination

    def rank(self):
        return len(self.piv)


def to_bits(W, index):
    x = 0
    for p in W:
        if p not in index:
            index[p] = len(index)
        x |= 1 << index[p]
    return x


def centralizer_basis(g, N):
    span = [pad({(a, b)}, N) for i in range(N + 1) for j in range(N + 1)
            for a in words(i) for b in words(j)]
    idx = {}
    E = Elim()
    basis = []
    for W in span:
        if E.add(to_bits(W, idx)) is None:
            basis.append(W)
    dimRN = len(basis)
    D = []
    for W in basis:
        l, r = common(left_mul(g, W), right_mul(W, g))
        D.append(l ^ r)
    D = common(*D)
    idx2 = {}
    E2 = Elim()
    ker = []
    for i, W in enumerate(D):
        tag = E2.add(to_bits(W, idx2), 1 << i)
        if tag is not None:
            z = set()
            for k in range(len(basis)):
                if tag >> k & 1:
                    z ^= basis[k]
            ker.append(z)
    return dimRN, ker


def increments(g, gens, J):
    fam = [set(z) for z in gens]
    incs = []
    prev = 0
    allv = []
    for j in range(J + 1):
        if j > 0:
            fam = [left_mul(g, z) for z in fam]
        allv += fam
        padded = common(*allv)
        idx = {}
        E = Elim()
        for W in padded:
            E.add(to_bits(W, idx))
        incs.append(E.rank() - prev)
        prev = E.rank()
    return incs


def rank_bound(g):
    Pa = {}
    for v, p, gam in germs(g):
        q = normalize(v, gam)
        orbit = []
        cur = q
        tot = 0
        while True:
            orbit.append(cur)
            cur, c = apply_point(g, cur)
            tot += c
            if cur == q:
                break
        Pa[frozenset(orbit)] = tot
    size = sum(len(o) for o in Pa)
    return size * sum(Pa.values()), size, sorted(Pa.values())


def part_B(N=2, J=7):
    c = [('0', '00'), ('10', '01'), ('11', '1')]
    units = {
        'c': c,
        'c^2': compose(c, c),
        'phi(c)': [('0' + b, '0' + a) for b, a in c] + [('1' + b, '1' + a) for b, a in c],
        'twocycle': [('0' + b, '1' + a) for b, a in c] + [('1', '0')],
        'c_on_[0]': [('0' + b, '0' + a) for b, a in c] + [('1', '1')],
    }
    rows = []
    for name, g in units.items():
        g = reduce_rules(g)
        bound, size, cyc = rank_bound(g)
        dimRN, ker = centralizer_basis(g, N)
        inc = increments(g, ker, J)
        rows.append((name, dimRN, len(ker), inc, bound, size, cyc))
    return rows


