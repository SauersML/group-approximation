"""Exact invariant-corner audit for ``<P,x_78(1),x_87(1)>``.

Run only through MSI.  The faithful sparse Leavitt normal form verifies that
the complement of the endpoint support is fixed by ``P`` and carries the
ordinary six-element native ``S_3`` generated by the two constant roots.
"""

from endpoint_chain_center_hecke_collision_audit import coeff, whitehead
from depth_one_paired_leavitt_return_search import (
    add,
    equal,
    multiply as coefficient_multiply,
)
from signed_hecke_literal_pauli_probe_audit import (
    COORDS,
    identity_matrix,
    matrices_equal,
    matrix_key,
    matrix_multiply,
    word_matrix,
    zero_matrix,
)


def root(target, source):
    return word_matrix(((source, target, coeff("", "")),))


def scalar_projection(value):
    matrix = zero_matrix()
    for index in range(len(COORDS)):
        matrix[index][index] = value
    return matrix


def corner(left_support, matrix):
    return matrix_multiply(matrix_multiply(left_support, matrix), left_support)


def generated_corner_group(identity, generators):
    seen = {matrix_key(identity): identity}
    frontier = [identity]
    while frontier:
        current = frontier.pop()
        for generator in generators:
            nxt = matrix_multiply(current, generator)
            key = matrix_key(nxt)
            if key not in seen:
                seen[key] = nxt
                frontier.append(nxt)
    return seen


def power(identity, matrix, exponent):
    answer = identity
    for _ in range(exponent):
        answer = matrix_multiply(answer, matrix)
    return answer


def main():
    one = coeff("", "")
    e = coeff("00", "00")
    complement = add(one, e)  # characteristic two: 1-e=1+e
    assert equal(coefficient_multiply(complement, complement), complement)
    assert equal(coefficient_multiply(complement, coeff("1", "1")),
                 coeff("1", "1"))

    support = scalar_projection(complement)
    endpoint = word_matrix(whitehead(8, 2, 2))
    n = root(7, 8)
    m = root(8, 7)

    # The support is reducing for all three generators, and P is the identity
    # on it.  The equality is in the faithful Leavitt normal form.
    for generator in (endpoint, n, m):
        assert matrices_equal(matrix_multiply(support, generator),
                              matrix_multiply(generator, support))
    assert matrices_equal(corner(support, endpoint), support)

    n_corner = corner(support, n)
    m_corner = corner(support, m)
    group = generated_corner_group(support, (n_corner, m_corner))
    assert len(group) == 6
    assert matrices_equal(power(support, n_corner, 2), support)
    assert matrices_equal(power(support, m_corner, 2), support)
    assert matrices_equal(
        power(support, matrix_multiply(n_corner, m_corner), 3), support
    )
    assert not matrices_equal(n_corner, support)
    assert not matrices_equal(m_corner, support)
    assert not matrices_equal(n_corner, m_corner)

    print("endpoint complement projection", complement)
    print("endpoint corner is identity", True)
    print("native corner group order", len(group))


if __name__ == "__main__":
    main()
