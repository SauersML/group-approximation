"""Exact constrained A_6 single-edge hexagons in the V0 shadow, and the specific-form test of the brief.

curver.load(0, 10): punctures e1, 1..7, e0, oo; sigma_i = curver s_i (i = 1..6).  Strands 1,2,3 = q's,
4,5,6 = p's, 7 = t; in V0 the cluster is C = {1,2,3,4} and rho_V(s4^2) is a meridian of the cluster wall,
taken here as D = Delta_C^2 = (s1 s2 s3)^4.
  x-vertex hA_X'' <-> h(s_7)  (arc 7 -- e0);   Y''-vertex gA_Y'' <-> g(spider0), spider0 = legs
  s_0, s1(s_0), s2 s1(s_0) from e1 to 1, 2, 3.  Adjacent <=> every leg is disjoint from the arc.
F'' = <A47, A57, A67>.  N-letters from the subgroup of N_V generated by D and the pair twists A_{j5}, A_{j6}
(j = 1,2,3); each lies in N_V (trivial on 456, restriction to C trivial or Delta_C^2).
Tuple (a1,a2,a3; b1,b2,b3) with a3 = (a1a2)^-1, b2 = b1^-1 b3^-1 and  b3^-1 (a1a2) b3 = a1 b1 a2 b1^-1  (*).
Forms: Y2 (y2 = a1b1.spider0 adjacent to x1) or TW (D^j.spider0 adjacent to x2 and x3, |j| <= M).
Run: PYTHONPATH=.:<curver>:<realalg> python3 a6.py [LF] [LN1] [LN3] [M]"""
import sys, itertools
from collections import Counter
import curver

sys.setrecursionlimit(20000)
S = curver.load(0, 10)
CHAIN = [S.arcs['s_%d' % i] for i in range(9)]


def A(i, j):
    return list(range(j - 1, i, -1)) + [i, i] + [-k for k in range(i + 1, j)]


def inv(w):
    return [-g for g in reversed(w)]


D = [1, 2, 3] * 4
FG = [A(4, 7), A(5, 7), A(6, 7)]
NG = [D] + [A(j, 5) for j in (1, 2, 3)] + [A(j, 6) for j in (1, 2, 3)]
NNAME = ['D', 'A15', 'A25', 'A35', 'A16', 'A26', 'A36']
_mc = {}


def mc(b):
    k = tuple(b)
    if k not in _mc:
        _mc[k] = S('.'.join(('s_%d' if g > 0 else 'S_%d') % abs(g) for g in b)) if b else S('')
    return _mc[k]


def words(gens, L):
    let = [(i, 1) for i in range(len(gens))] + [(i, -1) for i in range(len(gens))]
    out = []
    for n in range(1, L + 1):
        for w in itertools.product(let, repeat=n):
            if any(w[k][0] == w[k + 1][0] and w[k][1] == -w[k + 1][1] for k in range(n - 1)):
                continue
            b = []
            for i, s in w:
                b += gens[i] if s == 1 else inv(gens[i])
            out.append((w, b))
    return out


def sig(b):
    h = S('.'.join(('s_%d' if g > 0 else 'S_%d') % abs(g) for g in b)) if b else S('')
    return tuple(tuple(h(a).geometric) for a in CHAIN)


X0 = S.arcs['s_7']
LEGS = [S.arcs['s_0'], S('s_1')(S.arcs['s_0']), S('s_2.s_1')(S.arcs['s_0'])]


def xarc(b):
    return mc(b)(X0)


def spider(b):
    h = mc(b)
    return [h(l) for l in LEGS]


def adj(sp, x):
    return all(l.intersection(x) == 0 for l in sp)


def main(LF=1, LN1=1, LN3=1, M=4):
    assert all(adj(LEGS, X0) for _ in [0]) and all(l.intersection(m) == 0 for l in LEGS for m in LEGS if l != m)
    FA, N1, N3 = words(FG, LF), words(NG, LN1), words(NG, LN3)
    print('F words', len(FA), 'N words', len(N1), len(N3), flush=True)
    lhs = {}
    for (wa1, a1), (wa2, a2) in itertools.product(FA, FA):
        for wb3, b3 in N3:
            lhs.setdefault(sig(inv(b3) + a1 + a2 + b3), []).append((wa1, wa2, wb3, b3))
    print('lhs done', len(lhs), flush=True)
    x1 = xarc([])
    tw = {j: spider(D * j if j >= 0 else inv(D) * (-j)) for j in range(-M, M + 1)}
    stat, sols = Counter(), 0
    for (wa1, a1), (wb1, b1), (wa2, a2) in itertools.product(FA, N1, FA):
        rhs = a1 + b1 + a2 + inv(b1)
        for (va1, va2, wb3, b3) in lhs.get(sig(rhs), []):
            if (va1, va2) != (wa1, wa2) or mc(inv(b3) + a1 + a2 + b3) != mc(rhs):
                continue
            if mc(a1 + a2).is_identity() or mc(inv(b1) + inv(b3)).is_identity():
                continue
            sols += 1
            x2, x3 = xarc(a1), xarc(a1 + b1 + a2)
            y2 = adj(spider(a1 + b1), x1)
            je = tuple(j for j, sp in tw.items() if adj(sp, x2) and adj(sp, x3))
            stat[(y2, je)] += 1
            if not (y2 or je):
                nm = lambda w, names: ' '.join(names[i] + ('' if s == 1 else '^-1') for i, s in w)
                print('NOFORM a1', nm(wa1, ['A47', 'A57', 'A67']), '| b1', nm(wb1, NNAME), '| a2',
                      nm(wa2, ['A47', 'A57', 'A67']), '| b3', nm(wb3, NNAME), flush=True)
    for k, v in sorted(stat.items()):
        print('  y2~x1', k[0], 'twist j', list(k[1]), ':', v)
    print('nondegenerate tuples', sols, 'no-form', sum(v for k, v in stat.items() if not (k[0] or k[1])))


if __name__ == '__main__':
    main(*[int(x) for x in sys.argv[1:]])
