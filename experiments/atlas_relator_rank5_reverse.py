"""The reverse dictionary: the twelve atlas generators as rank-five words.

Why this is needed.  Let `T_St` be the translated rank-five Steinberg relation
family and `G = Pbar/<<T_St>>`.  The defining relators of `St_5(L)` all die in
`G` by construction, so there is a homomorphism

    psi : St_5(L) -> G,     X_kl(b) |-> [ x_kl(b) ].

The argument that `ker(G ->> Q)` is central needs `psi` to be **surjective**:
only then is `G` a quotient of `St_5(L)`, so that the central `K_2(5,L)` maps
onto `ker(G ->> Q)`.  Surjectivity is NOT automatic -- `G` is generated by the
images of `K1` and `K2`, not by the `x_kl(b)`.  It becomes automatic once
`T_St` also contains, for each of the twelve atlas generators `g`, a relator
`g w_g^{-1}` with `w_g` a word in the `x_kl(b)`.

This script produces those `w_g`, exactly verified.

Mechanism.  Each atlas generator is a chart leaf transvection `1 + d_u d_v^*`
with `u, v` distinct leaves of `D_1` or `D_2`.  The rank-five code
`E = (000, 001, 010, 011, 1)` refines both charts as a prefix code, so

    d_u = sum_{w in E, w extends u} d_w sigma_w^*,     u = w . sigma_w,

and likewise for `v`.  Hence

    d_u d_v^* = sum_{w, w'} d_w (sigma_w^* sigma_{w'}) d_{w'}^* ,

with each `sigma` of length zero or one, so each coefficient
`sigma_w^* sigma_{w'}` is one of `1, e, f, e^*, f^*` or zero.  Every cross
product of two such rank-one terms vanishes (`d_{w'}^* d_{w''} = 0` for
distinct `E`-leaves), so the terms are pairwise annihilating and

    1 + d_u d_v^* = prod over surviving (w, w') of x_{kl}(coefficient),

a product of at most four rank-five generators, in any order.
"""

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from atlas_kernel_collision_enumerator import evaluate_word  # noqa: E402
from atlas_relator_rank5_dictionary import (  # noqa: E402
    leaf,
    leavitt_equal,
    rank5_word,
    transvection_lengths,
)
from atlas_two_chart_search import (  # noqa: E402
    CHART_LEAVES,
    factor_generators,
    inverse,
    leavitt_chart_element,
    product,
    reduce_word,
    transvection,
)

CODE = {k: leaf(k) for k in range(1, 6)}
STAR = {"": "1", "0": "E", "1": "F"}       # sigma^* as a coefficient letter
PLAIN = {"": "1", "0": "e", "1": "f"}      # sigma as a coefficient letter


def refinement(u):
    """Pairs (index k, suffix) with E_k = u . suffix."""
    out = []
    for k, w in CODE.items():
        if w.startswith(u):
            out.append((k, w[len(u):]))
    assert out, u
    assert all(len(s) <= 1 for _k, s in out), (u, out)
    return out


def coefficient(sigma_w, sigma_wprime):
    """The single letter of sigma_w^* sigma_w', or None when it vanishes."""
    if sigma_w == "":
        return PLAIN[sigma_wprime]
    if sigma_wprime == "":
        return STAR[sigma_w]
    return "1" if sigma_w == sigma_wprime else None


def generate_relators(verify=True):
    """Return the twelve relators ``g w_g^-1`` in generator order."""
    lengths = transvection_lengths()
    memo = {}
    rows = []
    failures = []

    for name, gen_word in factor_generators():
        (chart, matrix), = gen_word
        rowcol = [(r, c) for r in range(4) for c in range(4)
                  if matrix[r, c] and r != c]
        assert len(rowcol) == 1
        r, c = rowcol[0]
        u = CHART_LEAVES[chart][r]
        v = CHART_LEAVES[chart][c]

        factors = []
        for k, sw in refinement(u):
            for l, swp in refinement(v):
                b = coefficient(sw, swp)
                if b is None:
                    continue
                assert k != l, (name, k, l)
                factors.append((k, l, b))

        word = []
        for k, l, b in factors:
            word = product(word, rank5_word(k, l, b, memo)[0])
        word = reduce_word(word)

        ok = (not verify) or leavitt_equal(
            evaluate_word(word), leavitt_chart_element(chart, matrix)
        )
        if not ok:
            failures.append(name)
        relator = reduce_word(product(gen_word, inverse(word)))
        rows.append((name, chart, u, v, factors, word, relator, ok))

    if failures:
        raise AssertionError("reverse dictionary failures: %r" % failures)
    return rows, lengths


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--verbose", action="store_true")
    parser.add_argument("--emit", default="")
    args = parser.parse_args()

    rows, lengths = generate_relators(verify=True)
    failures = []

    print("atlas generators expressed in rank-five words: %d" % len(rows))
    print("verified exactly:                              %d"
          % sum(1 for row in rows if row[7]))

    print()
    print("%-8s %-5s %-5s %-5s  %-34s %6s %8s"
          % ("gen", "chart", "u", "v", "rank-five factors", "syll", "X-len"))
    for name, chart, u, v, factors, word, _relator, _ok in rows:
        pretty = " ".join("x_%d%d(%s)" % (k, l, b) for k, l, b in factors)
        print("%-8s %-5d %-5s %-5s  %-34s %6d %8d"
              % (name, chart, u, v, pretty, len(word),
                 sum(lengths[m.tobytes()] for _f, m in word)))

    print()
    print("Every atlas generator is a product of at most four rank-five")
    print("generators, so adding the twelve relators  g . w_g^{-1}  to T_St")
    print("makes psi : St_5(L) -> Pbar/<<T_St>> surjective.")

    if args.emit:
        payload = []
        for name, _chart, _u, _v, _factors, _word, relator, _ok in rows:
            payload.append({
                "name": "reverse_%s" % name,
                "syllables": len(relator),
                "x_length": sum(lengths[m.tobytes()] for _f, m in relator),
                "word": [[int(f), "".join(str(int(v)) for v in m.reshape(-1))]
                         for f, m in relator],
            })
        with open(args.emit, "w") as handle:
            json.dump({"relators": payload}, handle)
        print("wrote", args.emit)

    return 0


if __name__ == "__main__":
    sys.exit(main())
