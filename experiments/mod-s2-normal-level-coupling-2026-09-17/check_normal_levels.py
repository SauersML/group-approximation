#!/usr/bin/env python3
"""Checks behind mod-s2-normal-level-torelli-floors-are-coupled.

Exact integer checks only (no floating point).  Inputs are existing census
artifacts; nothing is recomputed from a presentation.

Gamma(3): census-results-frame-3.json of the Torelli-scalar census (W basis,
class multiplicities, certificate).  Checks
  * the class multiplicities are all equal (necessary at a normal level);
  * cert_w lies in the Z-span of the W basis;
  * ||cert_w||_1 = 5 and aug(cert_w) = -5, so aug != 0 and 3 does not divide it;
  * gcd of augmentations of the W basis is 5.
By the orbit-averaging lemma (N1) this gives 1/5 <= e(Gamma(3)) <= 1/5 and,
with (RF)/(TA3), 1/15 <= d(Gamma(3)) <= 1/15.

Gamma(4): gamma4-results.json / gamma4-structure.json.  Checks the stored
numbers used by the route: one coset count per class, gcd aug 10, a W-vector
with l1 = aug = 10.

Gamma(2), Gamma(1): the W lattices are rank one, generated by the all-ones
vector on 10 classes (aug 10) and by 5 on one class (aug 5); these values
are taken from the census tables (rank W = 1 in both), not re-derived here.
"""
import json
import os
from fractions import Fraction
from math import gcd

HERE = os.path.dirname(os.path.abspath(__file__))
EXP = os.path.join(HERE, "..")
SC = os.path.join(EXP, "mod-s2-torelli-scalar-census-2026-09-17")
G4 = os.path.join(EXP, "mod-s2-gamma4-torsion-census-2026-09-17")


def in_z_span(basis, v):
    """Exact test that v is an integer combination of the rows of basis."""
    from flint import fmpz_mat
    B = fmpz_mat(basis)
    H = B.hnf()
    rows = [[int(H[i, j]) for j in range(H.ncols())] for i in range(H.nrows())]
    rows = [r for r in rows if any(r)]
    x = list(v)
    for r in rows:
        p = next(j for j, a in enumerate(r) if a)
        if x[p] % r[p]:
            return False
        q = x[p] // r[p]
        x = [a - q * b for a, b in zip(x, r)]
    return not any(x)


def floors(g, m0, m3):
    """(e_lo, e_hi, d_lo, d_hi) from (N1)-(N3) at a normal level."""
    return (Fraction(1, m0), Fraction(1, g), Fraction(1, 3 * m3),
            Fraction(1, 3 * g))


def main():
    out = {}

    # --- Gamma(3) ---------------------------------------------------------
    rec = next(r for r in json.load(open(os.path.join(
        SC, "census-results-frame-3.json"))) if r["case"] == "frame-3")
    basis = rec["W_basis"]
    mult = rec["class_multiplicities"]
    w = rec["cert_w"]
    assert len(set(mult)) == 1 and sum(mult) == rec["index"] == 51840
    assert in_z_span(basis, w)
    l1, aug = sum(abs(a) for a in w), sum(w)
    assert (l1, aug) == (5, -5)
    g = 0
    for r in basis:
        g = gcd(g, sum(r))
    assert g == 5 == rec["gcd_aug_W"]
    e_lo, e_hi, d_lo, d_hi = floors(g, l1, l1)
    assert e_lo == e_hi == Fraction(1, 5) and d_lo == d_hi == Fraction(1, 15)
    assert rec["distance"] == "1/15"
    out["Gamma(3)"] = {"index": 51840, "classes": len(mult),
                       "mult": mult[0], "gcd_aug": g, "cert_l1": l1,
                       "cert_aug": aug, "e": str(e_lo), "d": str(d_lo)}

    # --- Gamma(4) ---------------------------------------------------------
    r4 = json.load(open(os.path.join(G4, "gamma4-results.json")))
    s4 = json.load(open(os.path.join(G4, "gamma4-structure.json")))
    assert len(r4["class_coset_counts"]) == 1
    assert r4["gcd_aug"] == 10 and r4["cert_l1"] == r4["cert_aug"] == 10
    assert s4["transversal_relations"] == 1024
    e_lo, e_hi, d_lo, d_hi = floors(10, 10, 10)
    assert e_lo == e_hi == Fraction(1, 10) and d_lo == d_hi == Fraction(1, 30)
    assert r4["d"] == "1/30"
    out["Gamma(4)"] = {"index": 737280, "classes": r4["classes"],
                       "gcd_aug": 10, "cert_l1": 10, "cert_aug": 10,
                       "e": str(e_lo), "d": str(d_lo)}

    # --- Gamma(2), Gamma(1) (rank-one W, from the census tables) -----------
    for name, g, m in (("Gamma(2)", 10, 10), ("Gamma(1)", 5, 5)):
        e_lo, e_hi, d_lo, d_hi = floors(g, m, m)
        assert e_lo == e_hi and d_lo == d_hi and e_lo == 3 * d_lo
        out[name] = {"gcd_aug": g, "cert_l1": m, "e": str(e_lo),
                     "d": str(d_lo)}

    for v in out.values():
        assert Fraction(v["e"]) == 3 * Fraction(v["d"])
    json.dump(out, open(os.path.join(HERE, "normal-levels.json"), "w"),
              indent=1)
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
