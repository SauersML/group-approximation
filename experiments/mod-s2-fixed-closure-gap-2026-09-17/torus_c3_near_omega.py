"""Calibration for (FC5) of mod-s2-fixed-closure-torelli-gap-and-zero-windings.

Compact group K = T^2 x| C_3, where C_3 = <A> acts by A = [[0,-1],[1,-1]] (A^3 = I, I + A + A^2 = 0,
fixed-point-free on Z^2 \\ 0).  Take g = (sqrt 2, sqrt 3) in T^2 = R^2/Z^2.

- No continuous representation of K sends g to omega I exactly: on the 3-dimensional irreducible
  Ind chi_v (v in Z^2 \\ 0) the eigenvalues of g are e(<v, A^k g>), k = 0, 1, 2, and <v, g> is irrational.
  The 1-dimensional representations (characters of K/T^2 = C_3) send g to 1.
- K/[K,K] is finite (T^2 = (1 - A) T^2 lies in the commutator subgroup), so no determinant separates g.
- Yet min_v ||pi_v(g) - omega I|| -> 0 over |v|_inf <= R as R grows: the irreducibles of dimension 3
  come arbitrarily close to omega.  Their limit is a representation of the discrete group generated by
  g, Ag, A that is not continuous on K.

So the fixed-closure gap cannot come from compact-group structure alone: the proof uses, besides the
structure of K, the discrete input (ST5) plus compactness of Hom(M, U(n)) for the finitely generated M.
"""

import json
import sys

import numpy as np

A = np.array([[0, -1], [1, -1]])
assert (np.linalg.matrix_power(A, 3) == np.eye(2, dtype=int)).all()
assert (np.eye(2, dtype=int) + A + A @ A == 0).all()

g = np.array([np.sqrt(2.0), np.sqrt(3.0)])
orbit = [g, A @ g, A @ A @ g]  # A^k g in R^2; only classes mod Z^2 matter
omega = np.exp(2j * np.pi / 3)


def best(R):
    r = np.arange(-R, R + 1)
    v1, v2 = np.meshgrid(r, r, indexing="ij")
    v1 = v1.ravel()
    v2 = v2.ravel()
    keep = (v1 != 0) | (v2 != 0)
    v1, v2 = v1[keep], v2[keep]
    dist = np.zeros(v1.shape)
    for h in orbit:
        phase = np.exp(2j * np.pi * (v1 * h[0] + v2 * h[1]))
        dist = np.maximum(dist, np.abs(phase - omega))
    i = int(np.argmin(dist))
    return {"R": R, "v": [int(v1[i]), int(v2[i])], "opnorm_dist_to_omega": float(dist[i])}


def main():
    rows = [best(R) for R in (3, 10, 30, 100, 300, 1000)]
    for row in rows:
        print(row)
    ds = [row["opnorm_dist_to_omega"] for row in rows]
    assert ds[-1] < 0.01, ds
    assert all(ds[i + 1] <= ds[i] for i in range(len(ds) - 1))
    out = {
        "group": "T^2 x| C_3, A = [[0,-1],[1,-1]]",
        "g": "(sqrt 2, sqrt 3) in T^2",
        "irreducible_dim": 3,
        "rows": rows,
        "conclusion": "3-dim continuous irreducibles of a fixed compact group with finite abelianization "
        "approach omega I on g, with no exact omega; the gap of (FC1) needs the M-input (ST5 + compactness "
        "of Hom(M,U(n))).",
    }
    path = sys.argv[1] if len(sys.argv) > 1 else None
    if path:
        with open(path, "w") as f:
            json.dump(out, f, indent=2)
    print("OK")


if __name__ == "__main__":
    main()
