"""U_G2(2) via the Chevalley commutator presentation, over the FULL
envelope of char-2 structure-constant ambiguities.

Roots (a2 long, a3 short), height order:
  0: a3   1: a2   2: a2+a3   3: a2+2a3   4: a2+3a3   5: 2a2+3a3
Element = F2^6 exponent vector in the fixed product order
x0^e0 x1^e1 ... x5^e5.  Collection moves a generator left past
earlier ones using:
  [x1,x0] = x2^1 x3^b x4^c x5^d        (a=1 forced, N=+-1)
  [x2,x0] = x3^e x4^f x5^g             (via strings)
  [x3,x0] = x4^h
  [x3,x2] = x5^i
  [x4,x1] = x5^1                       (forced, p=0 string)
  all other pairs commute (no real roots in between).
Unknown bits: b,c,d,e,f,g,h,i in {0,1}: 256 candidates; keep those
where collection yields an associative 64-element group with
|Z| = 2 (center = highest root) and |[G,G]| = 16 (heights >= 2).
"""
import numpy as np
from itertools import product as iproduct

PAIRS = {}  # (i,j) with i>j -> dict of correction exponents on roots
def make_rules(b,c,d,e,f,g,h,i_):
    R = {}
    R[(1,0)] = {2:1, 3:b, 4:c, 5:d}
    R[(2,0)] = {3:e, 4:f, 5:g}
    R[(3,0)] = {4:h}
    R[(3,2)] = {5:i_}
    R[(4,1)] = {5:1}
    return R

def mult(x, y, R):
    """normal-form product of exponent vectors via collection."""
    word = []
    for k in range(6): word += [k]*x[k]
    for k in range(6): word += [k]*y[k]
    # bubble-sort with commutator corrections; letters are generators
    changed = True
    while changed:
        changed = False
        m = 0
        while m+1 < len(word):
            p, q = word[m], word[m+1]
            if p > q:
                corr = R.get((p,q), {})
                # x_p x_q = x_q x_p [x_p,x_q]^{-1}... char 2, and
                # [x_p, x_q] = prod x_r^{c_r}: x_p x_q = x_q x_p * prod
                word[m], word[m+1] = q, p
                ins = []
                for r,cr in corr.items(): ins += [r]*cr
                word[m+2:m+2] = ins
                changed = True
            elif p == q:
                del word[m:m+2]  # involutions
                changed = True
            else:
                m += 1
    v = [0]*6
    for k in word: v[k] ^= 1
    return tuple(v)

def build(Rbits):
    R = make_rules(*Rbits)
    els = list(iproduct(range(2), repeat=6))
    idx = {e:i for i,e in enumerate(els)}
    T = np.zeros((64,64), dtype=np.int16)
    for a_ in els:
        for b_ in els:
            T[idx[a_], idx[b_]] = idx[mult(a_,b_,R)]
    return els, idx, T

def group_ok(els, idx, T):
    # associativity
    A = T[T, :]           # A[a,b,c] = T[T[a,b],c]
    B = T[:, T]           # B[a,b,c] = T[a, T[b,c]]
    if not np.array_equal(A, B): return False
    e = idx[(0,)*6]
    if not (np.array_equal(T[e,:], np.arange(64)) and
            np.array_equal(T[:,e], np.arange(64))): return False
    # center
    Z = [a for a in range(64) if np.array_equal(T[a,:], T[:,a])]
    if len(Z) != 2: return False
    zc = idx[(0,0,0,0,0,1)]
    if zc not in Z: return False
    # derived subgroup: generated by commutators
    inv = np.argsort(T, axis=1)  # inv[a, T[a,b]] = ...? compute properly:
    invel = [int(np.where(T[a,:] == e)[0][0]) for a in range(64)]
    comms = set()
    for a in range(64):
        for b_ in range(64):
            comms.add(int(T[T[invel[a],invel[b_]], T[a,b_]]))
    # closure
    D = set(comms); frontier = set(comms)
    while frontier:
        nf = set()
        for a in D:
            for b_ in frontier:
                c_ = int(T[a,b_])
                if c_ not in D: nf.add(c_)
        D |= nf; frontier = nf
    if len(D) != 16: return False
    hi = {i for i,el in enumerate(els) if el[0]==0 and el[1]==0}
    if D != hi: return False
    return True

