#!/usr/bin/env python3
"""Search split class-two models N(Omega)/K x| (GL x GR) of Gamma_trap that
keep the head h = x_13(Q).  See class2.py for the model.

For fixed Levi permutations the W-level trap relations are linear in the
W-part v of u; for fixed v and C-part c_u every relator lies in the centre C,
and the smallest admissible K is the G0-submodule generated by the relator
C-parts.  The head survives iff its C-part is not in that K.
"""

import random
import sys

from class2 import Model, rand_involution, product_perm
from words import (GEN_NAMES, DERIVED, TRAP_RELS, INVOL_RELS, EXTRA_RELS,
                   LEFT, RIGHT)


def papply(perm, a):
    out = 0
    while a:
        low = a & -a
        i = low.bit_length() - 1
        a ^= low
        out |= 1 << perm[i]
    return out


def dop(perm):
    return lambda a: a ^ papply(perm, a)


class Echelon:
    def __init__(self):
        self.rows = {}

    def reduce(self, v):
        while v:
            p = v.bit_length() - 1
            r = self.rows.get(p)
            if r is None:
                return v
            v ^= r
        return 0

    def add(self, v):
        v = self.reduce(v)
        if v:
            self.rows[v.bit_length() - 1] = v
            return v
        return 0


def nullspace(fn, n):
    """Kernel of the F_2-linear map fn on F_2^n (ints), as a list of ints."""
    # columns: images of basis vectors; Gaussian elimination tracking combos
    rows = {}
    kernel = []
    for i in range(n):
        img, comb = fn(1 << i), 1 << i
        while img:
            p = img.bit_length() - 1
            if p in rows:
                ri, rc = rows[p]
                img ^= ri
                comb ^= rc
            else:
                rows[p] = (img, comb)
                break
        if not img:
            kernel.append(comb)
    return kernel


def w_level_system(perms, n):
    d = {g: dop(perms[g]) for g in LEFT + RIGHT}
    Ls = lambda v: d["as"](d["c"](v))
    Lt = lambda v: d["at"](d["c"](v))
    Ms = lambda v: d["bs"](d["b1"](v))
    Mt = lambda v: d["bt"](d["b1"](v))

    def fn(v):
        r1 = Ls(v) ^ Ms(v)
        r2 = Lt(v) ^ Mt(v)
        r3 = Lt(Ls(v)) ^ v
        return r1 | (r2 << n) | (r3 << (2 * n))

    return fn, Ls, Lt


def evaluate(M, perms, u):
    ident = tuple(range(M.n))
    vals = {g: ((0, 0), perms[g]) for g in LEFT + RIGHT}
    vals["u"] = (u, ident)
    for name, word in DERIVED:
        vals[name] = M.gword(vals, word)
    return vals


def relator_cparts(M, vals, rels):
    """Return (list of C-parts, list of names failing at W or G0 level)."""
    cs, bad = [], []
    for name, lhs, rhs in rels:
        X = M.gword(vals, lhs)
        Y = M.gword(vals, rhs)
        if X[1] != Y[1] or X[0][0] != Y[0][0]:
            bad.append(name)
            continue
        cs.append((name, X[0][1] ^ Y[0][1]))
    return cs, bad


def g0_closure(M, perms, vecs):
    E = Echelon()
    pps = [M.pair_perm(perms[g]) for g in LEFT + RIGHT]
    queue = [v for v in vecs if v]
    while queue:
        v = E.add(queue.pop())
        if not v:
            continue
        for pp in pps:
            w, x = 0, v
            while x:
                low = x & -x
                k = low.bit_length() - 1
                x ^= low
                w |= 1 << pp[k]
            if E.reduce(w):
                queue.append(w)
    return E


def build_perms(pl, pr, mL, mR):
    perms = {}
    for g in LEFT:
        perms[g] = product_perm(pl[g], None, mL, mR, "L")
    for g in RIGHT:
        perms[g] = product_perm(None, pr[g], mL, mR, "R")
    return perms


def test_u(M, perms, v, cu):
    """Return (head survives?, K echelon, vals)."""
    vals = evaluate(M, perms, (v, cu))
    cs, bad = relator_cparts(M, vals, TRAP_RELS + INVOL_RELS)
    if bad:
        raise RuntimeError("W-level failure %s" % bad)
    hW, hC = vals["h"][0]
    if hW:
        raise RuntimeError("head has W-part: orbit trap violated")
    E = g0_closure(M, perms, [c for _, c in cs])
    return bool(E.reduce(hC)), E, vals


def try_config(mL, mR, rng, n_v=4, n_c=2):
    pl = {g: rand_involution(mL, rng) for g in LEFT}
    pr = {g: rand_involution(mR, rng) for g in RIGHT}
    perms = build_perms(pl, pr, mL, mR)
    n = mL * mR
    fn, Ls, Lt = w_level_system(perms, n)
    ker = nullspace(fn, n)
    stats = {"kerdim": len(ker), "tried": 0}
    if not ker:
        return None, stats
    M = Model(n)
    for _ in range(n_v):
        v = 0
        while not v:
            for kv in ker:
                if rng.random() < 0.5:
                    v ^= kv
        for ci in range(n_c):
            cu = 0 if ci == 0 else rng.getrandbits(M.npairs)
            stats["tried"] += 1
            ok, E, vals = test_u(M, perms, v, cu)
            if ok:
                return {"mL": mL, "mR": mR, "pl": pl, "pr": pr, "v": v,
                        "cu": cu, "Kdim": len(E.rows),
                        "Cdim": M.npairs}, stats
    return None, stats


def main():
    seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
    trials = int(sys.argv[2]) if len(sys.argv) > 2 else 200
    sizes = [(3, 3), (4, 3), (4, 4), (5, 4), (6, 4), (6, 6)]
    rng = random.Random(seed)
    for (mL, mR) in sizes:
        nz = tried = 0
        for t in range(trials):
            hit, st = try_config(mL, mR, rng)
            nz += st["kerdim"] > 0
            tried += st["tried"]
            if hit:
                print("HIT", mL, mR, "Kdim", hit["Kdim"], "of", hit["Cdim"])
                print("  pl", hit["pl"], "pr", hit["pr"])
                print("  v", hex(hit["v"]), "cu", hex(hit["cu"]))
                return hit
        print("size %dx%d: %d configs, %d with v != 0, %d (v,c) tried, 0 hits"
              % (mL, mR, trials, nz, tried))
    return None


if __name__ == "__main__":
    main()
