#!/usr/bin/env python3
"""Split class-two models of the trap group Gamma_trap.

Let G0 = GL x GR act on a finite set Omega (GL, GR commuting groups of
permutations, generated by the six Levi involutions).  Let N = N(Omega) be the
free nilpotent class-two group generated by involutions x_w, w in Omega:
elements are pairs (a, z), a in F_2^Omega (W-part), z in Lambda^2 F_2^Omega
(C-part, basis e_{ij}, i<j), with product

    (a, z)(b, z') = (a + b, z + z' + f(a, b)),  f(a, b) = sum_{i>j} a_i b_j e_{ji}.

G0 acts on N by permuting the generators x_w.  For u in N the group
G = N/K x| G0, K a G0-invariant subgroup of the centre C = Lambda^2, is a
finite group generated by the seven involutions whenever u^2 in K.

Bitsets: a is an int with n bits, z an int with n(n-1)/2 bits.
"""

import random


class Model:
    def __init__(self, n):
        self.n = n
        self.pidx = {}
        k = 0
        for i in range(n):
            for j in range(i + 1, n):
                self.pidx[(i, j)] = k
                self.pidx[(j, i)] = k
                k += 1
        self.npairs = k
        # fmask[j] = C-bits e_{jk} for... built on demand
        self._fcache = {}

    # ---------- N arithmetic ----------
    def f(self, a, b):
        """sum_{i>j} a_i b_j e_{ji}."""
        z = 0
        pidx = self.pidx
        ai = a
        while ai:
            low = ai & -ai
            i = low.bit_length() - 1
            ai ^= low
            bj = b & ((1 << i) - 1)
            while bj:
                lowj = bj & -bj
                j = lowj.bit_length() - 1
                bj ^= lowj
                z ^= 1 << pidx[(i, j)]
        return z

    def nmul(self, x, y):
        return (x[0] ^ y[0], x[1] ^ y[1] ^ self.f(x[0], y[0]))

    def ninv(self, x):
        # x^{-1} = x * (0, q(a)) since x^2 = (0, f(a,a)) central
        return (x[0], x[1] ^ self.f(x[0], x[0]))

    def pair_perm(self, perm):
        key = tuple(perm)
        if key in self._fcache:
            return self._fcache[key]
        pp = [0] * self.npairs
        for (i, j), k in self.pidx.items():
            if i < j:
                pp[k] = self.pidx[(perm[i], perm[j])]
        self._fcache[key] = pp
        return pp

    def zperm(self, perm, z):
        pp = self.pair_perm(perm)
        out = 0
        while z:
            low = z & -z
            k = low.bit_length() - 1
            z ^= low
            out |= 1 << pp[k]
        return out

    def act(self, perm, x):
        """perm . x: x_w -> x_{perm(w)}."""
        a, z = x
        acc = (0, self.zperm(perm, z))
        # (a, z) = prod_{i ascending, a_i=1} x_i * (0, z)
        prod = (0, 0)
        ai = a
        while ai:
            low = ai & -ai
            i = low.bit_length() - 1
            ai ^= low
            prod = self.nmul(prod, (1 << perm[i], 0))
        return self.nmul(prod, acc)

    # ---------- semidirect product N x| G0 ----------
    def gmul(self, X, Y):
        nx, gx = X
        ny, gy = Y
        return (self.nmul(nx, self.act(gx, ny)), tuple(gx[k] for k in gy))

    def gword(self, vals, word):
        ident = tuple(range(self.n))
        acc = ((0, 0), ident)
        for w in word:
            acc = self.gmul(acc, vals[w])
        return acc


def rand_involution(m, rng, fixed_max=None):
    """Random involution of range(m) (possibly with fixed points)."""
    pts = list(range(m))
    rng.shuffle(pts)
    perm = list(range(m))
    k = rng.randint(1, m // 2) if m >= 2 else 0
    for t in range(k):
        i, j = pts[2 * t], pts[2 * t + 1]
        perm[i], perm[j] = j, i
    return perm


def product_perm(pl, pr, mL, mR, side):
    """Permutation of Omega = range(mL) x range(mR), index i*mR + j."""
    out = [0] * (mL * mR)
    for i in range(mL):
        for j in range(mR):
            if side == "L":
                out[i * mR + j] = pl[i] * mR + j
            else:
                out[i * mR + j] = i * mR + pr[j]
    return tuple(out)
