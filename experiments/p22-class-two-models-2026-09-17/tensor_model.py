#!/usr/bin/env python3
"""Universal equivariant class-two models of Gamma_trap over a Levi module W.

Let G0 act F_2-linearly on a finite module W (matrices A_g, g one of the six
Levi involutions, left commuting with right).  The group

    N_W = W x (W (x) W),  (w, z)(w', z') = (w + w', z + z' + w (x) w'),

is nilpotent of class two with centre containing C = W (x) W, and G0 acts on
it by (w, z) -> (A w, A z A^T).  For u = (v, c_u) put G = N_W/K x| G0 where K
is the G0-submodule of C generated by the C-parts of all relators of
Gamma_trap (u^2 = (0, v (x) v) included).  G is a finite group generated by
seven involutions satisfying every relation of Gamma_trap, and the head
survives in G iff its C-part is not in K.  Every class-two model in which the
extension cocycle is G0-equivariant is a quotient of one of these.

numpy uint8 arrays mod 2.
"""

import numpy as np

from words import DERIVED, TRAP_RELS, INVOL_RELS, EXTRA_RELS, LEFT, RIGHT


def m2(a):
    return (a % 2).astype(np.uint8)


class TensorModel:
    def __init__(self, mats):
        """mats: dict g -> n x n F_2 matrix (np.uint8)."""
        self.mats = {g: m2(np.array(A, dtype=np.int64)) for g, A in mats.items()}
        self.n = next(iter(self.mats.values())).shape[0]
        self.I = np.eye(self.n, dtype=np.uint8)

    def nmul(self, x, y):
        w, z = x
        w2, z2 = y
        return (w ^ w2, z ^ z2 ^ m2(np.outer(w, w2)))

    def act(self, A, x):
        w, z = x
        return (m2(A.astype(np.int64) @ w), m2(A.astype(np.int64) @ z @ A.T.astype(np.int64)))

    def gmul(self, X, Y):
        nx, A = X
        ny, B = Y
        return (self.nmul(nx, self.act(A, ny)), m2(A.astype(np.int64) @ B.astype(np.int64)))

    def unit(self):
        return ((np.zeros(self.n, np.uint8), np.zeros((self.n, self.n), np.uint8)), self.I)

    def word(self, vals, word):
        acc = self.unit()
        for g in word:
            acc = self.gmul(acc, vals[g])
        return acc

    def evaluate(self, v, cu):
        zero = (np.zeros(self.n, np.uint8), np.zeros((self.n, self.n), np.uint8))
        vals = {g: (zero, self.mats[g]) for g in LEFT + RIGHT}
        vals["u"] = ((m2(np.array(v)), m2(np.array(cu))), self.I)
        for name, w in DERIVED:
            vals[name] = self.word(vals, w)
        return vals

    def relator_cparts(self, vals, rels):
        cs, bad = [], []
        for name, lhs, rhs in rels:
            X = self.word(vals, lhs)
            Y = self.word(vals, rhs)
            if not (np.array_equal(X[1], Y[1]) and np.array_equal(X[0][0], Y[0][0])):
                bad.append(name)
                continue
            # X^{-1} Y = A^{-1}(n_X^{-1} n_Y); n_X^{-1} n_Y = (0, z_X + z_Y + w(x)w + w(x)w)
            cs.append((name, X[0][1] ^ Y[0][1]))
        return cs, bad


# ---------------- span closure in C = W (x) W ----------------

def vec_to_int(z):
    bits = np.flatnonzero(z.reshape(-1))
    out = 0
    for b in bits:
        out |= 1 << int(b)
    return out


def int_to_vec(x, N):
    out = np.zeros(N, np.uint8)
    k = 0
    while x:
        if x & 1:
            out[k] = 1
        x >>= 1
        k += 1
    return out


class Echelon:
    def __init__(self):
        self.rows = {}

    def reduce(self, v):
        while v:
            p = v.bit_length() - 1
            r = self.rows.get(p)
            if r is None:
                return v
            v ^= r
        return 0

    def add(self, v):
        v = self.reduce(v)
        if v:
            self.rows[v.bit_length() - 1] = v
        return v


def g0_closure(model, vecs):
    """G0-submodule of C generated by the given C-parts (n x n arrays)."""
    n = model.n
    krons = [m2(np.kron(A.astype(np.int64), A.astype(np.int64))) for A in model.mats.values()]
    E = Echelon()
    queue = [vec_to_int(z) for z in vecs]
    while queue:
        v = E.add(queue.pop())
        if not v:
            continue
        vv = int_to_vec(v, n * n).astype(np.int64)
        for Kr in krons:
            w = vec_to_int(m2(Kr @ vv))
            if E.reduce(w):
                queue.append(w)
    return E


def head_survives(model, v, cu, rels=None):
    rels = TRAP_RELS + INVOL_RELS if rels is None else rels
    vals = model.evaluate(v, cu)
    cs, bad = model.relator_cparts(vals, rels)
    if bad:
        raise RuntimeError("W-level failure: %s" % bad)
    hn, hA = vals["h"]
    if hn[0].any() or not np.array_equal(hA, model.I):
        raise RuntimeError("head not central")
    E = g0_closure(model, [z for _, z in cs])
    return bool(E.reduce(vec_to_int(hn[1]))), E, vals, cs
