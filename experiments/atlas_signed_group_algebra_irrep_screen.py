"""Test the signed atlas phase ideal in every characteristic-zero A8 sector.

For the inner classical alignment, form the signed prefix derivative
``d_w`` in Q[A8].  The relevant left ideal is generated by the 24
certified-zero derivatives and ``(g-1)d_s`` for the four survivor words and
six A8 generators.  Semisimplicity reduces membership of ``d_11`` to the
annihilator test in every irreducible A8 representation: every vector killed
by all ideal generators must also be killed by ``d_11``.  Restrictions of
one S8 Specht representation from each conjugate-partition pair cover all A8
irreducibles, including both constituents of self-conjugate partitions.
"""

import argparse
from collections import Counter
import json
from math import gcd

import numpy as np
from sage.all import (  # pylint: disable=import-error
    Partitions,
    QQ,
    SymmetricGroup,
    SymmetricGroupRepresentation,
    ZZ,
    identity_matrix,
    matrix,
    zero_matrix,
)

from atlas_certified_a8_alignment import (
    CERTIFIED_REPRESENTATIVE_INDICES,
    PHASE_INDEX,
    boundary_words,
)
from atlas_certified_dual_number_certificate import ALIGNMENT_KEY
from atlas_subset_dual_central_no_go import SURVIVOR_REPRESENTATIVES
from atlas_two_chart_search import (
    I4,
    factor_generators,
    gf2_inv,
    gf2_mul,
    matrix_key,
)


def compose(left, right):
    """Permutation of a matrix product in the column-action convention."""
    return tuple(right[left[index]] for index in range(len(left)))


def load_generator_permutations(path):
    with open(path, "r", encoding="utf-8") as stream:
        records = json.load(stream)["matrices"]
    generators = [word[0][1] for _name, word in factor_generators()[:6]]
    return [
        tuple(int(value) - 1 for value in records[
            matrix_key(generator).hex()
        ])
        for generator in generators
    ]


def enumerate_isomorphism(generator_permutations):
    generators = [word[0][1] for _name, word in factor_generators()[:6]]
    matrices = [I4.copy()]
    permutations = [tuple(range(8))]
    index = {matrix_key(I4): 0}
    for element, permutation in zip(matrices, permutations):
        for generator, generator_permutation in zip(
                generators, generator_permutations):
            target = gf2_mul(element, generator)
            target_permutation = compose(
                generator_permutation, permutation
            )
            key = matrix_key(target)
            if key in index:
                if permutations[index[key]] != target_permutation:
                    raise AssertionError("inconsistent exceptional isomorphism")
                continue
            index[key] = len(matrices)
            matrices.append(target)
            permutations.append(target_permutation)
    if len(matrices) != 20160 or len(set(permutations)) != 20160:
        raise AssertionError("GL(4,2) to A8 enumeration failed")
    return {
        matrix_key(element): permutation
        for element, permutation in zip(matrices, permutations)
    }


def selected_partitions():
    selected = []
    seen = set()
    for partition in Partitions(8):
        key = tuple(partition)
        conjugate = tuple(partition.conjugate())
        if key in seen:
            continue
        seen.add(key)
        seen.add(conjugate)
        selected.append(key)
    return selected


def validate_partition_cover(partitions):
    """Check the standard restriction classification for S8 down to A8."""
    all_partitions = {tuple(partition) for partition in Partitions(8)}
    covered = set()
    self_conjugate = []
    for partition in partitions:
        conjugate = tuple(Partitions(8)(partition).conjugate())
        covered.add(partition)
        covered.add(conjugate)
        if partition == conjugate:
            self_conjugate.append(partition)
    if covered != all_partitions:
        raise AssertionError("selected partitions do not cover S8 pairs")
    # A non-self-conjugate pair restricts to one A8 irreducible; a
    # self-conjugate Specht module restricts to two inequivalent irreducibles.
    complex_irreducibles = (
        (len(all_partitions) - len(self_conjugate)) // 2
        + 2 * len(self_conjugate)
    )
    if complex_irreducibles != 14:
        raise AssertionError("unexpected number of A8 irreducibles")
    return self_conjugate, complex_irreducibles


def signed_derivative(word, alignment, alignment_inverse):
    prefix = I4.copy()
    coefficients = Counter()
    for factor, source_matrix in word:
        image = source_matrix
        if factor == 2:
            image = gf2_mul(gf2_mul(
                alignment, source_matrix
            ), alignment_inverse)
        before = prefix
        prefix = gf2_mul(prefix, image)
        if factor == 2:
            coefficients[matrix_key(before)] += 1
            coefficients[matrix_key(prefix)] -= 1
    if matrix_key(prefix) != matrix_key(I4):
        raise AssertionError("aligned boundary word is nontrivial")
    return {
        key: coefficient
        for key, coefficient in coefficients.items() if coefficient
    }


def represented_sum(cache, coefficients, dimension):
    result = zero_matrix(QQ, dimension, dimension)
    for key, coefficient in coefficients.items():
        result += coefficient * cache[key]
    return result


def stack_rows(operators, dimension):
    rows = []
    for operator in operators:
        rows.extend(operator.rows())
    return matrix(QQ, rows, ncols=dimension)


def update_denominator(current, values):
    for value in values:
        denominator = QQ(value).denominator()
        current = current * denominator // gcd(current, denominator)
    return current


def matrix_values(input_matrix):
    for row in input_matrix.rows():
        yield from row


def run(natural_path):
    generator_permutations = load_generator_permutations(natural_path)
    permutation_by_matrix = enumerate_isomorphism(generator_permutations)
    alignment = np.frombuffer(
        bytes.fromhex(ALIGNMENT_KEY), dtype=np.uint8
    ).reshape(4, 4).copy()
    alignment_inverse = gf2_inv(alignment)
    words = boundary_words()
    selected_indices = sorted(set(
        CERTIFIED_REPRESENTATIVE_INDICES + SURVIVOR_REPRESENTATIVES
    ))
    derivatives = {
        index: signed_derivative(
            words[index], alignment, alignment_inverse
        )
        for index in selected_indices
    }
    generators = [word[0][1] for _name, word in factor_generators()[:6]]
    required_keys = {
        key for derivative in derivatives.values() for key in derivative
    }
    required_keys.update(matrix_key(generator) for generator in generators)

    symmetric_group = SymmetricGroup(8)
    permutation_elements = {
        key: symmetric_group([
            value + 1 for value in permutation_by_matrix[key]
        ])
        for key in required_keys
    }
    partitions = selected_partitions()
    self_conjugate, complex_irreducibles = validate_partition_cover(
        partitions
    )
    records = []
    global_certificate_denominator = 1
    global_representation_denominator = 1
    for partition in partitions:
        representation = SymmetricGroupRepresentation(
            list(partition), implementation="seminormal"
        )
        identity = representation(symmetric_group.one())
        dimension = identity.nrows()
        cache = {
            key: representation(permutation_elements[key])
            for key in required_keys
        }
        representation_denominator = 1
        for represented in cache.values():
            representation_denominator = update_denominator(
                representation_denominator, matrix_values(represented)
            )
        derivative_operators = {
            index: represented_sum(cache, derivative, dimension)
            for index, derivative in derivatives.items()
        }
        seed_operators = [
            derivative_operators[index]
            for index in CERTIFIED_REPRESENTATIVE_INDICES
        ]
        for index in SURVIVOR_REPRESENTATIVES:
            derivative = derivative_operators[index]
            for generator in generators:
                seed_operators.append(
                    (cache[matrix_key(generator)] - identity) * derivative
                )
        seed_rows = stack_rows(seed_operators, dimension)
        target = derivative_operators[PHASE_INDEX]
        seed_rank = seed_rows.rank()
        augmented = seed_rows.stack(target)
        augmented_rank = augmented.rank()
        common_kernel = seed_rows.right_kernel()
        target_on_kernel_rank = (
            target * common_kernel.basis_matrix().transpose()
        ).rank()
        if target_on_kernel_rank != augmented_rank - seed_rank:
            raise AssertionError(
                "row-rank and common-kernel tests disagree"
            )
        row_coefficients = seed_rows.transpose().solve_right(
            target.transpose()
        )
        if row_coefficients.transpose() * seed_rows != target:
            raise AssertionError("exact row-space certificate failed")
        certificate_denominator = update_denominator(
            1, matrix_values(row_coefficients)
        )
        global_certificate_denominator = (
            global_certificate_denominator * certificate_denominator
            // gcd(global_certificate_denominator, certificate_denominator)
        )
        global_representation_denominator = (
            global_representation_denominator * representation_denominator
            // gcd(
                global_representation_denominator,
                representation_denominator,
            )
        )
        records.append({
            "partition": [int(value) for value in partition],
            "dimension": int(dimension),
            "seed_row_rank": int(seed_rank),
            "common_kernel_dimension": int(common_kernel.dimension()),
            "target_rank_increment": int(augmented_rank - seed_rank),
            "target_on_common_kernel_rank": int(target_on_kernel_rank),
            "representation_matrix_denominator": str(
                representation_denominator
            ),
            "row_certificate_denominator": str(certificate_denominator),
            "phase_in_left_ideal_block": augmented_rank == seed_rank,
        })

    return {
        "field": "Q",
        "group": "A8 ~= GL(4,2)",
        "zero_derivatives": len(CERTIFIED_REPRESENTATIVE_INDICES),
        "central_survivors": list(SURVIVOR_REPRESENTATIVES),
        "centrality_generators": len(generators),
        "selected_s8_partitions": len(records),
        "self_conjugate_s8_partitions": [
            [int(value) for value in partition]
            for partition in self_conjugate
        ],
        "covered_a8_complex_irreducibles": complex_irreducibles,
        "covers_every_a8_irrep": True,
        "global_representation_matrix_denominator": str(
            global_representation_denominator
        ),
        "global_row_certificate_denominator": str(
            global_certificate_denominator
        ),
        "cross_characteristic_exceptional_prime_support": [
            [int(prime), int(exponent)]
            for prime, exponent in ZZ(
                global_representation_denominator
                * global_certificate_denominator
            ).factor()
        ],
        "records": records,
        "phase_in_generated_left_ideal": all(
            record["phase_in_left_ideal_block"] for record in records
        ),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--natural-a8-json", required=True)
    args = parser.parse_args()
    print(json.dumps(run(args.natural_a8_json), indent=2))


if __name__ == "__main__":
    main()
