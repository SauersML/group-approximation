"""Audit the exact block-eight phase against the complete atlas boundary.

The block-eight construction is amplified inside the honest 64-dimensional
A8 irrep W=(5,2,1), then every one of the 234 tensor-flip failures in the
complete radius-ten collision window is evaluated.  The representation uses
the standalone Young-orthogonal implementation and needs no Sage runtime.
"""

import json
import itertools
import math

import numpy as np

from atlas_clifford_window_search import (
    adjacent_matrices,
    permutation_matrix,
    tableaux,
)
from atlas_kernel_collision_enumerator import (
    enumerate_ball,
    factor_projections,
    spanning_tree_kernel_words,
)
from atlas_two_chart_search import I4, factor_generators, gf2_mul, matrix_key


def projector_basis(projector, tolerance=0.5):
    values, vectors = np.linalg.eigh((projector + projector.conj().T) / 2)
    return vectors[:, values > tolerance]


def joint_bases(first, second):
    identity = np.eye(first.shape[0], dtype=np.complex128)
    answer = {}
    for first_sign, second_sign in itertools.product((-1, 1), repeat=2):
        projector = (
            ((identity + first_sign * first) / 2)
            @ ((identity + second_sign * second) / 2)
        )
        answer[(first_sign, second_sign)] = projector_basis(projector)
    return answer


def exact_block_pair():
    x = np.array([[0, 1], [1, 0]], dtype=np.complex128)
    z = np.diag([1, -1]).astype(np.complex128)
    b = np.zeros((8, 8), dtype=np.complex128)
    c = np.zeros((8, 8), dtype=np.complex128)
    b[:2, :2] = x
    b[2:4, 2:4] = x
    c[:2, :2] = z
    c[2:4, 2:4] = z
    for offset, (b_sign, c_sign) in enumerate(
            ((-1, -1), (-1, 1), (1, -1), (1, 1)), start=4):
        b[offset, offset] = b_sign
        c[offset, offset] = c_sign
    identity = np.eye(8, dtype=np.complex128)
    reversal = np.fliplr(identity)
    bridge = np.zeros((8, 8), dtype=np.complex128)
    for left, right in ((0, 6), (2, 4), (5, 3), (7, 1)):
        bridge[left, right] = 1
        bridge[right, left] = 1
    square_root = (identity + 1j * c) / math.sqrt(2)
    a = b @ bridge @ b
    e = bridge @ reversal @ square_root
    return b, c, a, e


def standalone_representation():
    """Return the W=(5,2,1) representation of GL(4,2), with caching."""
    with open("experiments/atlas-a8-natural.json", encoding="utf-8") as stream:
        permutations = json.load(stream)["matrices"]
    adjacent = adjacent_matrices(tableaux())
    generators = [word[0][1] for _name, word in factor_generators()[:6]]
    generator_values = [
        permutation_matrix(permutations[matrix_key(value).hex()], adjacent)
        .astype(np.complex128)
        for value in generators
    ]
    identity_key = matrix_key(I4)
    parents = {identity_key: None}
    elements = [I4.copy()]
    for element in elements:
        parent_key = matrix_key(element)
        for generator_index, generator in enumerate(generators):
            target = gf2_mul(element, generator)
            key = matrix_key(target)
            if key not in parents:
                parents[key] = (parent_key, generator_index)
                elements.append(target)
    if len(parents) != 20160:
        raise AssertionError("GL(4,2) enumeration failed")
    cache = {identity_key: np.eye(64, dtype=np.complex128)}

    def representation(value):
        key = matrix_key(value)
        if key not in cache:
            path = []
            cursor = key
            while cursor not in cache:
                parent, generator_index = parents[cursor]
                path.append(generator_index)
                cursor = parent
            result = cache[cursor]
            for generator_index in reversed(path):
                result = result @ generator_values[generator_index]
            cache[key] = result
        return cache[key]

    return representation


def amplified_alignment():
    representation = standalone_representation()
    identity = np.eye(64, dtype=np.complex128)
    b8, c8, a8, e8 = exact_block_pair()

    # The fixed D8 is generated by b=I+E_01 and c=I+E_12.
    from atlas_two_chart_search import transvection
    b = representation(transvection(0, 1))
    c = representation(transvection(1, 2))
    center = (b @ c) @ (b @ c)
    tau_projector = (identity - center) / 2
    tau_plus = projector_basis(tau_projector @ (identity + c) / 2)
    if tau_plus.shape[1] != 16:
        raise AssertionError("unexpected faithful D8 multiplicity")
    tau_minus = b @ tau_plus

    character_bases = {}
    plus_center = (identity + center) / 2
    for b_sign in (-1, 1):
        for c_sign in (-1, 1):
            projector = (plus_center
                         @ ((identity + b_sign * b) / 2)
                         @ ((identity + c_sign * c) / 2))
            basis = projector_basis(projector)
            if basis.shape[1] != 8:
                raise AssertionError("unexpected D8 character multiplicity")
            character_bases[(b_sign, c_sign)] = basis

    columns = []
    character_keys = tuple(sorted(character_bases))
    for copy in range(8):
        columns.extend((
            tau_plus[:, 2 * copy],
            tau_minus[:, 2 * copy],
            tau_plus[:, 2 * copy + 1],
            tau_minus[:, 2 * copy + 1],
        ))
        columns.extend(character_bases[key][:, copy]
                       for key in character_keys)
    d8_frame = np.column_stack(columns)
    if np.linalg.norm(d8_frame.conj().T @ d8_frame - identity) > 1e-10:
        raise AssertionError("D8 decomposition frame is not unitary")
    block_b = np.kron(np.eye(8), b8)
    block_c = np.kron(np.eye(8), c8)
    if max(
            np.linalg.norm(d8_frame.conj().T @ b @ d8_frame - block_b),
            np.linalg.norm(d8_frame.conj().T @ c @ d8_frame - block_c),
    ) > 1e-10:
        raise AssertionError("canonical D8 block identification failed")

    target_a = d8_frame @ np.kron(np.eye(8), a8) @ d8_frame.conj().T
    target_e = d8_frame @ np.kron(np.eye(8), e8) @ d8_frame.conj().T

    source_a = representation(transvection(1, 0))
    source_e = representation(transvection(1, 2))
    source_bases = joint_bases(source_a, source_e)
    target_bases = joint_bases(target_a, target_e)
    source_frame = np.concatenate(
        [source_bases[key] for key in sorted(source_bases)], axis=1)
    target_frame = np.concatenate(
        [target_bases[key] for key in sorted(target_bases)], axis=1)
    relative = target_frame @ source_frame.conj().T
    if max(
            np.linalg.norm(relative @ source_a @ relative.conj().T - target_a),
            np.linalg.norm(relative @ source_e @ relative.conj().T - target_e),
            np.linalg.norm(relative.conj().T @ relative - identity),
    ) > 1e-10:
        raise AssertionError("V4 alignment failed")
    return representation, relative


def word_value(word, representation, relative):
    value = np.eye(64, dtype=np.complex128)
    adjoint = relative.conj().T
    for factor, matrix in word:
        letter = representation(matrix)
        if factor == 2:
            letter = relative @ letter @ adjoint
        value = value @ letter
    return value


def main():
    representation, relative = amplified_alignment()
    identity = np.eye(64, dtype=np.complex128)
    generator_values = []
    for _name, word in factor_generators():
        factor, matrix = word[0]
        value = representation(matrix)
        if factor == 2:
            value = relative @ value @ relative.conj().T
        generator_values.append(value)

    states, _level_sizes = enumerate_ball(5)
    kernel_words, _collision_sizes, _depths = spanning_tree_kernel_words(states)
    identity_key = matrix_key(I4)
    boundary = []
    for global_index, word in enumerate(kernel_words):
        projections = factor_projections(word)
        if any(matrix_key(value) != identity_key for value in projections):
            boundary.append((global_index, word, projections))
    if len(boundary) != 234:
        raise AssertionError("complete boundary does not have 234 words")

    records = []
    for boundary_index, (global_index, word, projections) in enumerate(boundary):
        value = word_value(word, representation, relative)
        trace = np.trace(value) / 64
        scalar_deviation = np.linalg.norm(value - trace * identity) / 8
        identity_error = np.linalg.norm(value - identity) / 8
        centrality = max(
            np.linalg.norm(value @ generator - generator @ value) / 8
            for generator in generator_values)
        records.append({
            "boundary_index": boundary_index,
            "global_index": global_index,
            "word_length": len(word),
            "projection_identity_pattern": [
                matrix_key(projection) == identity_key
                for projection in projections
            ],
            "trace": [float(trace.real), float(trace.imag)],
            "scalar_deviation": float(scalar_deviation),
            "identity_error": float(identity_error),
            "centrality_max": float(centrality),
        })

    scalar_records = [record for record in records
                      if record["scalar_deviation"] < 1e-8]
    identity_records = [record for record in records
                        if record["identity_error"] < 1e-8]
    phase_records = [record for record in scalar_records
                     if record["identity_error"] >= 1e-8]
    by_scalar = sorted(records, key=lambda record: record["scalar_deviation"])
    by_centrality = sorted(
        records, key=lambda record: record["centrality_max"], reverse=True)
    print(json.dumps({
        "boundary_words": len(records),
        "scalar_words": len(scalar_records),
        "identity_words": len(identity_records),
        "nonidentity_scalar_words": len(phase_records),
        "nonidentity_scalar_records": phase_records,
        "twenty_most_scalar": by_scalar[:20],
        "ten_worst_centrality": by_centrality[:10],
        "centrality_max_over_boundary": max(
            record["centrality_max"] for record in records),
        "centrality_rms_over_boundary": float(math.sqrt(sum(
            record["centrality_max"] ** 2 for record in records
        ) / len(records))),
    }, indent=2))


if __name__ == "__main__":
    main()
