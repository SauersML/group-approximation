#!/usr/bin/env python3
"""worklist.py <NON_MF_SENTENCE_CENSUS.tsv> <out WORKLIST.md> [<tag>]

Runs ON MSI (census lane).  Every sentence whose status is not formalized /
definition / structural / attribution / provenance, grouped by owner lane.
Owner = label / section / text rules for the 2026-09-11 swarm roster.
"""
import re, sys
from collections import defaultdict

src, out = sys.argv[1], sys.argv[2]
tag = sys.argv[3] if len(sys.argv) > 3 else ""
DONE = {"formalized", "definition", "structural", "attribution", "provenance"}
rows = []
for line in open(src, encoding="utf-8"):
    if line.startswith("#") or line.startswith("key\t"):
        continue
    p = line.rstrip("\n").split("\t")
    if len(p) < 8:
        continue
    key, ln, section, env, label, status, decls, sentence = p[:8]
    rows.append(dict(key=key, line=int(ln), section=section, env=env, label=label,
                     status=status, decls=decls, sentence=sentence))

def owner(r):
    s, lab, sec, env = r["sentence"], r["label"], r["section"], r["env"]
    if env == "abstract" or (sec == "" and r["line"] < 85):
        return "sec5-sentences" if re.search(r"torsion-free", s) else "sec2-sentences"
    if env == "proof" and re.search(r"Dahmani|Guirardel|\{DGO\}", s):
        return "dgo-analytic+go-sr1" if re.search(r"Gerasimova|\{GO\}", s) else "dgo-analytic"
    if env == "proof" and re.search(r"Gerasimova|\{GO\}|density of the invertible", s):
        return "go-sr1"
    if lab == "prop:torsion-defect-ring":
        return "torsion-ring" if env in ("proposition", "proof") else "jacobson"
    if lab == "thm:mf-quotient-units":
        return "agp-units"
    if lab == "cor:leavitt-mf-quotient":
        if re.search(r"D_d\(k\)|diagonal", s):
            return "leavitt-ge"
        return "leavitt-k1"
    if sec.startswith("A torsion-free"):
        if re.search(r"Fournier-Facio constructs|\[\\S2\]|\{FFF\}|finitely presented infinite simple|J\\le G_0|isomorphic to a", s):
            return "simple-group"
        return "sec5-sentences"
    if sec == "Introduction":
        if r["line"] >= 280 or re.search(r"torsion-free|Q\$", s) and r["line"] > 270:
            return "sec5-sentences"
        if re.search(r"Khanh|R_R\\cong|thm:mf-quotient-units|purely infinite", s):
            return "agp-units"
        if re.search(r"k\^\\times/\(k\^\\times\)\^\{d-1\}|K_1", s):
            return "leavitt-k1"
        if r["line"] >= 249:
            return "sec4-sentences"
        if r["line"] >= 225:
            return "agp-units"
        if r["line"] >= 207:
            return "sec3-sentences"
        return "sec2-sentences"
    if sec in ("Origin and authorship", "Acknowledgments", ""):
        return "census"
    if sec == "Related work":
        return "sec2-sentences"
    if sec.startswith("Amenable traces"):
        return "sec4-sentences"
    if sec.startswith("MF quotients"):
        return "agp-units"
    if sec.startswith("One-sided inverses") or sec.startswith("The binary example"):
        return "sec3-sentences"
    return "sec2-sentences"

groups = defaultdict(list)
counts = defaultdict(int)
for r in rows:
    counts[r["status"]] += 1
    if r["status"] not in DONE:
        groups[owner(r)].append(r)
with open(out, "w", encoding="utf-8") as fh:
    fh.write(f"# Non-MF census worklist {tag}\n\n")
    fh.write("Generated by the census lane from the regenerated census join (current tex). ")
    fh.write("Every sentence not graded formalized/definition/structural/attribution/provenance, by owner lane. ")
    fh.write("Owner rules are mechanical (label/section/text); a lane that finds a row is not its own tells the lead.\n\n")
    fh.write("| status | sentences |\n| --- | --- |\n")
    for k in sorted(counts, key=lambda k: -counts[k]):
        fh.write(f"| `{k}` | {counts[k]} |\n")
    fh.write(f"| **total** | {len(rows)} |\n\n")
    for lane in sorted(groups):
        fh.write(f"## {lane} ({len(groups[lane])})\n\n")
        for r in sorted(groups[lane], key=lambda r: r["line"]):
            dec = r["decls"] if r["decls"] else "—"
            fh.write(f"* `{r['key']}` line {r['line']} `{r['status']}` {r['label'] or r['env'] or r['section']}: "
                     f"{r['sentence'][:260]}\n  * decls: {dec}\n")
        fh.write("\n")
print("wrote", out, dict(counts))
